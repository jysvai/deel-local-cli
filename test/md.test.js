trace('8-줄끝이CRLF면');

// ── 서버가 \r\n 으로 흘려보내면 ─────────────────────────────────────────
//
// 줄을 \n 으로만 끊으면 줄 끝에 \r 가 남는다. 그러면 두 가지가 한꺼번에 나빠진다.
//
//   1) 제목·목록 정규식이 `(.*)$` 로 끝나는데 `.` 은 \r 를 안 먹는다.
//      그래서 **아무것도 안 그려지고** 별표와 우물정자가 그대로 뜬다.
//   2) 남은 \r 가 터미널로 나가면 커서가 줄 맨 앞으로 간다 — 앞에 세운
//      세로줄을 지우고 그 위에 덮어쓴다. 글자가 먹힌 것처럼 보인다.
{
  const md = new 마크다운({ 폭: 60 });
  const 나온것 = [...md.넣기('## 고친 것\r\n- **a.js** 고침\r\n'), ...md.끝()];
  const 줄들 = 나온것.map((x) => (typeof x === 'string' ? x : x.이어붙임));

  check('줄 끝에 \\r 를 안 남긴다', 줄들.every((l) => !l.includes('\r')),
    JSON.stringify(줄들));
  check('CRLF 여도 제목으로 그린다', !벗기기(줄들[0] ?? '').includes('#'), 벗기기(줄들[0] ?? ''));
  check('CRLF 여도 굵기를 잡는다', !벗기기(줄들[1] ?? '').includes('**'), 벗기기(줄들[1] ?? ''));

  // 통째로 그리는 자리도 마찬가지다.
  const 한번에 = 그리기('## 제목\r\n- 목록\r\n', 60).map(벗기기);
  check('통째로 그릴 때도 \\r 를 안 남긴다', 한번에.every((l) => !l.includes('\r')), JSON.stringify(한번에));
}

trace('9-이상한글자');

// ── 답에 NUL 이 섞여 와도 ───────────────────────────────────────────────
//
// 코드 조각을 빼 둘 때 NUL 을 자리표시자로 쓴다. 그런데 모델 답에 NUL 이
// 그대로 섞여 오면(도구가 읽은 바이너리 조각을 되읊는 경우) 그것이 자리표시자로
// 읽혀서 엉뚱한 글자로 바뀐다 — 모델이 한 말과 화면이 달라진다.
{
  // 소스에 진짜 NUL 을 박아 두면 편집 도구가 이 파일을 바이너리로 본다. 여기서 만든다.
  const 널 = String.fromCharCode(0);
  const r = 벗기기(인라인(`앞${널}0${널}뒤 \`코드\``));
  check('답에 섞인 NUL 이 글자를 안 바꾼다', r === '앞0뒤 코드', JSON.stringify(r));
  check('그래도 코드는 제대로 그린다', r.includes('코드') && !r.includes('`'), JSON.stringify(r));
}

trace('10-폭이좁아도');

// ── 폭을 아주 좁게 잡아도 ───────────────────────────────────────────────
//
// 창이 좁으면 repl 이 폭으로 (columns - 6) 을 넘긴다. columns 가 작으면 0 이나
// 음수가 되고, 그러면 모든 줄이 폭을 넘는 것으로 쳐서 **아무것도 안 그려진다.**
{
  const md = new 마크다운({ 폭: 0 });
  const 줄들 = [...md.넣기('## 제목\n'), ...md.끝()].map((x) => (typeof x === 'string' ? x : x.이어붙임));
  check('폭이 0 이어도 제목은 그린다', 줄들.some((l) => !벗기기(l).includes('#')), JSON.stringify(줄들.map(벗기기)));

  const md2 = new 마크다운({ 폭: -5 });
  const 줄들2 = [...md2.넣기('- 목록\n'), ...md2.끝()].map((x) => (typeof x === 'string' ? x : x.이어붙임));
  check('폭이 음수여도 안 죽는다', 줄들2.length > 0, JSON.stringify(줄들2.map(벗기기)));
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n답 그리기 검사  ${D}(모델 말을 읽는 모양으로 옮기는가)${X}\n`);
