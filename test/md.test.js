trace('6-글을안잃는다');

// ── 무슨 답이 와도 글자를 안 잃는다 ─────────────────────────────────────
{
  const 답 = [
    '## 고친 것',
    '',
    '**src/runner.js** 의 `console.log` 를 `log.info` 로 바꿨습니다.',
    '',
    '- 로그 형식 통일',
    '- 남은 것: `src/worker.js`',
    '',
    '```js',
    "log.info('시작', { id })",
    '```',
    '',
    '| 파일 | 고친 곳 |',
    '|---|---|',
    '| runner.js | 3군데 |',
    '',
    '> 되돌리려면 /undo 를 쓰세요.',
  ].join('\n');

  const 줄들 = 그리기(답, 70).map(벗기기);
  const 합친것 = 줄들.join('\n');

  /*
   * 표는 상자로 그리므로 위아래 테두리 두 줄이 더 생긴다(가름줄 하나는
   * 우리가 긋는 선으로 바뀌므로 ±0). 그래서 원본보다 딱 두 줄이 많다.
   */
  check('제목·목록·코드가 모두 그려진다', 줄들.length === 답.split('\n').length + 2,
    `${줄들.length}줄 / 원본 ${답.split('\n').length}줄`);
  check('꾸밈 기호가 화면에서 사라진다',
    !/\*\*|^#|`/m.test(합친것.replace(/^[─│┌└•☐☑▍]+/gm, '')), 합친것.slice(0, 80));

  // 글자 자체는 하나도 안 없어져야 한다.
  const 알맹이 = (s) => s.replace(/[\s*`#>|─│┼┌┬┐├┤└┴┘•☐☑▍-]/g, '');
  check('글자는 하나도 안 잃는다', 알맹이(합친것) === 알맹이(답),
    `${알맹이(합친것).length}자 / 원본 ${알맹이(답).length}자`);
  check('코드 안 따옴표가 그대로', 합친것.includes("log.info('시작', { id })"));
  check('표의 칸이 살아 있다', /runner\.js/.test(합친것) && /3군데/.test(합친것));

  /*
   * ★ 표는 칸이 아래위로 맞아야 표다.
   *
   * 예전에는 줄마다 바로 그려서 세로줄이 지그재그로 흘렀다. 그때는 「가름줄에
   * 작대기가 안 남는가」 정도만 잴 수 있었는데, 그건 표로 보이는지와 상관이
   * 없다. 이제는 **자리**를 잰다 — 글자 수가 아니라 화면 칸(한글은 두 칸)으로.
   */
  /*
   * 표만 잘라 낸다. `┌ │ └` 는 코드 울타리와 인용도 쓰는 글자라 그것으로
   * 고르면 엉뚱한 줄이 따라 들어온다. 표의 위아래 테두리만 갖는 글자는
   * `┬` 와 `┴` 다.
   */
  const 위 = 줄들.findIndex((l) => l.includes('┬'));
  const 아래 = 줄들.findIndex((l) => l.includes('┴'));
  const 표줄들 = 위 >= 0 && 아래 > 위 ? 줄들.slice(위, 아래 + 1) : [];
  const 칸자리 = (줄) => {
    const 자리 = [];
    let x = 0;
    for (const ch of 줄) {
      if ('│┬┼┴┌┐├┤└┘'.includes(ch)) 자리.push(x);
      x += width(ch);
    }
    return 자리;
  };
  check('표 가름줄에 작대기가 안 남는다',
    표줄들.some((l) => /^├/.test(l)) && !표줄들.some((l) => /[|]/.test(l)),
    표줄들.join(' / '));
  check('★ 표의 모든 줄이 같은 폭이다',
    표줄들.length >= 5 && new Set(표줄들.map((l) => width(l))).size === 1,
    표줄들.map((l) => width(l)).join('·'));
  check('★ 세로줄과 가름줄이 같은 자리에 선다',
    표줄들.length >= 5 && new Set(표줄들.map((l) => 칸자리(l).join(','))).size === 1,
    표줄들.map((l) => 칸자리(l).join(',')).join(' / '));

  /*
   * ── 표가 아닌 것을 표로 그리지 않는다 ────────────────────────────────
   *
   * 위 검사는 **표를 준 다음** 무엇이 나오는지만 본다. 정작 위험한 쪽은
   * 반대다 — 세로 작대기가 든 평범한 글(`a | b`, 코드 안의 파이프)을 표로
   * 읽어 버리면, 사람이 쓴 글이 상자에 갇힌 채로 나간다. 그때는 오류도 안
   * 난다. 그래서 「아니면 null」 을 여기서 따로 잰다.
   */
  check('★ 가름줄이 없으면 표가 아니다', 표그리기(['| a | b |', '| 1 | 2 |']) === null);
  check('★ 가름줄이 첫 줄이면 표가 아니다', 표그리기(['|---|---|', '| 1 | 2 |']) === null);
  check('빈 것도 null', 표그리기([]) === null && 표그리기(null) === null);

  // 머리줄만 있고 몸이 없어도 상자는 나온다 — 머리 자체가 한 행이다.
  const 머리만 = 표그리기(['| a | b |', '|---|---|']);
  check('머리줄만 있어도 그린다', Array.isArray(머리만) && 머리만.length === 3,
    Array.isArray(머리만) ? String(머리만.length) : String(머리만));

  // 좁은 창에서도 상자가 안 어긋난다. 폭을 줄이면 칸이 접힐 뿐이다.
  const 좁게 = 표그리기(['| 아주 긴 머리말 | 두 번째 | ', '|---|---|', '| 값 | 값 |'], 28);
  check('★ 좁은 창에서도 모든 줄이 같은 폭',
    Array.isArray(좁게) && new Set(좁게.map((l) => width(l))).size === 1,
    Array.isArray(좁게) ? 좁게.map((l) => width(l)).join('·') : String(좁게));
}

