/**
 * 종합 모드에서 단계가 일을 따라가나 — 옮기는 자리와 **안 옮기는 자리**를 잰다.
 *
 * ── 여기서 재야 하는 것 ─────────────────────────────────────────────────
 *
 * 「알아서 계획 → 디버그 → 코드로 넘어가 달라」 는 말은 쉬운데, 이 기능은
 * 잘못 만들면 조용히 **시킨 범위를 넘는다.** 옮기는 쪽이 아니라 안 옮기는
 * 쪽이 안전 장치라, 검사도 그쪽이 알맹이다.
 *
 *   1. 사람이 `/plan` 을 직접 쳤으면 계획 모드는 약속이다. 그 사람이 계획을
 *      다 적었다고 우리가 파일을 바꾸기 시작하면 그건 배신이다.
 *   2. `architect` · `inspect` · `ask` 는 라우터가 「고치라는 말이 없다」 고
 *      보고 고른 자리다(route.js 의 손대라했나). 거기서 스스로 코드로
 *      넘어가는 것은 단계가 나아가는 것이 아니라 안 시킨 일을 하는 것이다.
 *   3. 뒤로 안 간다. 걸음마다 오르내리면 시킴말이 걸음마다 바뀌고, 그건
 *      캐시를 매번 깨면서 모델에게는 갈피를 못 잡게 하는 짓이다.
 *
 * 그리고 신호를 **무엇으로 재는지**가 모드마다 다르다는 것도 잰다. 계획
 * 모드에는 파일을 바꾸는 도구가 아예 없으니 「바꿨나」 로는 영영 안 넘어간다.
 */
import { 다음단계, 도구가늘어나나 } from '../src/agent/단계.js';
import { get as getWork } from '../src/agent/modes.js';
import { toolSchemas } from '../src/tools/index.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

const 아무것도안함 = { 할일: false, 바꿈: false };
const 바꿨다 = { 할일: false, 바꿈: true };
const 적었다 = { 할일: true, 바꿈: false };

/*
 * 종합 모드에서 라우터가 짐작한 단계. 사람이 고른 것이 아니다.
 *
 * 계획에서 넘어가려면 말에 두 가지가 다 있어야 한다 — 「묻지 말고 끝까지」 와
 * 「고쳐라」. 그래서 도우미도 둘 다 받는다. 기본은 둘 다 없는 것으로 둔다.
 */
const 짐작 = (지금, 본것, 묻지말라 = false, 손대라 = 묻지말라) =>
  다음단계({ 지금, 종합인가: true, 본것, 묻지말라, 손대라 });

// 사람이 직접 그 모드를 골랐다.
const 사람이고름 = (지금, 본것, 묻지말라 = false, 손대라 = 묻지말라) =>
  다음단계({ 지금, 종합인가: false, 본것, 묻지말라, 손대라 });

{
  /*
   * ── 옮겨야 하는 자리 ──────────────────────────────────────────────────
   *
   * 사람이 겪은 그대로다. 「왜 안 되는지 찾아서 고쳐줘」 한 줄로 디버그가
   * 붙고, 열두 걸음쯤에 원인을 찾아 고치기 시작한다. 그 뒤 스물여덟 걸음이
   * 만드는 일인데 시킴말은 여전히 「고치기 전에 재현부터 하라」 였다.
   */
  check('★★ 디버그에서 파일을 바꾸기 시작하면 코드로 간다',
    짐작('debug', 바꿨다) === 'code', String(짐작('debug', 바꿨다)));
  check('★★ 종합에서 파일을 바꾸기 시작하면 코드로 간다',
    짐작('auto', 바꿨다) === 'code', String(짐작('auto', 바꿨다)));

  check('★ 아직 아무것도 안 바꿨으면 디버그 그대로',
    짐작('debug', 아무것도안함) === null, String(짐작('debug', 아무것도안함)));
  check('★ 아직 아무것도 안 바꿨으면 종합 그대로',
    짐작('auto', 아무것도안함) === null, String(짐작('auto', 아무것도안함)));

  /*
   * 디버그·종합은 할 일을 적은 것만으로는 안 넘어간다.
   *
   * 원인을 찾는 도중에 「볼 것 세 가지」 를 적어 두는 것은 흔한 일이고, 그건
   * 조사가 끝났다는 뜻이 아니다. 이 둘은 파일을 바꾸는 도구를 이미 들고
   * 있으므로, **정말 바꿨을 때**를 기다리면 된다.
   */
  check('★★ 디버그는 할 일만 적었다고 안 넘어간다',
    짐작('debug', 적었다) === null, String(짐작('debug', 적었다)));
  check('★★ 종합은 할 일만 적었다고 안 넘어간다',
    짐작('auto', 적었다) === null, String(짐작('auto', 적었다)));
}

{
  /*
   * ── 계획 모드 ─────────────────────────────────────────────────────────
   *
   * 계획 모드에는 파일을 바꾸는 도구가 없다. 그러니 「바꿨나」 로 재면 영영
   * 안 넘어간다 — 신호가 **적어 둔 할 일**이어야 하는 까닭이다.
   *
   * 그리고 조건이 하나 더 붙는다. 「계획해서 만들어줘」 에는 이미 다른 길이
   * 있다 — 계획을 내고 승인을 받아 이어서 하는 길(route.js 의 겹친요청).
   * 여기서 몰래 넘어가면 사람이 보자고 한 계획을 못 보고 파일부터 바뀐다.
   * 그래서 「묻지 말고 끝까지」 라고 적어 둔 사람에게만 넘어간다 — 그 사람은
   * route.js 가 이미 겹침 길을 꺼 둔 사람이라, 안 넘어가면 계획만 내고
   * 끝나는 턴이 남는다.
   */
  check('★★ 계획은 파일 바꿈으로는 안 넘어간다 (바꿀 도구가 없다)',
    짐작('plan', 바꿨다, true) === null, String(짐작('plan', 바꿨다, true)));
  check('★★ 묻지 말라고 했고 할 일을 다 적었으면 코드로 간다',
    짐작('plan', 적었다, true) === 'code', String(짐작('plan', 적었다, true)));
  check('★★ 묻지 말라고 안 했으면 계획만 내고 멈춘다',
    짐작('plan', 적었다, false) === null, String(짐작('plan', 적었다, false)));
  check('★ 묻지 말라고 했어도 할 일을 안 적었으면 안 넘어간다',
    짐작('plan', 아무것도안함, true) === null, String(짐작('plan', 아무것도안함, true)));

  /*
   * ── 「계획만 세워줘. 알아서 진행해」 ───────────────────────────────────
   *
   * 이 말에는 「묻지 말라」 는 있고 「고쳐라」 는 없다. 그 사람이 싫다고 한
   * 것은 **승인 창**이지 파일을 고쳐 달라고 한 것이 아니다. 여기서 넘어가면
   * 계획만 보자고 한 사람의 파일이 바뀐다 — 이 파일에서 유일하게 시킨 범위를
   * 넘을 수 있는 자리라, 조건 하나로는 부족했다.
   *
   * 「묻지 마라」 는 **어떻게** 의 말이고 「고쳐라」 는 **무엇을** 의 말이다.
   * 범위를 정하는 것은 뒤엣것이라 둘 다 봐야 한다.
   */
  check('★★★ 묻지 말라고만 했고 고쳐 달라고는 안 했으면 안 넘어간다',
    다음단계({ 지금: 'plan', 종합인가: true, 본것: 적었다, 묻지말라: true, 손대라: false }) === null,
    String(다음단계({ 지금: 'plan', 종합인가: true, 본것: 적었다, 묻지말라: true, 손대라: false })));
  check('★★★ 고쳐 달라고만 했고 묻지 말라고는 안 했으면 안 넘어간다 (승인 길이 있다)',
    다음단계({ 지금: 'plan', 종합인가: true, 본것: 적었다, 묻지말라: false, 손대라: true }) === null,
    String(다음단계({ 지금: 'plan', 종합인가: true, 본것: 적었다, 묻지말라: false, 손대라: true })));
  check('★★ 둘 다 있어야 넘어간다',
    다음단계({ 지금: 'plan', 종합인가: true, 본것: 적었다, 묻지말라: true, 손대라: true }) === 'code', '');

  /*
   * 이 두 조건은 **계획에만** 붙는다. 디버그·종합은 이미 파일을 바꿀 수 있는
   * 자리에서 시작했으므로, 거기서 코드로 가는 것은 범위를 넓히는 일이 아니다.
   * 여기에 같은 잠금을 걸면 「왜 안 되는지 찾아서 고쳐줘」 가 끝까지 디버그로
   * 남는다 — 이 기능이 없애려던 바로 그 모양이다.
   */
  check('★★ 디버그는 그 두 조건 없이도 넘어간다',
    다음단계({ 지금: 'debug', 종합인가: true, 본것: 바꿨다, 묻지말라: false, 손대라: false }) === 'code', '');
  check('★★ 종합도 그 두 조건 없이 넘어간다',
    다음단계({ 지금: 'auto', 종합인가: true, 본것: 바꿨다, 묻지말라: false, 손대라: false }) === 'code', '');
}

{
  /*
   * ── 사람이 고른 모드는 안 건드린다 ────────────────────────────────────
   *
   * 이게 이 파일에서 제일 중요한 검사다. `/plan` 을 친 사람에게 계획 모드는
   * 약속이고, `/debug` 를 친 사람은 원인만 듣고 싶을 수 있다. 여기서 옮기는
   * 것은 라우터가 **짐작한** 단계뿐이다.
   */
  check('★★★ 사람이 고른 계획은 안 옮긴다',
    사람이고름('plan', 적었다, true) === null, String(사람이고름('plan', 적었다, true)));
  check('★★★ 사람이 고른 디버그는 안 옮긴다',
    사람이고름('debug', 바꿨다, true) === null, String(사람이고름('debug', 바꿨다, true)));
  check('★★★ 사람이 고른 코드도 그대로다',
    사람이고름('code', 바꿨다, true) === null, String(사람이고름('code', 바꿨다, true)));
}

{
  /*
   * ── 말로 답하는 모드는 안 옮긴다 ──────────────────────────────────────
   *
   * 셋 다 라우터가 「이 턴은 말로 답하는 턴」 이라고 본 자리다. 그리고 그렇게
   * 보려면 사람의 말에 고치라는 말이 **없어야** 한다 (route.js 의 손대라했나
   * 가 그 셋을 후보에서 뺀다). 즉 사람이 고쳐 달라고 안 했다.
   *
   * 이 셋이 코드로 넘어가면, 「이 구조 어떻게 생겼는지 봐 줘」 라고만 한
   * 사람의 파일이 바뀐다. 신호가 뭐로 오든 상관없이 안 넘어가야 한다.
   */
  for (const 모드 of ['architect', 'inspect', 'ask']) {
    check(`★★★ ${모드} 는 파일을 바꿔도 안 옮긴다`,
      짐작(모드, 바꿨다, true) === null, String(짐작(모드, 바꿨다, true)));
    check(`★★★ ${모드} 는 할 일을 적어도 안 옮긴다`,
      짐작(모드, 적었다, true) === null, String(짐작(모드, 적었다, true)));
  }
}

{
  /*
   * ── 앞으로만 간다 ─────────────────────────────────────────────────────
   *
   * 코드에 닿으면 끝이다. 여기서 다시 조사로 내려가는 길을 하나라도 열어 두면
   * 걸음마다 모드가 오르내리고, 그때마다 시킴말이 통째로 바뀐다.
   */
  check('★★ 코드에서는 더 안 옮긴다',
    짐작('code', 바꿨다, true) === null && 짐작('code', 적었다, true) === null, '');
  check('★★ 어느 신호로도 디버그로 돌아가는 길은 없다',
    !['auto', 'code', 'debug', 'plan', 'architect', 'inspect', 'ask'].some((m) =>
      [바꿨다, 적었다, 아무것도안함].some((본것) =>
        짐작(m, 본것, true) === 'debug' || 짐작(m, 본것, false) === 'debug')), '');
  check('★★ 계획으로 돌아가는 길도 없다',
    !['auto', 'code', 'debug', 'plan', 'architect', 'inspect', 'ask'].some((m) =>
      [바꿨다, 적었다, 아무것도안함].some((본것) =>
        짐작(m, 본것, true) === 'plan' || 짐작(m, 본것, false) === 'plan')), '');

  /*
   * 옮겨 간 곳에서 한 번 더 부르면 null 이어야 한다 — 그래야 걸음마다 불러도
   * 알림이 한 번만 뜬다. loop.js 는 걸음마다 이 함수를 부른다.
   */
  const 첫걸음 = 짐작('debug', 바꿨다);
  check('★★ 옮긴 뒤 같은 신호로 다시 불러도 조용하다',
    첫걸음 === 'code' && 짐작(첫걸음, 바꿨다) === null, String(짐작(첫걸음, 바꿨다)));
}

{
  /*
   * ── 없는 모드·망가진 입력 ─────────────────────────────────────────────
   *
   * 이 함수는 걸음마다 돌고, 여기서 던지면 턴이 통째로 죽는다.
   */
  check('★ 모르는 모드는 그냥 안 옮긴다',
    짐작('없는모드', 바꿨다, true) === null, '');
  check('★ 본것이 없어도 안 죽는다',
    다음단계({ 지금: 'debug', 종합인가: true, 본것: undefined }) === null, '');
  check('★ 묻지말라를 안 줘도 안 죽는다',
    다음단계({ 지금: 'plan', 종합인가: true, 본것: 적었다 }) === null, '');
}

{
  /*
   * ── 도구가 정말 늘어나나 ──────────────────────────────────────────────
   *
   * 화면에 「앞머리를 다시 씁니다」 라고 적는 근거다. 규격이 도구 목록을
   * 앞머리 맨 앞에 렌더하므로 도구가 하나만 늘어도 그 턴의 캐시가 끊긴다.
   * 그 말을 적으려면 **정말 느는지**가 사실이어야 한다.
   */
  const 도구들 = (모드) =>
    toolSchemas(null, { work: 모드 }).map((t) => t.function.name);

  check('★★ 계획 → 코드 는 도구가 는다 (캐시가 한 번 끊긴다)',
    도구가늘어나나('plan', 'code', 도구들) === true, '');
  check('★★ 디버그 → 코드 는 도구가 안 는다 (조용히 넘어가도 된다)',
    도구가늘어나나('debug', 'code', 도구들) === false, '');
  check('★ 같은 모드끼리는 안 는다',
    도구가늘어나나('code', 'code', 도구들) === false, '');

  /*
   * 계획 모드에 파일을 바꾸는 도구가 없다는 것은 이 파일 전체의 전제다.
   * 언젠가 계획 모드가 Edit 를 갖게 되면 신호를 「할 일」 로 잡은 까닭이
   * 사라지므로, 그때 이 줄이 먼저 깨져야 한다.
   */
  const 계획도구 = new Set(도구들('plan'));
  check('★★★ 계획 모드에는 파일을 바꾸는 도구가 없다 (신호가 할 일인 까닭)',
    !계획도구.has('Edit') && !계획도구.has('Write'), [...계획도구].join(','));

  // 넘어갈 곳이 진짜 있는 모드인지. 오타 하나로 단계가 영영 안 옮겨진다.
  check('★★ 넘어갈 곳이 실제 작업 모드다',
    getWork('code')?.id === 'code', String(getWork('code')?.id));
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n단계 넘어가기 검사  ${D}(옮기는 자리보다 안 옮기는 자리)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
