/**
 * 겪은 것을 얼마나 믿을까 — 오염 방지 필터를 잰다.
 *
 * ── 여기서 재야 하는 것 ─────────────────────────────────────────────────
 *
 * 자기가 쓴 기록을 자기가 다시 읽어 프롬프트에 싣는 프로그램은 두 가지로 썩는다.
 * 둘 다 **오류가 아니라서 아무 데도 안 찍힌다** — 화면은 멀쩡하고 답만 나빠진다.
 *
 *   1. 작은 표본을 확신으로 읽는다. 두 번 실패한 것을 「이 PC 에서 안 되는
 *      명령」 이라고 적어 보낸다. 두 번은 우연일 수 있다.
 *
 *   2. 틀린 부정이 스스로를 봉인한다. 「다시 부르지 마라」 가 프롬프트에 들어가면
 *      모델이 안 부르고 → 성공 셈이 안 늘고 → 그 줄이 영영 안 사라진다.
 *      지난달에 없던 프로그램을 오늘 깔아도 계속 없다고 우긴다.
 *
 * 그래서 이 검사의 알맹이는 **「말한다」 가 아니라 「언제 입을 다무나」** 다.
 * 2번이 진짜 풀렸는지는 「한참 뒤에 모름으로 돌아오는가」 로만 확인할 수 있다.
 */
import {
  윌슨아래, 윌슨위, 삭힘, 며칠됐나, 뭐라할까,
  반감기된다, 반감기안된다, 하루할인된다, 하루할인안된다, 좋음문턱, 나쁨문턱,
} from '../src/agent/신뢰도.js';
import { 거른표, 성한열쇠인가, 성한기록인가 } from '../src/agent/성한기록.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

const 날 = (n) => new Date(Date.parse('2026-03-01T00:00:00Z') + n * 86400000).toISOString();
const 말 = (r, d = 0) => 뭐라할까({ ...r, at: 날(0) }, 날(d));

trace('1-나이재기');

// ── 나이 ────────────────────────────────────────────────────────────────
{
  check('★ 날짜를 알면 날수로 잰다', Math.round(며칠됐나(날(10), 날(0))) === 10, '');
  /*
   * 모르는 것을 「오늘」 로 치지 않는다.
   *
   * 옛 판에서 넘어왔거나 손으로 고쳐진 기록에는 날짜가 없을 수 있다. 그걸
   * 오늘 겪은 것으로 치면 **나이를 알 수 없는 주장이 통째로 되살아난다** —
   * 이 파일이 막으려는 바로 그 오염이다.
   */
  check('★★ 날짜를 모르면 무한대다 (그래서 아무 데도 안 실린다)',
    며칠됐나(날(0), undefined) === Infinity && 며칠됐나(날(0), '아무말') === Infinity, '');
  /*
   * 미래에 적힌 것은 0일로 친다. 시계가 틀어진 PC 에서 음수 날수가 나오면
   * 할인이 1보다 커져서 **겪지도 않은 것이 더 세진다.**
   */
  check('★★ 미래에 적힌 것은 0일로 친다', 며칠됐나(날(0), 날(30)) === 0, '');
}

trace('2-삭히기');

// ── 시간 할인 (Discounted-UCB) ──────────────────────────────────────────
{
  const 그대로 = 삭힘({ ok: 4, no: 2 }, 0);
  check('★ 오늘 것은 안 삭는다', 그대로.ok === 4 && 그대로.no === 2, JSON.stringify(그대로));

  /*
   * 반감기가 둘이다. 「된다」 는 세 주, 「안 된다」 는 사흘.
   *
   * 자의적으로 보이지만 근거가 있다 — 틀린 부정은 **해 보는 일 자체를 막아서**
   * 스스로 고쳐질 기회를 없앤다. 들통날 길이 막힌 주장은 더 빨리 잊어야 한다.
   */
  const 된반 = 삭힘({ ok: 4, no: 2 }, 반감기된다);
  check('★★ 「된다」 는 세 주에 절반이 된다', Math.abs(된반.ok - 2) < 1e-9, JSON.stringify(된반));
  const 안반 = 삭힘({ ok: 4, no: 2 }, 반감기안된다);
  check('★★ 「안 된다」 는 사흘에 절반이 된다', Math.abs(안반.no - 1) < 1e-9, JSON.stringify(안반));
  check('★★ 부정이 긍정보다 빨리 삭는다', 반감기안된다 < 반감기된다,
    `${반감기안된다} < ${반감기된다}`);

  check('★ 하루할인은 반감기에서 나온다',
    Math.abs(Math.pow(하루할인된다, 반감기된다) - 0.5) < 1e-12
    && Math.abs(Math.pow(하루할인안된다, 반감기안된다) - 0.5) < 1e-12, '');

  // 나이를 모르면(무한대) 통째로 0 이다 — 「모르는 것은 안 싣는다」 와 같은 자세.
  const 모름 = 삭힘({ ok: 9, no: 9 }, Infinity);
  check('★★ 나이를 모르면 힘이 하나도 안 남는다', 모름.ok === 0 && 모름.no === 0, JSON.stringify(모름));

  // 부스러기는 0 으로 떨군다 — 10^-9 짜리가 표에 남아 진짜 기록을 밀어낸다.
  const 부스 = 삭힘({ ok: 1, no: 0 }, 반감기된다 * 20);
  check('★ 다 삭은 것은 0 이 된다', 부스.ok === 0, String(부스.ok));
}

trace('3-윌슨');

// ── 윌슨 점수 (작은 표본을 깎아서 본다) ─────────────────────────────────
{
  /*
   * 이 구간이 하는 일 한 줄: **평균을 그대로 믿지 않는다.**
   * 1승 0패의 평균은 100% 지만, 그 100% 는 아무것도 안 말해 준다.
   */
  check('★★ 한 번 이긴 것은 열 번 이긴 것보다 덜 믿는다',
    윌슨아래(1, 1) < 윌슨아래(10, 10), `${윌슨아래(1, 1).toFixed(3)} < ${윌슨아래(10, 10).toFixed(3)}`);
  check('★★ 한 번 진 것은 열 번 진 것보다 덜 믿는다',
    윌슨위(0, 1) > 윌슨위(0, 10), `${윌슨위(0, 1).toFixed(3)} > ${윌슨위(0, 10).toFixed(3)}`);
  check('★ 아래끝은 언제나 위끝 아래다', 윌슨아래(3, 5) <= 윌슨위(3, 5), '');
  check('★ 겪은 것이 없으면 아무 말도 못 한다',
    윌슨아래(0, 0) === 0 && 윌슨위(0, 0) === 1, '');
  /*
   * 소수도 받아야 한다. 삭힌 셈은 정수가 아니다 — 여기가 정수만 받으면
   * 할인과 윌슨을 겹칠 수가 없고, 그러면 이 파일의 요점이 통째로 사라진다.
   */
  check('★★ 삭은 소수 셈도 잰다',
    Number.isFinite(윌슨아래(1.4, 1.9)) && 윌슨아래(1.4, 1.9) > 0, String(윌슨아래(1.4, 1.9)));
  check('★ 문턱은 서로 안 겹친다', 나쁨문턱 < 좋음문턱, `${나쁨문턱} < ${좋음문턱}`);
}

trace('4-판정');

// ── 무엇을 말할 수 있나 ─────────────────────────────────────────────────
{
  // 두 번 겪으면 말한다. 한 번은 우연일 수 있어서 안 말한다.
  check('★★ 두 번 되면 「된다」', 말({ ok: 2, no: 0 }) === '된다', '');
  check('★★ 한 번 된 것은 아직 모른다', 말({ ok: 1, no: 0 }) === '모름', '');
  check('★★ 두 번 안 되면 「안된다」', 말({ ok: 0, no: 2 }) === '안된다', '');
  check('★★ 한 번 안 된 것은 아직 모른다', 말({ ok: 0, no: 1 }) === '모름', '');

  /*
   * 섞인 증거는 「모름」 이다.
   *
   * 여태 이 자리는 `ok>=2 && no===0` 이었다. 그 규칙에는 「두 번 되고 한 번
   * 안 됨」 을 담을 칸이 아예 없어서, 실제로 제일 흔한 모양이 조용히 버려졌다.
   * 이제는 그것도 재고, 재 보니 아직 모른다고 답한다 — 그게 맞는 답이다.
   */
  check('★★ 섞인 증거는 모른다고 한다', 말({ ok: 2, no: 1 }) === '모름', '');
  check('★ 많이 겪으면 한 번 어긋나도 말한다', 말({ ok: 10, no: 1 }) === '된다', '');

  /*
   * ── 봉인이 풀리는가 ────────────────────────────────────────────────────
   *
   * 이 검사가 이 파일에서 제일 중요하다. 「안 된다」 는 스스로를 봉인한다 —
   * 프롬프트가 부르지 말라고 하니 모델이 안 부르고, 안 부르니 성공 셈이 영영
   * 안 늘고, 그래서 그 줄이 영영 안 사라진다. 지난달에 없던 프로그램을 오늘
   * 깔아도 deel 은 없다고 우긴다.
   *
   * 봉인을 깨는 장치를 따로 넣지 않았다. **잊는 것이 곧 다시 해 보는 것**이다.
   */
  check('★★ 이틀이면 「안된다」 가 입을 다문다 — 그래야 다시 해 본다',
    말({ ok: 0, no: 2 }, 2) === '모름', 말({ ok: 0, no: 2 }, 2));
  check('★ 여러 번 겪은 「안된다」 는 그보다 오래 간다',
    말({ ok: 0, no: 5 }, 2) === '안된다', 말({ ok: 0, no: 5 }, 2));

  /*
   * 「된다」 는 훨씬 천천히 삭는다.
   *
   * 이레로 뒀더니 **금요일에 확인한 명령이 월요일 아침에 백지가 됐다.**
   * 그건 잊는 것이 아니라 안 배우는 것이다. 주말은 넘겨야 한다.
   */
  check('★★ 금요일에 확인한 것이 월요일에도 남아 있다', 말({ ok: 2, no: 0 }, 3) === '된다',
    말({ ok: 2, no: 0 }, 3));
  check('★ 그래도 열흘이면 입을 다문다', 말({ ok: 2, no: 0 }, 10) === '모름',
    말({ ok: 2, no: 0 }, 10));

  /*
   * 다만 **자주 겪은 것은 오래 간다.** 이게 없으면 삭히기가 그냥 망각이 되고,
   * 이 프로그램이 배우는 값을 하나도 못 뽑는다.
   */
  check('★★ 자주 겪은 것은 한 달 뒤에도 말한다', 말({ ok: 5, no: 0 }, 30) === '된다',
    말({ ok: 5, no: 0 }, 30));
  check('★ 그것도 언젠가는 입을 다문다', 말({ ok: 5, no: 0 }, 60) === '모름',
    말({ ok: 5, no: 0 }, 60));
}

trace('5-들어올때거르기');

// ── 스키마로 거르기 ─────────────────────────────────────────────────────
{
  /*
   * 이 표의 **열쇠는 시스템 프롬프트에 그대로 실린다.** 그러니 파일에서 읽은
   * 것을 그대로 믿으면 안 된다 — 손으로 고쳤을 수도, 쓰다 만 채로 남았을 수도,
   * 다른 판이 다른 모양으로 적어 뒀을 수도 있다.
   */
  check('★ 평범한 명령 이름은 받는다',
    성한열쇠인가('npm test') && 성한열쇠인가('cargo build') && 성한열쇠인가('./x.sh'), '');
  /*
   * 역따옴표가 제일 위험하다. 이 글자는 프롬프트에서 역따옴표로 감싸여
   * 나가므로, 하나만 들어 있어도 그 자리에서 틀이 깨지고 그다음 글이 명령
   * 이름 행세를 한다.
   */
  check('★★ 역따옴표가 든 열쇠는 안 받는다', !성한열쇠인가('a`b'), '');
  check('★★ 줄바꿈이 든 열쇠는 안 받는다', !성한열쇠인가('a\nb'), '');
  check('★ 너무 긴 열쇠는 안 받는다', !성한열쇠인가('x'.repeat(41)), '');
  check('★ 빈 열쇠는 안 받는다', !성한열쇠인가('') && !성한열쇠인가(null), '');

  check('★ 성한 기록은 받는다', 성한기록인가({ ok: 1, no: 0, at: 날(0) }), '');
  check('★★ 셈이 숫자가 아니면 안 받는다', !성한기록인가({ ok: 'many', no: 0, at: 날(0) }), '');
  check('★★ 셈이 음수면 안 받는다', !성한기록인가({ ok: -1, no: 0, at: 날(0) }), '');
  check('★★ 날짜가 없으면 안 받는다', !성한기록인가({ ok: 1, no: 0 }), '');

  const 거른것 = 거른표({
    'npm test': { ok: 2, no: 0, at: 날(0) },
    'evil`cmd': { ok: 2, no: 0, at: 날(0) },
    'no date': { ok: 2, no: 0 },
    'bad count': { ok: {}, no: 0, at: 날(0) },
  });
  check('★★ 표에서 성한 것만 남긴다',
    Object.keys(거른것).join(',') === 'npm test', Object.keys(거른것).join(','));
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n오염 방지 필터 검사  ${D}(배운 것을 언제까지 사실로 우기나)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
