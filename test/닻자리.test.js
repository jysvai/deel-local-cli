// 닻을 **창 안**에 박는다.
//
// ── 서버가 뒤로 훑는 것은 블록 스무 개다 ────────────────────────────────
//
// 캐시 표식에서 서버가 뒤로 훑는 범위는 **블록 20개**다. 그 안에 먼저 굳혀 둔
// 표식이 없으면 못 찾고, 못 찾으면 앞이 통째로 다시 나간다. 닻은 바로 그 일을
// 막으려고 꼬리 앞에 하나 더 박아 두는 표식이다.
//
// 그런데 그 거리를 **메시지 수**로 재고 있었다. 도구를 도는 대화에서 그 둘은
// 완전히 다른 값이다.
//
//     assistant  [글 + 도구 부름 둘]   → 3블록
//     user       [도구 결과 둘]        → 2블록
//     한 바퀴가 메시지 2개인데 블록은 5개다.
//
// 그래서 「끝에서 메시지 12개」 는 실제로 **30블록**이었다. 창이 20인데.
// 닻이 창 밖에 있으니 꼬리 표식이 그걸 못 보고, 매 턴 앞이 통째로 다시 나갔다.
// 닻을 박는 코드가 있는데 값은 하나도 없었던 셈이다.
//
// ── 하필 제일 아까운 자리에서만 어긋났다 ────────────────────────────────
//
// 짧은 문답은 메시지와 블록 수가 비슷해서 잘 맞는다. 길게 일을 시킬수록,
// 도구를 많이 부를수록 어긋난다 — 그게 이 프로그램이 하는 일 그 자체다.
// 아낄 것이 제일 많은 대화에서만 안 아꼈다.
//
// 그리고 이건 오류가 아니라서 아무 데도 안 찍힌다. 화면에는 「캐시 표식」 이
// 그대로 떠 있고, 값은 청구서에만 나타난다.
import { 메시지표식, 창블록, 닻블록, 닻문턱 } from '../src/backend/cachemark.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

const 블록수 = (m) => (Array.isArray(m?.content) ? m.content.length : 1);
const 표식자리 = (ms) => {
  const 자리 = [];
  ms.forEach((m, i) => {
    if (Array.isArray(m.content) && m.content.some((b) => b?.cache_control)) 자리.push(i);
  });
  return 자리;
};
/** a 다음부터 b 까지 몇 블록인가 — 서버가 훑어야 하는 거리다. */
const 사이블록 = (ms, a, b) => ms.slice(a + 1, b + 1).reduce((n, m) => n + 블록수(m), 0);

/** 도구를 도는 한 바퀴. 메시지 2개 · 블록 5개. */
const 한바퀴 = (n) => ([
  {
    role: 'assistant',
    content: [
      { type: 'text', text: '해 보겠습니다' },
      { type: 'tool_use', id: `t${n}a`, name: 'Read', input: {} },
      { type: 'tool_use', id: `t${n}b`, name: 'Grep', input: {} },
    ],
  },
  {
    role: 'user',
    content: [
      { type: 'tool_result', tool_use_id: `t${n}a`, content: '읽은 것' },
      { type: 'tool_result', tool_use_id: `t${n}b`, content: '찾은 것' },
    ],
  },
]);
const 바퀴들 = (n) => Array.from({ length: n }, (_, i) => 한바퀴(i)).flat();

// ── 1. 닻이 창 안에 있다 ────────────────────────────────────────────────
trace('1-창안');
{
  /*
   * 이 검사 하나가 이 파일의 전부다. 닻이 창 밖이면 닻이 없는 것과 같다 —
   * 있는 것과 닿는 것은 다르다.
   */
  for (const 바퀴 of [6, 12, 20, 40]) {
    const ms = 바퀴들(바퀴);
    const 자리 = 표식자리(메시지표식(ms));
    check(`★★★ 바퀴 ${바퀴}개 — 표식이 둘이다 (꼬리 + 닻)`, 자리.length === 2, JSON.stringify(자리));
    if (자리.length !== 2) continue;
    const 거리 = 사이블록(ms, 자리[0], 자리[1]);
    check(`★★★ 바퀴 ${바퀴}개 — 닻에서 꼬리까지 ${거리}블록 ≤ 창 ${창블록}`,
      거리 <= 창블록, `${거리}블록`);
  }
}

// ── 2. 메시지로 세던 옛 자리는 창 밖이었다 ──────────────────────────────
trace('2-옛자리');
{
  /*
   * 고친 것이 진짜 고친 것인지 못 박는다. 옛 셈(끝에서 메시지 12개)이 창을
   * 넘는다는 것을 여기서 보인다 — 안 그러면 이 파일이 무엇을 막고 있는지
   * 다음 사람이 알 수 없다.
   */
  const ms = 바퀴들(12);
  const 옛거리 = 사이블록(ms, ms.length - 1 - 12, ms.length - 1);
  check('★★★ 옛 셈(메시지 12개)은 창 밖이다 — 이게 고장이었다',
    옛거리 > 창블록, `${옛거리}블록 > ${창블록}`);

  const 자리 = 표식자리(메시지표식(ms));
  check('★★★ 새 셈은 창 안이다', 사이블록(ms, 자리[0], 자리[1]) <= 창블록,
    `${사이블록(ms, 자리[0], 자리[1])}블록`);
}

// ── 3. 짧은 대화에는 닻을 안 박는다 ─────────────────────────────────────
trace('3-짧을때');
{
  /*
   * 통틀어 창 안이면 꼬리 하나로 앞까지 닿는다. 거기에 닻을 더 박으면 표식만
   * 하나 쓰고 얻는 것이 없다 — 표식은 넷까지만 쓸 수 있는 자원이다.
   */
  const 짧은것 = [
    { role: 'user', content: [{ type: 'text', text: '안녕' }] },
    { role: 'assistant', content: [{ type: 'text', text: '네' }] },
  ];
  check('★★★ 짧은 대화에는 표식 하나만', 표식자리(메시지표식(짧은것)).length === 1,
    JSON.stringify(표식자리(메시지표식(짧은것))));

  const 딱 = 바퀴들(3);   // 6메시지 · 15블록 — 창 안
  check('★★ 통틀어 창 안이면 닻이 없다', 표식자리(메시지표식(딱)).length === 1,
    `${딱.reduce((n, m) => n + 블록수(m), 0)}블록 · 자리 ${JSON.stringify(표식자리(메시지표식(딱)))}`);
}

// ── 4. 값이 서로 말이 된다 ──────────────────────────────────────────────
trace('4-값');
{
  /*
   * 닻블록 이 창블록 보다 크면 이 파일이 고친 고장이 그대로 돌아온다.
   * 숫자 하나만 고치면 되는 자리라 더더욱 못 박아 둔다.
   */
  check('★★★ 닻 거리가 창보다 안쪽이다', 닻블록 < 창블록, `${닻블록} < ${창블록}`);
  check('★★ 여유가 한 바퀴는 된다 — 꼬리 차례가 통째로 들어갈 자리',
    창블록 - 닻블록 >= 5, `${창블록 - 닻블록}블록 남음`);
  check('★★ 닻을 박기 시작하는 문턱이 창보다 크지 않다', 닻문턱 <= 창블록,
    `${닻문턱} ≤ ${창블록}`);
}

// ── 5. 도구만 부른 차례에도 닻이 선다 ───────────────────────────────────
trace('5-빈차례');
{
  /*
   * OpenAI 규격에서 도구만 부른 차례는 `content: null` 이라 표식을 못 붙인다.
   * 그때 앞으로 물러서지 않으면 닻이 통째로 사라진다 — 도구를 도는 턴은
   * 부름과 결과가 번갈아 오므로 **절반 확률로** 그 자리에 떨어진다.
   */
  const ms = 바퀴들(10);
  ms[ms.length - 6] = { role: 'assistant', content: null, tool_calls: [{ id: 'x', type: 'function' }] };
  const 자리 = 표식자리(메시지표식(ms));
  check('★★★ 붙일 자리가 없는 차례가 껴 있어도 표식 둘을 세운다', 자리.length === 2,
    JSON.stringify(자리));
  if (자리.length === 2) {
    check('★★★ 그래도 창 안이다', 사이블록(ms, 자리[0], 자리[1]) <= 창블록,
      `${사이블록(ms, 자리[0], 자리[1])}블록`);
  }
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n닻 자리 검사  ${D}(창은 메시지가 아니라 블록으로 센다)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
