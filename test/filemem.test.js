/**
 * 읽은 파일을 들고 있다가 **바뀐 만큼만** 싣는가.
 *
 * ── 여기서 재는 것 ──────────────────────────────────────────────────────
 *
 * 재는 자가 둘이다. 하나는 **얼마나 줄었나**(그게 이 기능의 목적이다),
 * 다른 하나는 **아무것도 안 잃었나**(그게 더 중요하다).
 *
 * 「앞에서 읽은 그대로입니다」 는 앞엣것이 대화에 살아 있을 때만 참인 말이다.
 * 그 말을 함부로 하면 모델은 있지도 않은 글을 가리키는 쪽지만 받는다 —
 * 통째로 다시 싣는 것보다 훨씬 나쁘다. 그래서 「언제 말하면 안 되나」 를
 * 줄인 양보다 먼저 잰다.
 */
import { 파일기억, 바뀐데만 } from '../src/agent/filemem.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

/** Read 가 돌려주는 모양 — 줄 번호가 붙어 있다. 그 모양대로 재야 뜻이 있다. */
const 읽은꼴 = (줄들) => 줄들.map((s, i) => `${String(i + 1).padStart(6)}\t${s}`).join('\n');
const 코드 = (n) => Array.from({ length: n }, (_, i) => `const x${i} = ${i};`);

trace('1-그대로면-다시-안-싣는다');

{
  const 기억 = new 파일기억();
  const 글 = 읽은꼴(코드(80));

  const a = 기억.실을것('/a.js', 글);
  check('처음에는 통째로 싣는다', a.어떻게 === 'full' && a.글 === 글, a.어떻게);

  const b = 기억.실을것('/a.js', 글);
  check('★ 그대로면 다시 안 싣는다', b.어떻게 === 'same', b.어떻게);
  check('★ 그 대신 앞엣것을 쓰라고 이른다', /앞에서 읽은 그대로/.test(b.글), b.글.slice(0, 40));
  check('줄어든 것이 눈에 띈다', b.글.length < 글.length / 10,
    `${글.length}자 → ${b.글.length}자`);

  // 다른 파일은 서로 안 섞인다. 섞이면 남의 파일 내용을 「그대로」 라고 한다.
  const c = 기억.실을것('/b.js', 글);
  check('★ 파일이 다르면 통째로 싣는다', c.어떻게 === 'full', c.어떻게);
}

trace('2-바뀐-만큼만');

{
  const 기억 = new 파일기억();
  const 원래 = 코드(80);
  기억.실을것('/a.js', 읽은꼴(원래));

  // 한 줄만 고친다 — 제일 흔한 모양이다(읽고, 고치고, 확인하러 다시 읽기).
  const 고친것 = [...원래];
  고친것[11] = 'const x11 = 999;';
  const r = 기억.실을것('/a.js', 읽은꼴(고친것));
  check('★ 한 줄 고치면 바뀐 자리만 싣는다', r.어떻게 === 'diff', r.어떻게);
  check('★ 실제로 크게 줄어든다', r.글.length < 읽은꼴(고친것).length / 3,
    `${읽은꼴(고친것).length}자 → ${r.글.length}자`);
  check('바뀐 줄이 실제로 들어 있다', /999/.test(r.글), r.글.slice(0, 60));
  check('바뀐 줄만 넣고 끝내지 않는다 — 곁줄도 준다', /x10|x12/.test(r.글));

  /*
   * ★ 줄 번호는 **지금 파일의 번호**여야 한다.
   *
   * 모델은 이 번호를 보고 Edit 을 건다. 1부터 다시 세거나 옛 번호를 주면
   * 엉뚱한 줄을 고치는데, 그건 안 줄이는 것보다 훨씬 나쁘다.
   */
  check('★ 새 파일의 줄 번호로 적는다', /\+\s*12\t/.test(r.글),
    (r.글.split('\n').find((l) => l.startsWith('+')) ?? '').slice(0, 30));
}

trace('3-줄-번호가-밀려도');

{
  /*
   * ★ 맨 앞에 한 줄이 끼면 그 아래 줄 번호가 전부 밀린다.
   *
   * 줄 번호를 그대로 두고 견주면 **파일 전체가 바뀐 줄**로 잡혀서 diff 가
   * 원본보다 길어진다 — 줄이려고 만든 것이 늘리는 쪽으로 돈다. 그래서
   * 번호를 떼고 견준 다음 새 번호로 다시 붙인다.
   */
  const 기억 = new 파일기억();
  const 원래 = 코드(80);
  기억.실을것('/a.js', 읽은꼴(원래));
  const 낀것 = 읽은꼴(['// 새 줄', ...원래]);
  const r = 기억.실을것('/a.js', 낀것);
  check('★ 맨 앞에 한 줄이 껴도 바뀐 자리만 싣는다', r.어떻게 === 'diff', r.어떻게);
  check('★ 그때도 실제로 줄어든다', r.글.length < 낀것.length / 3,
    `${낀것.length}자 → ${r.글.length}자`);
}

trace('4-줄이면-안-되는-자리');

{
  const 기억 = new 파일기억();
  const 글 = 읽은꼴(코드(80));

  /*
   * ★ 잘라 읽은 것은 기억하지 않는다.
   *
   * offset·limit 나 창 상한에 걸려 앞부분만 받은 경우, 우리가 들고 있는 것은
   * 파일이 아니라 조각이다. 그걸 「그대로입니다」 라고 하면 모델은 안 본
   * 데를 봤다고 여긴다 — 줄이려다 잃는 자리다.
   */
  기억.실을것('/c.js', 글, { 부분인가: true });
  const 다시 = 기억.실을것('/c.js', 글, { 부분인가: true });
  check('★ 잘라 읽은 것은 「그대로」 라고 안 한다', 다시.어떻게 === 'full', 다시.어떻게);

  // 앞서 통째로 읽어 뒀더라도, 이번이 조각이면 조각을 그대로 준다.
  기억.실을것('/d.js', 글);
  const 조각 = 기억.실을것('/d.js', 읽은꼴(코드(80).slice(0, 10)), { 부분인가: true });
  check('★ 통째로 읽은 뒤라도 조각은 조각대로 싣는다', 조각.어떻게 === 'full', 조각.어떻게);

  /*
   * ★ 요약해서 접으면 기억도 버린다.
   *
   * 접힌 뒤에는 앞엣것이 대화에 없다. 그때도 「앞에서 읽은 그대로」 라고 하면
   * 모델은 아무것도 못 받는다. compact.js 가 이 잊기() 를 부른다.
   */
  기억.실을것('/e.js', 글);
  기억.잊기();
  const 접힌뒤 = 기억.실을것('/e.js', 글);
  check('★ 접은 뒤에는 통째로 다시 싣는다', 접힌뒤.어떻게 === 'full', 접힌뒤.어떻게);
}

trace('5-줄여서-이득이-없으면-안-줄인다');

{
  const 기억 = new 파일기억();

  // 짧은 파일은 diff 로 만들 것이 없다. 오히려 머리말이 본문보다 길다.
  const 짧은것 = 읽은꼴(코드(5));
  기억.실을것('/f.js', 짧은것);
  const r1 = 기억.실을것('/f.js', 읽은꼴(['const y = 1;', ...코드(4)]));
  check('★ 짧은 파일은 그냥 통째로', r1.어떻게 === 'full', r1.어떻게);

  // 반쯤 갈아엎었으면 diff 가 원본만큼 길다. 그때는 통째로가 짧고 읽기도 쉽다.
  const 원래 = 코드(80);
  기억.실을것('/g.js', 읽은꼴(원래));
  const 갈아엎은것 = 원래.map((l, i) => (i % 2 ? `완전히 다른 줄 ${i}` : l));
  const r2 = 기억.실을것('/g.js', 읽은꼴(갈아엎은것));
  check('★ 절반이 바뀌었으면 통째로 싣는다', r2.어떻게 === 'full',
    `${r2.어떻게} · ${r2.글.length}자`);
}

trace('6-바뀐데만-혼자서도');

{
  // 바뀐데만() 자체도 밖에서 쓸 수 있어야 한다 — 이득이 없으면 null 이다.
  const 원래 = 읽은꼴(코드(80));
  const 같은것 = 바뀐데만(원래, 원래);
  check('안 바뀌었으면 null', 같은것 === null, String(같은것).slice(0, 30));
  check('짧은 것도 null', 바뀐데만(읽은꼴(코드(3)), 읽은꼴(코드(4))) === null);
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n읽은 파일 기억 검사  ${D}(바뀐 만큼만 싣는가 · 그러면서 아무것도 안 잃는가)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
