/**
 * 켤 때 뜨는 큰 이름.
 *
 * ── 여기서 재는 것 ──────────────────────────────────────────────────────
 *
 * 그림은 눈으로 봐야 아는 것이라 검사가 할 일이 별로 없어 보인다. 그런데
 * **틀리면 제일 크게 틀리는 것도 그림**이다. 여기가 깨지면 사용자가 이
 * 프로그램에서 처음 보는 화면이 깨진 화면이 된다.
 *
 * 깨지는 길은 셋뿐이고 다 잴 수 있다 —
 *   1. 틀마다 줄 수가 달라진다 → 다시 그릴 때 올릴 줄이 어긋나 조각이 남는다
 *   2. 틀마다 줄 폭이 달라진다 → 지우다 만 자리에 앞 글자가 남는다
 *   3. 좁은 터미널에서 접힌다 → 무슨 그림인지 알아볼 수가 없다
 *
 * 그리고 뜻 쪽으로 하나 더. 이 그림의 색은 **장식이 아니라 계기판**이라,
 * 밖으로 나가는 연결일 때 초록으로 그리면 그 순간 거짓말이 된다.
 */
import {
  글꼴, 이름, 높이, 줄수, 틀, 틀수, 마지막틀, 이름줄들, 선줄,
  이름폭, 글자폭, 쓸배율, 경계글, 잰너비,
} from '../src/ui/banner.js';
import { 보이기 } from '../src/ui/intro.js';
import { width } from '../src/ui/ansi.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });
const 적어둘것 = [];

const 벗기기 = (s) => String(s).replace(/\x1b\[[0-9;]*m/g, '');
// 색이 켜져 있나. FORCE_COLOR 없이 단독으로 돌 때도 이 파일이 돌아야 한다.
const 색켜짐 = 틀(0, { 배: 2 }).join('').includes('\x1b[');

// ══ 1. 글꼴 ════════════════════════════════════════════════════════════
trace('1-글꼴');
{
  for (const [ch, 그림] of Object.entries(글꼴)) {
    check(`${ch}: ${높이}줄이다`, 그림.length === 높이, `${그림.length}줄`);
    const 폭들 = new Set(그림.map((l) => l.length));
    check(`${ch}: 줄마다 폭이 같다`, 폭들.size === 1, [...폭들].join());
    check(`${ch}: 아는 글자만 쓴다`, 그림.every((l) => /^[.#]+$/.test(l)), 그림.join('|'));
    check(`${ch}: 빈 글자가 아니다`, 그림.some((l) => l.includes('#')));
  }
  check('이름에 쓰는 글자가 글꼴에 다 있다', [...이름].every((ch) => !!글꼴[ch]), 이름);

  /*
   * 소문자라야 하는 이유는 눈이 아니라 뜻이다 — 사람이 치는 글자가 그것이다.
   * d 와 l 은 위로 솟고 e 는 허리에서 시작한다. 그 들쭉날쭉함이 소문자를
   * 소문자로 보이게 하므로, 높이를 맞추려고 e 를 끌어올리면 안 된다.
   */
  check('이름은 소문자 그대로', 이름 === 이름.toLowerCase() && 이름 === 'deel', 이름);
  check('d 는 위로 솟는다', 글꼴.d[0].includes('#'), 글꼴.d[0]);
  check('l 도 위로 솟는다', 글꼴.l[0].includes('#'), 글꼴.l[0]);
  check('e 는 허리에서 시작한다', !글꼴.e[0].includes('#') && !글꼴.e[1].includes('#'), 글꼴.e.slice(0, 2).join('|'));
  check('e 는 가운데 가로획이 있다', 글꼴.e[4].startsWith('##'), 글꼴.e[4]);
}

// ══ 2. 줄 수와 폭 — 다시 그리기가 안 깨지는 조건 ════════════════════════
trace('2-줄수와폭');
{
  for (const 배 of [1, 2]) {
    const 줄수들 = new Set();
    const 폭들 = new Set();
    for (let i = 0; i < 틀수; i++) {
      const 줄들 = 틀(i, { 배, 곁말: '이 컴퓨터 안에서만' });
      줄수들.add(줄들.length);
      // 마지막 줄(선)은 곁말이 붙으면서 길어진다. 이름 줄들만 잰다.
      for (const l of 줄들.slice(0, 높이)) 폭들.add(width(벗기기(l)));
    }
    check(`배${배}: 틀마다 줄 수가 같다`, 줄수들.size === 1 && [...줄수들][0] === 줄수, [...줄수들].join());
    check(`배${배}: 이름 줄은 폭이 하나다`, 폭들.size === 1, [...폭들].join());
    check(`배${배}: 폭이 계산과 맞는다`, [...폭들][0] === 이름폭(배) + 2, `${[...폭들][0]} vs ${이름폭(배) + 2}`);
  }

  check('두 배는 한 배의 두 배다', 이름폭(2) === 이름폭(1) * 2, `${이름폭(1)} · ${이름폭(2)}`);
  check('잰너비가 이름폭과 맞는다', 잰너비(2) === 이름폭(2) + 2, `${잰너비(2)} vs ${이름폭(2) + 2}`);
  적어둘것.push(`큰 이름 ${이름폭(2)}칸 · 작은 것 ${이름폭(1)}칸 · ${줄수}줄 · ${틀수}틀`);
}

// ══ 3. 자라는 차례 ══════════════════════════════════════════════════════
trace('3-차례');
{
  // 처음에는 한 글자, 끝에는 다 있어야 한다.
  const 첫 = 이름줄들(1, { 배: 1 });
  const 끝 = 이름줄들(이름.length, { 배: 1 });
  const 셈 = (줄들) => 줄들.join('').split('█').length - 1;
  check('첫 틀은 글자 하나만', 셈(첫) > 0 && 셈(첫) < 셈(끝), `${셈(첫)} vs ${셈(끝)}`);
  check('마지막 틀은 다 찼다', 셈(끝) === 셈(이름줄들(99, { 배: 1 })));

  // 글자가 늘기만 하고 줄지 않는가. 되돌아가면 그림이 깜빡이는 것으로 보인다.
  let 앞셈 = -1;
  let 안줄었나 = true;
  for (let i = 0; i < 틀수; i++) {
    const n = 셈(틀(i, { 배: 1 }).slice(0, 높이));
    if (n < 앞셈) 안줄었나 = false;
    앞셈 = n;
  }
  check('글자가 줄어드는 틀이 없다', 안줄었나);

  // 선도 늘기만 해야 한다.
  let 앞선 = -1;
  let 선안줄었나 = true;
  for (let i = 0; i < 틀수; i++) {
    const n = (벗기기(틀(i, { 배: 1 })[높이]).match(/[─╰╯]/g) ?? []).length;
    if (n < 앞선) 선안줄었나 = false;
    앞선 = n;
  }
  check('선이 줄어드는 틀이 없다', 선안줄었나);

  /*
   * 순서가 뜻이다. 선이 다 닫힌 **다음에야** 곁말이 붙는다 —
   * 안 닫힌 채로 "이 컴퓨터 안에서만" 이라고 하면 그 순간만 거짓말이 된다.
   */
  const 곁말 = '이 컴퓨터 안에서만';
  const 곁붙은틀 = [];
  for (let i = 0; i < 틀수; i++) if (벗기기(틀(i, { 배: 2, 곁말 })[높이]).includes(곁말)) 곁붙은틀.push(i);
  check('곁말은 마지막 틀에만 붙는다', 곁붙은틀.length === 1 && 곁붙은틀[0] === 틀수 - 1, 곁붙은틀.join());
  check('곁말이 붙은 틀은 선이 닫혀 있다', 벗기기(마지막틀({ 배: 2, 곁말 })[높이]).includes('╯'));
  check('닫히기 전에는 오른쪽 끝을 안 그린다',
    !벗기기(틀(틀수 - 3, { 배: 2, 곁말 })[높이]).includes('╯'), 벗기기(틀(틀수 - 3, { 배: 2, 곁말 })[높이]));
}

// ══ 4. 색은 장식이 아니라 계기판이다 ════════════════════════════════════
trace('4-경계색');
{
  check('안에 있으면 집 표시', 경계글(false) === '⌂', 경계글(false));
  check('밖으로 나가면 화살표', 경계글(true) === '↗', 경계글(true));

  const 안 = 마지막틀({ 배: 2, 바깥: false, 곁말: '안' }).join('\n');
  const 밖 = 마지막틀({ 배: 2, 바깥: true, 곁말: '밖' }).join('\n');
  check('안과 밖의 그림이 다르다', 안 !== 밖);
  check('안에는 집 표시가 보인다', 벗기기(안).includes('⌂') && !벗기기(안).includes('↗'));
  check('밖에는 화살표가 보인다', 벗기기(밖).includes('↗') && !벗기기(밖).includes('⌂'));
  // 글자 모양은 같아야 한다 — 달라지는 것은 색과 표시뿐이다.
  check('글자 모양은 같다',
    벗기기(마지막틀({ 배: 2, 바깥: false })[3]) === 벗기기(마지막틀({ 배: 2, 바깥: true })[3]));

  if (색켜짐) {
    check('안과 밖은 색이 다르다',
      마지막틀({ 배: 2, 바깥: false })[0] !== 마지막틀({ 배: 2, 바깥: true })[0]);
    // 왼쪽에서 오른쪽으로 밝아진다. 이름이 자라는 방향과 같아야 자라는 것으로 보인다.
    const 색들 = [...마지막틀({ 배: 2 })[3].matchAll(/\x1b\[38;5;(\d+)m/g)].map((m) => Number(m[1]));
    check('네 글자가 저마다 색을 갖는다', new Set(색들).size === 이름.length, 색들.join());
    check('왼쪽에서 오른쪽으로 밝아진다', 색들.every((v, i) => i === 0 || v > 색들[i - 1]), 색들.join());
  } else {
    적어둘것.push('색이 꺼져 있어 색 검사는 건너뜁니다 (FORCE_COLOR=1 로 재세요).');
  }
}

// ══ 5. 좁으면 억지로 안 밀어 넣는다 ═════════════════════════════════════
trace('5-폭고르기');
{
  check('넓으면 두 배', 쓸배율(이름폭(2) + 4) === 2, String(쓸배율(이름폭(2) + 4)));
  check('한 칸 모자라면 한 배로 물러선다', 쓸배율(이름폭(2) + 3) === 1, String(쓸배율(이름폭(2) + 3)));
  check('더 좁으면 아예 안 쓴다', 쓸배율(이름폭(1) + 3) === 0, String(쓸배율(이름폭(1) + 3)));
  check('아주 좁아도 안 죽는다', 쓸배율(1) === 0 && 쓸배율(0) === 0);
  check('폭을 모르면 기본값으로 판단한다', [0, 1, 2].includes(쓸배율(undefined)));

  // 고른 배율이 실제로 그 폭에 들어가는가. 여기가 맞아야 접히지 않는다.
  for (const 칸 of [40, 60, 66, 80, 100, 120, 200]) {
    const 배 = 쓸배율(칸);
    if (!배) continue;
    const 최대 = Math.max(...마지막틀({ 배 }).slice(0, 높이).map((l) => width(벗기기(l))));
    check(`${칸}칸: 배${배}가 안 접힌다`, 최대 <= 칸, `${최대} > ${칸}`);
  }
}

// ══ 6. 선줄 혼자서도 안 깨지나 ══════════════════════════════════════════
trace('6-선줄');
{
  check('아무것도 안 자랐으면 빈 줄', 선줄(0, { 배: 2 }) === '');
  check('음수를 줘도 안 죽는다', 선줄(-5, { 배: 2 }) === '');
  check('1을 넘겨도 닫힌 것 하나', 벗기기(선줄(9, { 배: 2 })).includes('╯'));
  check('다 자란 선은 이름과 같은 폭',
    width(벗기기(선줄(1, { 배: 2 }))) === 이름폭(2) + 2,
    `${width(벗기기(선줄(1, { 배: 2 })))} vs ${이름폭(2) + 2}`);
  check('곁말이 없으면 표시도 안 붙는다', !벗기기(선줄(1, { 배: 2 })).includes('⌂'));
}

// ══ 7. 실제로 돌려 본다 ═════════════════════════════════════════════════
trace('7-돌려보기');
{
  // 움직임을 켜면 틀마다 커서를 올려야 한다. 올리는 줄 수가 그림 줄 수와
  // 같아야 그 위의 남의 글을 안 지운다.
  let 글 = '';
  const 그린수 = await 보이기({
    쓰기: (s) => { 글 += s; },
    움직임: true,
    칸: 120,
    곁말: '이 컴퓨터 안에서만',
    쉬기: async () => {},
  });
  check('큰 이름 틀 수만큼 돌았다', 그린수 === 틀수, `${그린수} vs ${틀수}`);
  const 올린것 = [...글.matchAll(/\x1b\[(\d+)A/g)].map((m) => Number(m[1]));
  check('올리는 줄 수가 언제나 그림 줄 수', 올린것.every((n) => n === 줄수), [...new Set(올린것)].join());
  check('첫 틀에서는 안 올린다', 올린것.length === 틀수 - 1, `${올린것.length} vs ${틀수 - 1}`);
  check('마지막 그림이 화면에 남는다', 벗기기(글).includes('╯') && 벗기기(글).includes('⌂'));

  // 좁은 자리에서는 작은 모션으로 물러선다.
  let 좁은글 = '';
  const 좁은수 = await 보이기({
    쓰기: (s) => { 좁은글 += s; },
    움직임: true,
    칸: 20,
    곁말: '이 컴퓨터 안에서만',
    쉬기: async () => {},
  });
  check('좁으면 작은 모션으로 간다', 좁은수 !== 틀수 && !좁은글.includes('█'), `${좁은수}틀`);
  check('좁아도 이름은 나온다', 벗기기(좁은글).includes('deel-local'));

  // 한 장만 찍을 때는 커서를 안 올린다. 파이프·기록에 제어문자가 안 섞여야 한다.
  let 한장 = '';
  const 한장수 = await 보이기({
    쓰기: (s) => { 한장 += s; },
    움직임: false,
    칸: 120,
    곁말: '이 컴퓨터 안에서만',
    쉬기: async () => {},
  });
  check('한 장만 찍는다', 한장수 === 1);
  check('한 장일 때는 커서를 안 움직인다', !/\x1b\[\d*[ABCDJK]/.test(한장), JSON.stringify(한장.slice(0, 60)));
}

// ── 마무리 ──────────────────────────────────────────────────────────────
const C = (n, s) => (process.stdout.isTTY || process.env.FORCE_COLOR ? `\x1b[${n}m${s}\x1b[0m` : s);
console.log('');
for (const f of fail) console.log(`  ${C(31, '✗')} ${f.name}${f.note ? C(90, `  ${f.note}`) : ''}`);
for (const 글 of 적어둘것) console.log(`  ${C(90, `· ${글}`)}`);
console.log('');
console.log(`  ${pass.length}개 통과 · ${fail.length}개 실패`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
