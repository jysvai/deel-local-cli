// ── 5. Ask 도구가 실제로 막는가 ────────────────────────────────────────
{
  const 물어본것 = [];
  const 판 = (요청) => ({
    요청,
    ask물음: async (물음, 고를것, 이해) => { 물어본것.push({ 물음, 고를것, 이해 }); return 고를것[0] ?? '네'; },
  });

  const 막힌것 = await TOOLS.Ask.run({
    question: '어떤 것부터 진행할까요?',
    options: ['붙여넣기 내용 표시', 'esc 중단', '요청 누락 방지'],
  }, 판(네가지));
  check('★ 이해 없이 부르면 도구가 오류를 낸다', !!막힌것.error, JSON.stringify(막힌것).slice(0, 60));
  check('★ 막힌 물음은 사람에게 안 간다', 물어본것.length === 0, JSON.stringify(물어본것));
  // 오류가 아니라 content 로 돌려주면 모델은 그것을 '사람의 답' 으로 읽는다.
  check('★ content 로는 안 돌려준다 (답으로 오해한다)', 막힌것.content === undefined);
  check('되풀이 억제가 걸리게 끝났다로 표시한다', 막힌것.끝났다 === true);
  check('무엇 때문에 막혔는지 남긴다', typeof 막힌것.물음막힘 === 'string', 막힌것.물음막힘);

  const 지나간것 = await TOOLS.Ask.run({
    이해: 제대로된이해,
    question: '붙여넣은 원문을 접은 뒤에도 들고 있을까요?',
    options: ['들고 있는다', '버린다'],
  }, 판(네가지));
  check('★ 제대로 물으면 사람에게 간다', 물어본것.length === 1, JSON.stringify(물어본것).slice(0, 50));
  check('★ 이해도 화면 쪽으로 같이 넘어간다',
    물어본것[0]?.이해 === 제대로된이해, 물어본것[0]?.이해 ?? '(안 넘어감)');
  check('고른 것이 모델에게 돌아온다', /들고 있는다/.test(지나간것.content ?? ''), 지나간것.content ?? '');

  /*
   * 물어본 것을 도구가 실제로 적어 두는가.
   *
   * 관문에 "이미 물었나" 규칙이 있어도, 적어 두는 자리가 없으면 볼 것이 없다.
   * 규칙만 있고 배선이 없는 상태는 오류도 안 나고 검사도 안 빨개진다 —
   * 고쳐 놓은 척만 하는 코드가 되기 딱 좋은 자리다.
   */
  {
    const ctx = 판('이 보고서 좀 봐줘');
    const 처음 = await TOOLS.Ask.run({
      이해: 제대로된이해, question: '글꼴은 어느 것을 쓸까요?', options: ['가', '나'],
    }, ctx);
    check('처음 물음은 지나간다 (기억 검사)', !처음.error, 처음.error ?? '');
    check('★ 물어본 것을 ctx 에 적어 둔다', (ctx.물은것 ?? []).length === 1,
      JSON.stringify(ctx.물은것 ?? []).slice(0, 60));
    check('답도 같이 적어 둔다', ctx.물은것?.[0]?.답 === '가', ctx.물은것?.[0]?.답 ?? '');

    const 또 = await TOOLS.Ask.run({
      이해: 제대로된이해, question: '글꼴은 어느 것으로 할까요?', options: ['가', '나'],
    }, ctx);
    check('★ 같은 ctx 로 또 물으면 도구가 막는다', !!또.error, JSON.stringify(또).slice(0, 60));
    check('앞의 답을 그대로 돌려준다', /가/.test(또.error ?? ''), (또.error ?? '').slice(0, 60));
    check('막힌 것은 기억에 안 쌓인다', (ctx.물은것 ?? []).length === 1,
      String((ctx.물은것 ?? []).length));
  }

  // 물을 데가 없는 자리(한 방 실행·하위 작업)에서는 관문이 앞을 막지 않는다.
  // 어차피 아무도 못 듣는데 "이해를 채워서 다시" 라고 하면 왕복만 는다.
  const 못묻는데 = await TOOLS.Ask.run({ question: '어느 쪽?' }, { 요청: 네가지 });
  check('★ 물을 데가 없으면 관문보다 그 사실이 먼저다',
    !못묻는것오류(못묻는데) && /스스로|가정/.test(못묻는데.content ?? ''),
    JSON.stringify(못묻는데).slice(0, 70));
}

