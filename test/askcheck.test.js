// ── 7. Recall 이 못 찾았으면 못 찾았다고 **모델에게** 말한다 ────────────
{
  const 방 = mkdtempSync(join(tmpdir(), 'deel-askchk-'));
  const ctx = {
    scope: makeScope(방), history: new History(방), audit: new Audit(방),
    seen: new Set(), 모델컨텍스트: 200000, enc: new Map(),
  };

  const r = await TOOLS.Recall.run({ query: '있을 리 없는 말' }, ctx);
  check('못 찾으면 찾은 것이 없다고 한다', (r.hits ?? []).length === 0, JSON.stringify(r.hits ?? []));
  check('★ 못 찾았다는 말이 content 에 든다 (모델이 듣는 자리)',
    /없습니다/.test(r.content ?? ''), (r.content ?? '(비어 있음)').slice(0, 50));
  check('몇 개를 뒤졌는지도 말해 준다', /뒤졌|멈춤/.test(r.content ?? ''), (r.content ?? '').slice(0, 60));
  check('★ 지어내지 말라고 못 박는다', /지어내지/.test(r.content ?? ''), (r.content ?? '').slice(-40));
  check('화면 쪽 요약도 그대로 있다', /없습니다/.test(r.summary ?? ''), r.summary ?? '');
  // 실을글 을 거쳐도 빈 글이 안 된다 — 두 겹으로 막는다.
  check('★ 대화에 실릴 때도 안 빈다', 실을글(r).trim().length > 10, `${실을글(r).length}자`);

  rmSync(방, { recursive: true, force: true });
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n되묻기 관문 검사  ${D}(알아들었다고 먼저 말하는가 · 이미 들은 것을 되묻지 않는가)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
