// ── 6. 도구가 말없이 끝나지 않는다 ─────────────────────────────────────
//
// 사슬의 뿌리. 대화에 실리는 것은 content 하나인데, 어떤 도구는 summary 만
// 돌려줬다. 사람 화면에는 멀쩡히 찍히니 아무도 눈치를 못 챘고, 모델은
// **아무 말도 못 들은 채** 그 다음을 이어 갔다.
{
  check('글이 있으면 그대로 싣는다', 실을글({ content: '찾았습니다' }) === '찾았습니다');
  check('오류는 오류로 싣는다', 실을글({ error: '없는 파일' }) === '오류: 없는 파일');
  check('★ 글이 없으면 요약이라도 싣는다',
    실을글({ summary: '지난 대화 12개를 다 뒤졌지만 없습니다' }) === '지난 대화 12개를 다 뒤졌지만 없습니다',
    실을글({ summary: '지난 대화 12개를 다 뒤졌지만 없습니다' }));
  check('빈 글도 없는 것으로 친다',
    실을글({ content: '   ', summary: '요약뿐' }) === '요약뿐', 실을글({ content: '   ', summary: '요약뿐' }));
  check('★ 둘 다 없으면 없다고 말한다 — 침묵은 지어내기를 부른다',
    /돌려준 것이 없습니다/.test(실을글({})), 실을글({}));
  check('지어내지 말라고 못 박는다', /지어내지/.test(실을글({})), 실을글({}));
  check('아무것도 안 줘도 안 터진다', typeof 실을글() === 'string');
  // 오류가 글보다 먼저다. 둘 다 있으면 오류가 실려야 한다 — 반쯤 된 결과를
  // 성공처럼 실으면 모델이 그걸 믿고 다음으로 넘어간다.
  check('오류가 글보다 먼저다', 실을글({ error: '탈남', content: '반쯤' }) === '오류: 탈남');
}

