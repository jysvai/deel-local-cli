trace('3.5-문턱재기');

// ── 3.5. 문턱이 어디에 서 있나 ─────────────────────────────────────────
//
// 관문의 문턱은 0.5 다. 그 숫자가 옳다는 근거는 코드 주석이 아니라 **잰 값**에
// 있어야 한다. 안 재 두면 나중에 누가 0.7 로 올려도 아무것도 안 빨개지고,
// 그때부터 관문은 있으나 마나가 된다.
//
// 잡아야 하는 쪽(줄여 적은 선택지)과 놓아야 하는 쪽(진짜 갈림길)이 각각
// 어디쯤인지 재서, 문턱이 그 사이에 있는지 본다.
{
  const 잡아야 = [
    ['붙여넣기 내용 표시', 0.5],
    ['다른 cli 대비 기능', 0.5],
  ];
  for (const [것, 밑] of 잡아야) {
    const 값 = 얼마나들었나(것, 네가지);
    check(`줄여 적은 선택지는 문턱 위 — "${것}"`, 값 >= 밑, 값.toFixed(2));
  }

  const 놓아야 = [
    '버린다 — 긴 붙여넣기에서 메모리를 아낀다',
    '들고 있는다 — 되돌려 볼 수 있다',
  ];
  for (const 것 of 놓아야) {
    const 값 = 얼마나들었나(것, 네가지);
    check(`진짜 갈림길 선택지는 문턱 아래 — "${것.slice(0, 12)}…"`, 값 < 0.5, 값.toFixed(2));
  }

  // 두 무리 사이가 벌어져 있어야 문턱을 놓을 자리가 있다. 붙어 있으면
  // 어디에 그어도 한쪽은 틀리므로, 그때는 재는 방법 자체를 바꿔야 한다.
  const 위 = Math.min(...잡아야.map(([것]) => 얼마나들었나(것, 네가지)));
  const 아래 = Math.max(...놓아야.map((것) => 얼마나들었나(것, 네가지)));
  check('★ 두 무리 사이가 벌어져 있다 (문턱을 놓을 자리가 있다)',
    위 - 아래 >= 0.25, `잡아야 ${위.toFixed(2)} ↔ 놓아야 ${아래.toFixed(2)}`);
}

