//
// 앞의 관문들로는 못 막혔다. 이 요청에는 번호 목록이 없고, 선택지도 사용자
// 말을 되읽은 것이 아니라 새로 지어낸 것이기 때문이다. 이해만 채우면 그냥
// 지나갔다 — 실제로 재 보고 확인했다.
{
  const PDF요청 = '현재 각 부문 OCR txt 기반으로 각 부문의 A4 용지 기준 2장 씩으로 해서 PDF 하나 만들어줘'
    + ' 내용은 가로로 짜주고, 각 부문별로 따로따로 줘 신규_IT부문.pdf 이런 식으로 해서 만들어줘\n\n'
    + '대신 기존 A3_편집.html 파일은 건들지말고 독자적으로 만들어주고 글씨체는 zip 안에 있는 것 써주면 돼';
  const 제대로읽음 = '부문별로 A4 가로 2쪽짜리 PDF 를 OCR 내용 기반으로 따로따로 만들라는 것으로 이해했습니다';

  const 첫물음 = '현재 A3 경영진보고 편집 파일과 원본 자료를 확인했습니다. 어떤 작업을 진행할까요?';
  const 막힌것 = 물음검사({
    요청: PDF요청, 이해: 제대로읽음, 물음: 첫물음,
    고를것: ['현재 편집본의 내용·디자인을 검토하고 개선', '원본 자료를 반영해 보고서 내용을 업데이트',
      '배포본/PDF 생성·검증', '특정 문구·수치만 수정'],
  });
  check('★ 만들라고 했는데 "무슨 작업 할까요" 로 되물으면 막는다', 막힌것.ok === false,
    막힌것.왜 ?? '통과함 — 뺑뺑이가 그대로다');
  check('시킨 대로 하라고 말해 준다', /그 말대로 하세요/.test(막힌것.할말 ?? ''), (막힌것.할말 ?? '').slice(0, 40));
  // "묻지 마라" 로만 끝내면 진짜 막혔을 때 길이 없어진다. 좁게 물을 길을 준다.
  check('★ 정말 정할 것이 있으면 좁게 물으라고 알려 준다',
    /한 가지.*만 콕 집어/.test(막힌것.할말 ?? ''), (막힌것.할말 ?? '').slice(-60));

  // 같은 것을 또 묻는 것 — 두 번째 화면이 이것이었다.
  const 이미물음 = [{ 물음: 첫물음, 고를것: [], 답: '아예 새로 PDF 해서 만들어줘' }];
  const 또한것 = 물음검사({
    요청: '이 보고서 좀 봐줘', 이해: 제대로읽음, 이미물은것: 이미물음,
    물음: 'A3 경영진 보고 편집본에서 어떤 작업을 진행할까요?',
  });
  check('★ 거의 같은 것을 또 물으면 막는다', 또한것.ok === false, 또한것.왜 ?? '통과함');
  check('★ 앞의 답을 그대로 돌려준다 — 못 찾으니까 또 묻는 것이다',
    (또한것.할말 ?? '').includes('아예 새로 PDF 해서 만들어줘'), (또한것.할말 ?? '').slice(0, 80));
  check('그 답대로 진행하라고 한다', /그 답대로 진행/.test(또한것.할말 ?? ''));

  // 답을 안 했어도 같은 것을 또 묻는 것은 막는다.
  const 답없이 = 물음검사({
    요청: '이 보고서 좀 봐줘', 이해: 제대로읽음,
    이미물은것: [{ 물음: 첫물음, 답: '' }],
    물음: 'A3 경영진 보고 편집본에서 어떤 작업을 진행할까요?',
  });
  check('답을 안 받았어도 또 안 묻는다', 답없이.ok === false, 답없이.왜 ?? '통과함');
  check('답이 없었다는 것도 말해 준다', /답을 안 했습니다/.test(답없이.할말 ?? ''));

  // 다른 것을 묻는 것은 막지 않는다. 이쪽이 더 중요하다 — 한 번 물었다고
  // 그 턴 내내 입을 막으면, 진짜 갈림길에서 제멋대로 정하고 지나간다.
  const 다른것 = 물음검사({
    요청: '이 보고서 좀 봐줘', 이해: 제대로읽음, 이미물은것: 이미물음,
    물음: 'zip 안에 글꼴 파일이 둘인데 어느 것을 쓸까요?',
    고를것: ['Pretendard', '나눔스퀘어'],
  });
  check('★ 다른 것을 묻는 것은 막지 않는다', 다른것.ok === true, 다른것.왜 ?? '');

  /*
   * 같은 것을 놓고 **다르게** 묻는 자리.
   *
   * 위의 글꼴 물음은 앞의 물음과 아예 남남이라(겹침 0.11) 문턱이 아무리
   * 낮아도 안 막힌다. 그래서 이 짝이 따로 필요하다 — 같은 물건(PDF)을 두고
   * 다른 것을 묻는 자리. 여기는 겹침이 0.3~0.4 라, 문턱을 조금만 낮춰도
   * 통째로 막히기 시작한다. 그러면 두 번째 갈림길에서 묻지도 못하고
   * 제멋대로 정하고 지나간다.
   */
  const 같은물건다른물음 = [
    ['PDF 에 쪽 번호를 넣을까요?', 0.45],
    ['부문별 PDF 에 표지를 넣을까요?', 0.45],
  ];
  const 앞PDF = [{ 물음: 'PDF 를 부문별로 따로 만들까요, 하나로 합칠까요?', 답: '따로' }];
  for (const [물음, 밑] of 같은물건다른물음) {
    const 겹침 = 얼마나들었나(물음, 앞PDF[0].물음);
    check(`★ 같은 물건을 두고 다르게 물으면 안 막는다 — "${물음.slice(0, 16)}…"`,
      물음검사({ 요청: 'PDF 만들어줘', 이해: 제대로된이해, 이미물은것: 앞PDF, 물음 }).ok === true
      && 겹침 < 밑,
      `겹침 ${겹침.toFixed(2)}`);
  }
  // 같은 물음을 줄여 다시 적은 것은 0.7 위다. 두 무리 사이가 벌어져 있어야
  // 문턱을 놓을 자리가 있다.
  check('★ 같은 물음과 다른 물음 사이가 벌어져 있다',
    얼마나들었나('PDF 를 부문별로 나눌까요 합칠까요?', 앞PDF[0].물음)
      - 얼마나들었나('부문별 PDF 에 표지를 넣을까요?', 앞PDF[0].물음) >= 0.25,
    `같은 것 ${얼마나들었나('PDF 를 부문별로 나눌까요 합칠까요?', 앞PDF[0].물음).toFixed(2)}`
    + ` ↔ 다른 것 ${얼마나들었나('부문별 PDF 에 표지를 넣을까요?', 앞PDF[0].물음).toFixed(2)}`);

  // 세 번째부터는 막는다. 세 번 묻는다는 것은 물음으로 풀 문제가 아니라는 뜻이다.
  const 세번째 = 물음검사({
    요청: '이 보고서 좀 봐줘', 이해: 제대로읽음,
    이미물은것: [{ 물음: '가나다라마바사', 답: '1' }, { 물음: '아자차카타파하', 답: '2' }],
    물음: '글꼴은 어느 것을 쓸까요?', 고를것: ['가', '나'],
  });
  check('★ 한 턴에 두 번까지만 묻는다', 세번째.ok === false, 세번째.왜 ?? '통과함');
  check('대신 무엇을 하라는지 말한다', /가장 그럴듯한 쪽/.test(세번째.할말 ?? ''));
  check('두 번째까지는 지나간다', 물음검사({
    요청: '이 보고서 좀 봐줘', 이해: 제대로읽음,
    이미물은것: [{ 물음: '가나다라마바사', 답: '1' }],
    물음: '글꼴은 어느 것을 쓸까요?', 고를것: ['가', '나'],
  }).ok === true);
}

