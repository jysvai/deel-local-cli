// ── 지어낸 요금이 없다 ──────────────────────────────────────────────────
{
  check('100만 토큰당으로 센다', 단위 === 1000000, String(단위));

  /*
   * 딸려 온 표에 값이 있다면 **기준 날짜가 반드시 있어야 한다.**
   *
   * '표를 비워 둬라' 로 재지 않는 까닭은, 언제든 확인한 값을 채울 수 있어야
   * 하기 때문이다. 지켜야 하는 것은 비어 있음이 아니라 '언제 기준인지 모르는
   * 값이 없음' 이다. 날짜 없는 값은 낡았는지조차 말할 수 없다.
   */
  const 날짜없는것 = [];
  for (const p of 제공자들) {
    const 칸들 = Object.entries(p.요금 ?? {});
    if (!칸들.length) continue;
    if (!p.요금기준 && 칸들.some(([, v]) => !v?.기준)) 날짜없는것.push(p.id);
  }
  check('★ 딸려 온 요금에는 기준 날짜가 있다', 날짜없는것.length === 0, 날짜없는것.join(' '));

  // 요금표 주소는 들고 있어야 한다 — 모를 때 사람을 어디로 보낼지가 그것뿐이다.
  const 주소없는것 = 제공자들.filter((p) => p.id !== 'custom' && !p.요금표주소).map((p) => p.id);
  check('어디서 요금을 보는지는 안다', 주소없는것.length === 0, 주소없는것.join(' '));
}

