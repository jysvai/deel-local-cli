trace('4-셈');

// ── 셈이 맞나 ───────────────────────────────────────────────────────────
{
  const 값 = 요금찾기('m', { 설정: { m: { 입력: 2.5, 출력: 10 } } });
  const r = 돈셈({ in: 1000000, out: 1000000 }, 값);
  check('★ 100만 토큰이 표의 값 그대로', Math.abs(r.달러 - 12.5) < 1e-9, String(r.달러));
  check('입력·출력을 나눠서도 준다', Math.abs(r.입력 - 2.5) < 1e-9 && Math.abs(r.출력 - 10) < 1e-9);
  const 반 = 돈셈({ in: 500000, out: 0 }, 값);
  check('절반이면 절반', Math.abs(반.달러 - 1.25) < 1e-9, String(반.달러));
  check('안 썼으면 0', 돈셈({ in: 0, out: 0 }, 값).달러 === 0);
  check('숫자가 아닌 사용량은 0으로 본다', 돈셈({ in: null, out: undefined }, 값).달러 === 0);

  /*
   * ══ 캐시로 읽힌 토큰을 정가로 세면 안 된다 ═══════════════════════════
   *
   * 캐시 표식이 실제로 걸리기 시작하면 보낸 토큰의 대부분이 캐시 몫이 된다.
   * 그걸 정가로 세면 금액이 몇 배로 부풀고, 캐시를 켠 보람이 화면에서
   * 사라진다 — 고쳐 놨는데 고친 표가 안 나는 셈이다.
   *
   * 그렇다고 배수를 지어내지도 않는다. 모르면 정가로 세고 **모른다고 말한다.**
   * 그 금액은 실제보다 크다. 큰 쪽으로 틀리면 사람이 놀라고 끝나지만, 작은
   * 쪽으로 틀리면 그 숫자로 예산을 잡는다.
   */
  {
    const 캐시값 = 요금찾기('m', {
      설정: { m: { 입력: 2.5, 출력: 10, 캐시읽기: 0.25, 캐시쓰기: 3.125 } },
    });
    check('★ 요금표가 캐시 값을 받는다',
      캐시값.캐시읽기 === 0.25 && 캐시값.캐시쓰기 === 3.125,
      `${캐시값.캐시읽기} / ${캐시값.캐시쓰기}`);

    /*
     * 보낸 것 100만 중 80만이 캐시 읽기, 10만이 캐시 쓰기, 20만이 정가.
     *   정가 20만 × 2.5  = 0.5
     *   읽기 80만 × 0.25 = 0.2
     *   쓰기 10만 × 3.125 = 0.3125   ← 100만 - 80만 - 10만 = 10만이 정가다
     */
    const r2 = 돈셈({ prompt: 1000000, out: 0, cacheRead: 800000, cacheWrite: 100000 }, 캐시값);
    const 기대 = (100000 / 1000000 * 2.5) + (800000 / 1000000 * 0.25) + (100000 / 1000000 * 3.125);
    check('★★ 캐시 몫을 갈라서 센다', Math.abs(r2.달러 - 기대) < 1e-9, `${r2.달러} vs ${기대}`);
    check('캐시 몫을 따로도 준다', Math.abs(r2.캐시 - 0.5125) < 1e-9, String(r2.캐시));
    check('값을 알면 모른다고 안 한다', r2.캐시모름 === false);

    /*
     * ★★ 같은 사용량인데 캐시 값을 모르면 **더 비싸게** 나와야 한다.
     * 그리고 그렇다고 말해 줘야 한다 — 말 안 하면 그 숫자가 진짜가 된다.
     */
    const r3 = 돈셈({ prompt: 1000000, out: 0, cacheRead: 800000, cacheWrite: 100000 }, 값);
    check('★★ 모르면 정가로 세고 — 그래서 더 비싸다', r3.달러 > r2.달러, `${r3.달러} > ${r2.달러}`);
    check('★★ 모른다고 말한다', r3.캐시모름 === true);
    check('모를 때 금액은 정가 총계와 같다', Math.abs(r3.달러 - 2.5) < 1e-9, String(r3.달러));

    // 캐시를 안 썼으면 「모른다」 고 할 것도 없다. 쓸데없는 경고를 띄우지 않는다.
    check('캐시를 안 썼으면 조용하다', 돈셈({ prompt: 1000, out: 0 }, 값).캐시모름 === false);

    /*
     * ★★ (8회차 뒷단-전선) 한쪽만 적혀 있으면 **모르는 쪽을 모른다고 말해야 한다.**
     *
     * 여태는 「캐시 값이 하나라도 있나」 로만 봤다. 그래서 캐시읽기만 적고 캐시쓰기를
     * 안 적은 표에서, 캐시 쓰기 몫을 **정가로** 물려 놓고 `캐시모름:false` — 즉
     * 「이 금액은 정확합니다」 — 라고 적었다. 상태줄의 `?` 도 안 붙는다. 모르는
     * 것을 아는 낯으로 내미는 것, 이 파일이 통째로 그러지 말자고 있는 파일이다.
     */
    const 읽기만 = 요금찾기('m', { 설정: { m: { 입력: 2.5, 출력: 10, 캐시읽기: 0.25 } } });
    const 쓴것만 = 돈셈({ prompt: 1000000, out: 0, cacheRead: 0, cacheWrite: 1000000 }, 읽기만);
    check('★★ 캐시쓰기 값을 모르는 채로 쓰기를 썼으면 모른다고 말한다', 쓴것만.캐시모름 === true,
      JSON.stringify(쓴것만));
    check('  그때 그 몫은 정가로 세어 둔다 — 큰 쪽으로 틀린다',
      Math.abs(쓴것만.캐시 - 2.5) < 1e-9, String(쓴것만.캐시));
    // 아는 쪽만 썼으면 여전히 조용하다 — 값을 아는 자리까지 흐리게 만들면 안 된다.
    check('  아는 쪽만 썼으면 조용하다',
      돈셈({ prompt: 1000000, out: 0, cacheRead: 800000, cacheWrite: 0 }, 읽기만).캐시모름 === false, '');
    const 쓰기만 = 요금찾기('m', { 설정: { m: { 입력: 2.5, 출력: 10, 캐시쓰기: 3.125 } } });
    check('★★ 거꾸로도 같다 — 캐시읽기를 모르는 채로 읽기를 썼으면',
      돈셈({ prompt: 1000000, out: 0, cacheRead: 800000, cacheWrite: 0 }, 쓰기만).캐시모름 === true, '');

    /*
     * ★★ 두 번 세지 않는다.
     *
     * Anthropic 은 input_tokens 에 캐시를 **안 넣고**, OpenAI 는 prompt_tokens
     * 에 **다 넣는다**. 그 차이는 usage.prompt 한 곳에서 이미 흡수했으므로
     * (backend/adapter.js 의 보낸토큰), 여기서는 총계에서 캐시를 빼기만 한다.
     * 빼는 것을 잊으면 캐시 토큰이 정가와 캐시값 양쪽에서 두 번 세어진다.
     */
    const 다캐시 = 돈셈({ prompt: 1000000, out: 0, cacheRead: 1000000, cacheWrite: 0 }, 캐시값);
    check('★★ 전부 캐시면 정가 몫이 0 이다', Math.abs(다캐시.입력) < 1e-9, String(다캐시.입력));
    check('★★ 그때 금액은 캐시값 그대로', Math.abs(다캐시.달러 - 0.25) < 1e-9, String(다캐시.달러));

    // 셈이 어긋나 캐시가 총계보다 커도 음수로 안 간다.
    const 어긋남 = 돈셈({ prompt: 100, out: 0, cacheRead: 9999, cacheWrite: 0 }, 캐시값);
    check('숫자가 어긋나도 음수로 안 간다', 어긋남.입력 === 0 && 어긋남.달러 >= 0, String(어긋남.달러));

    // prompt 가 없는 옛 자리는 in 을 총계로 본다 — 여태 하던 셈과 같아야 한다.
    check('★ prompt 가 없으면 in 을 총계로 본다',
      Math.abs(돈셈({ in: 1000000, out: 0 }, 값).달러 - 2.5) < 1e-9);
  }
}

trace('5-글자');

// ── 사람이 읽는 글 ──────────────────────────────────────────────────────
{
  /*
   * 아주 작은 값을 $0.00 으로 반올림하면 안 된다.
   *
   * 두어 턴 돌린 뒤 화면에 $0.00 이 서 있으면 '공짜네' 로 읽히고, 그 상태로
   * 백 턴을 돌린다. 자릿수가 안 되면 반올림하지 말고 미만이라고 적어야 한다.
   */
  check('★ 작은 값을 $0.00 으로 안 만든다', 돈말(0.00001) === '<$0.0001', 돈말(0.00001));
  check('진짜 0 은 0 이라고 적는다', 돈말(0) === '$0', 돈말(0));
  check('1달러 밑은 넷째 자리까지', 돈말(0.0021) === '$0.0021', 돈말(0.0021));
  check('1달러 위는 둘째 자리까지', 돈말(3.14159) === '$3.14', 돈말(3.14159));
  check('큰돈은 자릿점을 찍는다', 돈말(12345.6) === '$12,346', 돈말(12345.6));
  check('이상한 값은 글자를 안 만든다', 돈말(NaN) === null && 돈말(-1) === null && 돈말('싼거') === null);

  /*
   * (8회차 뒷단-전선) `Number()` 는 **금액이 아닌 것들을 0 으로 받는다.**
   *
   * `Number(null)` · `Number(false)` · `Number('')` · `Number([])` 가 전부 0 이고,
   * 여기서 0 은 `$0` 으로 찍힌다 — 화면에서 「공짜」 라는 뜻이다. 셈이 한 자리
   * 어긋나 null 이 흘러 들어오면, 화면은 요금을 모르는 것이 아니라 **공짜라고**
   * 말한다. 같은 파일의 값읽기() 는 바로 그 까닭으로 형을 가려 두었는데
   * (56–59줄) 이 함수만 안 가렸다. 모르는 것은 글자를 안 만드는 쪽이다.
   */
  const 아닌것 = [['null', null], ['false', false], ['true', true], ['빈 글자', ''], ['빈칸 글자', '   '], ['빈 배열', []]];
  for (const [이름, v] of 아닌것) {
    check(`★★ 금액이 아닌 것을 「$0」(공짜)으로 안 찍는다 — ${이름}`, 돈말(v) === null, String(돈말(v)));
  }
  check('  undefined 도 그대로 없음이다', 돈말(undefined) === null, String(돈말(undefined)));
  // 사람이 JSON 에 따옴표로 적은 숫자는 여전히 받는다 — 값읽기 와 같은 규칙이다.
  check('  숫자를 적은 글자는 그대로 받는다', 돈말('2.5') === '$2.50' && 돈말('0') === '$0',
    `${돈말('2.5')} · ${돈말('0')}`);
}

