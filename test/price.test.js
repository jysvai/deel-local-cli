// 요금 셈 — 모르는 값을 아는 낯으로 내밀지 않는가.
//
// ── 무엇이 문제였나 ─────────────────────────────────────────────────────
//
// 바깥 API 로도 붙을 수 있게 되면서, 이제 한 턴에 돈이 나간다. 그런데 요금은
// 회사가 아무 때나 바꾸는 값이라 소스에 박아 두면 고칠 사람이 없다. 박아 둔
// 채로 반년이 지나면 이 도구는 **틀린 금액을 자신 있게 찍는 도구**가 된다.
// 사람은 화면에 뜬 숫자를 믿고 예산을 잡으므로, 그건 안 보여 주는 것보다
// 훨씬 나쁘다.
//
// ── 무엇을 지키나 ───────────────────────────────────────────────────────
//
//   1. 지어낸 요금이 없다. 값의 출처는 사람이 적은 설정과, 기준 날짜가
//      붙은 딸려 온 표뿐이다.
//   2. 모르면 0 이 아니라 **없음**이다. 0 을 주면 '공짜' 와 '모름' 이
//      화면에서 같아진다.
//   3. 우리 맘대로 이름을 잘라 맞추지 않는다. gpt-4o 요금이 -mini 에
//      붙으면 아무도 못 알아챈다.
//   4. 반올림해서 $0.00 을 찍지 않는다. 그건 공짜라는 뜻으로 읽힌다.
//   5. 로컬만 쓰는 사람 화면에는 돈 이야기가 아예 안 뜬다.
