trace('8-대화에-걸린-요금');

// ── 세션에 붙였을 때 ────────────────────────────────────────────────────
{
  const s = 새것('gpt-4o');
  s.요금표 = { 'gpt-4o': { 입력: 2.5, 출력: 10 }, 'gpt-4o-mini': { 입력: 0.15, 출력: 0.6 } };
  check('대화에 걸린 요금을 찾는다', 세션요금(s)?.입력 === 2.5);
  check('두 번째도 같은 답', 세션요금(s)?.입력 === 2.5);

  /*
   * 모델을 갈아타면 저절로 다시 찾아야 한다.
   *
   * 캐시를 지워 달라고 부탁하는 방식이면 언젠가 한 군데를 빠뜨리고, 그때
   * 사람은 옛 모델의 요금으로 새 모델을 센 화면을 보게 된다. 그런 고장은
   * 화면에 아무 표시도 안 난다.
   */
  s.conn.model = 'gpt-4o-mini';
  check('★ 모델을 바꾸면 다시 찾는다', 세션요금(s)?.입력 === 0.15, String(세션요금(s)?.입력));

  const 없는것 = 새것('모르는모델');
  check('요금표가 아예 없어도 안 죽는다', 세션요금(없는것) === null);
}

trace('9-화면');

// ── 화면에 어떻게 나오나 ────────────────────────────────────────────────
{
  const s = 새것('gpt-4o');
  s.요금표 = { 'gpt-4o': { 입력: 2.5, 출력: 10 } };
  s.usage.in = 1000000; s.usage.out = 100000;
  check('상태줄에 금액이 뜬다', 민글(SEGMENTS.cost.make(s)) === '$3.50', 민글(SEGMENTS.cost.make(s)));

  /*
   * 요금을 모르면 상태줄에는 **아무것도** 안 그린다.
   *
   * 여기에 '요금 모름' 을 적으면 로컬로만 쓰는 사람 화면에 평생 그 다섯
   * 글자가 서 있게 된다. 로컬은 공짜라 그 자리는 영영 안 채워진다.
   * 모른다는 말은 물어본 자리(/cost)에서 한다.
   */
  const 로컬 = 새것('llama3');
  로컬.usage.in = 999999; 로컬.usage.out = 999999;
  check('★ 요금을 모르면 상태줄에 아무것도 안 그린다', SEGMENTS.cost.make(로컬) === null,
    JSON.stringify(민글(SEGMENTS.cost.make(로컬))));

  // 안 썼으면 $0 도 안 그린다. 갓 켠 화면에 0원이 서 있으면 자리만 먹는다.
  const 갓켬 = 새것('gpt-4o');
  갓켬.요금표 = { 'gpt-4o': { 입력: 2.5, 출력: 10 } };
  check('갓 켰을 때는 안 그린다', SEGMENTS.cost.make(갓켬) === null);

  check('토큰 옆에 붙어 다닌다', SEGMENT_GROUPS.at(-1).join() === 'tok,cost', SEGMENT_GROUPS.at(-1).join());
  check('설명이 있다', typeof SEGMENTS.cost.desc === 'string' && SEGMENTS.cost.desc.length > 0);
}

trace('10-배선');

// ── 부르는 자리가 실제로 있나 ───────────────────────────────────────────
//
// 셈이 맞아도 아무도 안 부르면 사람에게는 하나도 안 고쳐진 것이다.
{
  const repl = readFileSync(new URL('../src/repl.js', import.meta.url), 'utf8');
  check('★ 턴 꼬리말이 이번 턴 돈을 붙인다',
    /const 이번돈 = 돈셈\(\{ in: dIn, out: dOut \}, 세션요금\(session\)\)[\s\S]{0,200}?bits\.push\(돈말\(이번돈\.달러\)\)/.test(repl));
  check('설정의 요금표를 대화에 싣는다', /session\.요금표 = cfg\?\.요금 \?\?/.test(repl));
  // 한글 자판이 없는 사람도 적을 수 있어야 한다. 이름이 하나뿐이면
  // 「영어로 켤 수는 있는데 요금은 못 적는」 자리가 남는다.
  check('★ pricing 으로 적어도 받는다', /cfg\?\.pricing/.test(repl));
  check('어디 것인지도 싣는다', /session\.제공자 = prof\?\.제공자 \?\? null/.test(repl));

  const cmds = readFileSync(new URL('../src/commands.js', import.meta.url), 'utf8');
  check('★ /cost 가 금액을 적는다', /const 쓴돈 = 돈셈\(session\.usage, 요금값\)[\s\S]{0,300}?돈말\(쓴돈\.달러\)/.test(cmds));
  check('/cost 가 어디서 온 값인지 같이 적는다', /어디서온값\(요금값\)/.test(cmds));
  check('★ /cost 가 모를 때 적는 법을 알려 준다', /요금적는법\(session\.conn\.model/.test(cmds));
  // 로컬 사용자에게는 그 안내조차 안 뜬다.
  check('★ 그 안내는 바깥으로 나갈 때만',
    /\} else if \(바깥인가\(session\.conn\.base\) && \(session\.usage\.in \|\| session\.usage\.out\)\) \{[\s\S]{0,300}?요금적는법/.test(cmds));
  check('설정에 잘못 적은 것을 알려 준다', /요금값\?\.탈들/.test(cmds));
  check('모델을 갈아타면 제공자도 따라간다', /session\.제공자 = p\.제공자 \?\? null/.test(cmds));

  const setup = readFileSync(new URL('../src/setup.js', import.meta.url), 'utf8');
  check('설정할 때 어디 것인지 적어 둔다', /제공자: 붙일곳\.id/.test(setup));
}

trace('11-끝');

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n요금 셈 검사  ${D}(모르는 값을 아는 낯으로 내밀지 않는가)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
