// 터미널 크기를 바꿀 때 상자가 쌓이지 않는가.
//
// ── 무슨 일이 났었나 ────────────────────────────────────────────────────
//
// 「작업하다가 오피스 화면 늘리면 뭔가 엄청 다다다 늘어나는 현상」.
//
// 크기가 지난번과 다르면 상자는 들고 있던 값(그린줄·커서위)을 다 버리고 지금
// 자리에서 새로 그렸다. 옛 폭에서 센 값으로 커서를 올리면 대화를 지우기
// 때문인데, "낡은 상자가 한 번 위에 남지만 스크롤 자국일 뿐" 이라는 셈이었다.
//
// **한 번이 아니었다.** 창을 마우스로 끌면 터미널은 한 칸마다 새 크기를
// 알려 준다. 끌면서 쉰 번이 오면 상자를 쉰 벌 찍고 하나도 안 지운다.
// 세로로 늘릴 때 특히 심하다 — 28줄을 넘는 순간 사무실 열두 줄이 통째로
// 더 붙기 때문이다.
//
// ── 여기서 무엇을 지키나 ────────────────────────────────────────────────
//
//   1. 높이만 바뀌면 **제대로 지우고** 다시 그린다. 줄 접힘은 폭이 정하므로
//      폭이 그대로면 들고 있던 수도 아직 맞다.
//   2. 폭이 바뀌면 옛 수는 못 믿지만, 커서 아래는 쓸어낸다. 상자는 늘 맨
//      아래라 그 아래에는 아무것도 없다.
//   3. 그러면서도 **대화는 안 건드린다.** 지우려고 커서를 위로 올리면 위쪽
//      대화가 지워진다 — 원래 다 버리고 새로 그렸던 이유가 그것이다.
import { InputBox } from '../src/ui/inputbox.js';
import { Session } from '../src/agent/session.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

const 원래 = {
  cols: process.stdout.columns, rows: process.stdout.rows,
  isTTY: process.stdout.isTTY, write: process.stdout.write,
};
const 크기 = (cols, rows) => {
  Object.defineProperty(process.stdout, 'columns', { value: cols, configurable: true });
  Object.defineProperty(process.stdout, 'rows', { value: rows, configurable: true });
};

/** 찍히는 것을 가로챈다. 진짜로 나가면 검사 화면이 제어문자 범벅이 된다. */
let 찍힌것 = '';
const 가로채기 = () => {
  찍힌것 = '';
  process.stdout.write = (s) => { 찍힌것 += String(s); return true; };
};
const 되돌리기 = () => { process.stdout.write = 원래.write; };

/*
 * 진짜 Session 을 쓴다. 상태줄이 세션에서 읽는 값이 여럿이라 흉내를 내면
 * 그 목록을 여기에 베껴 두는 꼴이 되고, 상태줄이 하나 더 읽기 시작하는 날
 * 이 검사만 조용히 깨진다. 어차피 망을 안 타므로 값이 싸다.
 */
const 가짜세션 = new Session(
  { kind: 'openai', base: 'http://127.0.0.1:1/v1', model: '스텁', ctx: 32768 },
  { root: process.cwd() },
);

Object.defineProperty(process.stdout, 'isTTY', { value: true, configurable: true });

trace('1-높이만-바뀔때');

/*
 * 사무실이 켜지는 크기(28줄 이상)에서 세로로만 늘린다. 사용자가 겪은 그
 * 동작이다 — 폭은 그대로 두고 창을 아래로 끄는 것.
 *
 * 재는 것은 **바이트 수가 아니라 앞엣것을 치웠는가** 다.
 *
 * 크기가 바뀌면 판을 새로 그리는 것이 맞다 — 열다섯 번 바뀌면 열다섯 판이
 * 나가는 것이 정상이고, 바이트로는 쌓이는 것과 구분이 안 된다. 결함은
 * "새 판을 그리면서 **먼저 있던 것을 안 치웠다**" 이다.
 *
 * 찍힌 글자로만 보려다 한 번 헛짚었다. 평소에 그리는 것도 줄마다 \x1b[K 를
 * 쓰기 때문에, "K 가 있나" 로는 옛 동작도 그냥 통과한다. 그래서 치우는
 * **동작 자체**를 본다 — 높이만 바뀐 판은 지우기() 가 불려야 하고, 폭이
 * 바뀐 판은 \x1b[J 가 나가야 한다.
 */
{
  const 상자 = new InputBox();
  크기(100, 30);
  가로채기();
  상자.그리기(가짜세션, '안녕', 2);

  // 치우는 동작을 센다. 진짜 지우기를 그대로 부르고 횟수만 얹는다.
  let 지운수 = 0;
  const 진짜지우기 = 상자.지우기.bind(상자);
  상자.지우기 = () => { 지운수 += 1; return 진짜지우기(); };

  // 한 칸씩 늘린다. 마우스로 끄는 동안 실제로 이렇게 온다.
  let 판수 = 0;
  for (let r = 31; r <= 45; r++) { 크기(100, r); 상자.그리기(가짜세션, '안녕', 2); 판수 += 1; }
  되돌리기();

  check('세로로 늘릴 때 판마다 먼저 치운다', 지운수 === 판수,
    `${지운수}/${판수}판을 치웠다`);
}

trace('2-폭이-바뀔때');

/*
 * 폭이 바뀌면 터미널이 이미 줄을 다시 접어서 옛 수를 못 믿는다. 그래도
 * 커서 아래는 쓸어내야 한다 — 안 그러면 여기서 다시 쌓인다.
 */
{
  const 상자 = new InputBox();
  크기(100, 30);
  가로채기();
  상자.그리기(가짜세션, '안녕', 2);

  const 판들 = [];
  for (let c = 99; c >= 85; c--) {
    찍힌것 = '';
    크기(c, 30);
    상자.그리기(가짜세션, '안녕', 2);
    판들.push(찍힌것);
  }
  되돌리기();

  // \x1b[J = 커서 아래를 쓸어낸다. 위로는 안 올라가므로 대화는 안 건드린다.
  const 안쓴판 = 판들.filter((p) => p && !/\x1b\[J/.test(p)).length;
  check('가로로 줄일 때 판마다 커서 아래를 쓸어낸다', 안쓴판 === 0,
    `${판들.length}판 중 ${안쓴판}판이 안 쓸고 덧그렸다`);
}

trace('3-대화를-안-건드리나');

/*
 * 여기가 이 고침에서 제일 조심해야 하는 자리다. 지우려고 커서를 **위로**
 * 올리면 대화가 지워진다 — 원래 다 버리고 새로 그렸던 이유가 그것이다.
 * 폭이 바뀐 판에서는 위로 올라가는 글자가 하나도 없어야 한다.
 */
{
  const 상자 = new InputBox();
  크기(100, 30);
  가로채기();
  상자.그리기(가짜세션, '안녕', 2);

  찍힌것 = '';
  크기(70, 30);                       // 폭만 바꾼다
  상자.그리기(가짜세션, '안녕', 2);
  되돌리기();

  // 그린 뒤 커서를 제자리에 놓느라 올라가는 것은 상자 안쪽이다. 크기가
  // 바뀐 것을 알아채는 자리에서 **지우려고** 올라가지 않는 것을 본다.
  const 쓸기앞 = 찍힌것.slice(0, 찍힌것.indexOf('\x1b[J') + 3);
  check('폭이 바뀐 판은 지우려고 위로 안 올라간다', !/\x1b\[\d*A/.test(쓸기앞),
    JSON.stringify(쓸기앞.slice(0, 40)));
}

trace('4-크기가-그대로면');

/*
 * 크기가 안 바뀌면 예전 길(줄마다 견줘서 바뀐 것만 보내기)이 그대로여야 한다.
 * 고치면서 그 길을 막아 버리면 90ms 마다 열두 줄이 통째로 나간다.
 */
{
  const 상자 = new InputBox();
  크기(100, 40);
  가로채기();
  상자.그리기(가짜세션, '안녕', 2);
  const 첫판 = 찍힌것.length;

  찍힌것 = '';
  상자.그리기(가짜세션, '안녕', 2);   // 똑같은 판을 다시
  const 같은판 = 찍힌것.length;
  되돌리기();

  check('바뀐 것이 없으면 거의 안 보낸다', 같은판 < 첫판 / 2,
    `첫 판 ${첫판}자 · 다시 그린 판 ${같은판}자`);
}

trace('5-한-판을-통째로-바꾸나');

/*
 * ── 떨림·잔상 ───────────────────────────────────────────────────────────
 *
 * 「화면이 떨리고 잔상이 남는다」. 한 번의 write 로 보내도 터미널은 받는 대로
 * 그리므로, 열두 줄이 같이 바뀌는 판에서는 고쳐 그리는 중간 모습이 그대로
 * 눈에 들어온다.
 *
 * ?2026 은 "다 받은 뒤에 한 번에 보여 달라" 는 뜻이다. 여는 표와 닫는 표가
 * **한 번의 write 안에 짝으로** 있어야 한다. 하나만 나가면 그 뒤로 화면이
 * 통째로 멈춘 것처럼 보인다 — 터미널이 계속 기다린다.
 */
{
  const 상자 = new InputBox();
  크기(100, 40);
  가로채기();
  상자.그리기(가짜세션, '안녕', 2);
  const 한판 = 찍힌것;
  되돌리기();

  check('판을 여는 표를 보낸다', 한판.includes('\x1b[?2026h'));
  check('판을 닫는 표를 보낸다', 한판.includes('\x1b[?2026l'));
  check('여는 표와 닫는 표가 한 번씩 짝으로 나간다',
    (한판.match(/\x1b\[\?2026h/g) ?? []).length === 1
    && (한판.match(/\x1b\[\?2026l/g) ?? []).length === 1,
    `여 ${(한판.match(/\x1b\[\?2026h/g) ?? []).length} · 닫 ${(한판.match(/\x1b\[\?2026l/g) ?? []).length}`);
  check('여는 표가 먼저고 닫는 표가 나중이다',
    한판.indexOf('\x1b[?2026h') < 한판.indexOf('\x1b[?2026l'));
}

trace('6-끝');

크기(원래.cols, 원래.rows);
Object.defineProperty(process.stdout, 'isTTY', { value: 원래.isTTY, configurable: true });

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n크기 바꾸기 검사  ${D}(상자가 쌓이지 않는가)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
