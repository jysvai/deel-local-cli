// 429 를 맞았을 때 **얼마나 띄우나.**
//
// ── 왜 이 검사가 생겼나 ─────────────────────────────────────────────────
//
// 사내 게이트웨이에서 이런 것이 왔다.
//
//   litellm.RateLimitError: BedrockException - Too many requests sent to
//   ApplyGuardrail: On-demand ApplyGuardrail sensitive information policy
//   text units per second limit exceeded.
//   ... LiteLLM Retried: 2 times, LiteLLM Max Retries: 2
//
// 두 가지가 보인다.
//
//   1. 한도가 **초당**이다. 분당이 아니다. 그리고 재는 것이 토큰이 아니라
//      「text unit」 이라, 프롬프트가 크면 한 번의 요청만으로 그 초의 몫을 다 쓴다.
//   2. **게이트웨이가 이미 두 번 다시 불렀다.** 우리가 그 답을 보기 전에 벌써
//      세 번 나간 것이다.
//
// 그런데 우리는 거기에 1초·2초·4초를 얹고 있었다. 7초 안에 여섯 번이다.
// 게이트웨이 상당수는 **막아서 돌려보낸 요청도 한도에 세기** 때문에, 빨리
// 두드릴수록 구덩이가 깊어진다. 사람이 본 것은 「호출 한도 초과」 한 줄이다.
//
// ── 여기서 제일 조심할 것 ───────────────────────────────────────────────
//
// 반대로 가면 **멀쩡한 연결이 굼떠진다.** 502 는 여전히 1초에 다시 불러야 하고,
// 한 번 막혔다고 그 뒤 1분 내내 요청마다 띄우면 그건 고친 게 아니라 새 고장이다.
// 그래서 3·5번(안 띄우는 쪽)이 이 파일의 알맹이다.
import {
  기다릴시간, 다시부를지, 다시부를까, 기본정책, 정책고르기,
} from '../src/backend/retry.js';
import {
  할당량기억, 마지막할당량, 할당량잊기, 미리기다릴까, 막힘띄움, 낡은값, 미리기다림상한,
} from '../src/backend/quota.js';
import { serverMessage, 막힘힌트 } from '../src/backend/http.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

const 정책 = 기본정책();
// 흔들림(±30%)이 있어 한 번 재고 단정하면 검사가 들쭉날쭉해진다. 여러 번 재서 본다.
const 여러번 = (fn, n = 60) => Array.from({ length: n }, fn);
const 최소 = (a) => Math.min(...a);
const 최대값 = (a) => Math.max(...a);

// ── 1. 429 는 제 사다리를 쓴다 ──────────────────────────────────────────
trace('1-사다리');
{
  for (const [걸음, 바닥] of [[1, 5000], [2, 15000], [3, 30000]]) {
    const 잰것 = 여러번(() => 기다릴시간({ attempt: 걸음, status: 429 }, 정책));
    check(`★★★ 429 ${걸음}번째는 ${바닥 / 1000}초 아래로 안 내려간다`,
      최소(잰것) >= 바닥, `${최소(잰것)}~${최대값(잰것)}ms`);
  }
  check('★★★ 세 번이면 50초는 기다린 셈이다 — 한도 창 하나를 넘긴다',
    5000 + 15000 + 30000 >= 50000, '');

  /*
   * 여기가 제일 중요하다. 딸꾹질과 한도 초과는 다른 것이고, 그래서 박자가
   * 달라야 한다. 502 까지 5초로 늦추면 멀쩡한 연결이 굼떠진다.
   */
  const 오공삼 = 여러번(() => 기다릴시간({ attempt: 1, status: 503 }, 정책));
  check('★★★ 502·503 은 그대로 1초대다 — 딸꾹질은 한도 초과가 아니다',
    최대값(오공삼) < 2000, `${최소(오공삼)}~${최대값(오공삼)}ms`);
  check('★★★ 그래서 429 가 503 보다 확실히 느리다',
    최소(여러번(() => 기다릴시간({ attempt: 1, status: 429 }, 정책)))
    > 최대값(오공삼), '');
}

// ── 2. 서버가 말해 주면 그 말이 이긴다 ──────────────────────────────────
trace('2-서버말');
{
  /*
   * 우리 사다리는 서버가 아무 말도 안 할 때의 짐작이다. 말해 주면 짐작을 버린다 —
   * 서버가 2초라는데 5초를 기다리면 그만큼 일이 늦어질 뿐이다.
   */
  check('★★★ Retry-After 2초면 2초다 (우리 사다리를 안 쓴다)',
    기다릴시간({ attempt: 1, status: 429, retryAfter: '2' }, 정책) === 2000, '');
  check('★★ Retry-After 가 사다리보다 길어도 그 말대로',
    기다릴시간({ attempt: 1, status: 429, retryAfter: '45' }, 정책) === 45000, '');
  check('★★ 상한은 그대로 씌운다', 기다릴시간({ attempt: 1, status: 429, retryAfter: '9999' }, 정책) === 정책.상한,
    String(정책.상한));
  check('★★ 못 읽을 값이면 사다리로 떨어진다',
    기다릴시간({ attempt: 1, status: 429, retryAfter: '어제' }, 정책) >= 5000, '');
}

// ── 3. 설정을 건드린 사람은 어떻게 되나 ────────────────────────────────
trace('3-설정');
{
  /*
   * 설정은 언제나 정책고르기 를 지난다 — `{...기본정책(), ...conn.retry}` 다.
   * 그래서 `retry.base` 만 적어 둔 사람은 **429 사다리를 안 건드린 것**이고,
   * 새 사다리를 그대로 받는다. 그게 맞다: 그 사람이 조정한 것은 딸꾹질 박자지
   * 한도 초과 박자가 아니다. 둘을 가르려고 사다리를 둘로 나눈 것이다.
   */
  const 설정한사람 = 정책고르기({ retry: { base: [200, 400, 800] } }, null);
  check('★★★ base 만 고친 사람도 429 는 새 사다리를 받는다',
    기다릴시간({ attempt: 1, status: 429 }, 설정한사람) >= 5000, '');
  check('★★★ 그 사람의 503 은 본인이 정한 대로다',
    기다릴시간({ attempt: 1, status: 503 }, 설정한사람) < 300, '');
  check('★★ 429 사다리를 직접 정하면 그게 이긴다',
    기다릴시간({ attempt: 1, status: 429 },
      정책고르기({ retry: { 막힘base: [111] } }, null)) >= 111, '');

  /*
   * 정책 객체를 손으로 만들어 넘기는 자리(검사·부르는 쪽)도 있다. 거기서
   * 막힘base 를 빠뜨렸다고 죽거나 NaN 초를 기다리면 안 된다.
   */
  const 손으로만든것 = { 최대: 3, 막힘최대: null, base: [200, 400, 800], 흔들림: 0, 상한: 60000, 총상한: 300000 };
  check('★★ 막힘base 가 아예 없으면 제 base 로 떨어진다',
    기다릴시간({ attempt: 1, status: 429 }, 손으로만든것) === 200, '');
  check('★★ 사다리가 통째로 이상하면 기본으로 떨어진다',
    기다릴시간({ attempt: 1, status: 429 }, { ...정책, 막힘base: [] }) >= 5000, '');
}

// ── 4. 한 번 막히면 다음 부름도 띄운다 ──────────────────────────────────
trace('4-다음부름');
{
  /*
   * 200걸음짜리 턴에서 41번째가 바로 다시 두드리면 한도는 영영 안 풀린다.
   * 사다리는 **그 한 번의 부름 안**에서만 듣는다 — 부름과 부름 사이는 여기가 맡는다.
   */
  const 지금 = Date.now();
  const 아무말없이막힘 = { 있나: false, 막힘: true, 요청: null, 토큰: null, 풀림: null, 때: 지금 };
  check('★★★ 아무 말 없이 막아도 다음 부름을 띄운다',
    미리기다릴까(아무말없이막힘, 지금) === 막힘띄움, String(미리기다릴까(아무말없이막힘, 지금)));
  check('★★ 흐른 만큼은 빼 준다 — 두 번 기다리지 않는다',
    미리기다릴까(아무말없이막힘, 지금 + 3000) === 막힘띄움 - 3000, '');
  check('★★★ 띄울 만큼 띄웠으면 그만 띄운다',
    미리기다릴까(아무말없이막힘, 지금 + 막힘띄움 + 1) === null, '');

  const 말해준막힘 = { 있나: true, 막힘: true, 요청: null, 토큰: null, 풀림: 30, 때: 지금 };
  check('★★★ 서버가 30초라고 하면 30초다 (바닥값이 아니라)',
    미리기다릴까(말해준막힘, 지금) === 30000, '');
  const 아주긴것 = { 있나: true, 막힘: true, 요청: null, 토큰: null, 풀림: 3600, 때: 지금 };
  check('★★★ 한 시간이라고 해도 상한에서 자른다 — 사람이 정할 일이다',
    미리기다릴까(아주긴것, 지금) === 미리기다림상한, '');
}

// ── 5. 안 띄우는 쪽 ─────────────────────────────────────────────────────
trace('5-안띄움');
{
  const 지금 = Date.now();
  check('★★★ 멀쩡한 응답에는 안 띄운다',
    미리기다릴까({ 있나: true, 막힘: false, 요청: 500, 토큰: 900000, 풀림: 60, 때: 지금 }, 지금) === null, '');
  check('★★★ 아무것도 모르면 안 띄운다 — 모르는 것을 0 으로 치면 안 된다',
    미리기다릴까({ 있나: false, 막힘: false, 요청: null, 토큰: null, 풀림: null, 때: 지금 }, 지금) === null, '');
  check('★★★ 낡은 값으로는 안 정한다 — 그 사이 풀렸을 수 있다',
    미리기다릴까({ 있나: false, 막힘: true, 풀림: null, 요청: null, 토큰: null, 때: 지금 - 낡은값 - 1 }, 지금) === null, '');
  check('★★ 빈 값에도 안 죽는다',
    미리기다릴까(null) === null && 미리기다릴까(undefined) === null, '');
}

// ── 6. 한 번 성공하면 막힘 표시를 지운다 ────────────────────────────────
trace('6-지우기');
{
  /*
   * 여기를 빠뜨리면 「고친 것」 이 아니라 **새 고장**이다. 한 번 막힌 뒤로 낡을
   * 때까지(1분) 멀쩡한 요청마다 5초씩 띄우게 된다.
   */
  할당량잊기();
  const 자리 = 'gw.example|claude-opus-5#openai';
  const 빈머리 = new Map();

  할당량기억(빈머리, 자리, { 막힘: true });
  check('★★★ 429 는 머리가 비어 있어도 적어 둔다',
    마지막할당량(자리)?.막힘 === true, JSON.stringify(마지막할당량(자리)));
  check('★★ 그래서 다음 부름이 띄운다', 미리기다릴까(마지막할당량(자리)) > 0, '');

  할당량기억(빈머리, 자리, { 막힘: false });
  check('★★★ 머리 없는 성공이 와도 막힘 표시를 지운다',
    마지막할당량(자리)?.막힘 === false, JSON.stringify(마지막할당량(자리)));
  check('★★★ 그러면 다음 부름은 안 띄운다', 미리기다릴까(마지막할당량(자리)) === null, '');

  // 창구는 따로 센다. 한쪽이 막혔다고 옆 창구까지 띄우면 안 된다.
  할당량기억(빈머리, '가.example|m#openai', { 막힘: true });
  check('★★★ 옆 창구는 안 띄운다',
    미리기다릴까(마지막할당량(자리)) === null, '');
  할당량잊기();
}

// ── 7. 실제로 온 그 응답을 그대로 넣어 본다 ─────────────────────────────
trace('7-실물');
{
  /*
   * 사내 LiteLLM 이 준 모양 그대로. `Retry-After` 도 남은 수도 없다 —
   * 우리가 아는 것은 429 하나뿐인 자리다.
   */
  const 온것 = {
    status: 429,
    headers: new Map(),
    json: { error: { message: 'litellm.RateLimitError: BedrockException - Too many requests sent to ApplyGuardrail' } },
  };
  const 알림 = 다시부를지(온것, 1, 정책, 0);
  check('★★★ 그래도 다시 부르기는 한다', !!알림, JSON.stringify(알림));
  check('★★★ 첫 기다림이 5초 이상이다 (여태 1초였다)', 알림.wait >= 5000, `${알림.wait}ms`);
  check('★★ 화면에 몇 번째인지 적을 것이 있다', 알림.attempt === 1 && 알림.max >= 1,
    `${알림.attempt}/${알림.max}`);
  check('★★ 429 라고 적어 준다', 알림.status === 429, '');

  // 총상한 울타리는 그대로다. 사다리가 길어졌다고 무한히 붙들면 안 된다.
  const 거의다씀 = 다시부를지(온것, 3, 정책, 정책.총상한 - 1000);
  check('★★★ 총 기다린 시간이 울타리를 넘으면 그만둔다', 거의다씀 === null, String(거의다씀));

  check('★★ 429 를 다시 부르는 규칙 자체는 그대로다',
    다시부를까({ status: 429, attempt: 1 }, 정책) === true, '');
  check('★★★ 횟수를 넘기면 그만둔다',
    다시부를까({ status: 429, attempt: 정책.최대 + 1 }, 정책) === false, '');
}

// ── 8. 무슨 429 인지 말해 준다 ──────────────────────────────────────────
trace('8-무슨한도');
{
  /*
   * 「서버가 잠시 막았습니다 (HTTP 429)」 만 뜨면 사람이 할 수 있는 것이 기다리는
   * 것뿐이다. 그런데 429 는 한 가지가 아니다 — 어떤 것은 1분 뒤에 저절로 풀리고,
   * 어떤 것은 관리자가 할당량을 올려 주기 전까지 안 풀린다. 그 둘에 같은 말을
   * 하면 사람은 30분을 기다리다 포기한다.
   *
   * 특히 이 자리가 헷갈리기 쉽다: 모델의 분당 한도(RPM·TPM)를 무제한으로 풀어
   * 놓고도 계속 걸린다. 가드레일은 **다른 API 의 다른 할당량**이라 그렇다.
   * 그걸 화면이 말해 주지 않으면 아무도 스스로 알아낼 수 없다.
   */
  const 실물 = 'litellm.RateLimitError: BedrockException - Too many requests sent to ApplyGuardrail:'
    + ' On-demand ApplyGuardrail sensitive information policy text units per second limit exceeded.';
  const 가드레일 = serverMessage({ status: 429, json: { error: { message: 실물 } } });

  check('★★★ 가드레일 한도라고 알아본다', /가드레일/.test(가드레일), 가드레일.slice(0, 40));
  check('★★★ 모델 토큰 한도가 아니라고 못 박는다', /모델 토큰 한도가 아닙니다/.test(가드레일), '');
  check('★★★ RPM·TPM 을 올려도 안 된다고 말해 준다 — 여기서 제일 헤맨다',
    /RPM·TPM/.test(가드레일) && /안 움직입니다/.test(가드레일), '');
  check('★★★ 캐시가 안 듣는 까닭도 적는다', /캐시/.test(가드레일), '');
  check('★★ 지금 당장 할 수 있는 것을 알려 준다', /\/compact/.test(가드레일), '');
  check('★★★ 원문을 안 지운다 — 담당자에게 그대로 보여 줘야 한다',
    /원문:/.test(가드레일) && /ApplyGuardrail/.test(가드레일), '');

  const 분당 = serverMessage({ status: 429, json: { error: { message: 'Rate limit reached: 40000 tokens per minute' } } });
  check('★★★ 분당 한도는 다른 말을 한다 — 이건 기다리면 풀린다',
    /분당 한도/.test(분당) && !/가드레일/.test(분당), 분당.slice(0, 40));

  /*
   * 안 하는 쪽. 모르는 것에 아는 척하면 그 화면은 그때부터 못 믿는다.
   */
  check('★★★ 알아볼 수 없으면 원문 그대로 준다',
    serverMessage({ status: 429, json: { error: { message: 'too many requests' } } }) === 'too many requests', '');
  check('★★★ 429 가 아니면 힌트를 안 붙인다 — 400 에 한도 이야기를 하면 안 된다',
    serverMessage({ status: 400, json: { error: { message: 'guardrail text units' } } }) === 'guardrail text units', '');
  check('★★ 막힘힌트 는 못 알아보면 null 이다',
    막힘힌트('아무 말') === null && 막힘힌트(null) === null && 막힘힌트(undefined) === null, '');
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n한도 초과 띄우기 검사  ${D}(빨리 두드릴수록 구덩이가 깊어진다)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
trace('끝-정상종료');
process.exitCode = fail.length ? 1 : 0;
