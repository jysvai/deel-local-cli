// 붙박이 사무실.
//
// ── 여기서 무엇을 지키나 ────────────────────────────────────────────────
//
// 이것도 꾸미기라 "예쁜가" 는 못 잰다. 대신 **깨뜨릴 수 있는 것**을 잰다.
//
//   1. 폭·줄 수. 상자 위에 얹히는 것이라 한 줄이라도 폭이 다르면 그 순간
//      화면이 어긋난다. 90ms 마다 다시 그려지므로 눈에는 '떨리는 화면' 이다.
//   2. **전부 진짜 숫자인가.** 이 화면의 존재 이유가 그것이다. 없는 값을
//      그럴듯하게 채우기 시작하면 그냥 배경화면이 된다.
//   3. 가벼운가. 판이 바뀔 때 실제로 달라지는 줄이 몇 개인지 잰다 — 상자가
//      바뀐 줄만 보내므로, 이 수가 곧 터미널로 나가는 양이다.
//   4. 안 켜져야 할 자리에서 안 켜지나. 화면이 낮은데 켜면 대화가 들어갈
//      자리가 없어진다 — 사무실을 보려고 도구를 못 쓰게 되는 것은 앞뒤가 바뀐 것이다.
import { 사무실줄들, 상태만들기, 켜나, 켜달라했나, 줄수, 최소높이 } from '../src/ui/office.js';
import { 그림고르기 } from '../src/ui/motion.js';
import { width } from '../src/ui/ansi.js';
import { trace } from './trace.mjs';

const pass = [];
const fail = [];
const check = (name, cond, note = '') => (cond ? pass : fail).push({ name, note });

const 벗기기 = (s) => s.replace(/\x1b\[[0-9;]*m/g, '');
const 환경되돌리기 = () => {
  delete process.env.DEEL_OFFICE;
  delete process.env.DEEL_NO_MOTION;
  delete process.env.DEEL_MOTION;
};
환경되돌리기();

trace('1-크기');
// ── 폭과 줄 수가 한 칸도 안 어긋나나 ────────────────────────────────────
{
  const 상태 = 상태만들기({}, { 갈래: '쓰기' }, 0);
  for (const 폭 of [60, 80, 100, 132, 200]) {
    const 줄들 = 사무실줄들(상태, 폭);
    const 칸들 = [...new Set(줄들.map((l) => width(벗기기(l))))];
    check(`폭 ${폭}: 모든 줄이 같은 칸`, 칸들.length === 1, 칸들.join(','));
    check(`폭 ${폭}: 준 폭만큼 그린다`, 칸들[0] === Math.max(60, 폭), `${칸들[0]}칸`);
    check(`폭 ${폭}: 줄 수가 ${줄수}`, 줄들.length === 줄수, `${줄들.length}줄`);
  }
  // 아주 좁아도 안 터진다. 최소 폭으로 눌러 그린다 — 깨진 화면보다 낫다.
  const 좁게 = 사무실줄들(상태, 10);
  check('아주 좁아도 안 터진다', 좁게.length === 줄수 && width(벗기기(좁게[0])) === 60);
}

trace('2-진짜숫자');
/*
 * ── 여기가 이 화면의 존재 이유다 ────────────────────────────────────────
 *
 * 그린 것이 전부 세션에서 온 값이어야 한다. 하나라도 지어내기 시작하면
 * 사람이 화면을 안 믿게 되고, 그러면 이 열두 줄은 자리만 먹는 그림이 된다.
 */
{
  const 세션 = {
    usage: { in: 8000, out: 4400, calls: 4 },
    filesRead: new Map([['a', 1], ['b', 1], ['c', 1]]),
    changes: new Map([['a', 1]]),
    conn: { ctx: 32768 },
  };
  const 할일들 = [{ state: 'done' }, { state: 'done' }, { state: 'todo' }];
  const s = 상태만들기(세션, { 갈래: '쓰기' }, 0, 할일들, 2);

  check('읽은 파일이 filesRead 에서 온다', s.읽은파일 === 3, `${s.읽은파일}`);
  check('고친 파일이 changes 에서 온다', s.고친파일 === 1, `${s.고친파일}`);
  check('모델 호출이 usage.calls 에서 온다', s.부른횟수 === 4, `${s.부른횟수}`);
  check('토큰이 usage in+out 에서 온다', s.토큰 === 12400, `${s.토큰}`);
  check('끝난 일·남은 일을 따로 센다', s.끝난일 === 2 && s.할일 === 1, `${s.끝난일}/${s.할일}`);
  check('창이 컨텍스트 찬 비율이다',
    Math.abs(s.창 - 12400 / 32768) < 1e-9, `${s.창.toFixed(3)}`);
  check('하위 작업만큼 자리가 는다 (부모 1 + 하위 2)', s.일꾼들.length === 3, `${s.일꾼들.length}`);

  /*
   * 모르는 것은 0 으로 둔다 — 그럴듯한 값으로 채우지 않는다.
   * 빈 세션에서 '파일 세 개쯤 읽었겠지' 를 그리면 그게 거짓말의 시작이다.
   */
  const 빈것 = 상태만들기({}, null, 0);
  check('빈 세션이면 전부 0', 빈것.읽은파일 === 0 && 빈것.고친파일 === 0
    && 빈것.부른횟수 === 0 && 빈것.토큰 === 0 && 빈것.창 === 0, JSON.stringify(빈것));
  check('일이 안 돌면 앉은 사람도 없다', 빈것.일꾼들.length === 0);
  check('할 일을 안 알려 주면 빈 보드', 빈것.할일 === 0 && 빈것.끝난일 === 0);
  // 컨텍스트 길이를 모르면 창을 밤으로 만들지 않는다. 모르는 것은 0 이다.
  const 창모름 = 상태만들기({ usage: { in: 9e9, out: 0 } }, null, 0);
  check('컨텍스트 길이를 모르면 창은 0', 창모름.창 === 0, `${창모름.창}`);
}

trace('3-화면이바뀌나');
// ── 값이 바뀌면 화면도 바뀌어야 한다 ────────────────────────────────────
//
// 안 바뀌면 '진짜 숫자' 라는 말이 거짓이 된다. 실제로 눈에 보이는지를 잰다.
{
  const 기본 = 상태만들기({}, { 갈래: '쓰기' }, 0);
  const 그림 = (s) => 사무실줄들(s, 100).join('\n');
  const 바탕 = 그림(기본);

  const 다름 = (이름, 고친상태) => {
    check(`${이름} 이 화면을 바꾼다`, 그림({ ...기본, ...고친상태 }) !== 바탕);
  };
  다름('읽은 파일', { 읽은파일: 20 });
  다름('고친 파일', { 고친파일: 3 });
  다름('할 일', { 할일: 2, 끝난일: 1 });
  다름('모델 호출', { 부른횟수: 6 });
  다름('일하는 자리 수', { 일꾼들: [{ 갈래: '쓰기' }, { 갈래: '쓰기' }] });
  다름('갈래(쓰기→읽기)', { 일꾼들: [{ 갈래: '읽기' }] });
  다름('틱(자세가 돈다)', { 틱: 5 });

  // 컨텍스트가 차면 창이 밤이 된다.
  const 낮 = 그림({ ...기본, 창: 0.2 });
  const 밤 = 그림({ ...기본, 창: 0.9 });
  check('컨텍스트가 차면 창이 밤이 된다', 낮 !== 밤);

  // 오래 걸리면(느긋) 사람이 존다.
  const 조는것 = 상태만들기({}, { 갈래: '느긋' }, 0);
  check('오래 걸리면 조는 자세', 조는것.일꾼들[0]?.갈래 === '졸기', 조는것.일꾼들[0]?.갈래);
}

trace('4-가벼운가');
/*
 * ── 터미널로 얼마나 나가나 ──────────────────────────────────────────────
 *
 * 상자는 **바뀐 줄만** 보낸다. 그러니 여기서 잴 것은 '판이 바뀔 때 몇 줄이
 * 달라지나' 다. 그 수가 곧 나가는 양이다.
 *
 * 벽·창문·서류함·빈 책상은 안 바뀐다. 바뀌는 것은 사람이 있는 줄뿐이라야 한다.
 * 이 수가 갑자기 커지면 무언가가 쓸데없이 매 판 다시 그려지고 있다는 뜻이다.
 */
{
  const 상태 = (틱) => 상태만들기({}, { 갈래: '쓰기' }, 틱);
  let 바뀐줄합 = 0;
  let 앞 = 사무실줄들(상태(0), 100);
  const 판수 = 40;
  for (let i = 1; i < 판수; i++) {
    const 지금 = 사무실줄들(상태(i), 100);
    바뀐줄합 += 지금.filter((l, j) => l !== 앞[j]).length;
    앞 = 지금;
  }
  const 판당 = 바뀐줄합 / (판수 - 1);
  check('한 판에 바뀌는 줄이 세 줄 아래', 판당 < 3, `${판당.toFixed(1)}줄 / ${줄수}줄`);

  // 값이 안 바뀌면 화면도 그대로여야 한다 — 같은 것을 다시 보내면 그냥 낭비다.
  const 한번 = 사무실줄들(상태만들기({}, { 갈래: '쓰기' }, 7), 100);
  const 또한번 = 사무실줄들(상태만들기({}, { 갈래: '쓰기' }, 7), 100);
  check('같은 값이면 같은 화면', 한번.join('\n') === 또한번.join('\n'));
}

trace('5-켜고끄기');
// ── 안 켜져야 할 자리에서 안 켜지나 ────────────────────────────────────
{
  환경되돌리기();
  check('기본은 꺼져 있다', 켜나(50) === false);
  check('기본은 켜 달라고 한 적도 없다', 켜달라했나() === false);

  process.env.DEEL_OFFICE = '1';
  check('켜 달라면 켜진다', 켜나(50) === true);
  for (const v of ['on', '켬', '사무실', 'ON']) {
    process.env.DEEL_OFFICE = v;
    check(`"${v}" 로도 켜진다`, 켜나(50) === true);
  }
  process.env.DEEL_OFFICE = '그런거없음';
  check('모르는 값은 조용히 꺼진 채로', 켜나(50) === false);

  process.env.DEEL_OFFICE = '1';
  check(`화면이 ${최소높이}줄보다 낮으면 안 켠다`, 켜나(최소높이 - 1) === false);
  check(`${최소높이}줄이면 켠다`, 켜나(최소높이) === true);
  check('화면 높이를 모르면 안 켠다', 켜나(undefined) === false);

  // 그림을 끈 사람에게는 사무실도 안 그린다. 화면 읽기 프로그램을 쓰는 자리다.
  process.env.DEEL_NO_MOTION = '1';
  check('그림을 껐으면 사무실도 안 뜬다', 켜나(50) === false);
  delete process.env.DEEL_NO_MOTION;

  /*
   * 사무실을 켜면 상자 안 그림은 조용한 것으로 돌아간다.
   * 둘 다 같은 것을 말하므로 나란히 두면 같은 소리를 두 번 하는 셈이다.
   */
  process.env.DEEL_MOTION = '기사';
  process.env.DEEL_OFFICE = '1';
  check('사무실을 켜면 상자 그림은 한 칸짜리로', [...그림고르기('쓰기', 0)].length === 1);
  delete process.env.DEEL_OFFICE;
  check('사무실을 끄면 기사가 돌아온다', [...그림고르기('쓰기', 0)].length === 6);

  // 화면이 낮아 사무실이 실제로 안 떠도, 상자 그림은 '켜 달라 했나' 만 본다.
  // 창을 줄였다 늘였다 할 때마다 상자 안 그림이 바뀌면 규칙이 안 보인다.
  process.env.DEEL_OFFICE = '1';
  check('화면이 낮아도 상자 그림 규칙은 안 흔들린다',
    켜나(10) === false && [...그림고르기('쓰기', 0)].length === 1);

  환경되돌리기();
}

const G = '\x1b[32m'; const R = '\x1b[31m'; const D = '\x1b[90m'; const X = '\x1b[0m';
console.log(`\n붙박이 사무실 검사  ${D}(열두 줄이 전부 진짜 숫자인가)${X}\n`);
for (const p of pass) console.log(`  ${G}✓${X} ${p.name}${p.note ? `${D}  ${p.note}${X}` : ''}`);
for (const f of fail) console.log(`  ${R}✗${X} ${f.name}  ${D}${f.note}${X}`);
console.log(`\n  ${pass.length}개 통과 · ${fail.length}개 실패\n`);
if (fail.length) process.exitCode = 1;
