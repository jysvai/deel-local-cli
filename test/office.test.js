// ── 폭과 줄 수가 한 칸도 안 어긋나나 ────────────────────────────────────
{
  const 상태 = 상태만들기({}, { 갈래: '쓰기' }, 0);
  for (const 폭 of [60, 80, 100, 132, 200]) {
    const 줄들 = 사무실줄들(상태, 폭);
    const 칸들 = [...new Set(줄들.map((l) => width(벗기기(l))))];
    check(`폭 ${폭}: 모든 줄이 같은 칸`, 칸들.length === 1, 칸들.join(','));
    check(`폭 ${폭}: 준 폭만큼 그린다`, 칸들[0] === Math.max(60, 폭), `${칸들[0]}칸`);
    check(`폭 ${폭}: 줄 수가 ${줄수}`, 줄들.length === 줄수, `${줄들.length}줄`);
    // 이것이 진짜로 지켜야 하는 것이다 — 한 줄이라도 터미널보다 넓으면 접히고,
    // 상자는 접힌 줄을 못 세서 그만큼 어긋난 자리에 다음 판을 덮어쓴다.
    check(`폭 ${폭}: 터미널보다 넓은 줄이 없다`, 칸들[0] <= 폭, `${칸들[0]}칸 / ${폭}칸`);
  }

  /*
   * 좁은 터미널에서는 **안 켜는** 것이 답이다.
   *
   * 예전 이 자리에는 '아주 좁아도 안 터진다' 며 폭 10 에서도 60칸으로 눌러
   * 그리는 것을 통과시키는 검사가 있었다. 그것이 바로 화면을 깨는 동작이었다 —
   * 60칸짜리 열두 줄이 50칸 터미널에서 스물네 줄로 접히는데 상자는 열둘로
   * 세고 커서를 올린다. 200판이면 테두리도 대화도 안 남는다.
   */
  const 예전TERM = process.env.TERM;
  process.env.DEEL_OFFICE = '1';
  process.env.TERM = 'xterm-256color';
  for (const 칸 of [10, 40, 50, 59]) {
    check(`${칸}칸에서는 아예 안 켠다`, 켜나(40, 칸) === false);
  }
  for (const 칸 of [60, 80, 120]) {
    check(`${칸}칸에서는 켜고, 넘치지 않는다`,
      켜나(40, 칸) === true && width(벗기기(사무실줄들(상태, 칸)[0])) <= 칸);
  }
  환경되돌리기();
  if (예전TERM === undefined) delete process.env.TERM; else process.env.TERM = 예전TERM;
}

trace('1.5-상자를-거쳐-그려도-안-넘치나');
/*
 * ── 이 검사가 없어서 1.5.0 이 깨진 채로 나갔다 ──────────────────────────
 *
 * 여태 사무실은 사무실줄들() 만 따로 불러서 쟀다. 그래서 「폭 10 에 60칸을
 * 그린다」가 정상으로 통과했다 — 그 줄이 실제로 상자에 얹혔을 때 터미널에서
 * 두 줄로 접힌다는 것을 아무도 안 봤다. 결함은 늘 이음매에 있다.
 *
 * 그래서 여기서는 프레임() 을 거쳐서 잰다. 상자가 세는 줄 수와 터미널이
 * 실제로 쓰는 줄 수가 같아야 한다 — 한 줄이라도 폭을 넘으면 그 순간 어긋난다.
 */
{
  const 상태 = 상태만들기({}, { 갈래: '쓰기', 시작: Date.now() }, 0);
  for (const 폭 of [60, 62, 80, 100, 132]) {
    const 방 = 사무실줄들(상태, 폭);
    const { 줄들 } = 프레임({ 사무실: 방, 글: '집계 함수도 줄여줘', 커서: 9, 폭, 상태: '▏a ▏ 22%' });
    const 넘친줄 = 줄들.filter((l) => width(벗기기(l)) > 폭);
    check(`폭 ${폭}: 상자를 거쳐도 넘치는 줄이 없다`, 넘친줄.length === 0,
      넘친줄.length ? `${넘친줄.length}줄이 넘침 (가장 넓은 것 ${Math.max(...넘친줄.map((l) => width(벗기기(l))))}칸)` : '');
    check(`폭 ${폭}: 사무실 ${줄수}줄이 상자에 그대로 얹힌다`,
      줄들.length >= 줄수 + 3, `${줄들.length}줄`);
  }
}

trace('2-진짜숫자');
/*
 * ── 여기가 이 화면의 존재 이유다 ────────────────────────────────────────
 *
 * 그린 것이 전부 세션에서 온 값이어야 한다. 하나라도 지어내기 시작하면
 * 사람이 화면을 안 믿게 되고, 그러면 이 열두 줄은 자리만 먹는 그림이 된다.
 */
{
  const 세션 = {
    usage: { in: 8000, out: 4400, calls: 4 },
    filesRead: new Map([['a', 1], ['b', 1], ['c', 1]]),
    changes: new Map([['a', 1]]),
    conn: { ctx: 32768 },
  };
  const 할일들 = [{ state: 'done' }, { state: 'done' }, { state: 'todo' }];
  const s = 상태만들기(세션, { 갈래: '쓰기' }, 0, 할일들, 2);

  check('읽은 파일이 filesRead 에서 온다', s.읽은파일 === 3, `${s.읽은파일}`);
  check('고친 파일이 changes 에서 온다', s.고친파일 === 1, `${s.고친파일}`);
  check('모델 호출이 usage.calls 에서 온다', s.부른횟수 === 4, `${s.부른횟수}`);
  check('토큰이 usage in+out 에서 온다', s.토큰 === 12400, `${s.토큰}`);
  check('끝난 일·남은 일을 따로 센다', s.끝난일 === 2 && s.할일 === 1, `${s.끝난일}/${s.할일}`);
  check('창이 컨텍스트 찬 비율이다',
    Math.abs(s.창 - 12400 / 32768) < 1e-9, `${s.창.toFixed(3)}`);
  // 자리는 도는 것 + 맡은 것이다. 부모 1 + 하위 2 + 남은 할 일 1 = 4.
  check('도는 것과 맡은 것이 다 자리를 차지한다', s.일꾼들.length === 4, `${s.일꾼들.length}`);
  check('남은 할 일은 화면 꺼진 자리로', s.일꾼들.at(-1).갈래 === '기다림', s.일꾼들.at(-1).갈래);

  /*
   * 모르는 것은 0 으로 둔다 — 그럴듯한 값으로 채우지 않는다.
   * 빈 세션에서 '파일 세 개쯤 읽었겠지' 를 그리면 그게 거짓말의 시작이다.
   */
  const 빈것 = 상태만들기({}, null, 0);
  check('빈 세션이면 전부 0', 빈것.읽은파일 === 0 && 빈것.고친파일 === 0
    && 빈것.부른횟수 === 0 && 빈것.토큰 === 0 && 빈것.창 === 0, JSON.stringify(빈것));
  check('일이 안 돌면 앉은 사람도 없다', 빈것.일꾼들.length === 0);
  check('할 일을 안 알려 주면 빈 보드', 빈것.할일 === 0 && 빈것.끝난일 === 0);
  // 컨텍스트 길이를 모르면 창을 밤으로 만들지 않는다. 모르는 것은 0 이다.
  const 창모름 = 상태만들기({ usage: { in: 9e9, out: 0 } }, null, 0);
  check('컨텍스트 길이를 모르면 창은 0', 창모름.창 === 0, `${창모름.창}`);
}

trace('3-화면이바뀌나');
// ── 값이 바뀌면 화면도 바뀌어야 한다 ────────────────────────────────────
//
// 안 바뀌면 '진짜 숫자' 라는 말이 거짓이 된다. 실제로 눈에 보이는지를 잰다.
{
  const 기본 = 상태만들기({}, { 갈래: '쓰기' }, 0);
  const 그림 = (s) => 사무실줄들(s, 100).join('\n');
  const 바탕 = 그림(기본);

  const 다름 = (이름, 고친상태) => {
    check(`${이름} 이 화면을 바꾼다`, 그림({ ...기본, ...고친상태 }) !== 바탕);
  };
  다름('읽은 파일', { 읽은파일: 20 });
  다름('고친 파일', { 고친파일: 3 });
  다름('할 일', { 할일: 2, 끝난일: 1 });
  다름('모델 호출', { 부른횟수: 6 });
  다름('일하는 자리 수', { 일꾼들: [{ 갈래: '쓰기' }, { 갈래: '쓰기' }] });
  다름('갈래(쓰기→읽기)', { 일꾼들: [{ 갈래: '읽기' }] });
  다름('틱(자세가 돈다)', { 틱: 5 });

  // 컨텍스트가 차면 창이 밤이 된다.
  const 낮 = 그림({ ...기본, 창: 0.2 });
  const 밤 = 그림({ ...기본, 창: 0.9 });
  check('컨텍스트가 차면 창이 밤이 된다', 낮 !== 밤);

  // 오래 걸리면(느긋) 사람이 존다.
  const 조는것 = 상태만들기({}, { 갈래: '느긋' }, 0);
  check('오래 걸리면 조는 자세', 조는것.일꾼들[0]?.갈래 === '졸기', 조는것.일꾼들[0]?.갈래);
}

trace('3.5-하루가가나');

/*
 * ── 창밖이 컨텍스트를 따라 저무는가 ─────────────────────────────────────
 *
 * 예전에는 낮/밤 둘뿐이었다. 그래서 컨텍스트 5% 와 50% 가 **똑같은 대낮**
 * 으로 나왔다 — 창이 열두 줄을 먹으면서 아무 말도 안 하고 있었던 셈이다.
 * 넷으로 나눴으니, 넷이 정말로 다르게 보이는지를 잰다. 값이 달라도 화면이
 * 같으면 그건 안 나눈 것과 같다.
 */
{
  const 방 = (창비율) => 사무실줄들(
    상태만들기({ usage: { in: Math.round(창비율 * 100000), out: 0 }, conn: { ctx: 100000 } },
      { 갈래: '쓰기', 시작: Date.now() }, 0), 100).slice(0, 3).join('\n');
  const 하루 = [0.05, 0.35, 0.65, 0.9].map(방);
  const 다른가 = new Set(하루).size === 4;
  check('아침·낮·노을·밤이 다 다르게 보인다', 다른가, `서로 다른 그림 ${new Set(하루).size}개`);

  // 경계 바로 옆은 같은 때여야 한다 — 한 토큰 차이로 밤이 되면 화면이 떤다.
  check('같은 때 안에서는 안 바뀐다', 방(0.30) === 방(0.50));
  check('경계를 넘으면 바뀐다', 방(0.50) !== 방(0.60));

  /*
   * 벽시계 — 이번 턴이 얼마나 걸렸나. 여기서 재는 것은 '바늘이 도는가' 다.
   * 안 돌면 그냥 벽에 붙은 무늬고, 무늬는 이 방에 놓지 않기로 했다.
   */
  const 시계 = (초) => 사무실줄들(
    상태만들기({}, { 갈래: '쓰기', 시작: Date.now() - 초 * 1000 }, 0), 100).slice(0, 3).join('\n');
  check('시간이 가면 바늘이 돈다', 시계(0) !== 시계(20), '0초 vs 20초');
  check('한 바퀴 돌면 제자리', 시계(3) === 시계(63), '3초 vs 63초');
  // 좁은 터미널에는 시계 걸 자리가 없다. 없다고 터지면 안 된다.
  check('좁아도 안 터진다', 사무실줄들(상태만들기({}, { 갈래: '쓰기', 시작: Date.now() }, 0), 60).length === 줄수);
}

trace('3.6-동시에도는만큼-자리가차나');

/*
 * ── 방이 늘 한 명짜리로 보이던 이유 ─────────────────────────────────────
 *
 * 자리는 '부모 1 + 도는 하위 작업' 으로 셌다. 그런데 하위 작업은 loop.js 가
 * `for await` 로 기다리므로 **순서대로** 돈다 — 그 수는 사실상 0 아니면 1 이라,
 * 뭘 시키든 방에는 한 명만 앉아 있었다.
 *
 * 정작 진짜로 동시에 도는 것은 읽기 도구 묶음(loop.js 의 Promise.all)이고,
 * 그 개수는 화면에 「3개를 함께 돌립니다」로 이미 찍히고 있었다. 방만 그걸
 * 안 보고 있었다.
 */
{
  const 자리 = (함께, 하위) => 상태만들기({}, { 갈래: '읽기', 시작: Date.now() }, 0, [], 하위, 함께).일꾼들;

  check('혼자면 한 명', 자리(0, 0).length === 1, `${자리(0, 0).length}`);
  check('셋을 함께 돌리면 세 자리', 자리(3, 0).length === 3, `${자리(3, 0).length}`);
  check('하위까지 있으면 더 찬다', 자리(3, 1).length === 4, `${자리(3, 1).length}`);
  check('한 개짜리 묶음은 자리를 안 늘린다', 자리(1, 0).length === 1, `${자리(1, 0).length}`);

  /*
   * 자세는 지어낸 것이 아니어야 한다.
   *
   * 묶어서 도는 것은 읽기 전용 도구뿐이다(loop.js 의 읽기전용 집합 —
   * Read·Glob·Grep·Skill·WebFetch). 그러니 저 자리는 전부 읽는 중인 게 맞다.
   * 반면 하위 작업이 지금 읽는지 쓰는지는 여기까지 안 올라오므로 '대기' 로 둔다 —
   * 모르는 것을 그럴듯하게 채우지 않는다.
   */
  const 섞인것 = 자리(3, 1);
  check('함께 도는 자리는 읽는 중', 섞인것[1].갈래 === '읽기' && 섞인것[2].갈래 === '읽기',
    섞인것.map((x) => x.갈래).join(','));
  check('하위 자리는 모른다고 둔다', 섞인것[3].갈래 === '대기', 섞인것[3].갈래);

  // 이상한 값이 와도 자리를 지어내지 않는다.
  check('음수는 없는 것으로', 자리(-5, -2).length === 1);
}

trace('3.7-계획이있으면-방이-찬다');

/*
 * ── 「계획을 세웠는데도 한 명뿐이냐」 ───────────────────────────────────
 *
 * 맞는 말이었다. 자리를 '지금 도는 일' 로만 셌는데 deel 은 한 번에 하나씩
 * 하므로 늘 하나였고, 계획 다섯 개는 화이트보드 쪽지로만 있고 방은 텅 비어
 * 있었다. 남은 할 일도 이 방이 떠맡은 일감이니 사람으로 앉힌다.
 */
{
  const 방 = (할일수, 폭 = 100) => {
    const 할일들 = Array.from({ length: 할일수 }, () => ({ state: 'todo' }));
    const s = 상태만들기({}, { 갈래: '쓰기', 시작: Date.now() }, 0, 할일들);
    return { 상태: s, 줄들: 사무실줄들(s, 폭) };
  };

  check('계획이 없으면 한 명', 방(0).상태.일꾼들.length === 1, `${방(0).상태.일꾼들.length}`);
  check('할 일 다섯이면 여섯 명', 방(5).상태.일꾼들.length === 6, `${방(5).상태.일꾼들.length}`);
  check('맨 앞은 지금 도는 일', 방(5).상태.일꾼들[0].갈래 === '쓰기', 방(5).상태.일꾼들[0].갈래);
  check('나머지는 차례를 기다리는 일',
    방(5).상태.일꾼들.slice(1).every((x) => x.갈래 === '기다림'));
  // 끝난 일은 사람이 아니다 — 이미 나간 사람을 방에 앉혀 두면 안 된다.
  const 끝난것 = 상태만들기({}, { 갈래: '쓰기', 시작: Date.now() }, 0,
    [{ state: 'done' }, { state: 'done' }]);
  check('끝난 할 일은 자리를 안 차지한다', 끝난것.일꾼들.length === 1, `${끝난것.일꾼들.length}`);

  /*
   * 사람이 늘면 화면도 달라져야 한다. 여기서 값만 재고 그림을 안 보면,
   * 일꾼들 배열만 길어지고 방은 그대로인 것을 못 잡는다 — 실제로 그렇게
   * 한 번 나갔다(자리는 셋인데 그려지는 사람은 하나).
   */
  check('사람이 늘면 그림도 달라진다',
    방(0).줄들.join('\n') !== 방(5).줄들.join('\n'));
  check('사람이 늘어도 폭은 그대로', 방(5).줄들.every((l) => 벗기기(l).length <= 100));

  /*
   * 셋 이상이면 하나는 자리에서 일어나 있다 — 다 앉아만 있으면 사무실이
   * 아니라 독서실이다. 그 사람은 방을 돌아다니므로, 판이 흐르면 그 줄이 바뀐다.
   */
  const 걷나 = (할일수) => {
    const 할일들 = Array.from({ length: 할일수 }, () => ({ state: 'todo' }));
    const 판 = (틱) => 사무실줄들(상태만들기({}, { 갈래: '쓰기', 시작: Date.now() }, 틱, 할일들), 100);
    // 걷는 자리는 굽도리 바로 아래 — 12줄 중 넷째 줄이다.
    return 판(0)[3] !== 판(6)[3] || 판(0)[4] !== 판(6)[4];
  };
  check('셋 이상이면 누군가 방을 돌아다닌다', 걷나(2), '할 일 2개 + 도는 일 1개');
  check('혼자일 때는 아무도 안 서성인다', !걷나(0));
}

trace('4-가벼운가');
/*
 * ── 터미널로 얼마나 나가나 ──────────────────────────────────────────────
 *
 * 상자는 **바뀐 줄만** 보낸다. 그러니 여기서 잴 것은 '판이 바뀔 때 몇 줄이
 * 달라지나' 다. 그 수가 곧 나가는 양이다.
 *
 * 벽·창문·서류함·빈 책상은 안 바뀐다. 바뀌는 것은 사람이 있는 줄뿐이라야 한다.
 * 이 수가 갑자기 커지면 무언가가 쓸데없이 매 판 다시 그려지고 있다는 뜻이다.
 */
{
  const 재기 = (할일수) => {
    const 할일들 = Array.from({ length: 할일수 }, () => ({ state: 'todo' }));
    const 상태 = (틱) => 상태만들기({}, { 갈래: '쓰기' }, 틱, 할일들);
    let 바뀐줄합 = 0;
    let 앞 = 사무실줄들(상태(0), 100);
    const 판수 = 60;
    for (let i = 1; i < 판수; i++) {
      const 지금 = 사무실줄들(상태(i), 100);
      바뀐줄합 += 지금.filter((l, j) => l !== 앞[j]).length;
      앞 = 지금;
    }
    return 바뀐줄합 / (판수 - 1);
  };

  // 계획이 없으면 한 명뿐이라 거의 안 바뀐다.
  const 조용할때 = 재기(0);
  check('조용한 방은 한 판에 한 줄도 안 바뀐다', 조용할때 < 1.5, `${조용할때.toFixed(1)}줄 / ${줄수}줄`);

  /*
   * 사람이 늘면 그만큼 나간다 — 그게 움직임의 값이다.
   *
   * 사람 하나가 1픽셀 움직이면 그 자리 세 줄이 통째로 다시 나간다. 방이 살아
   * 있으려면 치러야 하는 값이고, 숨길 것이 아니라 **재서 적어 둘** 값이다.
   * 여기가 갑자기 커지면 뭔가가 쓸데없이 매 판 다시 그려지고 있다는 뜻이다.
   *
   * 절반(6줄)을 넘으면 견주는 뜻이 옅어진다. 거기를 선으로 둔다.
   */
  const 바쁠때 = 재기(10);
  check('사람이 꽉 차도 절반 아래', 바쁠때 < 6, `${바쁠때.toFixed(1)}줄 / ${줄수}줄`);
  check('바쁠수록 더 나간다 — 그게 맞다', 바쁠때 > 조용할때,
    `${조용할때.toFixed(1)} → ${바쁠때.toFixed(1)}`);

  // 값이 안 바뀌면 화면도 그대로여야 한다 — 같은 것을 다시 보내면 그냥 낭비다.
  const 한번 = 사무실줄들(상태만들기({}, { 갈래: '쓰기' }, 7), 100);
  const 또한번 = 사무실줄들(상태만들기({}, { 갈래: '쓰기' }, 7), 100);
  check('같은 값이면 같은 화면', 한번.join('\n') === 또한번.join('\n'));
}

