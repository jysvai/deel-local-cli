// 표에 없는 검사의 기본값(초). 아는 값들의 가운뎃값쯤으로, 모르는 것을 느린
// 쪽으로도 빠른 쪽으로도 심하게 치우치지 않게 둔다.
const 기본시간 = 2;
/*
 * 바닥은 0.1초다. 표는 0.1초 밑을 **0** 으로 적는데(검사 열세 개가 그렇다), 그런
 * 검사 하나에 걸린 어긋만 고른 판에서는 고른 몫이 0 이 되어 0÷0 = NaN 이 나왔고,
 * NaN 으로 자른 덩이가 **빈 배열**이 되어 조각 여덟이 전부 TypeError 로 죽었다
 * (2.0.1 릴리스 푸시 — README 어긋 하나, 짝 검사 shipmeta 0초). 전부 도는 판에서는
 * 몫이 커서 안 드러난다. 0초 검사도 노드를 한 번 띄우는 값은 치른다.
 */
const 한판시간 = (검사) => Math.max(0.1, Number.isFinite(검사시간[검사]) ? 검사시간[검사] : 기본시간);

const 조각내기 = (목록, 몇째, 몇) => {
  if (몇 <= 1) return 목록;
  const 덩이 = new Map();
  for (const x of 목록) {
    if (!덩이.has(x.검사)) 덩이.set(x.검사, []);
    덩이.get(x.검사).push(x);
  }
  // 덩이 하나의 값: 어긋마다 한 판씩 + 맨 것 한 판. 맨 판을 빼면 검사 하나에
  // 어긋이 한 개뿐인 덩이(맨 판이 값의 절반)를 너무 가볍게 센다.
  const 값 = (한덩이) => (한덩이.length + 1) * 한판시간(한덩이[0].검사);

  /*
   * ── 한 덩이가 조각 하나보다 크면 **갈라서** 나눈다 ────────────────────
   *
   * 덩이째 나누는 까닭은 맨 판을 한 번만 돌리기 위해서다. 그런데 그 규칙을
   * 끝까지 지키면 **제일 큰 덩이가 곧 관문 시간의 바닥**이 된다.
   * `oneshot.test.js` 가 어긋 54개 × 43.9초 = 40분이라, 시간으로 고르게 담아도
   * 한 조각이 40분이고 나머지 일곱은 18분에서 논다.
   *
   * 그래서 고른 몫(전체 ÷ 조각 수)보다 큰 덩이는 그 몫에 맞게 갈라 놓고 담는다.
   * 갈린 쪽마다 맨 판을 한 번씩 더 치르지만(위 `값` 이 +1 로 이미 센다),
   * 40분이 20분 둘로 갈리는 값이 훨씬 크다.
   */
  const 덩이들 = [...덩이.values()];
  const 고른몫 = 덩이들.reduce((a, d) => a + 값(d), 0) / 몇;
  const 담을것 = [];
  for (const 한덩이 of 덩이들) {
    const 갈래수 = Math.min(한덩이.length, Math.max(1, Math.ceil(값(한덩이) / 고른몫)));
    if (갈래수 <= 1) { 담을것.push(한덩이); continue; }
    // 고르게 자른다. `slice` 라 하나도 안 빠지고 겹치지도 않는다 —
    // 죽은규칙의 「조각을 다 합치면 전부를 덮는다」 가 이 자리를 지킨다.
    const 크기 = Math.ceil(한덩이.length / 갈래수);
    for (let i = 0; i < 한덩이.length; i += 크기) 담을것.push(한덩이.slice(i, i + 크기));
  }

  const 통 = Array.from({ length: 몇 }, () => ({ 셈: 0, 것: [] }));
  for (const 한덩이 of 담을것.sort((a, b) => 값(b) - 값(a))) {
    const 가장한가한 = 통.reduce((a, b) => (b.셈 < a.셈 ? b : a));
    가장한가한.셈 += 값(한덩이);
    가장한가한.것.push(...한덩이);
  }
  return 통[몇째 - 1].것;
};
