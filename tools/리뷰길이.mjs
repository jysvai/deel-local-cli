/**
 * 2차 리뷰가 **말이 길어서 통째로 버려지는** 자리.
 *
 * ── 무슨 일이 있었나 ────────────────────────────────────────────────────
 *
 * 일곱 판을 돌리는 동안 **네 번** 빈 손으로 돌아왔다. 그 중 셋이 같은
 * 까닭이었다 —
 *
 *     "error": "Your previous response was cut off because it exceeded
 *               the output token limit … Retries remaining: 3"
 *
 * 쪽지에 「최대 12건 · 한 건 네 줄」 이라고 못박아 뒀는데도 그랬다. 한국어로
 * 조리 있게 쓰면 그 한도 안에서도 출력 한도를 넘긴다. agy 는 제 나름대로 세
 * 번 다시 시도하고, 그래도 안 되면 아무것도 안 준다.
 *
 * ── 왜 그냥 두면 안 되나 ────────────────────────────────────────────────
 *
 * 빈 답은 **「지적할 것이 없다」 와 화면에서 똑같이 생겼다.** 이 저장소가
 * 되풀이해 고치는 부류(조용한 실패)이고, 도구가 그걸 그대로 갖고 있으면
 * 「2차 리뷰를 돌렸다」 는 말이 거짓이 된다. 사람은 초록을 보고 그 커밋을
 * 다 봤다고 믿고 넘어간다.
 *
 * ── 어떻게 하나 ─────────────────────────────────────────────────────────
 *
 * 길어서 버려졌으면 **짧게 다시 묻는다.** 사람이 손으로 다시 돌리는 것과
 * 같은 일인데, 그 사이에 사람이 자리를 뜨면 그 판은 영영 안 본 판이 된다.
 *
 * 두 번째 판은 건수와 줄수를 크게 줄인다. 열두 건을 못 받느니 다섯 건이라도
 * 받는 편이 낫다 — 어차피 사람이 한 번에 고치는 양은 그 언저리다.
 */

/**
 * 쪽지에 붙일 길이 규칙.
 *
 * @param {number} 판 1 이면 처음, 2 면 짧게 다시 묻는 판.
 * @returns {string[]} 쪽지에 그대로 이어 붙일 줄들.
 */
export function 길이규칙(판 = 1) {
  if (판 >= 2) {
    return [
      '',
      '앞 판은 말이 길어 답이 **통째로 버려졌다.** 이번엔 짧게 써라:',
      '  · 제일 위험한 것 **최대 5건**. 나머지는 버려라.',
      '  · 한 건은 **두 줄** — `파일:줄 · 한 문장 결함 · 심각도` 와 `재현 입력` 한 줄.',
      '  · 코드 조각·머리말·맺음말·요약을 쓰지 마라.',
      '  · 짧게 못 쓰겠으면 건수를 더 줄여라. 긴 답은 여기서 없는 답이다.',
    ];
  }
  return [
    '',
    '길이를 지켜라. 이걸 어기면 답이 통째로 버려진다:',
    '  · 심각한 것부터 **최대 12건**. 그 아래는 버려라.',
    '  · 한 건은 **네 줄 안**. 코드 조각은 한 줄을 넘기지 마라.',
    '  · 머리말·맺음말·요약표를 쓰지 마라. 발견만 죽 적어라.',
  ];
}

/**
 * 이 실패가 **길어서** 생긴 것인가. 그때만 짧게 다시 묻는다.
 *
 * 다른 까닭(도구 거절·연결 끊김·모델 없음)으로 빈 답이 온 것은 다시 물어도
 * 같은 자리에서 막힌다. 그때 또 부르면 시간만 두 배로 쓰고 화면에는 실패가
 * 두 번 찍힌다.
 *
 * `cut off` 를 맨낱말로 잡았더니 바로 그 자리가 뚫렸다(8차 리뷰) —
 * `connection cut off by peer` 가 걸려서, 망이 끊긴 판을 40분짜리 재시도로
 * 보냈다. 주석에는 안 그런다고 적어 놓고서다. **무엇이** 잘렸는지를 같이
 * 본다 — 여기서 잘린 것은 답이지 연결이 아니다.
 *
 * 낱말 하나를 앞에 두는 것으로는 모자랐다(9차 리뷰). `output` · `response`
 * 가 마흔 자 안에 있기만 하면 됐으니 —
 *
 *     "response stream cut off by peer"
 *     "the response connection was cut off by the proxy"
 *
 * 가 다시 걸렸다. 답이 잘렸다는 말은 **그 낱말이 바로 앞에 있는** 꼴이다
 * (`response was cut off` · `output truncated`). 사이에 다른 이름씨가
 * 끼면 잘린 것은 그 이름씨지 답이 아니다.
 *
 * @param {{status?: string, error?: unknown}|null} 끝맺음 agy 의 마지막 result 사건
 * @param {string} 답 받아 낸 글
 * @returns {boolean}
 */
export function 짧게다시할까(끝맺음, 답) {
  if (String(답 ?? '').trim()) return false;
  const 말 = String(끝맺음?.error ?? '');
  return /output token limit|exceeded the output|\b(?:output|response|answer)\s+(?:was\s+|is\s+|got\s+)?(?:cut off|truncated)\b/i.test(말);
}

/**
 * 한 판 돌리고, **길어서 버려졌으면** 짧게 한 판 더 돌린다.
 *
 * 판을 도는 자리를 여기로 뺀 까닭은 검사다. 앞 판은 위 두 함수만 재고
 * **그걸 쓰는 자리**는 안 쟀다 — review2.mjs 에서 재시도 토막을 통째로
 * 지워도 검사가 초록이었다(8차 리뷰). 모델을 부르는 일은 `한판` 이 하고
 * 여기는 판단만 하므로, 가짜 `한판` 을 넣으면 밖으로 안 나가고 잴 수 있다.
 *
 * @param {(판: number) => {r: any, 끝맺음: any, 답: string, 걸린초: number}} 한판
 * @param {(걸린초: number) => void} [알림] 다시 묻기 직전에 사람에게 할 말
 * @returns {{r: any, 끝맺음: any, 답: string, 걸린초: number, 두판: boolean}}
 */
export function 두판돌리기(한판, 알림) {
  const 첫판 = 한판(1);
  if (!짧게다시할까(첫판.끝맺음, 첫판.답)) return { ...첫판, 두판: false };
  알림?.(첫판.걸린초);
  const 둘째 = 한판(2);
  return { ...둘째, 걸린초: 첫판.걸린초 + 둘째.걸린초, 두판: true };
}
