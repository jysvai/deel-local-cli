/**
 * 2차 리뷰가 **말이 길어서 통째로 버려지는** 자리.
 *
 * ── 무슨 일이 있었나 ────────────────────────────────────────────────────
 *
 * 일곱 판을 돌리는 동안 **네 번** 빈 손으로 돌아왔다. 그 중 셋이 같은
 * 까닭이었다 —
 *
 *     "error": "Your previous response was cut off because it exceeded
 *               the output token limit … Retries remaining: 3"
 *
 * 쪽지에 「최대 12건 · 한 건 네 줄」 이라고 못박아 뒀는데도 그랬다. 한국어로
 * 조리 있게 쓰면 그 한도 안에서도 출력 한도를 넘긴다. agy 는 제 나름대로 세
 * 번 다시 시도하고, 그래도 안 되면 아무것도 안 준다.
 *
 * ── 왜 그냥 두면 안 되나 ────────────────────────────────────────────────
 *
 * 빈 답은 **「지적할 것이 없다」 와 화면에서 똑같이 생겼다.** 이 저장소가
 * 되풀이해 고치는 부류(조용한 실패)이고, 도구가 그걸 그대로 갖고 있으면
 * 「2차 리뷰를 돌렸다」 는 말이 거짓이 된다. 사람은 초록을 보고 그 커밋을
 * 다 봤다고 믿고 넘어간다.
 *
 * ── 어떻게 하나 ─────────────────────────────────────────────────────────
 *
 * 길어서 버려졌으면 **짧게 다시 묻는다.** 사람이 손으로 다시 돌리는 것과
 * 같은 일인데, 그 사이에 사람이 자리를 뜨면 그 판은 영영 안 본 판이 된다.
 *
 * 두 번째 판은 건수와 줄수를 크게 줄인다. 열두 건을 못 받느니 다섯 건이라도
 * 받는 편이 낫다 — 어차피 사람이 한 번에 고치는 양은 그 언저리다.
 */

/**
 * 쪽지에 붙일 길이 규칙.
 *
 * @param {number} 판 1 이면 처음, 2·3 이면 다시 묻는 판. 판이 늘수록 조인다.
 * @param {'길이'|'막힘'} 까닭 직전 판이 왜 빈 손이었나. 머리말만 이걸 탄다.
 * @returns {string[]} 쪽지에 그대로 이어 붙일 줄들.
 */
export function 길이규칙(판 = 1, 까닭 = '길이') {
  if (판 < 2) {
    return [
      '',
      '길이를 지켜라. 이걸 어기면 답이 통째로 버려진다:',
      '  · 심각한 것부터 **최대 12건**. 그 아래는 버려라.',
      '  · 한 건은 **네 줄 안**. 코드 조각은 한 줄을 넘기지 마라.',
      '  · 머리말·맺음말·요약표를 쓰지 마라. 발견만 죽 적어라.',
    ];
  }
  return ['', ...왜또묻나(까닭), ...얼마나조이나(판)];
}

/*
 * ── 왜 잃었나와 몇 판 잃었나는 따로다 ──────────────────────────────────
 *
 * 한 덩이로 묶어 뒀더니 **섞인 판에서 한쪽이 통째로 빠졌다** — 첫 판을
 * 길이로 잃고 둘째 판을 도구로 잃으면, 셋째 판이 「도구 얘기」 만 받고
 * 3건·한 줄 조이기를 못 받았다(23차 리뷰). 셋째 판은 마지막 판이라
 * 조이기가 빠지면 또 길이로 잃는다.
 *
 * 그래서 머리말은 **직전 판이 왜 죽었나**, 조이기는 **여태 몇 판을
 * 잃었나**로 나눠서 각자 고른다.
 */

/**
 * 직전 판이 왜 빈 손이었는지 — 다시 묻는 말의 **머리**다.
 *
 * 머리만 까닭을 탄다. 조이기는 **몇 판 잃었느냐**로만 정하므로 막힌 판에도
 * 그대로 붙는다 — 마지막 판이 조이기를 못 받으면 그 판마저 길이로 잃기
 * 때문이다(23차 리뷰). 그래서 막힌 판 쪽지에도 건수 얘기가 같이 들어간다.
 */
const 왜또묻나 = (까닭) => (까닭 === '막힘'
  ? [
    '앞 판은 도구를 쓰려다 거절당하고 **거기서 멈췄다.** 이 판에서는 도구가',
    '하나도 안 열린다 — 열릴 때까지 기다리지 마라.',
    '  · 위 diff 만 보고 아는 만큼 적어라. 파일을 안 봐도 아는 것이 있다.',
    '  · 못 본 자리는 「못 봤다」 고 한 줄 적고 넘어가라.',
  ]
  : ['앞 판은 말이 길어 답이 **통째로 버려졌다.**']);

/*
 * 셋째 판. 둘째 판(5건·두 줄)도 넘긴 커밋이 있었다 — 19차 리뷰에서
 * 3.8KB 짜리 diff 하나를 두 판 다 잃었다. 들어간 것이 작아도 나오는
 * 말이 길면 똑같이 버려진다. 그때는 **건수를 더 줄이는 수밖에 없다.**
 */
const 얼마나조이나 = (판) => (판 >= 3
  ? [
    '두 판을 잃었다. 이번이 마지막이다 — 이보다 짧게 못 쓰면 아무것도 못 남긴다:',
    '  · 제일 위험한 것 **최대 3건**. 하나만 확실해도 그 하나만 적어라.',
    '  · 한 건은 **한 줄** — `파일:줄 · 결함 · 재현 입력`. 그 밖은 아무것도 쓰지 마라.',
    '  · 설명·근거·코드 조각을 쓰지 마라. 짧게 못 쓰겠으면 건수를 줄여라.',
  ]
  : [
    '이번엔 짧게 써라:',
    '  · 제일 위험한 것 **최대 5건**. 나머지는 버려라.',
    '  · 한 건은 **두 줄** — `파일:줄 · 한 문장 결함 · 심각도` 와 `재현 입력` 한 줄.',
    '  · 코드 조각·머리말·맺음말·요약을 쓰지 마라.',
    '  · 짧게 못 쓰겠으면 건수를 더 줄여라. 긴 답은 여기서 없는 답이다.',
  ]);

/**
 * 이 실패가 **길어서** 생긴 것인가. 그때만 짧게 다시 묻는다.
 *
 * 다른 까닭(도구 거절·연결 끊김·모델 없음)으로 빈 답이 온 것은 다시 물어도
 * 같은 자리에서 막힌다. 그때 또 부르면 시간만 두 배로 쓰고 화면에는 실패가
 * 두 번 찍힌다.
 *
 * `cut off` 를 맨낱말로 잡았더니 바로 그 자리가 뚫렸다(8차 리뷰) —
 * `connection cut off by peer` 가 걸려서, 망이 끊긴 판을 40분짜리 재시도로
 * 보냈다. 주석에는 안 그런다고 적어 놓고서다. **무엇이** 잘렸는지를 같이
 * 본다 — 여기서 잘린 것은 답이지 연결이 아니다.
 *
 * 낱말 하나를 앞에 두는 것으로는 모자랐다(9차 리뷰). `output` · `response`
 * 가 마흔 자 안에 있기만 하면 됐으니 —
 *
 *     "response stream cut off by peer"
 *     "the response connection was cut off by the proxy"
 *
 * 가 다시 걸렸다. 답이 잘렸다는 말은 **그 낱말이 바로 앞에 있는** 꼴이다
 * (`response was cut off` · `output truncated`). 사이에 다른 이름씨가
 * 끼면 잘린 것은 그 이름씨지 답이 아니다.
 *
 * 10차 리뷰가 그 사이로 하나 더 넣었다 — 끼는 이름씨가 **없는** 꼴이다.
 *
 *     "response cut off by peer"       "answer truncated by remote"
 *
 * 앞이 아니라 **뒤**를 봐야 하는 자리다. `by peer` · `by the proxy` ·
 * `ECONNRESET` 은 누가 끊었는지를 말한다. 그러니 무엇이 잘렸는지를 재기
 * 전에, 끊은 쪽이 적혀 있으면 그 판은 망이다.
 *
 * 반대쪽으로는 무늬가 너무 좁았다. 낱말 사이를 빈칸으로만 봐서
 * `output: truncated` · `output (truncated)` 를 놓쳤고, `the` 를 박아 둬서
 * `exceeded output limit` 도 놓쳤다. 관사는 늘 붙는 것이 아니다.
 *
 * ── 답이 조금이라도 왔으면 다시 안 묻는다 ───────────────────────────────
 *
 * 잘린 채로도 발견이 몇 건 들어 있는 답이 있다. 그걸 버리고 40분을 더
 * 쓰는 것보다 있는 것을 쓰는 편이 낫다 — 여기서 막는 것은 **빈 답**이
 * 조용히 「지적할 것이 없다」 로 보이는 자리다. 그래서 첫 줄은 까닭을
 * 보기 전에 답부터 본다. 이건 고장이 아니라 **정해 둔 것**이다.
 *
 * @param {{status?: string, error?: unknown}|null} 끝맺음 agy 의 마지막 result 사건
 * @param {string} 답 받아 낸 글
 * @returns {boolean}
 */
export function 짧게다시할까(끝맺음, 답) {
  return 왜다시(끝맺음, 답) === '길이';
}

/**
 * 다시 물어야 하면 **왜** 인지 돌려준다 — `'길이'` · `'막힘'` · `false`.
 *
 * 다시 묻는 까닭이 하나가 아니다. 여태는 「길어서 잘렸다」 만 다시 물었고,
 * **도구가 거절당해 멈춘 판은 한 번 부르고 버렸다.** 눈금을 재 보니 같은
 * diff 를 다섯 번 돌렸을 때 길이초과와 도구거절이 각각 한 번씩 났다 —
 * 둘 다 빈 손으로 끝나는데 한쪽만 다시 물었다(22차 눈금).
 *
 * 까닭에 따라 다시 묻는 말이 달라야 한다. 도구를 거절당한 판에 대고
 * 「더 짧게 써라」 라고 하면 엉뚱한 소리다.
 */
export function 왜다시(끝맺음, 답) {
  /*
   * 답이 조금이라도 왔으면 **안 묻는다.** 이건 가르기와 다른 물음이다 —
   * 잘린 답에도 발견이 들었으니 그걸 쓰는 편이 낫다(정해 둔 것). 갈래를
   * 한 자리로 모으면서 이 줄을 잃었고, 검사가 그 자리에서 잡았다(26차).
   */
  if (String(답 ?? '').trim()) return false;
  const 갈래 = 실패갈래(끝맺음, 답);
  if (갈래 === '길이초과') return '길이';
  if (갈래 === '도구거절') return '막힘';
  return false;
}

/**
 * 한 판이 어떻게 끝났는지 **한 낱말**로 가른다.
 *
 * `'성공' · '길이초과' · '도구거절' · '망끊김' · '그밖에'`
 *
 * 이 가르기를 두 벌 두면 반드시 어긋난다. 실제로 눈금(`리뷰눈금.mjs`)이
 * 제 무늬를 따로 갖고 있었고, 셋이 다 도구 쪽보다 좁았다 — `finish_reason:
 * length` 도, `denied` 홀로도, `by peer` 도 못 알아보고 「그밖에」 로
 * 뭉갰다(26차 리뷰). **재는 쪽이 재이는 쪽보다 덜 보면 그 표는 거짓말이다.**
 *
 * 그래서 가르는 자리는 여기 하나뿐이다. 눈금도 이걸 불러 쓴다.
 */
export function 실패갈래(끝맺음, 답) {
  if (String(답 ?? '').trim() && 끝맺음?.status === 'SUCCESS') return '성공';
  const 칸들 = 까닭칸들(끝맺음);
  if (칸들.some((칸) => 망끊김.test(칸))) return '망끊김';
  if (칸들.some((칸) => 길이초과.test(칸))) return '길이초과';
  if (칸들.some((칸) => 도구막힘.test(칸))) return '도구거절';
  return String(답 ?? '').trim() ? '성공' : '그밖에';
}

/**
 * 도구를 쓰려다 거절당하고 **거기서 멈춘** 판.
 *
 * 쪽지에 「도구를 쓰지 마라, 거절당해도 멈추지 말고 적어라」 라고 적어
 * 뒀는데도 모델이 그냥 멈춘다. `--mode plan` 이 원래 저장소를 뒤지라고
 * 있는 모드라 계속 부딪힌다. 쪽지로는 못 막으니 **다시 묻는 쪽**으로 푼다.
 *
 * 거절 말이 따옴표를 달고 오리라고 믿지 않는다 — `required the "command"
 * permission` 만 보게 했더니 따옴표 없는 꼴(`required the read_file
 * permission`)과 짧은 꼴(`RunCommand was denied`)이 그대로 샜다(23차 리뷰).
 *
 * 넓게 잡는 쪽으로 기운다. **틀려도 값이 다르기 때문이다** — 아닌 것을
 * 막힘으로 보면 두 판 더 부르고 끝나지만, 막힌 것을 놓치면 그 판은 통째로
 * 없어진다. 사이를 `[^.]` 로 뒀더니 `file.read permission` 처럼 점 찍힌
 * 권한 이름이 빠져서, 줄바꿈만 빼고 받는다(24차 리뷰).
 */
const 도구막힘 = /\bno output produced\b|\brequired the\b[^\n]{0,60}?\bpermission\b|\bpermission that headless mode\b|\b(?:auto-)?denied\b/i;

/**
 * 「길어서 잘렸다」 를 알리는 말은 하나가 아니다.
 *
 * agy 는 사람 말로 적어 주지만(`exceeded the output token limit`), 밑에
 * 깔린 API 는 마침 까닭을 낱말로 준다 — `finishReason: MAX_TOKENS`,
 * `finish_reason: length`. 그 둘을 못 알아보면 짧게 다시 묻지도 않고
 * 화면에는 「쪼개서 보라」 만 남는다(20차 리뷰).
 *
 * 낱말은 **꼬리가 붙어서** 오기도 한다. `MAX_TOKENS` 뒤에 `\b` 를 박았더니
 * `MAX_TOKENS_EXCEEDED` 가 빠졌다 — 밑줄은 낱말 경계가 아니다. 그리고
 * `context_length_exceeded` 는 오픈AI 가 실제로 주는 오류 이름인데
 * `length` 앞에 말이 붙어 어느 갈래에도 안 걸렸다(27차 리뷰).
 *
 * `length` 는 홀로 두면 넓다(`content length` · `array length`). 까닭을
 * 적는 자리와 붙어 있을 때만 본다 — 그 자리 이름이 `finish` 든 `done` 이든
 * `stop` 이든. **그래서 `까닭칸들` 이 자리 이름을 같이 실어 보낸다** —
 * 값만 이으면 `length` 가 홀로 남아, 옆에 `error` 하나만 더 있어도
 * 못 알아본다(22차 리뷰). (`끝난까닭` 은 그 칸들을 화면용으로 한 줄에
 * 잇기만 한다 — 재는 데는 안 쓴다.)
 *
 * 값이 `length` 로 **시작**하면 그 칸은 길이다(`^[A-Za-z_]+:\s*length\b`).
 * 끝을 `$` 로 막았더니 `error: 'length exceeded'` 처럼 뒤에 말이 붙은 꼴이
 * 빠졌다(26차 리뷰). 이름을 싣기 전에는 `^length$` 가 하던
 * 일인데, 이름을 실으면서 그 무늬만 지우고 새 꼴을 안 넣어 `error:
 * 'length'` 가 한동안 샜다(23차 리뷰). `content length` 처럼 앞에 말이
 * 붙은 것은 여전히 안 잡는다 — 자리 이름 바로 뒤여야 한다.
 *
 * **이 앵커가 한 칸을 가리킨다**(`까닭칸들`). 이어 붙인 글에 걸면 자리가
 * 둘만 돼도 `$` 가 안 맞아 또 샌다 — 24차에서 그렇게 한 번 더 샜다.
 */
const 길이초과 = /output token limit|exceeded\s+(?:the\s+)?output|\b(?:output|response|answer)[\s:(-]+(?:was\s+|is\s+|got\s+)?(?:cut off|truncated)\b|\bMAX_TOKENS|\bcontext_length_exceeded\b|\b(?:finish|done|stop)(?:_|\s*)reason[\s:="'-]*(?:max_tokens|length)\b|^[A-Za-z_]+:\s*length\b/i;

/**
 * 끝맺음에서 **까닭이 적힌 자리**를 다 긁는다.
 *
 * agy 는 사람 말로 `error` 에 적어 준다. 그런데 밑에 깔린 것이 무엇이냐에
 * 따라 까닭이 **속성 이름**으로 올라오기도 한다 — `finishReason`(제미나이),
 * `finish_reason`(오픈AI 꼴), `done_reason`(오라마). 하나만 보면 나머지는
 * 못 알아보고, 못 알아보면 짧게 다시 묻지도 않는다(21차 리뷰).
 *
 * 끝맺음을 통째로 글자로 만들지는 않는다 — 거기엔 모델이 쓴 **답**도 들어
 * 있어서, 답 안에 `MAX_TOKENS` 라고 적힌 판을 잘린 것으로 오해한다.
 * 까닭이 적히는 자리만 골라 본다.
 *
 * **자리 이름을 값에 붙여서 낸다**(`finish_reason: length`). 값만 이으면
 * `length` 가 무엇의 `length` 인지 사라져서, 무늬가 `^length$` 로만 잡을
 * 수 있게 된다 — 그러면 `{error: '…', finish_reason: 'length'}` 처럼
 * 자리가 둘만 돼도 못 알아보고 판을 통째로 잃는다(22차 리뷰).
 */
/*
 * 까닭이 적히는 자리들. `status` 도 자리다 — 밑에 깔린 것에 따라 까닭이
 * 상태 한 칸으로만 오기도 한다(`{status: 'MAX_TOKENS'}`). 그 판은
 * `까닭칸들` 이 빈 배열이 돼서 다시 묻지도 않고 끝났다(26차 리뷰).
 * `status: ERROR` 처럼 뜻 없는 값은 어느 무늬에도 안 걸리므로 해롭지 않다.
 */
const 까닭자리 = ['status', 'error', 'reason', 'finishReason', 'finish_reason',
  'doneReason', 'done_reason', 'stopReason', 'stop_reason'];

export /**
 * 끝맺음에 적힌 까닭을 **칸마다 따로** 낸다. 이어 붙이지 않는다.
 *
 * 이어 붙인 글 하나를 재려니 같은 실수를 세 판 내리 했다 — 값만 이으면
 * 자리 이름이 사라지고(22차), 이름을 실으면 `^length$` 가 안 맞고(23차),
 * 새 앵커를 넣었더니 자리가 둘일 때 또 안 맞았다(24차). 무늬를 고칠 때마다
 * **이어 붙인다**는 전제가 그대로 남아 있어서 그랬다.
 *
 * 그래서 칸을 쪼갠 채로 잰다. `^...$` 가 한 칸을 가리키게 되니 앵커가
 * 옆 칸 때문에 무너지는 부류가 통째로 없어진다.
 */
const 까닭칸들 = (끝맺음) => 까닭자리
  .map((이름) => [이름, 끝맺음?.[이름]])
  .map(([이름, 값]) => [이름, 글자로(값)])
  .filter(([, 값]) => 값 !== '')
  .map(([이름, 값]) => `${이름}: ${값}`);

/**
 * 까닭 자리에 글자가 아닌 것이 들어 있을 수도 있다.
 *
 * `String({message: '…'})` 는 `[object Object]` 다 — 무늬가 조용히
 * 빗나가고, 빈 답으로 끝난 판을 「까닭을 모르겠다」 로 넘긴다(24차 리뷰).
 * 오류를 객체로 주는 SDK 가 흔하다.
 *
 * 여기 오는 것은 **까닭 자리뿐**이라(`response` 는 `까닭자리` 에 없다)
 * 통째로 글자로 만들어도 모델이 쓴 답을 긁을 일이 없다.
 */
const 글자로 = (값) => {
  if (값 == null) return '';
  if (typeof 값 === 'string') return 값.trim();
  if (typeof 값 === 'object') {
    const 속 = 값.message ?? 값.reason ?? 값.error;
    if (typeof 속 === 'string') return 속.trim();
    try { return JSON.stringify(값).slice(0, 500); } catch { return ''; }
  }
  return String(값).trim();
};

/** 화면에 적을 때는 이어 붙인 한 줄이 읽기 좋다. 재는 데는 안 쓴다. */
export const 끝난까닭 = (끝맺음) => 까닭칸들(끝맺음).join(' · ');

/** 끊은 쪽이 적혀 있으면 그 판은 답이 아니라 망이 잘린 것이다. */
const 망끊김 = /\bby\s+(?:the\s+)?(?:peer|proxy|remote|server|client|gateway)\b|\bECONN(?:RESET|ABORTED|REFUSED)\b|\bEPIPE\b|\bsocket\s+hang\s+up\b/i;

/**
 * 한 판 돌리고, **길어서 버려졌으면** 더 짧게 다시 묻기를 되풀이한다.
 *
 * 여태 두 판이었다. 그런데 둘째 판(5건·두 줄)도 넘기는 커밋이 있었다 —
 * 19차 리뷰에서 3.8KB 짜리 diff 하나를 두 판 다 잃고 아무것도 못 남겼다.
 * 셋째 판(3건·한 줄)까지 간다. **한 건이라도 받는 것이 낫다.**
 *
 * 판을 도는 자리를 여기로 뺀 까닭은 검사다. 앞 판은 위 두 함수만 재고
 * **그걸 쓰는 자리**는 안 쟀다 — review2.mjs 에서 재시도 토막을 통째로
 * 지워도 검사가 초록이었다(8차 리뷰). 모델을 부르는 일은 `한판` 이 하고
 * 여기는 판단만 하므로, 가짜 `한판` 을 넣으면 밖으로 안 나가고 잴 수 있다.
 *
 * @param {(판: number) => {r: any, 끝맺음: any, 답: string, 걸린초: number}} 한판
 * @param {(걸린초: number, 다음판: number) => void} [알림] 다시 묻기 직전에 할 말
 * @param {number} [끝판] 몇 판까지 갈까 (기본 3)
 * @returns {{r: any, 끝맺음: any, 답: string, 걸린초: number, 두판: boolean, 몇판: number}}
 */
export function 두판돌리기(한판, 알림, 끝판 = 3) {
  let 이번 = 한판(1);
  let 쌓인초 = 이번.걸린초;
  let 판 = 1;
  let 까닭 = 왜다시(이번.끝맺음, 이번.답);
  while (판 < 끝판 && 까닭) {
    판 += 1;
    알림?.(쌓인초, 판, 까닭);
    이번 = 한판(판, 까닭);
    쌓인초 += 이번.걸린초;
    까닭 = 왜다시(이번.끝맺음, 이번.답);
  }
  return { ...이번, 걸린초: 쌓인초, 두판: 판 > 1, 몇판: 판 };
}

/**
 * 빈 손으로 돌아왔을 때 **이 판에서 실제로 줄일 수 있는 것**을 짚어 준다.
 *
 * 여태 「`--files` 로 쪼개 보라」 고만 했다. 그런데 이미 `--files` 로 파일
 * 하나를 준 판에서는 그게 할 수 있는 말이 아니다 — 19차 리뷰를 그렇게
 * 한 판 잃고, 화면에는 쪼갤 수 없는 방법만 남았다.
 *
 * 답이 잘린 것이면 **잘렸다고 말한다.** 「빈 채로 돌아왔다」 와 「길어서
 * 잘렸다」 는 사람이 할 일이 다르다.
 *
 * @param {object} 판
 * @param {string} 판.무엇   화면 머리에 찍은 말 (`파일 1개 · a..b` 꼴)
 * @param {string} 판.까닭   끝맺음 오류와 표준오류를 이어 붙인 것
 * @param {string} [판.부터] `--since`
 * @param {string} [판.까지] `--to`
 * @returns {string[]} 화면에 한 줄씩 찍을 말
 */
export function 줄일말({ 무엇 = '', 까닭 = '', 부터 = '', 까지 = '' }) {
  const 넘침 = 길이초과.test(까닭) || /too long/i.test(까닭);
  const 파일하나 = /파일 1개/.test(무엇);
  const 말 = [`다시 해 보려면: node tools/review2.mjs --timeout 90m`];
  if (!넘침) {
    말.push(`쪼개서 보려면: node tools/review2.mjs ${부터 ? `--since ${부터} --to ${까지} ` : ''}--files <파일 몇 개>`);
    return 말;
  }
  말.push('답이 길어서 잘렸습니다 — 볼 것을 줄여야 합니다:');
  if (!파일하나) 말.push('  · 파일을 나눠서 — --files <파일 한둘>');
  말.push(`  · 판을 좁혀서 — --since <한 판 앞> --to <그 판>${부터 ? ` (지금은 ${부터}..${까지})` : ''}`);
  if (파일하나) 말.push('  · 파일이 이미 하나입니다. 그래도 잘리면 그 파일이 한 판에 보기엔 큽니다.');
  return 말;
}
