const git = (...args) => spawnSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

/** 무엇을 보일 것인가. 아무것도 안 바뀌었으면 그렇다고 말하고 끝낸다. */
function 볼것() {
  /*
   * ── 옵션이 어긋났을 때는 고르지 말고 멈춘다 ──────────────────────────
   *
   * 3차 리뷰가 셋을 짚었다. 셋 다 한 가지 탈이다 — **조용히 다른 것을 본다.**
   *
   *   · `--to` 만 주면 아래 `if (부터)` 에 안 걸려 통째로 무시되고, 화면에는
   *     「아직 커밋 안 한 것」 이라고 적힌 채 엉뚱한 것이 리뷰로 나간다.
   *   · `--files` 갈래가 먼저 돌아가서, `--files` 와 범위를 같이 주면
   *     범위가 소리 없이 사라진다.
   *
   * 리뷰 도구가 엉뚱한 자리를 리뷰하는 것은 안 도는 것보다 나쁘다. 사람은
   * 초록을 보고 그 자리를 다 봤다고 믿고 넘어간다. 그래서 조용히 하나를
   * 고르는 대신, 멈춰서 되묻는다.
   */
  if (있나('--to') && !부터) {
    console.error('\n\x1b[31m✗ --to 는 --since 와 같이 써야 합니다\x1b[0m');
    console.error(`  어디부터인지가 없습니다. 예: --since HEAD~3 --to ${까지}\n`);
    process.exit(2);
  }
  const i = 인자.indexOf('--files');
  if (i >= 0) {
    /*
     * 다음 `--` 에서 **멈춘다.** 걸러 내기만 하면 그 옵션의 **값**이 파일
     * 목록에 남는다 — `--files a.js --out 보고.md` 에서 `--out` 은 빠지고
     * `보고.md` 가 파일로 들어간다. 2차 리뷰가 짚은 자리다.
     *
     * 재 봤더니 git 은 여기서 **안 죽는다.** 안 맞는 경로는 그냥 아무것도
     * 안 내놓는다. 그래서 더 나쁘다 — 아무 말 없이 남의 파일이 리뷰 거리에
     * 섞이거나(그 이름의 파일이 진짜 있으면), 조용히 빠진다.
     * 죽을 때를 대비해 종료코드도 같이 본다.
     */
    const 파일들 = [];
    for (const x of 인자.slice(i + 1)) {
      if (x.startsWith('-')) break;
      파일들.push(x);
    }
    /*
     * 하나도 안 남으면 **여기서 멈춘다.** 그냥 두면 `git diff HEAD --` 가
     * 되어 **저장소 전체**가 나오는데, 화면에는 「파일 0개」 라고 적힌다 —
     * 몇 개를 콕 집었다고 믿는 사람에게 통째로 보여 주는 꼴이다.
     * 2차 리뷰가 짚었다.
     */
    if (!파일들.length) {
      console.error('\n\x1b[31m✗ --files 뒤에 파일이 없습니다\x1b[0m');
      console.error('  그냥 두면 저장소 전체가 나갑니다. 전체를 보려면 --files 를 빼세요.\n');
      process.exit(2);
    }
    /*
     * 범위를 같이 주면 그 범위 안에서 그 파일만 본다(12차 리뷰). 한 판이
     * 출력 한도에 걸렸을 때 도구가 내놓던 「쪼개서 보라」 는 말이, 여태
     * 커밋된 판에는 쓸 수가 없었다 — `--files` 가 늘 안 올린 것만 봤다.
     */
    const 범위 = 부터 ? `${부터}..${까지}` : 'HEAD'
    const r = git('diff', 범위, '--', ...파일들);
    if (r.status !== 0) {
      console.error(`\n\x1b[31m✗ 그 파일들을 못 읽었습니다\x1b[0m\n  ${String(r.stderr ?? '').trim().split('\n')[0]}\n`);
      process.exit(2);
    }
    /*
     * 빈 diff 는 두 가지 뜻이다 — 「안 바뀌었다」 와 「이름을 잘못 적었다」.
     * git 은 둘을 구별해 주지 않으므로(안 맞는 경로에도 0 으로 끝난다) 우리가
     * 이름을 되읊어 준다. 잘못 적은 사람이 그 자리에서 알아본다.
     */
    if (!r.stdout.trim()) {
      console.log(`\n볼 것이 없습니다 — 이 파일들에 바뀐 자리가 없습니다.\n  ${파일들.join('\n  ')}`);
      console.log('\x1b[90m  (이름을 잘못 적어도 똑같이 보입니다 — 위 이름을 한 번 보세요)\x1b[0m\n');
      process.exit(0);
    }
    return { 무엇: 부터 ? `파일 ${파일들.length}개 · ${범위}` : `파일 ${파일들.length}개`, diff: r.stdout };
  }
  if (부터) {
    /*
     * 범위가 비었는데도 그대로 보내고 있었다 — 빈 몸통으로 모델을 부르면
     * 돈과 시간만 쓰고 「지적할 것 없음」 이 돌아온다. 사람은 그걸 **다 봤는데
     * 깨끗하다** 로 읽는다. 파일 갈래는 이미 이렇게 막고 있었는데 여기만
     * 안 막혀 있었다 — 같은 도구 안에서 두 갈래가 서로 달랐다.
     */
    const 사이 = git('diff', `${부터}..${까지}`).stdout;
    if (!사이.trim()) {
      console.log(`\n볼 것이 없습니다 — ${부터}..${까지} 사이에 바뀐 자리가 없습니다.\n`);
      process.exit(0);
    }
    return { 무엇: `${부터}..${까지}`, diff: 사이 };
  }
  const 안커밋 = git('diff', 'HEAD').stdout;
  if (안커밋.trim()) return { 무엇: '아직 커밋 안 한 것', diff: 안커밋 };
  return { 무엇: '마지막 판(HEAD~1..HEAD)', diff: git('diff', 'HEAD~1..HEAD').stdout };
}

