// 모델 답을 사람이 읽는 모양으로 그린다.
//
// ── 왜 만드나 ───────────────────────────────────────────────────────────
//
// 여태 답을 **글자 그대로** 찍었다. 모델은 마크다운으로 말하는데 화면은 그걸
// 모르니, 실제로 이렇게 보였다.
//
//   ▌ ## 고친 것
//   ▌ **src/runner.js** 의 `console.log` 를 바꿨습니다.
//   ▌ - 로그 형식 통일
//   ▌ ```js
//   ▌ log.info('x')
//   ▌ ```
//
// 별표와 백틱과 우물정자가 글에 섞여 눈이 걸린다. 무엇이 제목이고 무엇이
// 코드인지 사람이 머릿속에서 다시 파싱해야 한다. 답이 길수록 심해진다.
//
// ── 왜 줄 단위인가 ─────────────────────────────────────────────────────
//
// 답은 토막토막 흘러온다. `**굵` 까지 왔을 때는 그게 굵은 글씨가 될지 알 수 없다.
// 한 번 찍은 글자는 되돌릴 수 없으니, **줄이 끝나야** 그릴 수 있다.
//
// 그런데 줄이 안 끝나면? 긴 문단 하나가 통째로 한 줄이면 몇 초 동안 화면에
// 아무것도 안 나온다 — 사람 눈에는 멈춘 것으로 보인다. 그래서 한 줄이 화면 폭을
// 넘게 길어지면 거기까지를 **날것 그대로** 흘려보낸다. 모양은 못 내지만 글은
// 계속 흐른다. 모양보다 '살아 있다' 가 먼저다.
//
// 실제로는 제목·목록·코드펜스가 다 짧은 줄이라 거의 다 그려진다. 안 그려지는
// 것은 긴 산문뿐인데, 산문은 원래 꾸밀 것이 없다.
import { c, width } from './ansi.js';
import { 접어쓰기 } from './wrap.js';

const 굵게 = (s) => c.bold(s);
const 코드 = (s) => c.hyellow(s);

// 줄 전체를 흐리게 할 때 쓴다.
//
// 그냥 c.gray() 로 감싸면 안 된다. 안쪽 꾸밈(링크·코드)이 제 색을 끝내면서
// 리셋을 남기는데, 그 리셋이 바깥 흐림까지 같이 꺼 버린다 — 한 줄이 반만
// 흐려 보인다. 그래서 안쪽이 색을 끝낼 때마다 흐림을 다시 켠다.
const 회색앞 = c.gray('·').replace(/·[\s\S]*$/, '');
const 이어흐리게 = (s) => c.gray(String(s).replace(/\x1b\[0m/g, `\x1b[0m${회색앞}`));

// 굵게도 같은 문제를 겪는다 — 칸 안의 코드가 색을 끝내면서 굵기까지 꺼 버린다.
const 굵게앞 = c.bold('·').replace(/·[\s\S]*$/, '');
const 이어굵게 = (s) => c.bold(String(s).replace(/\x1b\[0m/g, `\x1b[0m${굵게앞}`));

/**
 * 한 줄 안쪽 꾸밈. `코드` → **굵게** → *기울임* → ~~취소~~ → [글](주소) 차례.
 *
 * 코드부터 하는 이유: 코드 안에 별표가 들어 있으면(`a ** b`) 굵게 처리가 먼저
 * 먹어서 코드가 깨진다. 먼저 뽑아서 자리표시자로 빼 두고 맨 끝에 되돌린다.
 */
export function 인라인(글) {
  // 들어온 NUL 은 먼저 버린다. 아래에서 코드 조각을 빼 둘 때 NUL 을 자리표시자로
  // 쓰는데, 답에 NUL 이 섞여 오면(도구가 읽은 바이너리를 되읊는 경우) 그것이
  // 자리표시자로 읽혀 엉뚱한 글자로 바뀐다 — 모델이 한 말과 화면이 달라진다.
  let s = String(글 ?? '').replace(/\x00/g, '');
  const 뺀것 = [];
  s = s.replace(/`([^`]+)`/g, (_, 안) => {
    뺀것.push(코드(안));
    return `\x00${뺀것.length - 1}\x00`;
  });

  s = s.replace(/\*\*([^*]+)\*\*/g, (_, 안) => 굵게(안));
  s = s.replace(/(^|[\s(])\*([^*\s][^*]*)\*(?=$|[\s.,)])/g, (_, 앞, 안) => `${앞}${c.italic(안)}`);
  s = s.replace(/~~([^~]+)~~/g, (_, 안) => c.gray(안));
  // 링크는 글만 보이고 주소는 흐리게. 주소를 지우면 따라갈 수가 없다.
  s = s.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, 글자, 주소) => `${c.under(글자)} ${c.gray(주소)}`);

  return s.replace(/\x00(\d+)\x00/g, (_, i) => 뺀것[Number(i)]);
}

/**
 * 줄 하나를 그린다.
 *
 * @param {string} 줄
 * @param {object} 상태  {펜스: boolean} — 코드 블록 안인가
 * @param {number} 폭
 * @returns {{글: string, 상태: object}}
 */
export function 한줄(줄, 상태 = { 펜스: false }, 폭 = 80) {
  // 줄 끝의 \r 를 먼저 뗀다. 서버가 \r\n 으로 흘려보내면 여기까지 딸려 오는데,
  // 아래 정규식들이 다 `(.*)$` 로 끝나고 `.` 은 \r 를 안 먹는다 — 그래서 제목도
  // 목록도 하나도 안 잡히고 별표와 우물정자가 그대로 화면에 뜬다.
  const s = String(줄 ?? '').replace(/\r+$/, '');

  // 코드 울타리. 여는 줄에 언어가 붙어 있으면 그걸 알려 준다.
  const 울타리 = s.match(/^\s*```(.*)$/);
  if (울타리) {
    const 안쪽 = 울타리[1].trim();
    return {
      글: 상태.펜스 ? c.gray('└' + '─'.repeat(Math.max(2, Math.min(30, 폭 - 6))))
        : c.gray('┌' + '─'.repeat(Math.max(2, Math.min(30, 폭 - 6))) + (안쪽 ? ` ${안쪽}` : '')),
      상태: { ...상태, 펜스: !상태.펜스 },
    };
  }

  // 코드 안에서는 아무것도 해석하지 않는다. 별표는 별표고 우물정자는 우물정자다.
  if (상태.펜스) return { 글: `${c.gray('│')} ${c.white(s)}`, 상태 };

  // 가로줄
  if (/^\s*([-*_])\s*\1\s*\1[\s\-*_]*$/.test(s)) {
    return { 글: c.gray('─'.repeat(Math.max(4, Math.min(40, 폭 - 6)))), 상태 };
  }

  // 제목. 굵기와 색으로 가른다 — 우물정자를 남기면 그게 제일 먼저 눈에 띈다.
  const 제목 = s.match(/^(#{1,6})\s+(.*)$/);
  if (제목) {
    const 깊이 = 제목[1].length;
    const 글자 = 인라인(제목[2]);
    if (깊이 <= 2) return { 글: `${c.hcyan('▍')} ${c.bold(글자)}`, 상태 };
    return { 글: c.bold(글자), 상태 };
  }

  // 인용
  const 인용 = s.match(/^\s*>\s?(.*)$/);
  if (인용) return { 글: `${c.gray('│')} ${이어흐리게(인라인(인용[1]))}`, 상태 };

  // 할 일 목록은 목록보다 먼저 본다 — `- [ ]` 가 그냥 목록으로 먹히면 안 된다.
  const 할일 = s.match(/^(\s*)[-*+]\s+\[([ xX])\]\s+(.*)$/);
  if (할일) {
    const 표 = 할일[2] === ' ' ? c.gray('☐') : c.green('☑');
    return { 글: `${할일[1]}${표} ${인라인(할일[3])}`, 상태 };
  }

  // 글머리표
  const 목록 = s.match(/^(\s*)[-*+]\s+(.*)$/);
  if (목록) return { 글: `${목록[1]}${c.hcyan('•')} ${인라인(목록[2])}`, 상태 };

  // 번호 목록. 번호는 살린다 — 순서가 뜻을 갖는 자리다.
  const 번호 = s.match(/^(\s*)(\d+)([.)])\s+(.*)$/);
  if (번호) return { 글: `${번호[1]}${c.hcyan(번호[2] + 번호[3])} ${인라인(번호[4])}`, 상태 };

  // 표는 세로줄만 흐리게 한다. 칸을 맞추려면 표 전체를 들고 있어야 하는데,
  // 그러면 표가 끝날 때까지 화면에 아무것도 안 나온다.
  if (/^\s*\|.*\|\s*$/.test(s)) {
    // 가름줄(`|---|---|`). 그대로 두면 화면에 작대기가 그대로 뜬다.
    // 바로 앞 머리줄의 칸 너비를 기억해 뒀다가 그 자리에 맞춰 긋는다 —
    // 그래야 세로줄과 가로줄이 만나서 표처럼 보인다.
    if (/^\s*\|[\s:|-]+\|\s*$/.test(s)) {
      const 너비 = 상태.표너비 ?? s.split('|').map(() => 3);
      return { 글: c.gray(너비.map((w) => '─'.repeat(w)).join('┼')), 상태 };
    }
    // 칸에 먼저 꾸밈을 먹이고 그 다음에 잇는다. 순서가 반대면 색 제어문자가
    // 이미 낀 글에 정규식을 돌리게 되어 칸이 통째로 망가진다.
    const 칸들 = s.split('|').map((칸) => 인라인(칸));
    return { 글: 칸들.join(c.gray('│')), 상태: { ...상태, 표너비: 칸들.map((칸) => width(칸)) } };
  }

  return { 글: 인라인(s), 상태 };
}

/*
 * ── 표 ──────────────────────────────────────────────────────────────────
 *
 * 표만은 **모아서** 그린다. 칸 너비는 그 열에서 제일 긴 칸이 정하는데, 그건
 * 마지막 줄까지 봐야 안다. 줄마다 바로 그리면 칸이 안 맞아서 세로줄이
 * 지그재그로 흐른다 — 여태 나오던 모양이 그것이다.
 *
 * 다 모으는 것이 아니라 **표인 동안만** 모은다. 표가 아닌 줄이 하나 오면 그
 * 자리에서 표를 그려 내보내고 하던 대로 돌아간다. 그래서 산문이 늦어지는 일은
 * 없고, 표는 몇 줄 안 되고 붙어서 오므로 사람 눈에는 한 덩이로 뜬다.
 *
 * 모으다가 표가 아니었던 것으로 드러나면(가름줄이 없으면) 모아 둔 줄을 옛
 * 방식으로 한 줄씩 내보낸다. 글이 사라지는 것이 제일 나쁘다.
 */

/*
 * 붙들기의 상한 둘.
 *
 * 표라고 우기는 것이 몇백 줄이거나 한 줄이 끝없이 길면, 그동안 화면은 멈춘
 * 것처럼 보인다. 모양보다 '살아 있다' 가 먼저라는 이 파일의 규칙은 표에도
 * 그대로 적용된다.
 */
const 표붙들상한 = 200;      // 몇 줄까지 모아 두나
const 표줄최대배 = 8;        // 한 줄이 창 폭의 몇 배까지면 줄 끝을 기다리나

/** `| 가 | 나 |` 모양인가. 바깥 세로줄을 요구한다 — 산문에 든 `|` 를 안 삼키려고. */
const 표줄인가 = (s) => /^\s*\|.*\|\s*$/.test(String(s ?? '').replace(/\r+$/, ''));

/** `---` `:---` `---:` `:---:` — 가름줄의 한 칸인가. */
const 가름칸인가 = (칸) => /^:?-+:?$/.test(String(칸).trim());

/**
 * 한 줄을 칸으로 가른다.
 *
 * 그냥 split('|') 로 하면 두 자리에서 깨진다. `\|` 로 적은 세로줄(칸 안에
 * 세로줄을 쓰려면 이 방법뿐이다)과, `` `a | b` `` 처럼 인라인 코드 안에 든
 * 세로줄이다. 둘 다 칸을 가르면 안 되는 자리다.
 */
function 칸가르기(줄) {
  const s = String(줄 ?? '').replace(/\r+$/, '').trim().replace(/^\|/, '').replace(/\|$/, '');
  const 칸들 = [];
  let 지금 = '';
  let 코드안 = false;
  for (let i = 0; i < s.length; i += 1) {
    const ch = s[i];
    if (ch === '\\' && s[i + 1] === '|') { 지금 += '|'; i += 1; continue; }
    if (ch === '`') { 코드안 = !코드안; 지금 += ch; continue; }
    if (ch === '|' && !코드안) { 칸들.push(지금); 지금 = ''; continue; }
    지금 += ch;
  }
  칸들.push(지금);
  return 칸들.map((x) => x.trim());
}

/** 가름줄이 알려 주는 정렬. `---:` 는 오른쪽, `:---:` 는 가운데. 숫자 칸에 쓴다. */
function 기울기(칸) {
  const t = String(칸).trim();
  if (t.startsWith(':') && t.endsWith(':')) return '가운데';
  if (t.endsWith(':')) return '오른쪽';
  return '왼쪽';
}

/** 칸을 제 너비까지 밀어 준다. width() 가 제어문자를 안 세므로 색이 끼어도 맞는다. */
function 채우기(글, 폭, 쪽) {
  const 남은 = Math.max(0, 폭 - width(글));
  if (쪽 === '오른쪽') return ' '.repeat(남은) + 글;
  if (쪽 === '가운데') {
    const 왼 = Math.floor(남은 / 2);
    return ' '.repeat(왼) + 글 + ' '.repeat(남은 - 왼);
  }
  return 글 + ' '.repeat(남은);
}

/**
 * 모아 둔 표 줄들을 칸 맞춰 그린다. 표가 아니면 null 을 돌려준다.
 *
 * 창보다 넓으면 **제일 넓은 칸부터** 한 칸씩 줄인다. 골고루 줄이면 `번호` 같은
 * 짧은 칸까지 같이 좁아져서 거기부터 글자가 접힌다 — 정작 줄여야 할 것은 긴
 * 설명 칸이다. 줄인 칸은 잘라 버리지 않고 접는다(접어쓰기). 표에서 글자가
 * 사라지면 그 줄은 아예 못 읽는다.
 */
export function 표그리기(줄들, 폭 = 80) {
  const 행들 = (줄들 ?? []).map(칸가르기);
  // 가름줄이 있어야 표다. 첫 줄일 수는 없다 — 머리줄이 그 위에 있어야 한다.
  const 가름 = 행들.findIndex((행) => 행.length > 1 && 행.every(가름칸인가));
  if (가름 < 1) return null;

  const 열수 = Math.max(...행들.map((행) => 행.length));
  const 쪽들 = Array.from({ length: 열수 }, (_, i) => 기울기(행들[가름][i] ?? ''));

  // 가름줄은 자리만 알려 주고 화면에는 안 나간다 — 우리가 진짜 선을 긋는다.
  const 몸 = 행들
    .filter((_, i) => i !== 가름)
    .map((행) => Array.from({ length: 열수 }, (_, i) => 인라인(행[i] ?? '')));
  if (!몸.length) return null;

  /*
   * 치레가 먹는 폭: 칸마다 세로줄 하나와 좌우 한 칸씩(3), 그리고 맨 오른쪽
   * 세로줄 하나. 이걸 빼고 남는 것이 글자가 쓸 수 있는 폭이다.
   */
  const 치레 = 3 * 열수 + 1;
  const 쓸수있는 = Math.max(열수, 폭 - 치레);
  const 너비 = Array.from({ length: 열수 }, (_, i) => Math.max(1, ...몸.map((행) => width(행[i]))));
  let 합 = 너비.reduce((a, b) => a + b, 0);
  while (합 > 쓸수있는) {
    let 큰 = 0;
    for (let i = 1; i < 너비.length; i += 1) if (너비[i] > 너비[큰]) 큰 = i;
    if (너비[큰] <= 1) break;
    너비[큰] -= 1;
    합 -= 1;
  }

  const 가로 = (왼, 사이, 오른) =>
    c.gray(왼 + 너비.map((w) => '─'.repeat(w + 2)).join(사이) + 오른);
  const 세로 = c.gray('│');

  const 한행 = (행) => {
    // 접힌 칸이 여럿이면 그 행은 여러 줄이 된다. 제일 높은 칸에 키를 맞춘다.
    const 접힌 = 행.map((칸, i) => (칸 === '' ? [''] : 접어쓰기(칸, 너비[i])));
    const 높이 = Math.max(1, ...접힌.map((x) => x.length));
    const 나갈것 = [];
    for (let k = 0; k < 높이; k += 1) {
      const 칸들 = 접힌.map((x, i) => 채우기(x[k] ?? '', 너비[i], 쪽들[i]));
      나갈것.push(`${세로} ${칸들.join(` ${세로} `)} ${세로}`);
    }
    return 나갈것;
  };

  const 화면 = [가로('┌', '┬', '┐')];
  몸.forEach((행, i) => {
    // 머리줄만 굵게. 어디까지가 이름이고 어디부터가 값인지가 한눈에 갈린다.
    화면.push(...한행(i === 0 ? 행.map(이어굵게) : 행));
    화면.push(i === 몸.length - 1 ? 가로('└', '┴', '┘') : 가로('├', '┼', '┤'));
  });
  return 화면;
}

/**
 * 흘러오는 토막을 받아 그릴 수 있게 된 줄만 내놓는다.
 *
 * 쓰는 쪽은 이렇게 한다:
 *   for (const 줄 of md.넣기(토막)) 화면에 찍는다
 *   ... 답이 끝나면
 *   for (const 줄 of md.끝()) 화면에 찍는다
 */
export class 마크다운 {
  constructor({ 폭 = 80 } = {}) {
    // 창이 좁으면 부르는 쪽이 (columns - 6) 을 넘기는데, 그게 0 이나 음수가 될 수
    // 있다. 그러면 모든 줄이 '폭을 넘는다' 가 되어 **아무것도 안 그려진다.**
    // 바닥을 둬서, 좁은 창에서도 짧은 줄은 제 모양으로 나가게 한다.
    this.폭 = Math.max(20, Number(폭) || 0);
    this.담긴것 = '';
    this.상태 = { 펜스: false };
    // 이 줄은 이미 날것으로 흘려보내기 시작했다 — 뒤늦게 꾸미면 앞뒤가 안 맞는다.
    this.날것중 = false;
    // 그리려고 붙들고 있는 표 줄들. 표가 끝나는 순간 칸을 맞춰 한꺼번에 나간다.
    this.표줄들 = [];
  }

  /** 붙들고 있던 표를 내보낸다. 표가 아니었으면 옛 방식으로 한 줄씩 내보낸다. */
  #표비우기() {
    const 줄들 = this.표줄들;
    this.표줄들 = [];
    if (!줄들.length) return [];
    const 그린것 = 표그리기(줄들, this.폭);
    if (그린것) return 그린것;
    const 나갈것 = [];
    for (const 줄 of 줄들) {
      const r = 한줄(줄, this.상태, this.폭);
      this.상태 = r.상태;
      나갈것.push(r.글);
    }
    return 나갈것;
  }

  #그리기(줄) {
    // 이 줄은 이미 날것으로 나가기 시작했다. 뒤늦게 꾸미면 앞뒤가 안 맞으므로
    // 남은 만큼을 그대로 이어 붙이고 줄만 끝낸다.
    if (this.날것중) {
      this.날것중 = false;
      return [{ 이어붙임: String(줄).replace(/\r/g, ''), 끝났나: true }];
    }

    /*
     * 표 줄은 붙든다. 다만 **코드 울타리 안에서는 안 한다** — 거기서는 세로줄도
     * 그냥 글자다. SQL 이나 아스키 그림을 표로 읽어 다시 그리면 코드가 망가진다.
     *
     * 끝없이 붙들지는 않는다. 표라고 우기는 것이 몇백 줄이면 화면이 그동안
     * 멈춘 것처럼 보인다. 그때는 붙들기를 그만두고 흘려보낸다.
     */
    if (!this.상태.펜스 && 표줄인가(줄)) {
      this.표줄들.push(줄);
      return this.표줄들.length >= 표붙들상한 ? this.#표비우기() : [];
    }

    const 앞 = this.#표비우기();
    const r = 한줄(줄, this.상태, this.폭);
    this.상태 = r.상태;
    return [...앞, r.글];
  }

  넣기(토막) {
    this.담긴것 += String(토막 ?? '');
    const 나갈것 = [];

    for (;;) {
      const i = this.담긴것.indexOf('\n');
      if (i >= 0) {
        // \r\n 으로 온 줄은 여기서 \r 를 뗀다. 남겨서 내보내면 터미널에서 커서가
        // 줄 맨 앞으로 돌아가 앞에 세운 세로줄 위에 덮어쓴다 — 글자가 먹힌 것처럼
        // 보인다. 토막이 \r 와 \n 사이에서 끊겨 와도 여기로 모여서 걸린다.
        나갈것.push(...this.#그리기(this.담긴것.slice(0, i)));
        this.담긴것 = this.담긴것.slice(i + 1);
        continue;
      }
      /*
       * 표 줄은 길어도 안 흘려보낸다.
       *
       * 표 한 줄은 창보다 넓은 것이 보통이다(칸이 셋만 돼도 넘는다). 여기서
       * 날것으로 내보내면 그 줄은 표로 모이지도 못하고 세로줄이 그대로 뜬다 —
       * 고치려던 바로 그 모양이다. 그래서 세로줄로 시작하는 줄은 줄이 끝날
       * 때까지 기다린다.
       *
       * 그래도 상한은 둔다. 표가 아닌데 세로줄로 시작하는 긴 글(로그 한 덩이
       * 같은 것)이 오면 화면이 멈춘 것처럼 보이면 안 된다.
       */
      const 표기다림 = !this.상태.펜스
        && (this.표줄들.length > 0 || /^\s*\|/.test(this.담긴것))
        && width(this.담긴것) <= this.폭 * 표줄최대배;
      if (표기다림) break;

      // 줄이 안 끝나는데 너무 길어졌다. 여기까지 날것으로 흘려보낸다 —
      // 멈춘 것처럼 보이는 것보다 안 꾸며진 글이 흐르는 편이 낫다.
      if (width(this.담긴것) > this.폭) {
        // 붙들고 있던 표부터 내보낸다. 안 그러면 표가 뒤에 나와서 순서가 뒤집힌다.
        나갈것.push(...this.#표비우기());
        // 날것으로 나가는 길에는 한줄() 이 안 끼므로 여기서 \r 를 턴다.
        나갈것.push({ 이어붙임: this.담긴것.replace(/\r/g, ''), 첫조각: !this.날것중, 끝났나: false });
        this.담긴것 = '';
        this.날것중 = true;
      }
      break;
    }
    return 나갈것;
  }

  /** 답이 끝났다. 남은 것을 내놓는다. */
  끝() {
    // 담긴 것은 없는데 날것으로 나가던 중이면 줄만 끝내 준다.
    if (!this.담긴것) {
      const 닫을것 = this.날것중 ? [{ 이어붙임: '', 끝났나: true }] : [];
      this.날것중 = false;
      // 표로 끝나는 답이 흔하다(마지막이 정리 표). 여기서 안 비우면 통째로 사라진다.
      return [...(닫을것.length ? 닫을것 : []), ...this.#표비우기()];
    }
    const 남은것 = this.#그리기(this.담긴것);
    this.담긴것 = '';
    this.날것중 = false;
    return [...남은것, ...this.#표비우기()];
  }
}

/** 통째로 있는 글을 한 번에 그린다 (스트리밍이 아닌 자리). */
export function 그리기(글, 폭 = 80) {
  const md = new 마크다운({ 폭 });
  const 줄들 = [];
  for (const x of md.넣기(String(글 ?? ''))) 줄들.push(typeof x === 'string' ? x : x.이어붙임);
  for (const x of md.끝()) 줄들.push(typeof x === 'string' ? x : x.이어붙임);
  return 줄들;
}
