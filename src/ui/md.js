// 모델 답을 사람이 읽는 모양으로 그린다.
//
// ── 왜 만드나 ───────────────────────────────────────────────────────────
//
// 여태 답을 **글자 그대로** 찍었다. 모델은 마크다운으로 말하는데 화면은 그걸
// 모르니, 실제로 이렇게 보였다.
//
//   ▌ ## 고친 것
//   ▌ **src/runner.js** 의 `console.log` 를 바꿨습니다.
//   ▌ - 로그 형식 통일
//   ▌ ```js
//   ▌ log.info('x')
//   ▌ ```
//
// 별표와 백틱과 우물정자가 글에 섞여 눈이 걸린다. 무엇이 제목이고 무엇이
// 코드인지 사람이 머릿속에서 다시 파싱해야 한다. 답이 길수록 심해진다.
//
// ── 왜 줄 단위인가 ─────────────────────────────────────────────────────
//
// 답은 토막토막 흘러온다. `**굵` 까지 왔을 때는 그게 굵은 글씨가 될지 알 수 없다.
// 한 번 찍은 글자는 되돌릴 수 없으니, **줄이 끝나야** 그릴 수 있다.
//
// 그런데 줄이 안 끝나면? 긴 문단 하나가 통째로 한 줄이면 몇 초 동안 화면에
// 아무것도 안 나온다 — 사람 눈에는 멈춘 것으로 보인다. 그래서 한 줄이 화면 폭을
// 넘게 길어지면 거기까지를 **날것 그대로** 흘려보낸다. 모양은 못 내지만 글은
// 계속 흐른다. 모양보다 '살아 있다' 가 먼저다.
//
// 실제로는 제목·목록·코드펜스가 다 짧은 줄이라 거의 다 그려진다. 안 그려지는
// 것은 긴 산문뿐인데, 산문은 원래 꾸밀 것이 없다.
import { c, width, 화면글거르기 } from './ansi.js';
import { 접어쓰기 } from './wrap.js';

const 굵게 = (s) => c.bold(s);
const 코드 = (s) => c.hyellow(s);

// 줄 전체를 흐리게 할 때 쓴다.
//
// 그냥 c.gray() 로 감싸면 안 된다. 안쪽 꾸밈(링크·코드)이 제 색을 끝내면서
// 리셋을 남기는데, 그 리셋이 바깥 흐림까지 같이 꺼 버린다 — 한 줄이 반만
// 흐려 보인다. 그래서 안쪽이 색을 끝낼 때마다 흐림을 다시 켠다.
const 회색앞 = c.gray('·').replace(/·[\s\S]*$/, '');
const 이어흐리게 = (s) => c.gray(String(s).replace(/\x1b\[0m/g, `\x1b[0m${회색앞}`));

// 굵게도 같은 문제를 겪는다 — 칸 안의 코드가 색을 끝내면서 굵기까지 꺼 버린다.
const 굵게앞 = c.bold('·').replace(/·[\s\S]*$/, '');
const 이어굵게 = (s) => c.bold(String(s).replace(/\x1b\[0m/g, `\x1b[0m${굵게앞}`));

/**
 * 한 줄 안쪽 꾸밈. `코드` → **굵게** → *기울임* → ~~취소~~ → [글](주소) 차례.
 *
 * 코드부터 하는 이유: 코드 안에 별표가 들어 있으면(`a ** b`) 굵게 처리가 먼저
 * 먹어서 코드가 깨진다. 먼저 뽑아서 자리표시자로 빼 두고 맨 끝에 되돌린다.
 */
export function 인라인(글) {
  // 들어온 NUL 은 먼저 버린다. 아래에서 코드 조각을 빼 둘 때 NUL 을 자리표시자로
  // 쓰는데, 답에 NUL 이 섞여 오면(도구가 읽은 바이너리를 되읊는 경우) 그것이
  // 자리표시자로 읽혀 엉뚱한 글자로 바뀐다 — 모델이 한 말과 화면이 달라진다.
  let s = String(글 ?? '').replace(/\x00/g, '');
  const 뺀것 = [];
  // 백틱은 **같은 수만큼** 짝을 짓는다. 하나만 보면 ``a`` 나 ```x``` 처럼 겹쳐
  // 적은 코드가 안쪽만 걸려서 바깥 백틱이 화면에 그대로 남는다.
  s = s.replace(/(`+)([\s\S]+?)\1/g, (_, __, 안) => {
    뺀것.push(코드(안));
    return `\x00${뺀것.length - 1}\x00`;
  });

  // 별표 안쪽이 공백으로 시작하거나 끝나면 굵게가 아니다. 안 막으면 파이썬의
  // 거듭제곱을 적은 `2 ** 3 ** 4` 가 화면에서 `2  3  4` 가 된다 — 별표가
  // 소리 없이 사라지고 사람은 모델이 그렇게 말한 줄 안다.
  s = s.replace(/\*\*([^*\s](?:[^*]*[^*\s])?)\*\*/g, (_, 안) => 굵게(안));
  // 닫는 별표 뒤는 별표만 아니면 된다. `[\s.,)]` 로 좁혀 두면 조사가 붙는
  // 한국어(`*중요*입니다`)와 `*주의*!` 에서 별표가 화면에 그대로 남는다.
  // 굵게와 같이, 안쪽이 공백으로 끝나면 기울임이 아니다 — `5 *x * y` 의 별표를
  // 먹으면 화면에서 별표가 사라진다.
  s = s.replace(/(^|[\s(])\*([^*\s](?:[^*]*[^*\s])?)\*(?=$|[^*])/g, (_, 앞, 안) => `${앞}${c.italic(안)}`);
  s = s.replace(/~~([^~]+)~~/g, (_, 안) => c.gray(안));
  // 링크는 글만 보이고 주소는 흐리게. 주소를 지우면 따라갈 수가 없다.
  s = s.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, 글자, 주소) => `${c.under(글자)} ${c.gray(주소)}`);

  return s.replace(/\x00(\d+)\x00/g, (_, i) => 뺀것[Number(i)]);
}

/**
 * 줄 하나를 그린다.
 *
 * @param {string} 줄
 * @param {object} 상태  {펜스: boolean} — 코드 블록 안인가
 * @param {number} 폭
 * @returns {{글: string, 상태: object}}
 */
export function 한줄(줄, 상태 = { 펜스: false }, 폭 = 80) {
  // 줄 끝의 \r 를 먼저 뗀다. 서버가 \r\n 으로 흘려보내면 여기까지 딸려 오는데,
  // 아래 정규식들이 다 `(.*)$` 로 끝나고 `.` 은 \r 를 안 먹는다 — 그래서 제목도
  // 목록도 하나도 안 잡히고 별표와 우물정자가 그대로 화면에 뜬다.
  const s = String(줄 ?? '').replace(/\r+$/, '');

  // 코드 울타리. 여는 줄에 언어가 붙어 있으면 그걸 알려 준다.
  //
  // 언어 자리에 백틱이 또 들어 있으면 울타리가 아니다 — 마크다운 규칙이 그렇고,
  // 안 막으면 ```` ```js console.log(1)``` ```` 처럼 한 줄에 다 적은 코드가
  // 울타리를 **열기만** 한다. 그 뒤로 오는 답 전체가 코드로 그려진다 — 제목도
  // 굵기도 다 사라지고, 화면은 멀쩡해 보인다.
  const 울타리 = s.match(/^\s*(`{3,})[ \t]*([^`]*?)[ \t]*$/);
  if (울타리) {
    const 길이 = 울타리[1].length;
    const 안쪽 = 울타리[2];
    const 줄긋기 = (앞) => c.gray(앞 + '─'.repeat(Math.max(2, Math.min(30, 폭 - 6))));
    if (상태.펜스) {
      /*
       * 닫는 울타리는 언어를 못 갖고, 연 것보다 짧을 수도 없다.
       *
       * 마크다운 문서를 보여 주려고 백틱 넷으로 열고 그 안에 ```js 를 적는 일이
       * 흔하다. 안 막으면 그 ```js 가 상자를 일찍 닫아 버린다 — 나머지 코드가
       * 코드가 아닌 것으로 그려지고, 상자는 열자마자 닫힌 빈 상자가 된다.
       */
      if (안쪽 || 길이 < (상태.울타리길이 ?? 길이)) return { 글: `${c.gray('│')} ${c.white(s)}`, 상태 };
      return { 글: 줄긋기('└'), 상태: { ...상태, 펜스: false, 울타리길이: 0 } };
    }
    return {
      글: 줄긋기('┌') + (안쪽 ? c.gray(` ${안쪽}`) : ''),
      상태: { ...상태, 펜스: true, 울타리길이: 길이 },
    };
  }

  // 코드 안에서는 아무것도 해석하지 않는다. 별표는 별표고 우물정자는 우물정자다.
  if (상태.펜스) return { 글: `${c.gray('│')} ${c.white(s)}`, 상태 };

  // 가로줄
  if (/^\s*([-*_])\s*\1\s*\1[\s\-*_]*$/.test(s)) {
    return { 글: c.gray('─'.repeat(Math.max(4, Math.min(40, 폭 - 6)))), 상태 };
  }

  // 제목. 굵기와 색으로 가른다 — 우물정자를 남기면 그게 제일 먼저 눈에 띈다.
  const 제목 = s.match(/^(#{1,6})\s+(.*)$/);
  if (제목) {
    const 깊이 = 제목[1].length;
    // 이어굵게 로 감싼다. c.bold 로 감싸면 제목 안의 코드가 제 색을 끝내면서
    // 굵기까지 꺼 버려서, 코드 뒷부분만 가늘어진다.
    const 글자 = 이어굵게(인라인(제목[2]));
    if (깊이 <= 2) return { 글: `${c.hcyan('▍')} ${글자}`, 상태 };
    return { 글: 글자, 상태 };
  }

  // 인용
  const 인용 = s.match(/^\s*>\s?(.*)$/);
  if (인용) return { 글: `${c.gray('│')} ${이어흐리게(인라인(인용[1]))}`, 상태 };

  // 할 일 목록은 목록보다 먼저 본다 — `- [ ]` 가 그냥 목록으로 먹히면 안 된다.
  // 뒤에 글이 없는 빈 칸(`- [ ]`)도 할 일이다. 뒷글을 요구하면 그것만 글머리표로
  // 빠져서 화면에 `• [ ]` 라고 대괄호가 그대로 뜬다. 다만 대괄호에 글이 바로 붙은
  // `- [ ]foo` 는 할 일이 아니다 — 마크다운도 그렇게 안 읽는다.
  const 할일 = s.match(/^(\s*)[-*+]\s+\[([ xX])\](\s+.*)?$/);
  if (할일) {
    const 표 = 할일[2] === ' ' ? c.gray('☐') : c.green('☑');
    const 뒤 = 할일[3]?.trim() ? ` ${인라인(할일[3].trim())}` : '';
    return { 글: `${할일[1]}${표}${뒤}`, 상태 };
  }

  // 글머리표
  const 목록 = s.match(/^(\s*)[-*+]\s+(.*)$/);
  if (목록) return { 글: `${목록[1]}${c.hcyan('•')} ${인라인(목록[2])}`, 상태 };

  // 번호 목록. 번호는 살린다 — 순서가 뜻을 갖는 자리다.
  const 번호 = s.match(/^(\s*)(\d+)([.)])\s+(.*)$/);
  if (번호) return { 글: `${번호[1]}${c.hcyan(번호[2] + 번호[3])} ${인라인(번호[4])}`, 상태 };

  // 여기는 **표가 아니었던 것**이 오는 자리다. 진짜 표는 마크다운 클래스가
  // 모아서 표그리기() 로 칸을 맞춰 그린다. 여기서는 칸 너비를 모르므로
  // 세로줄만 흐리게 해서 내보낸다.
  if (/^\s*\|.*\|\s*$/.test(s)) {
    // 가름줄(`|---|---|`). 그대로 두면 화면에 작대기가 그대로 뜬다.
    // 바로 앞 머리줄의 칸 너비를 기억해 뒀다가 그 자리에 맞춰 긋는다 —
    // 그래야 세로줄과 가로줄이 만나서 표처럼 보인다.
    //
    // 하이픈을 하나는 **꼭** 요구한다. 안 그러면 빈칸과 세로줄뿐인 줄(`|   |   |`)까지
    // 걸려서, 내용이 빈 데이터 행이 가로선으로 그려진다 — 그 행의 글이 아니라 행 자체가
    // 사라진 것으로 보인다 (2.0.0 8회차).
    if (/^\s*\|[\s:|-]*-[\s:|-]*\|\s*$/.test(s)) {
      const 너비 = 상태.표너비 ?? s.split('|').map(() => 3);
      return { 글: c.gray(너비.map((w) => '─'.repeat(w)).join('┼')), 상태 };
    }
    // 칸에 먼저 꾸밈을 먹이고 그 다음에 잇는다. 순서가 반대면 색 제어문자가
    // 이미 낀 글에 정규식을 돌리게 되어 칸이 통째로 망가진다.
    const 칸들 = s.split('|').map((칸) => 인라인(칸));
    return { 글: 칸들.join(c.gray('│')), 상태: { ...상태, 표너비: 칸들.map((칸) => width(칸)) } };
  }

  return { 글: 인라인(s), 상태 };
}

/*
 * ── 표 ──────────────────────────────────────────────────────────────────
 *
 * 표만은 **모아서** 그린다. 칸 너비는 그 열에서 제일 긴 칸이 정하는데, 그건
 * 마지막 줄까지 봐야 안다. 줄마다 바로 그리면 칸이 안 맞아서 세로줄이
 * 지그재그로 흐른다 — 여태 나오던 모양이 그것이다.
 *
 * 다 모으는 것이 아니라 **표인 동안만** 모은다. 표가 아닌 줄이 하나 오면 그
 * 자리에서 표를 그려 내보내고 하던 대로 돌아간다. 그래서 산문이 늦어지는 일은
 * 없고, 표는 몇 줄 안 되고 붙어서 오므로 사람 눈에는 한 덩이로 뜬다.
 *
 * 모으다가 표가 아니었던 것으로 드러나면(가름줄이 없으면) 모아 둔 줄을 옛
 * 방식으로 한 줄씩 내보낸다. 글이 사라지는 것이 제일 나쁘다.
 */

/*
 * 붙들기의 상한 둘.
 *
 * 표라고 우기는 것이 몇백 줄이거나 한 줄이 끝없이 길면, 그동안 화면은 멈춘
 * 것처럼 보인다. 모양보다 '살아 있다' 가 먼저라는 이 파일의 규칙은 표에도
 * 그대로 적용된다.
 */
const 표붙들상한 = 200;      // 몇 줄까지 모아 두나
const 표줄최대배 = 8;        // 한 줄이 창 폭의 몇 배까지면 줄 끝을 기다리나

/** `| 가 | 나 |` 모양인가. 바깥 세로줄을 요구한다 — 산문에 든 `|` 를 안 삼키려고. */
const 표줄인가 = (s) => /^\s*\|.*\|\s*$/.test(String(s ?? '').replace(/\r+$/, ''));

/** `---` `:---` `---:` `:---:` — 가름줄의 한 칸인가. */
const 가름칸인가 = (칸) => /^:?-+:?$/.test(String(칸).trim());

/** 가름줄이 몇 번째 줄인가. 머리줄이 위에 있어야 하므로 1 보다 작으면 표가 아니다. */
const 가름찾기 = (행들) =>
  행들.findIndex((행) => 행.length > 0 && 행.every(가름칸인가));

/**
 * 한 줄을 칸으로 가른다.
 *
 * 그냥 split('|') 로 하면 두 자리에서 깨진다. `\|` 로 적은 세로줄(칸 안에
 * 세로줄을 쓰려면 이 방법뿐이다)과, `` `a | b` `` 처럼 인라인 코드 안에 든
 * 세로줄이다. 둘 다 칸을 가르면 안 되는 자리다.
 */
function 칸가르기(줄) {
  // 끝의 바깥 세로줄만 뗀다 — `\|` 로 끝나면 칸 안의 세로줄이다 (2.0.0 6회차 마크6: `2 \` 만 남았다).
  //
  // 「앞이 백슬래시면 무조건 안 뗀다」 로 두면 반대로 샌다. 백슬래시가 **짝수** 개면
  // 그것들은 서로를 벗긴 것이라 마지막 세로줄은 여전히 바깥 것이다 — `C:\\|` 의 닫는
  // 세로줄을 못 떼서 칸에 `C:\|` 가 남았다 (2.0.0 8회차). 짝을 먼저 먹고 판단한다.
  const s = String(줄 ?? '').replace(/\r+$/, '').trim().replace(/^\|/, '').replace(/(^|[^\\])((?:\\\\)*)\|$/, '$1$2');
  const 칸들 = [];
  let 지금 = '';
  /*
   * 인라인 코드는 **같은 길이의 백틱 줄**로 닫힌다(``` ``a | b`` ```). 백틱 하나마다 「코드 안」 을
   * 뒤집었더니 겹백틱 코드 안의 `|` 에서 칸이 갈려 2칸 표가 3칸이 됐다 (2.0.0 6회차 마크6).
   * 0 이면 코드 밖, 아니면 연 백틱 줄의 길이.
   */
  let 코드길이 = 0;
  for (let i = 0; i < s.length; i += 1) {
    const ch = s[i];
    // `\\` 는 백슬래시 한 자다. 안 벗기면 위에서 짝수로 세어 세로줄을 뗀 칸이
    // 화면에는 `C:\\` 로 뜬다 — 뗀 만큼 글이 딴 것이 된다 (2.0.0 8회차).
    if (ch === '\\' && s[i + 1] === '\\') { 지금 += '\\'; i += 1; continue; }
    if (ch === '\\' && s[i + 1] === '|') { 지금 += '|'; i += 1; continue; }
    if (ch === '`') {
      let n = 1;
      while (s[i + n] === '`') n += 1;
      if (코드길이 === 0) 코드길이 = n;
      else if (n === 코드길이) 코드길이 = 0;
      지금 += s.slice(i, i + n);
      i += n - 1;
      continue;
    }
    if (ch === '|' && 코드길이 === 0) { 칸들.push(지금); 지금 = ''; continue; }
    지금 += ch;
  }
  칸들.push(지금);
  return 칸들.map((x) => x.trim());
}

/** 가름줄이 알려 주는 정렬. `---:` 는 오른쪽, `:---:` 는 가운데. 숫자 칸에 쓴다. */
function 기울기(칸) {
  const t = String(칸).trim();
  if (t.startsWith(':') && t.endsWith(':')) return '가운데';
  if (t.endsWith(':')) return '오른쪽';
  return '왼쪽';
}

/** 칸을 제 너비까지 밀어 준다. width() 가 제어문자를 안 세므로 색이 끼어도 맞는다. */
function 채우기(글, 폭, 쪽) {
  const 남은 = Math.max(0, 폭 - width(글));
  if (쪽 === '오른쪽') return ' '.repeat(남은) + 글;
  if (쪽 === '가운데') {
    const 왼 = Math.floor(남은 / 2);
    return ' '.repeat(왼) + 글 + ' '.repeat(남은 - 왼);
  }
  return 글 + ' '.repeat(남은);
}

/**
 * 모아 둔 표 줄들을 칸 맞춰 그린다. 표가 아니면 null 을 돌려준다.
 *
 * 창보다 넓으면 **제일 넓은 칸부터** 한 칸씩 줄인다. 골고루 줄이면 `번호` 같은
 * 짧은 칸까지 같이 좁아져서 거기부터 글자가 접힌다 — 정작 줄여야 할 것은 긴
 * 설명 칸이다. 줄인 칸은 잘라 버리지 않고 접는다(접어쓰기). 표에서 글자가
 * 사라지면 그 줄은 아예 못 읽는다.
 */
export function 표그리기(줄들, 폭 = 80, 어떻게 = {}) {
  return 짜기(줄들, 폭, 어떻게)?.화면 ?? null;
}

/**
 * 그 표를 그렸다면 칸 너비가 얼마였을까. 표가 아니면 null.
 *
 * 상한에 걸려 표를 나눠 그릴 때, 뒤 묶음에 앞 묶음의 너비를 그대로 물려 주려고
 * 쓴다. 묶음마다 제 폭을 다시 재면 같은 표인데 위아래의 세로줄이 안 맞는다.
 */
export function 표칸너비(줄들, 폭 = 80) {
  return 짜기(줄들, 폭)?.너비 ?? null;
}

function 짜기(줄들, 폭 = 80, { 너비고정 = null } = {}) {
  const 행들 = (줄들 ?? []).map(칸가르기);
  // 가름줄이 있어야 표다. 첫 줄일 수는 없다 — 머리줄이 그 위에 있어야 한다.
  //
  // 칸이 하나뿐인 표(`| 항목 |`)도 표다. 칸 둘을 요구하면 그것만 표로 안 읽혀
  // 테두리 없이 세로줄만 그어진 채 나가고, 가름줄의 작대기도 화면에 남는다.
  const 가름 = 가름찾기(행들);
  if (가름 < 1) return null;

  const 열수 = Math.max(...행들.map((행) => 행.length));
  const 쪽들 = Array.from({ length: 열수 }, (_, i) => 기울기(행들[가름][i] ?? ''));

  // 가름줄은 자리만 알려 주고 화면에는 안 나간다 — 우리가 진짜 선을 긋는다.
  const 몸 = 행들
    .filter((_, i) => i !== 가름)
    .map((행) => Array.from({ length: 열수 }, (_, i) => 인라인(행[i] ?? '')));
  if (!몸.length) return null;

  /*
   * 치레가 먹는 폭: 칸마다 세로줄 하나와 좌우 한 칸씩(3), 그리고 맨 오른쪽
   * 세로줄 하나. 이걸 빼고 남는 것이 글자가 쓸 수 있는 폭이다.
   */
  const 치레 = 3 * 열수 + 1;
  const 쓸수있는 = Math.max(열수, 폭 - 치레);
  // 앞 묶음이 쓰던 너비가 있으면 그대로 쓴다. 다시 재면 같은 표의 위아래가
  // 서로 다른 폭으로 그려진다 — 세로줄이 이음매에서 어긋난다.
  const 물려받나 = Array.isArray(너비고정) && 너비고정.length === 열수;
  const 너비 = 물려받나
    ? 너비고정.map((w) => Math.max(1, w))
    : Array.from({ length: 열수 }, (_, i) => Math.max(1, ...몸.map((행) => width(행[i]))));
  let 합 = 너비.reduce((a, b) => a + b, 0);
  while (!물려받나 && 합 > 쓸수있는) {
    let 큰 = 0;
    for (let i = 1; i < 너비.length; i += 1) if (너비[i] > 너비[큰]) 큰 = i;
    if (너비[큰] <= 1) break;
    너비[큰] -= 1;
    합 -= 1;
  }

  const 가로 = (왼, 사이, 오른) =>
    c.gray(왼 + 너비.map((w) => '─'.repeat(w + 2)).join(사이) + 오른);
  const 세로 = c.gray('│');

  const 한행 = (행) => {
    // 접힌 칸이 여럿이면 그 행은 여러 줄이 된다. 제일 높은 칸에 키를 맞춘다.
    const 접힌 = 행.map((칸, i) => (칸 === '' ? [''] : 접어쓰기(칸, 너비[i])));
    const 높이 = Math.max(1, ...접힌.map((x) => x.length));
    const 나갈것 = [];
    for (let k = 0; k < 높이; k += 1) {
      const 칸들 = 접힌.map((x, i) => 채우기(x[k] ?? '', 너비[i], 쪽들[i]));
      나갈것.push(`${세로} ${칸들.join(` ${세로} `)} ${세로}`);
    }
    return 나갈것;
  };

  const 화면 = [가로('┌', '┬', '┐')];
  몸.forEach((행, i) => {
    // 머리줄만 굵게. 어디까지가 이름이고 어디부터가 값인지가 한눈에 갈린다.
    화면.push(...한행(i === 0 ? 행.map(이어굵게) : 행));
    화면.push(i === 몸.length - 1 ? 가로('└', '┴', '┘') : 가로('├', '┼', '┤'));
  });
  return { 화면, 너비 };
}

/**
 * 흘러오는 토막을 받아 그릴 수 있게 된 줄만 내놓는다.
 *
 * 쓰는 쪽은 이렇게 한다:
 *   for (const 줄 of md.넣기(토막)) 화면에 찍는다
 *   ... 답이 끝나면
 *   for (const 줄 of md.끝()) 화면에 찍는다
 */
export class 마크다운 {
  constructor({ 폭 = 80 } = {}) {
    // 창이 좁으면 부르는 쪽이 (columns - 6) 을 넘기는데, 그게 0 이나 음수가 될 수
    // 있다. 그러면 모든 줄이 '폭을 넘는다' 가 되어 **아무것도 안 그려진다.**
    // 바닥을 둬서, 좁은 창에서도 짧은 줄은 제 모양으로 나가게 한다.
    this.폭 = Math.max(20, Number(폭) || 0);
    this.담긴것 = '';
    // 토막 끝에서 끊긴 제어 순서의 앞머리(`ESC [1`). 다음 토막과 붙여서 통째로 뗀다 — 토막마다 따로
    // 떼면 ESC 만 빠지고 `[1A[2K` 가 글자로 화면에 남는다.
    this.날토막 = '';
    this.상태 = { 펜스: false };
    // 이 줄은 이미 날것으로 흘려보내기 시작했다 — 뒤늦게 꾸미면 앞뒤가 안 맞는다.
    this.날것중 = false;
    // 그리려고 붙들고 있는 표 줄들. 표가 끝나는 순간 칸을 맞춰 한꺼번에 나간다.
    this.표줄들 = [];
    // 상한에 걸려 끊은 표의 머리줄(가름줄까지)과 그때 쓰던 칸 너비.
    // 다음 묶음이 같은 표로 이어 그려지도록 물려준다.
    this.이어갈머리 = null;
    this.표너비 = null;
  }

  /** 붙들고 있던 표를 내보낸다. 표가 아니었으면 옛 방식으로 한 줄씩 내보낸다. */
  #표비우기() {
    const 줄들 = this.표줄들;
    this.표줄들 = [];
    if (!줄들.length) return [];
    let 쓴것 = 줄들;
    let 그린것 = 표그리기(줄들, this.폭, { 너비고정: this.표너비 });
    /*
     * 제 가름줄이 없으면 상한에 걸려 끊긴 표의 뒷동강이다. 그때만 앞 묶음의
     * 머리줄을 얹어 다시 그린다. 무조건 얹으면, 상한 직후에 진짜 새 표가
     * 시작될 때 남의 머리줄이 그 표에 섞여 들어간다.
     */
    if (!그린것 && this.이어갈머리) {
      쓴것 = [...this.이어갈머리, ...줄들];
      그린것 = 표그리기(쓴것, this.폭, { 너비고정: this.표너비 });
    }
    if (그린것) {
      // 상한에 걸려 끊기는 묶음일 때만 너비를 기억해 둔다. 여느 표는 한 번에
      // 다 나가므로 물려줄 데가 없다 — 그때까지 재면 헛일을 한 번 더 하는 것이다.
      if (this.표너비 === null && 줄들.length >= 표붙들상한) this.표너비 = 표칸너비(쓴것, this.폭);
      return 그린것;
    }
    const 나갈것 = [];
    for (const 줄 of 줄들) {
      const r = 한줄(줄, this.상태, this.폭);
      this.상태 = r.상태;
      나갈것.push(r.글);
    }
    return 나갈것;
  }

  #그리기(줄) {
    // 이 줄은 이미 날것으로 나가기 시작했다. 뒤늦게 꾸미면 앞뒤가 안 맞으므로
    // 남은 만큼을 그대로 이어 붙이고 줄만 끝낸다.
    if (this.날것중) {
      this.날것중 = false;
      return [{ 이어붙임: String(줄).replace(/\r/g, ''), 끝났나: true }];
    }

    /*
     * 표 줄은 붙든다. 다만 **코드 울타리 안에서는 안 한다** — 거기서는 세로줄도
     * 그냥 글자다. SQL 이나 아스키 그림을 표로 읽어 다시 그리면 코드가 망가진다.
     *
     * 끝없이 붙들지는 않는다. 표라고 우기는 것이 몇백 줄이면 화면이 그동안
     * 멈춘 것처럼 보인다. 그때는 붙들기를 그만두고 흘려보낸다.
     */
    if (!this.상태.펜스 && 표줄인가(줄)) {
      this.표줄들.push(줄);
      if (this.표줄들.length < 표붙들상한) return [];
      /*
       * 여기서 끊는다. 다음 묶음이 표로 안 읽히지 않도록 머리줄을 기억해 둔다 —
       * 세 번째 묶음까지 갈 수 있으므로, 이 묶음에 제 머리줄이 없으면 앞서
       * 기억해 둔 것을 그대로 들고 간다.
       */
      const 가름 = 가름찾기(this.표줄들.map(칸가르기));
      const 머리 = 가름 >= 1 ? this.표줄들.slice(0, 가름 + 1) : this.이어갈머리;
      const 나갈것 = this.#표비우기();
      this.이어갈머리 = 머리;
      return 나갈것;
    }

    // 표가 끝났다. 비운 **뒤에** 지운다 — 끝() 이 적어 둔 것과 같은 까닭이다.
    // 먼저 지우면 상한에 끊긴 표의 뒷동강이 머리줄과 칸 너비를 잃어, 산문이 한 줄
    // 오는 것만으로 표 아래쪽이 테두리도 정렬도 없는 딴 모양으로 나간다.
    const 앞 = this.#표비우기();
    // 다음 표는 제 폭을 처음부터 다시 잰다.
    this.이어갈머리 = null;
    this.표너비 = null;
    const r = 한줄(줄, this.상태, this.폭);
    this.상태 = r.상태;
    return [...앞, r.글];
  }

  넣기(토막) {
    // 모델 답은 바깥 글이다 — 섞여 온 터미널 제어 순서는 여기서 뗀다(ansi.js 화면글거르기 머리말).
    // 그리기() 도 이 길을 지나므로 한 자리에서 막힌다.
    let 날것 = this.날토막 + String(토막 ?? '');
    this.날토막 = '';
    let 끝ESC = Math.max(날것.lastIndexOf('\x1b'), 날것.lastIndexOf('\x9b'));
    // `ESC ] … ESC` 로 끝나면 마침 글자(ESC \) 가 반만 왔다. 그 ESC 만 붙들면 앞 몸통(링크 주소)이
    // 끝 안 난 순서로 걸러져 글자로 샌다 — 순서 머리부터 붙든다.
    if (끝ESC > 0 && 날것.slice(끝ESC) === '\x1b') {
      const 앞ESC = 날것.lastIndexOf('\x1b', 끝ESC - 1);
      if (앞ESC >= 0 && /^\x1b(?:\][^\x07\x1b\n]*|[PX^_][^\x1b\n]*)$/.test(날것.slice(앞ESC, 끝ESC))) 끝ESC = 앞ESC;
    }
    // 끝난 순서가 아니면(마침 글자 없음) 붙들어 둔다. 너무 길면 순서가 아니라 보고 그냥 뗀다.
    // 8비트 CSI(0x9b) 와 ESC 두 글자 꼴의 가운데 글자(`ESC (`)도 같다 — 안 붙들면 `2J` · `0` 이 글자로 남는다.
    if (끝ESC >= 0 && 날것.length - 끝ESC < 256
      && /^(?:\x1b(?:\[[0-?]*[ -/]*|\][^\x07\x1b\n]*\x1b?|[PX^_][^\x1b\n]*\x1b?|[ -/]*)?|\x9b[0-?]*[ -/]*)$/.test(날것.slice(끝ESC))) {
      this.날토막 = 날것.slice(끝ESC);
      날것 = 날것.slice(0, 끝ESC);
    }
    this.담긴것 += 화면글거르기(날것);
    const 나갈것 = [];

    for (;;) {
      const i = this.담긴것.indexOf('\n');
      if (i >= 0) {
        // \r\n 으로 온 줄은 여기서 \r 를 뗀다. 남겨서 내보내면 터미널에서 커서가
        // 줄 맨 앞으로 돌아가 앞에 세운 세로줄 위에 덮어쓴다 — 글자가 먹힌 것처럼
        // 보인다. 토막이 \r 와 \n 사이에서 끊겨 와도 여기로 모여서 걸린다.
        나갈것.push(...this.#그리기(this.담긴것.slice(0, i)));
        this.담긴것 = this.담긴것.slice(i + 1);
        continue;
      }
      /*
       * 표 줄은 길어도 안 흘려보낸다.
       *
       * 표 한 줄은 창보다 넓은 것이 보통이다(칸이 셋만 돼도 넘는다). 여기서
       * 날것으로 내보내면 그 줄은 표로 모이지도 못하고 세로줄이 그대로 뜬다 —
       * 고치려던 바로 그 모양이다. 그래서 세로줄로 시작하는 줄은 줄이 끝날
       * 때까지 기다린다.
       *
       * 그래도 상한은 둔다. 표가 아닌데 세로줄로 시작하는 긴 글(로그 한 덩이
       * 같은 것)이 오면 화면이 멈춘 것처럼 보이면 안 된다.
       */
      // 지금 담긴 것이 세로줄로 시작할 때만 기다린다. 「표를 붙들고 있으면
      // 무조건 기다린다」 로 두면, 표 뒤에 이어지는 긴 산문이 줄이 끝날 때까지
      // 화면에 한 글자도 안 나온다 — 사람 눈에는 답이 멈춘 것으로 보인다.
      const 표기다림 = !this.상태.펜스
        && /^\s*\|/.test(this.담긴것)
        && width(this.담긴것) <= this.폭 * 표줄최대배;
      if (표기다림) break;

      // 줄이 안 끝나는데 너무 길어졌다. 여기까지 날것으로 흘려보낸다 —
      // 멈춘 것처럼 보이는 것보다 안 꾸며진 글이 흐르는 편이 낫다.
      if (width(this.담긴것) > this.폭) {
        // 붙들고 있던 표부터 내보낸다. 안 그러면 표가 뒤에 나와서 순서가 뒤집힌다.
        나갈것.push(...this.#표비우기());
        // 날것으로 나가는 길에는 한줄() 이 안 끼므로 여기서 \r 를 턴다.
        나갈것.push({ 이어붙임: this.담긴것.replace(/\r/g, ''), 첫조각: !this.날것중, 끝났나: false });
        this.담긴것 = '';
        this.날것중 = true;
      }
      break;
    }
    return 나갈것;
  }

  /*
   * ── 여기서 **코드 울타리 안인지**까지 지운다 ────────────────────────────
   *
   * 이 파일 위쪽이 한 번 적어 뒀다 — 「울타리를 열기만 하면 그 뒤로 오는 답
   * 전체가 코드로 그려진다. 제목도 굵기도 다 사라지고, 화면은 멀쩡해 보인다」.
   * 그 일이 실제로 나던 자리가 여기다.
   *
   * 끝() 은 담긴 반 줄과 붙들고 있던 표는 비우면서 `상태.펜스` 만 켜 둔 채로
   * 돌아갔다. 부르는 쪽(repl.js)은 마크다운 하나를 한 턴 내내 쓰고, 도구를
   * 부를 때마다 여기를 거친다. 그래서 도구 부르기 직전에 ```js 한 줄이
   * 나갔으면 **그 턴의 남은 답이 통째로** 회색 세로줄 붙은 날글로 그려졌다.
   * 잘려서 다시 받는 자리(retry)는 더 나쁘다 — 새로 받은 답 전체가 그 꼴이 된다.
   *
   * 화면에 글자는 다 있다. 그래서 아무도 고장으로 안 읽고, 「모델이 오늘
   * 이상하게 답한다」 로 읽힌다. 흘려보내던 상태는 흘려보내기가 끝나는
   * **이 자리에서 다 지운다.**
   */
  /** 그리던 것을 다 잊는다. 다음 글은 처음부터 읽는다. */
  처음으로() {
    this.담긴것 = '';
    this.날토막 = '';
    this.상태 = { 펜스: false };
    this.날것중 = false;
    this.표줄들 = [];
    this.이어갈머리 = null;
    this.표너비 = null;
  }

  /** 답이 끝났다. 남은 것을 내놓는다. */
  끝() {
    const 나갈것 = [];
    // 끝내 마침 글자가 안 온 순서 앞머리는 글자가 아니다 — 떼고 버린다. 거르개에 넣었더니
    // ESC·`[` 만 떼이고 `ESC [1` 의 `1` 이 글자로 남았다 (2.0.0 6회차 마크6).
    this.날토막 = '';   // 붙들던 앞머리는 버린다
    // 담긴 것은 없는데 날것으로 나가던 중이면 줄만 끝내 준다.
    if (!this.담긴것) {
      if (this.날것중) 나갈것.push({ 이어붙임: '', 끝났나: true });
      this.날것중 = false;
      // 표로 끝나는 답이 흔하다(마지막이 정리 표). 여기서 안 비우면 통째로 사라진다.
      나갈것.push(...this.#표비우기());
    } else {
      const 남은것 = this.#그리기(this.담긴것);
      this.담긴것 = '';
      this.날것중 = false;
      나갈것.push(...남은것, ...this.#표비우기());
    }
    // 비운 **뒤에** 지운다. 먼저 지우면 위 두 줄이 붙들고 있던 표를 옛 방식으로
    // 내보낼 때 쓸 상태를 잃는다 — 글이 사라지는 것이 제일 나쁘다.
    this.처음으로();
    return 나갈것;
  }
}

/** 통째로 있는 글을 한 번에 그린다 (스트리밍이 아닌 자리). */
export function 그리기(글, 폭 = 80) {
  const s = String(글 ?? '');
  const md = new 마크다운({ 폭 });
  const 줄들 = [];
  // 마지막 줄에 개행을 얹어 준다. 흘려보내는 자리가 아니므로 줄이 안 끝날 일이
  // 없는데, 안 얹으면 마지막 줄이 폭을 넘는 순간 「아직 안 끝난 줄」 로 보여
  // 그 줄만 날것으로 나간다 — 별표와 우물정자가 거기서만 화면에 남는다.
  for (const x of md.넣기(s && !s.endsWith('\n') ? `${s}\n` : s)) 줄들.push(typeof x === 'string' ? x : x.이어붙임);
  for (const x of md.끝()) 줄들.push(typeof x === 'string' ? x : x.이어붙임);
  return 줄들;
}
