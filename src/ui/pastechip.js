// 붙여넣은 덩이를 표 하나로 접는다.
//
// ── 무슨 일이 났었나 ────────────────────────────────────────────────────
//
// 「붙여넣기 해도 창에 붙여넣기된 내용이 다 뜨는게 아니야 claude/codex 처럼
//  압축된 거 처럼 보이면 더 좋을거같아, 그래야 자기가 뭘 붙여넣기 한건지
//  보기 더 편하잖아」
//
// 입력 상자는 여덟 줄까지만 보여 주고(안쪽최대), 넘치면 **끝 여덟 줄**만
// 남긴다. 그래서 마흔 줄을 붙이면 앞 서른두 줄이 화면에서 사라진다. 사람
// 눈에는 앞부분이 안 들어간 것으로 보이고, 그래서 다시 붙인다. 다시 붙이면
// 이번엔 진짜로 두 번 들어간다.
//
// 접는 쪽이 낫다. 무엇을 붙였는지는 줄 수와 크기로 알 수 있고, 상자에는
// 그 표만 한 줄로 남으니 앞뒤로 무슨 말을 덧붙였는지가 그대로 보인다.
//
// ── 여기서 지키는 것 ────────────────────────────────────────────────────
//
// **접은 것은 보낼 때 글자 하나 안 틀리고 되돌아와야 한다.** 접기는 보기
// 좋으라고 하는 짓이지, 내용을 줄이는 짓이 아니다. 줄바꿈도 탭도 이모지도
// 바이트 그대로다. 되돌릴 수 없는 접기는 접기가 아니라 잘라내기다.
import { 접어쓰기 } from './wrap.js';
import { 안쪽최대 } from './inputbox.js';
import { 말, 말모두 } from '../i18n/index.js';

/** 사람이 읽는 크기. 47줄이 몇 KB 인지 알아야 뭘 붙였는지 감이 온다. */
export function 크기말(바이트) {
  const n = Number(바이트) || 0;
  if (n < 1024) return `${n}B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)}KB`;
  return `${(n / (1024 * 1024)).toFixed(1)}MB`;
}

/**
 * 이 덩이가 상자에 안 들어가나.
 *
 * 들어가면 접지 않는다 — 세 줄짜리는 그냥 보이는 편이 낫다. 접을지는
 * 줄 수만 세면 안 된다. 한 줄이어도 폭보다 길면 상자 안에서 여러 줄로
 * 접히기 때문이다. 그래서 상자가 쓰는 접어쓰기 로 똑같이 세어 본다.
 */
export function 접을까(글, { 폭 = 80, 최대 = 안쪽최대 } = {}) {
  const 원 = String(글 ?? '');
  if (!원) return false;

  /*
   * 줄이 둘 이상이면 무조건 접는다 — 상자가 그것밖에 못 보여 주기 때문이다.
   *
   * readline 의 `rl.line` 에는 개행을 못 넣는다. 넣으면 보낼 때 줄 순서가
   * 뒤집힌다(newline.test.js 가 지키는 자리다). 그래서 붙여넣은 나머지 줄은
   * 상자 밖 버퍼에 따로 두는데, 상자는 `rl.line` 만 그린다. 결과는 이렇다.
   *
   *     넉 줄을 붙인다 → 「4줄을 붙여넣었습니다」 가 뜨고
   *                      상자에는 **맨 밑 한 줄만** 보인다
   *
   * 여덟 줄까지는 들어가니까 안 접어도 된다고 여겼던 것이 틀렸다. 들어갈
   * 자리가 있느냐가 아니라 **그릴 수 있느냐**가 갈림이다. 못 그릴 바에는
   * 표 한 줄로 접는 편이 낫다 — 몇 줄 몇 바이트인지는 그대로 보이고,
   * 앞뒤에 덧붙인 말도 안 가려진다.
   */
  if (원.includes('\n')) return true;

  const 쓸폭 = Math.max(4, Number(폭) || 80);
  let 줄수 = 0;
  for (const 한줄 of 원.split('\n')) {
    줄수 += Math.max(1, 접어쓰기(한줄, 쓸폭).length);
    if (줄수 > 최대) return true;
  }
  return false;
}

/**
 * 대화에 **남길** 글. 표는 작을 때만 펴서 남긴다.
 *
 * 상자에 그릴 때와 대화에 남길 때는 셈이 다르다. 상자는 `rl.line` 이라
 * 여러 줄을 못 그리니 몇 줄이든 접어야 한다. 대화는 그냥 찍는 자리라
 * 못 그릴 것이 없다 — 오히려 접으면 나중에 스크롤을 올렸을 때 무엇을
 * 보냈는지가 사라진다.
 *
 * 그렇다고 마흔 줄을 다 찍으면 화면이 붙인 글로 뒤덮인다. 그래서 상자에
 * 들어갈 만한 크기(안쪽최대)까지만 펴고, 그보다 크면 표를 남긴다 — 표에는
 * 줄 수와 크기가 적혀 있어서 그 자체가 기록이 된다.
 */
export function 남길글(글, 붙인것들) {
  const 원 = String(글 ?? '');
  const 펴진것 = 펼치기(원, 붙인것들);
  if (펴진것 === 원) return 원;
  return 펴진것.split('\n').length <= 안쪽최대 ? 펴진것 : 원;
}

/** `[붙여넣기 #1 · 47줄 · 2.1KB]` — 낱말은 고른 말을 따른다. */
export function 표만들기(번호, 글) {
  const 원 = String(글 ?? '');
  const 줄 = 말('paste.chipLines', { n: 원.split('\n').length });
  return `[${말('paste.chip')} #${번호} · ${줄} · ${크기말(Buffer.byteLength(원, 'utf8'))}]`;
}

/*
 * 표를 알아보는 무늬.
 *
 * 대괄호를 안에 안 받는다. 안 그러면 표 두 개가 붙어 있을 때 욕심껏
 * 한 덩이로 먹어서 둘 다 못 알아본다.
 *
 * /g 를 안 붙인다 — 붙이면 lastIndex 가 남아서 같은 무늬로 test() 를
 * 두 번 부를 때 두 번째가 조용히 거짓이 된다. 훑는 자리에서만 새로 만든다.
 */
/*
 * 낱말은 **네 말을 다 받는다.**
 *
 * 표를 찍은 뒤에 `/lang en` 을 치면, 지금 말로만 찾는 무늬는 앞서 찍어 둔
 * 표를 못 알아본다. 그러면 사람이 붙인 40줄이 표 글자 그대로 모델에게
 * 가고, 아무 데도 안 적히는 채로 그렇게 된다. 어느 말로 찍힌 표든 편다.
 */
const 낱말들 = 말모두('paste.chip').map((w) => String(w).replace(/[.*+?^${}()|[\]\\]/g, (ch) => `\\${ch}`));
export const 표무늬 = new RegExp(`\\[(?:${낱말들.join('|')}) #(\\d+) · [^[\\]]*\\]`);

/** 글 안의 표를 원문으로 되돌린다. 모르는 번호는 사람이 친 글로 보고 둔다. */
export function 펼치기(글, 붙인것들) {
  const 원 = String(글 ?? '');
  if (!붙인것들 || typeof 붙인것들.get !== 'function') return 원;
  return 원.replace(new RegExp(표무늬.source, 'g'), (통째, 번호) => {
    const 속 = 붙인것들.get(Number(번호));
    return 속 === undefined ? 통째 : 속;
  });
}

/** 이 글이 쓴 표 번호들. 다 쓴 것은 치워야 대화가 길어져도 안 쌓인다. */
export function 쓴번호들(글) {
  const 본것 = [];
  String(글 ?? '').replace(new RegExp(표무늬.source, 'g'), (_통째, 번호) => {
    본것.push(Number(번호));
    return '';
  });
  return 본것;
}
