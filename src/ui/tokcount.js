// 화면에 적을 토큰 수 — 실측과 어림을 한 자리에서 가른다.
//
// ── 왜 따로 있나 ────────────────────────────────────────────────────────
//
//   「모델도 명확한 모델명이 뜨는데 out / in 토큰값을 못 받는다고 확인 못하는건 좀 문제가 있어보여」
//
// 창구가 usage 를 안 주면 /cost · 끝맺음 줄 · 상태줄이 셋 다 입력 0 · 출력 0 을 적었다. 103번을 부르고
// 「0」 이라고 적는 것은 모른다는 말을 숫자로 지어낸 것이다. 그렇다고 어림을 실측 칸에 섞으면 금액과
// 배수 배우기가 지어낸 값 위에 선다(agent/session.js 의 추정in 머리말).
//
// 그래서 둘을 따로 들고 있다가 **화면에서만** 더한다. 어림이 섞인 수에는 언제나 「≈」 를 붙인다. 셋이
// 저마다 더하면 언젠가 한 곳이 ≈ 를 빠뜨린다 — 그래서 이 파일 하나를 같이 쓴다.

/**
 * @param {object} u session.usage (또는 갈래 합)
 * @returns {{입력: number, 출력: number, 추정: boolean, 잰입력: number, 잰출력: number, 추정입력: number, 추정출력: number}}
 *   입력 · 출력 — 실측 + 어림. 추정 — 어림이 하나라도 섞였나.
 */
export function 토큰셈(u = {}) {
  const 잰입력 = Number(u?.prompt || u?.in || 0);
  const 잰출력 = Number(u?.out || 0);
  const 추정입력 = Number(u?.추정in || 0);
  const 추정출력 = Number(u?.추정out || 0);
  return {
    입력: 잰입력 + 추정입력,
    출력: 잰출력 + 추정출력,
    추정: 추정입력 + 추정출력 > 0,
    잰입력, 잰출력, 추정입력, 추정출력,
  };
}

/** 어림이 섞였으면 앞에 ≈ 를 붙인다. `꼴` 은 수를 글로 바꾸는 함수(toLocaleString · short). */
export function 토큰글(수, 추정, 꼴 = (n) => n.toLocaleString()) {
  return `${추정 ? '≈' : ''}${꼴(Number(수) || 0)}`;
}
