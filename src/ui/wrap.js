// 색을 유지하면서 폭에 맞춰 접기.
//
// 전에는 전체화면(tui.js)에만 쓰던 것이라 거기 있었다. 전체화면을 걷어내면서
// 여기로 옮긴다 — 입력 상자가 긴 입력을 접을 때 같은 것이 필요하다.
// 한덩이 — 보이는 한 덩이 떼기. clip 도 같은 것을 써야 해서 ansi.js 로 옮겼다(그 머리말).
import { width, 한덩이 } from './ansi.js';

const 색코드들 = /\x1b\[[0-9;]*m/g;

/**
 * 색을 유지하면서 폭에 맞춰 접는다.
 *
 * clip 은 잘라 버리지만 사람이 친 글은 잘리면 안 된다 — 뒷부분이 통째로
 * 사라진다. 그래서 접는다. 색 코드는 폭이 0 이므로 세지 않고, 줄을 넘길 때
 * 마지막으로 켜져 있던 색을 다음 줄 앞에 다시 켜 준다. 안 그러면 접힌 줄부터
 * 색이 풀려 화면이 얼룩덜룩해진다.
 */
export function 접어쓰기(글, 폭, 설정 = {}) {
  /*
   * `빈칸줄남김` — 빈칸뿐인 마지막 줄을 버리지 않는다.
   *
   * 대화 글을 접을 때는 끝의 빈칸이 넘친 줄을 버리는 것이 맞다(보이는 것이 없는 줄이 한 줄
   * 더 생길 뿐이다). 그런데 입력 상자는 **사람이 친 빈칸**을 그리고 그 뒤에 커서를 세운다.
   * 터미널은 넘친 빈칸을 다음 줄로 보내 커서를 거기 두는데, 줄을 버리면 상자는 한 줄로 세고
   * 커서를 윗줄 끝에 세운다 — 친 빈칸이 안 들어간 것처럼 보이고 줄 셈이 한 줄 어긋난다.
   */
  const { 빈칸줄남김 = false } = 설정 ?? {};
  const s = String(글 ?? '');
  /*
   * 줄바꿈(\n)이 있으면 그 자리에서 반드시 갈라진다.
   *
   * 안 가르고 그냥 폭만 재면, \n 도 그저 글자 하나로 세여서(너비는
   * width() 가 정하는 대로) 다음 글자와 한 '줄'에 같이 담긴다. 입력 상자를
   * 그리는 쪽(inputbox.js 의 그리기())은 여기서 나온 배열 길이를 그대로
   * "화면에 몇 줄 찍었나" 로 믿고 커서를 되짚어 올라가므로, \n 이 숨어
   * 있으면 터미널이 실제로 그린 줄 수와 어긋나 화면이 깨진다. 문단마다
   * 따로 접어서 이 배열이 실제 화면 줄 수와 늘 같게 만든다.
   */
  if (s.includes('\n')) return s.split('\n').flatMap((줄) => 접어쓰기(줄, 폭, 설정));
  if (폭 < 2) return [s];
  if (width(s) <= 폭) return [s];

  /*
   * 접힌 줄에 앞 들여쓰기를 물려 준다.
   *
   * 안 물려 주면 `  ▌ 모델의 답…` 이 접히는 순간 다음 줄이 왼쪽 끝에서
   * 시작한다. 화면에서 세로줄이 끊겨 보이고, 도구 결과의 `    └ …` 도
   * 두 번째 줄부터 갑자기 튀어나온다 — 무엇에 딸린 글인지 알 수 없게 된다.
   * 들여쓴 만큼은 글자 자리에서 빼야 하므로 접는 폭도 같이 줄인다.
   *
   * 빈칸을 세기 전에 맨 앞의 색 코드를 건너뛴다. 빈칸만 찾으면 색이 먼저 온 줄
   * (`c.gray('    └ …')` 처럼 줄 전체에 색을 씌운 자리)에서 들여쓰기를 0 으로 재고,
   * 접힌 줄이 왼쪽 끝에서 시작한다. 보이는 모양은 민 글과 똑같은데 접은 결과만
   * 달라지는 자리라 화면으로는 늦게 잡힌다 (2.0.0 8회차 uimisc WR2).
   */
  const 들여 = ((/^(?:\x1b\[[0-9;]*m)*( *)/.exec(s) ?? [])[1] ?? '').slice(0, Math.max(0, 폭 - 8));
  const 이어폭 = Math.max(2, 폭 - 들여.length);

  const 줄들 = [];
  let 지금 = '';
  let w = 0;
  let 색 = '';                       // 지금 켜져 있는 SGR

  for (let i = 0; i < s.length;) {
    // 색 코드는 통째로 옮긴다. 폭에는 안 센다.
    if (s[i] === '\x1b') {
      const m = /^\x1b\[[0-9;]*m/.exec(s.slice(i));
      if (m) {
        지금 += m[0];
        색 = /\x1b\[0?m/.test(m[0]) ? '' : 색 + m[0];
        i += m[0].length;
        continue;
      }
    }
    const ch = 한덩이(s, i);
    const cw = width(ch);
    // 첫 줄은 원래 폭, 접힌 줄부터는 들여쓴 만큼 좁아진다.
    const 한도 = 줄들.length === 0 ? 폭 : 이어폭 + 들여.length;
    if (w + cw > 한도) {
      줄들.push(지금 + (색 ? '\x1b[0m' : ''));
      지금 = 들여 + 색;
      w = 들여.length;
    }
    지금 += ch;
    w += cw;
    i += ch.length;
  }
  // 빈칸뿐인지는 색 코드를 떼고 본다. 색이 켜진 채 넘친 빈칸 줄은 코드가 붙어 있어 trim 으로는 안
  // 비는데, 보이는 것은 똑같이 없다 — 색 없는 글과 줄 수가 달라진다 (2.0.0 6회차 WR1).
  if (빈칸줄남김 || 지금.replace(색코드들, '').trim() !== '' || 줄들.length === 0) 줄들.push(지금 + (색 ? '\x1b[0m' : ''));
  return 줄들;
}
