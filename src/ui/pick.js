// 고른 번호 + 하고 싶은 말, 한 줄에서 갈라 읽기.
//
// ── 사람 말 ─────────────────────────────────────────────────────────────
//
//   「사용자에게 계획 물어볼 때 번호만 입력하는 게 아니라, 번호를 고르고
//    의견이 있으면 의견도 입력할 수 있게」
//
// 여태는 둘 중 하나였다. 숫자만 치면 그 줄을 고른 것이고, 그 밖의 글은
// **고른 것 없이** 통째로 자유 답이었다. 그래서 「2번인데 파일은 나눠서」
// 라고 치면 2번을 고른 사실이 사라진다. 사람은 골랐다고 생각하는데
// 모델에게는 고른 것이 없는 문장 하나만 간다.
//
// 실제로는 이렇게 답하고 싶어진다 —
//
//     2 파일은 나눠서 해줘        (고르고 + 덧붙이고)
//     2: 파일은 나눠서 해줘
//     2, 파일은 나눠서 해줘
//     2 - 파일은 나눠서 해줘
//     1,3                        (둘 다)
//     1 3 둘 다 하되 순서는 반대로
//     2번 파일은 나눠서           (한국 사람은 번호를 「2번」 이라고 친다)
//
// ── 어디서 멈추나 ───────────────────────────────────────────────────────
//
// 숫자로 읽는 것은 **머리에 붙은, 목록 안에 있는 수**뿐이다. 그 뒤로는 다
// 사람 말이다. 이 선이 없으면 「3개만 해줘」 가 3번을 고른 것이 된다 —
// 사람이 고른 적 없는 것을 골랐다고 하는 셈이라, 안 받느니만 못하다.
// 그래서 수 바로 뒤에 글자가 붙어 있으면(3개) 수로 안 읽는다.
//
// 「번」 하나만 그 선 안으로 들인다. 「2번」 을 못 읽으면 가장 흔한 답이 고른 것 없는 글이
// 된다. 「번」 뒤에도 끝이나 구분표가 와야 한다 — 「2번째로」 · 「2번으로 해줘」 는 여태처럼
// 사람 말로 둔다(골랐다고 우기는 쪽이 더 나쁘다).
//
// 목록에 없는 수도 안 읽는다. 선택지가 둘인데 「5분만 기다려」 라고 치면
// 그건 고른 것이 아니라 하는 말이다.

/*
 * 수 뒤에 올 수 있는 것 — 끝, 빈칸, 그리고 흔한 구분표. `1.5` 는 수가 아니다.
 *
 * 「번」 앞의 빈칸도 받는다. 「1 번」 이라고 치면 「번」 이 하고 싶은 말로 남아 모델에게
 * 「가 — 번」 이 갔다 (2.0.0 6회차 고르기6cg PK1).
 *
 * 붙임표도 구분표다. 머리말이 적어 둔 「2 - 나눠서」 는 읽으면서 빈칸 없는 「2- 나눠서」 는
 * 아무것도 못 골랐다. 다만 뒤가 숫자면 안 읽는다 — 「2-3」 은 범위로 친 말이지 둘을 고른 것이
 * 아니다 (PK2).
 *
 * 「번」 뒤도 마찬가지다. 전방탐색에 붙임표가 빠져 있어서 「2번- 나눠서」 만 아무것도 못 골랐다 —
 * 「2- 나눠서」 는 읽는데 「번」 을 하나 더 친 사람만 고른 것이 사라진다 (8회차 PK4).
 */
const 수뒤 = /^(\d{1,3})(?:\s*번(?=[\s,，、·.):：\]\-–—]|$))?(?:\s*[.):：\]](?!\d)|\s*[,，、·]|\s*[-–—](?!\d)|\s|$)/;

/** 수와 말 사이에 사람이 흔히 넣는 것들. 말 앞머리에서 떼어 낸다. */
const 사이표 = /^[\s,，、·:：\-–—>]+/;

/** 전각 숫자(０–９)를 보통 숫자로. 일본어·중국어 입력기는 번호를 이렇게 낸다. */
const 숫자펴기 = (s) => String(s ?? '').replace(/[０-９]/g, (d) => String.fromCharCode(d.charCodeAt(0) - 0xfee0));

/**
 * 답 한 줄을 「고른 번호들」과 「덧붙인 말」로 가른다.
 *
 * @param {string} 답 사람이 친 그대로
 * @param {string[]} 고를것 보여 준 선택지
 * @returns {{번호들: number[], 덧말: string, 글: string}}
 *   글 — 모델에게 보낼 한 줄. 고른 것이 없으면 친 글 그대로다.
 */
export function 고른것풀기(답, 고를것 = []) {
  const 원 = String(답 ?? '').trim();
  const 목록 = Array.isArray(고를것) ? 고를것 : [];
  if (!원) return { 번호들: [], 덧말: '', 글: '' };

  const 번호들 = [];
  let 남은 = 숫자펴기(원);
  for (;;) {
    const m = 수뒤.exec(남은);
    if (!m) break;
    const n = Number(m[1]);
    // 목록 밖의 수는 고른 것이 아니라 하는 말이다.
    if (!Number.isInteger(n) || n < 1 || n > 목록.length) break;
    // 같은 것을 두 번 쳐도 한 번만 센다 — 「1 1」 을 두 갈래로 읽을 까닭이 없다.
    if (!번호들.includes(n)) 번호들.push(n);
    남은 = 남은.slice(m[0].length).replace(사이표, '');
  }

  const 덧말 = 남은.trim();
  // 아무 수도 못 읽었으면 여태와 똑같다 — 친 글이 그대로 답이다.
  if (!번호들.length) return { 번호들: [], 덧말: '', 글: 원 };

  const 고른 = 번호들.map((n) => String(목록[n - 1] ?? '').trim()).filter(Boolean);
  const 글 = 고른.join(' · ') + (덧말 ? ` — ${덧말}` : '');
  return { 번호들, 덧말, 글 };
}

/*
 * 계획 상자 첫 낱말을 표와 견주기 전에 다듬는다.
 *
 * 글자 그대로 견줬더니 「ok.」 「네.」 「yes!」 가 표에 없는 글이 되어 「그 말대로 다시 짜라」 로
 * 갔다. 자음을 두 번 친 「ㅇㅇ」 「ㄴㄴ」 도 그랬다 — 그러라고 했는데 계획이 또 나오고, 그만하라고
 * 했는데 또 나온다.
 *
 * 떼는 것은 끝의 마침표·느낌표·물결뿐이다. **물음표는 안 뗀다** — 「네?」 「ok?」 는 되묻는
 * 말이지 그러라는 말이 아니다. 애매하면 여태처럼 「다시」 로 두는 편이 낫다(계획을 한 번 더
 * 보는 것이, 안 시킨 일을 하는 것보다 싸다).
 */
function 낱말다듬기(낱말) {
  return String(낱말 ?? '').toLowerCase()
    .replace(/[.!~。！]+$/u, '')
    .replace(/^(ㅇ|ㄴ|ㄱ)\1+$/u, '$1');
}

/*
 * ── 멈추라는 말 · 진행을 뒤집는 말 (Gemini 화면4) ──────────────────────────
 *
 * 첫 낱말만 표와 견줬다. 그래서 두 자리가 틀렸다.
 *   · 「그만」 「멈춰」 「stop」 「cancel」 이 멈춤 표에 없어서 「그 말대로 다시 짜라」 로 갔다 —
 *     그만하라는데 계획이 또 나온다.
 *   · 첫 낱말이 진행 쪽이면 뒤는 「진행하되 한마디」 로 얹었다. 「ok 말고」 「진행 하지 마」
 *     「응 취소」 「y 아니 멈춰」 가 전부 **계획 실행**으로 갔다 — 안 시킨 일을 한다.
 *
 * 뒤에 부정·멈춤 말이 붙은 진행은 뜻이 둘로 읽힌다. 멈춤으로 못 박지도 않는다(「y 테스트는 하지
 * 말고」 는 진행하되 빼라는 말일 수 있다). 여태 원칙대로 「다시」 — 계획을 한 번 더 보는 것이
 * 안 시킨 일을 하는 것보다 싸다. 영어 낱말은 낱말 경계로만 본다 — 「note」 의 not 에 안 걸리게.
 */
const 멈춤낱말 = ['n', 'no', 'nope', 'ㄴ', '아니', '아니요', '아뇨', '취소', '그만', '그만해', '멈춰', '중단', '종료', '중지', '포기', 'stop', 'cancel', 'abort', 'quit'];
const 뒤집는말 = /말고|하지\s*마|하지\s*말|안\s*돼|안\s*되|멈춰|멈추|그만|취소|중단|종료|포기|중지|아니|아뇨|잠깐|(?:^|[^a-z])(?:no|not|nope|don['’]?t|abort|quit|halt|stop|cancel|wait)(?![a-z])/i;
/*
 * 멈추라는 말을 **뒤집는** 말. 「취소 말고」 「그만 말고」 는 멈추라는 말이 아니다.
 *
 * 위 뒤집는말 을 그대로 쓰면 안 된다 — 거기에는 멈춤 말이 다 들어 있어서 「no 그만해」 처럼
 * 두 번 멈추라는 답까지 「다시」 로 가고, 그만하라는데 계획이 또 나온다. 그래서 여기서는
 * 부정하는 말만 본다. 진행 쪽에 이미 있는 원칙(애매하면 다시)을 멈춤 쪽에도 맞춘 것이다
 * (2.0.0 6회차 고르기6cg PK3).
 */
const 부정말 = /말고|하지\s*마|하지\s*말|안\s*돼|안\s*되/;
/*
 * 그러라는 말. 「진행해」 「좋아」 「ㄱㄱ」 「okay」 가 표에 없어서 「그 말대로 다시 짜라」 로 갔다 —
 * 그러라고 했는데 계획이 또 나온다(Gemini 화면5). 멈추라는 말만큼 비싸지는 않지만 한 번 더 도는 값을 치른다.
 */
const 진행낱말 = ['y', 'yes', 'ㅇ', '응', '네', '예', '진행', '진행해', '진행해줘', '좋아', '좋아요', '좋습니다', '그래', '그래요',
  'ok', 'okay', 'sure', 'go', 'ㄱ', '고', '고고'];

/**
 * 계획 상자의 답을 읽는다.
 *
 * 갈래는 셋(진행·그만·다시)이고, 들어오는 모양은 다섯이다.
 *   · 그냥 진행      — ⏎ · y · yes · ㅇ · ㅇㅇ · 응 · 진행 (끝의 . ! 는 떼고 본다)
 *   · 진행하되 한마디 — `y 검사도 같이 넣어줘`
 *   · 그만            — n · no · ㄴ · ㄴㄴ · 그만 · 멈춰 · 취소 · stop · cancel
 *   · 그 밖의 글      — 그 말대로 다시 짜라 (여태 그대로). 진행 낱말 뒤에 뒤집는 말이 붙어도(「ok 말고」) 여기다
 *   · `3 이건 빼자`   — 3단계에 대한 말로 붙여서 다시 짜라 (`3번 이건 빼자` 도)
 *
 * ⏎ 하나로 진행하는 것은 안 건드린다. 계획을 읽고 「그래」 하는 데
 * 두 글자를 더 치게 하면, 그 두 글자 때문에 안 읽고 넘기게 된다.
 *
 * @param {string} 답
 * @param {number} 단계수 계획이 몇 단계인가 (번호를 가려내는 데 쓴다)
 * @returns {{갈래: '진행'|'그만'|'다시', 덧말: string, 단계: number|null}}
 */
export function 계획답풀기(답, 단계수 = 0) {
  const 원 = String(답 ?? '').trim();
  if (!원) return { 갈래: '진행', 덧말: '', 단계: null };

  const 첫낱말 = 낱말다듬기(원.split(/\s+/)[0]);
  const 나머지 = 원.slice(원.split(/\s+/)[0].length).replace(사이표, '').trim();

  if (멈춤낱말.includes(첫낱말)) {
    // 「취소 말고」 「그만 말고」 — 첫 낱말은 멈춤인데 뒤가 뒤집는다. 진행 쪽과 같이 「다시」 로 둔다.
    if (부정말.test(나머지)) return { 갈래: '다시', 덧말: 원, 단계: null };
    return { 갈래: '그만', 덧말: '', 단계: null };
  }
  if (진행낱말.includes(첫낱말)) {
    // 「ok 말고」 「응 취소」 — 첫 낱말은 진행인데 뒤가 뒤집는다. 애매하면 다시 (위 뒤집는말 머리말).
    if (뒤집는말.test(나머지)) return { 갈래: '다시', 덧말: 원, 단계: null };
    return { 갈래: '진행', 덧말: 나머지, 단계: null };
  }

  // 「3 이건 빼자」 — 그 단계에 대고 하는 말이다.
  const 펴진 = 숫자펴기(원);
  const m = 수뒤.exec(펴진);
  if (m) {
    const n = Number(m[1]);
    if (Number.isInteger(n) && n >= 1 && n <= 단계수) {
      const 말 = 펴진.slice(m[0].length).replace(사이표, '').trim();
      if (말) return { 갈래: '다시', 덧말: 말, 단계: n };
    }
  }

  return { 갈래: '다시', 덧말: 원, 단계: null };
}
