/**
 * 테마 하나. 이름 → { 칸수, 가로, 그림들, 틀 }.
 *
 * 기본은 위에서 이미 만들어 둔 것을 그대로 쓴다 — 다시 만들면 같은 것이
 * 두 벌 생긴다.
 */
const 테마만들기 = (그림들, 폭) => ({
  칸수: 폭,
  가로: 폭 * 2,
  그림들,
  틀: Object.fromEntries(
    Object.entries(그림들).map(([갈래, 장들]) => [갈래, 장들.map((g) => 점자로(g, 폭))]),
  ),
});

export const 테마들 = {
  기본: { 칸수, 가로, 그림들, 틀 },
  기사: 테마만들기(기사그림들, 넓은칸수),
  동물: 테마만들기(동물그림들, 넓은칸수),
};

/**
 * 지금 고른 테마.
 *
 * DEEL_MOTION=기사 · knight · 동물 · animal 로 고른다. 영어 이름도 받는 것은
 * 한글을 못 치는 자리(CI 설정 파일·도커 환경변수)가 있기 때문이다.
 * 모르는 이름이면 조용히 기본으로 간다 — 오타 하나로 프로그램이 안 뜨면 안 된다.
 */
const 이름표 = {
  기사: '기사', knight: '기사', 동물: '동물', animal: '동물', animals: '동물',
  기본: '기본', default: '기본', plain: '기본',
};
export const 테마이름 = () => 이름표[String(process.env.DEEL_MOTION ?? '').trim().toLowerCase()]
  ?? 이름표[String(process.env.DEEL_MOTION ?? '').trim()]
  ?? '기본';
export const 테마 = () => 테마들[테마이름()] ?? 테마들.기본;

/*
 * 그림을 끄고 싶을 때.
 *
 * 점자가 안 나오는 터미널·화면 읽기 프로그램·화면을 그대로 캡처해 붙여야 하는
 * 자리가 있다. 그럴 때 DEEL_NO_MOTION=1 이면 예전처럼 한 칸짜리 돌림표만 돈다.
 * 아예 못 끄게 해 두면 그런 사람은 도구를 못 쓴다.
 */
export const 끔 = () => !!process.env.DEEL_NO_MOTION;

// 못 끄는 자리에서 쓸 한 칸짜리. working.js 의 돌림틀과 같은 것이다.
const 한칸 = ['⠋', '⠙', '⠹', '⠸', '⠼', '⠴', '⠦', '⠧', '⠇', '⠏'];

/**
 * 지금 그릴 그림 한 장.
 *
 * 틱을 받는다. 시각을 안에서 읽으면 검사가 '한 장 뒤' 를 재려고 진짜로
 * 기다려야 한다 — working.js 의 문구고르기와 같은 이유다.
 *
 * @param {string} 갈래 working.js 의 갈래 이름
 * @param {number} 틱   90ms 마다 하나씩 오르는 수
 * @returns {string} 점자 세 글자 (끈 상태면 한 글자)
 */
export function 그림고르기(갈래, 틱 = 0) {
  const n = Math.trunc(틱) || 0;
  if (끔()) return 한칸[((n % 한칸.length) + 한칸.length) % 한칸.length];
  // 테마는 매번 읽는다. 켤 때 한 번 굳혀 두면 검사가 테마를 바꿔 가며
  // 못 잰다 — 90ms 마다 객체 하나 집는 값은 화면에 안 잡힌다.
  const 이틀 = 테마().틀;
  const 장들 = 이틀[갈래] ?? 이틀.기본;
  return 장들[((n % 장들.length) + 장들.length) % 장들.length];
}
