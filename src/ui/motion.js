/**
 * 일하는 중에 도는 작은 그림.
 *
 * ── 왜 넣나 ─────────────────────────────────────────────────────────────
 *
 * working.js 에 적어 둔 이유가 그대로 여기에도 해당한다. 로컬 모델은 한 걸음에
 * 수십 초가 걸리고, 그 동안 화면이 조용하면 사람은 멈춘 줄 알고 Ctrl+C 를 누른다.
 *
 * 그런데 이유가 하나 더 있다. **몇 분을 기다리는 화면은 보고 있을 만해야 한다.**
 * 점 하나가 도는 것과 지금 무슨 일을 하는지가 그림으로 보이는 것은 다르다.
 * 파일을 읽는 중이면 훑는 줄이 내려가고, 코드를 짜는 중이면 자판을 두드린다.
 * 재미로 넣은 것이 맞고, 그 재미가 기다리는 시간을 견디게 한다.
 *
 * ── 왜 점자인가 ─────────────────────────────────────────────────────────
 *
 * 상자 안에 들어가야 하므로 폭이 정확해야 한다. 이모지는 터미널마다 한 칸이
 * 되기도 두 칸이 되기도 해서 테두리가 어긋난다. ● ○ ▪ 같은 기호도 동아시아
 * 로캘에서는 두 칸으로 잡히는 것들이 섞여 있다(East Asian Ambiguous).
 *
 * 점자(U+2800~)는 어디서나 **한 칸**이다. 이 저장소가 이미 점자 돌림표를 쓰는
 * 이유가 그것이고, 같은 이유로 여기서도 점자만 쓴다.
 *
 * 그리고 점자 한 칸은 **가로 2 · 세로 4 점**이다. 세 칸을 붙이면 6×4 격자가
 * 생긴다. 작지만 자판을 두드리는 노트북이 들어간다.
 *
 * ── 어떻게 그리나 ───────────────────────────────────────────────────────
 *
 * 그림을 점자 코드로 직접 적으면 나중에 아무도 못 고친다. 그래서 눈에 보이는
 * 대로 '#' 과 '.' 으로 적고, 켜질 때 한 번 점자로 바꾼다.
 */

// 점 번호와 자리. 점자는 이렇게 번호가 매겨져 있다 —
//   1 4
//   2 5
//   3 6
//   7 8
// 아래 표는 [행][열] → 그 점의 비트값이다.
const 비트 = [
  [0x01, 0x08],
  [0x02, 0x10],
  [0x04, 0x20],
  [0x40, 0x80],
];

export const 칸수 = 3;      // 점자 세 칸
export const 가로 = 칸수 * 2; // 점 6개
export const 세로 = 4;       // 점 4줄

/**
 * 6×4 그림 한 장을 점자 세 글자로. 격자를 벗어난 자리는 꺼진 것으로 본다.
 *
 * @param {string[]} 그림 '#'(켜짐)과 그 밖(꺼짐)으로 그린 4줄
 */
export function 점자로(그림) {
  let out = '';
  for (let 칸 = 0; 칸 < 칸수; 칸++) {
    let v = 0;
    for (let r = 0; r < 세로; r++) {
      for (let cc = 0; cc < 2; cc++) {
        if (그림[r]?.[칸 * 2 + cc] === '#') v |= 비트[r][cc];
      }
    }
    out += String.fromCharCode(0x2800 + v);
  }
  return out;
}

