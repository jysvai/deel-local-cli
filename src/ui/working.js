/** 도구 이름으로 갈래를 고른다. 밖에서 붙인 도구(mcp__…)는 무엇을 할지 모른다. */
export function 갈래고르기(도구이름) {
  if (!도구이름) return '기본';
  if (String(도구이름).startsWith('mcp__')) return '기본';
  return 도구갈래[도구이름] ?? '기본';
}

/**
 * 갈래와 회차로 문구 하나. 회차가 늘면 다음 것으로 넘어간다.
 *
 * 시각이 아니라 회차를 받는 이유: 이래야 검사가 잴 수 있다. 시각을 안에서
 * 읽으면 '4초 뒤에 바뀌는가' 를 재려고 검사가 진짜로 4초를 기다려야 한다.
 */
export function 문구고르기(갈래, 회차 = 0) {
  const 목록 = 문구[갈래] ?? 문구.기본;
  const i = ((Math.trunc(회차) % 목록.length) + 목록.length) % 목록.length;
  return 목록[i];
}

// 돌아가는 표시. 점자 여덟 칸짜리는 폭이 한 칸이라 테두리를 안 밀어낸다.
