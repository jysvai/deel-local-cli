/** 걸린 시간을 짧게. 1분이 넘으면 분까지 적는다 — 90초보다 1분 30초가 읽힌다. */
export function 걸린시간(ms) {
  const 초 = Math.max(0, Math.floor(ms / 1000));
  if (초 < 60) return `${초}초`;
  return `${Math.floor(초 / 60)}분 ${String(초 % 60).padStart(2, '0')}초`;
}

