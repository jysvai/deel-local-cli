// JSON-RPC 2.0 을 줄 단위로 주고받는 관. ACP 가 표준입출력에서 쓰는 그 방식이다.
//
// ── 왜 따로 냈나 ────────────────────────────────────────────────────────
//
// 이 파일에는 deel 이야기가 한 줄도 없다. 넣을 수 있었지만 안 넣었다.
//
// 붙이는 쪽(serve.js)은 진짜 프로세스를 띄우고, 진짜 파이프로 주고받고, 진짜
// 모델을 부른다. 그 안에서 "덩이가 반 토막 나서 왔을 때 잘 붙이는가" 를 재려면
// 대화 한 판을 통째로 돌려야 한다. 그러면 검사가 느려지고, 무엇보다 **틀린 자리를
// 짚어 주지 못한다** — 화면에는 "답이 안 왔습니다" 만 남는다.
//
// 관을 따로 떼어 두면 그 자리를 함수 하나로 잴 수 있다. 실제로 이 파일에서
// 잡은 것들이다:
//
//   · 한 덩이에 메시지가 두 개 실려 온다 (파이프는 줄 단위로 안 끊어 준다)
//   · 한 메시지가 세 덩이로 쪼개져 온다 (한글이 섞이면 더 잘 그런다)
//   · id 가 0 인 요청 — `if (msg.id)` 로 보면 알림으로 오해한다. ACP 는 0부터 센다
//   · 다루는 함수가 늦게 끝나는 사이에 취소가 들어온다
//
// ── 지켜야 하는 것 ──────────────────────────────────────────────────────
//
// ACP 규격은 "메시지는 개행으로 나뉘며 **개행을 품어서는 안 된다**" 고 못 박는다.
// JSON.stringify 는 문자열 안의 개행을 \n 두 글자로 바꾸므로 이 조건은 저절로
// 지켜진다 — 대신 여기 말고 다른 데서 표준출력에 무언가를 적으면 그 순간
// 관이 깨진다. 그 자리는 serve.js 가 막는다.
import { EOL } from 'node:os';
import { StringDecoder } from 'node:string_decoder';

/** 규격이 정한 오류 번호. 우리가 새로 지어내면 클라이언트가 못 알아본다. */
export const 오류번호 = {
  파싱: -32700,
  잘못된요청: -32600,
  모르는방법: -32601,
  잘못된인자: -32602,
  안쪽오류: -32603,
  /*
   * 인증이 있어야 한다.
   *
   * 다른 번호와 달리 이건 JSON-RPC 가 아니라 **ACP 가 정한 번호**다
   * (규격의 ErrorCode::AuthRequired). 에디터는 이 번호를 봐야 initialize
   * 때 받아 둔 authMethods 를 꺼내 「인증」 단추를 그린다. 잘못된인자로
   * 답하면 그냥 빨간 글씨가 뜨고, 사람은 이게 설정 문제인지 버그인지
   * 모른다 — 할 수 있는 안내를 안 한 셈이다.
   */
  인증필요: -32000,
};

/**
 * 이어 붙여 오는 바이트를 줄 단위로 끊어 준다.
 *
 * 왜 직접 만드나: readline 을 쓰면 될 것 같지만, readline 은 스트림 하나를
 * 통째로 물고 자기 방식으로 끝을 판단한다. 검사에서 문자열을 조각내 밀어 넣는
 * 식으로 흉내 내기가 어렵고, 무엇보다 관을 닫는 시점을 우리가 못 정한다.
 * 하는 일이 이만큼이라면 직접 두는 편이 읽기 쉽다.
 *
 * @param {(줄: string) => void} 한줄  완성된 줄 하나가 나올 때마다 불린다
 * @returns {(덩이: Buffer|string) => void}
 */
export function 줄나누기(한줄) {
  let 남은것 = '';
  /*
   * 덩이마다 toString('utf8') 하면 안 된다.
   *
   * 파이프는 글자 단위가 아니라 바이트 단위로 끊긴다. '녕' 한가운데서 끊기면
   * 앞 덩이의 남은 바이트와 뒤 덩이의 첫 바이트가 각자 U+FFFD 로 바뀐다.
   * JSON 은 여전히 파싱되므로 오류가 안 나고 **글자만 조용히 뭉개진다** —
   * 프롬프트도 파일 내용도 도구 결과도 전부 한글인 이 프로그램에서는
   * 반드시 밟는 자리다. StringDecoder 는 잘린 바이트를 물고 있다가 다음
   * 덩이와 붙여 준다.
   */
  const 해독기 = new StringDecoder('utf8');
  return (덩이) => {
    남은것 += typeof 덩이 === 'string' ? 덩이 : 해독기.write(덩이);
    /*
     * \r\n 도 받는다.
     *
     * 규격은 \n 만 말하지만, 윈도우에서 다른 언어로 짠 클라이언트가 줄을 쓸 때
     * \r 이 딸려 오는 일이 실제로 있다. 여기서 한 글자 지워 주는 값이
     * "왜 아무 반응이 없지" 를 며칠 파는 값보다 훨씬 싸다.
     */
    let 자리;
    while ((자리 = 남은것.indexOf('\n')) >= 0) {
      let 줄 = 남은것.slice(0, 자리).replace(/\r$/, '');
      남은것 = 남은것.slice(자리 + 1);
      /*
       * ── 줄 앞의 BOM 을 뗀다 (사냥5 H5-9) ──────────────────────────────────
       *
       * .NET 의 `StreamWriter(Encoding.UTF8)` 처럼 첫 바이트에 BOM(U+FEFF) 을 붙여
       * 쓰는 클라이언트가 있다. 그 글자는 JSON 이 받지 않아서 **첫 줄 = initialize**
       * 가 -32700 · id null 로 떨어졌고, 저쪽은 initialize 답을 영영 기다렸다 —
       * 붙자마자 멈추는데 우리 로그에는 「읽을 수 없는 JSON」 한 줄뿐이다.
       * 줄마다 보는 것은, 메시지마다 새 writer 를 여는 클라이언트면 BOM 이 매 줄 앞에
       * 오기 때문이다. 글자는 번호로 비교한다 — 소스에 보이지 않는 글자를 안 둔다.
       */
      if (줄.charCodeAt(0) === 0xfeff) 줄 = 줄.slice(1);
      if (줄.trim()) 한줄(줄);   // 빈 줄은 그냥 넘긴다. 오류로 칠 것이 아니다
    }
  };
}

/**
 * 한쪽 끝. 요청을 받아 답하고, 저쪽에 요청을 걸어 답을 기다린다.
 *
 * ACP 에서는 에이전트와 클라이언트가 **둘 다** 요청을 건다. 에이전트가
 * "이 명령을 돌려도 되나" 하고 되묻는 자리가 그것이다. 그래서 이 물건은
 * 서버도 클라이언트도 아니고 그냥 '한쪽 끝' 이다.
 */
export class 연결 {
  /**
   * @param {object} o
   * @param {(줄: string) => void} o.보내기  한 줄을 저쪽으로 내보낸다 (개행은 여기서 붙인다)
   * @param {(방법: string, 인자: object) => any} o.다루기
   *        저쪽에서 온 요청·알림을 처리한다. 값을 돌려주면 그것이 답이 된다.
   *        모르는 방법이면 모르는방법오류() 를 던진다.
   */
  constructor({ 보내기, 다루기 }) {
    this.보내기줄 = 보내기;
    this.다루기 = 다루기;
    this.다음번호 = 1;
    this.기다리는것 = new Map();   // 번호 → {풀기, 깨기}
    this.닫혔나 = false;
  }

  #쓰기(덩이) {
    if (this.닫혔나) return;
    // 개행을 여기 한 곳에서만 붙인다. 붙이는 자리가 둘이 되면 언젠가
    // 빈 줄이 하나 더 나가고, 그건 저쪽에서 파싱 오류로 보인다.
    this.보내기줄(JSON.stringify(덩이) + '\n');
  }

  /**
   * 저쪽에 요청을 걸고 답을 기다린다.
   *
   * ── 기다림에도 끊는 줄이 있어야 한다 (사냥5 H5-3) ───────────────────────
   *
   * 승인 창을 띄워 두고 사람이 안 누른 채 턴을 취소하면, 여기 기다림은 끊기는 줄을
   * 몰라서 **답이 올 때까지** 서 있었다. 그 턴은 취소된 뒤에도 살아 있고, 한참 뒤에
   * 옛 창의 「이번만 실행」 이 닿으면 그대로 도구를 돌렸다. signal 을 주면 끊기는
   * 순간 기다림을 거둔다 — 표에서도 지우므로 늦게 온 답은 「이미 포기한 것」 으로
   * 조용히 버려진다.
   *
   * @param {object} [o]
   * @param {AbortSignal|null} [o.signal]  끊기면 기다림을 거두고 `거둠: true` 오류로 깬다
   */
  요청(방법, 인자, { signal = null } = {}) {
    const id = this.다음번호++;
    return new Promise((풀기, 깨기) => {
      if (this.닫혔나) { 깨기(new Error('관이 닫혔습니다')); return; }
      const 거둔오류 = () => Object.assign(new Error('기다리던 요청을 거뒀습니다 — 턴이 끊겼습니다'), { 거둠: true });
      // 이미 끊긴 턴의 물음은 내보내지도 않는다. 에디터에 답할 수 없는 창만 남는다.
      if (signal?.aborted) { 깨기(거둔오류()); return; }
      const 거두기 = () => { if (this.기다리는것.delete(id)) 깨기(거둔오류()); };
      signal?.addEventListener?.('abort', 거두기, { once: true });
      const 떼기 = () => signal?.removeEventListener?.('abort', 거두기);
      this.기다리는것.set(id, {
        풀기: (값) => { 떼기(); 풀기(값); },
        깨기: (오류) => { 떼기(); 깨기(오류); },
      });
      this.#쓰기({ jsonrpc: '2.0', id, method: 방법, params: 인자 ?? {} });
    });
  }

  /** 답을 안 받는 한마디. */
  알림(방법, 인자) {
    this.#쓰기({ jsonrpc: '2.0', method: 방법, params: 인자 ?? {} });
  }

  /**
   * 저쪽에서 온 줄 하나.
   *
   * 일부러 await 하지 않는다. 여기서 기다리면 앞의 요청이 끝날 때까지 다음
   * 줄을 못 읽는데, 그러면 **취소가 영영 안 닿는다** — 취소는 늘 무언가가
   * 돌고 있는 중에 온다. 그게 취소의 정의다.
   */
  받았다(줄) {
    let 온것;
    try {
      온것 = JSON.parse(줄);
    } catch {
      // id 를 모르니 null 로 답한다. 규격이 그렇게 하라고 적어 두었다.
      this.#쓰기({ jsonrpc: '2.0', id: null, error: { code: 오류번호.파싱, message: '읽을 수 없는 JSON 입니다' } });
      return;
    }
    /*
     * 묶음(batch) — `[{…}, {…}]` 한 줄.
     *
     * 배열도 typeof 로는 'object' 라 바로 아래 갈래를 지나쳤다. 그 뒤로는 method 도
     * id 도 없는 것으로 읽혀 **답이 한 줄도 안 나갔다** — 저쪽은 영영 기다린다.
     * ACP 는 묶음을 쓰지 않고 우리도 안 받는다. 안 받는다고 답한다. 안에 든 id 를
     * 골라 답하지 않는 것은, 받지 않은 요청에 답이 붙으면 저쪽이 된 줄 알기 때문이다.
     */
    if (Array.isArray(온것)) {
      this.#쓰기({ jsonrpc: '2.0', id: null, error: { code: 오류번호.잘못된요청, message: '묶음(batch)은 받지 않습니다 — 한 줄에 요청 하나씩 보내 주세요' } });
      return;
    }
    if (!온것 || typeof 온것 !== 'object') {
      this.#쓰기({ jsonrpc: '2.0', id: null, error: { code: 오류번호.잘못된요청, message: '객체가 아닙니다' } });
      return;
    }

    // 저쪽이 우리 요청에 답한 것.
    //
    // 'id' in 온것 으로 본다. id 가 0 일 수 있기 때문이다 — ACP 클라이언트는
    // 실제로 0번부터 센다. 여기서 truthy 로 보면 첫 요청의 답을 통째로 잃는다.
    //
    // method 도 **칸이 있나**로 본다 (사냥5 H5-10). `!온것.method` 는 빈 글도 거짓으로
    // 쳐서 `{"id":77,"method":""}` 가 이 답 갈래로 왔다 — 77번에는 아무 답도 안 나가
    // 저쪽이 영영 기다렸고, 같은 번호의 우리 요청이 있으면 그게 엉뚱하게 풀렸다.
    // id 와 method 가 같이 있으면 요청이다. 빈 method 는 아래에서 -32600 으로 답한다.
    //
    // 그리고 **result·error 칸이 있어야** 답이다 (8회차 ACP-3). method 칸이 아예
    // 없는 줄은 위 빈 method 검사에 안 걸려 그대로 답 갈래로 갔고, result 가 없으니
    // 기다리던 우리 요청이 `풀기(undefined)` 로 풀렸다 — 승인 묻기가 이 길로 오므로
    // 답이 아닌 줄 하나가 승인 결과를 「아무것도 안 고름」 으로 만든다. 그 id 에는
    // 답도 안 나가 저쪽도 영영 기다렸다. 무엇이 답인가는 규격이 정해 두었다.
    if ('id' in 온것 && !('method' in 온것) && ('result' in 온것 || 'error' in 온것)) {
      const 기다림 = this.기다리는것.get(온것.id);
      if (!기다림) return;   // 이미 포기한 것. 늦게 온 답은 조용히 버린다
      this.기다리는것.delete(온것.id);
      if (온것.error) {
        const e = new Error(온것.error?.message ?? '저쪽에서 오류로 답했습니다');
        e.code = 온것.error?.code;
        e.data = 온것.error?.data;
        기다림.깨기(e);
      } else {
        기다림.풀기(온것.result);
      }
      return;
    }

    if (typeof 온것.method !== 'string' || !온것.method) {
      /*
       * ── 우리 기다림을 **영영 매달아 두지 않는다** (사냥6 막판-뒷단) ───────
       *
       * 위 ACP-3 고침이 「result·error 가 없으면 답이 아니다」 로 막으면서, 그런 줄이
       * 여기로 굴러떨어지게 됐다. 그런데 여기서는 저쪽에만 -32600 을 답하고 끝난다 —
       * 그 번호를 기다리던 **우리** 요청은 아무도 안 깨운다. 요청() 에는 시계가 없어서
       * 턴을 사람이 취소하기 전까지 서 있는다(재 봤다: pending 인 채로 남는다).
       * 승인 묻기가 이 길로 오므로, 규격을 어긴 줄 하나에 화면이 말없이 멎는다 —
       * 바로 위 문단이 「저쪽도 영영 기다렸다」 고 적어 둔 것의 우리 쪽 판이다.
       *
       * 깨뜨리면 serve.js 의 승인묻기 가 받아 「못 물어봐서 거부했습니다」 를 로그에
       * 적고 안 한다. 못 물어본 것을 못 물어봤다고 말하는 것이 이 프로그램의 자세다.
       * 깨뜨리는 것은 **method 칸이 아예 없는** 줄뿐이다. 빈 method 는 H5-10 이 정한
       * 대로 「요청」 이라, 저쪽이 빈 글자 하나로 우리 승인 물음을 마음대로 끊게 된다 —
       * 끊긴 물음의 답은 거부라 위험하진 않지만, 남이 끊을 수 있는 자리를 열어 줄 까닭이
       * 없다. 칸째 없는 줄만 답이 깨진 것으로 본다.
       */
      if ('id' in 온것) {
        const 기다림 = 'method' in 온것 ? null : this.기다리는것.get(온것.id);
        if (기다림) {
          this.기다리는것.delete(온것.id);
          try { 기다림.깨기(new Error('저쪽 답에 result·error 가 없습니다 — 규격에 맞는 답이 아닙니다')); } catch { /* 이미 정리된 것 */ }
        }
        this.#쓰기({ jsonrpc: '2.0', id: 온것.id, error: { code: 오류번호.잘못된요청, message: 'method 가 없습니다' } });
      }
      return;
    }

    // 알림은 id **칸이 없는** 요청이다(JSON-RPC 2.0). id 가 null 이어도 요청이라 답한다 —
    // null 을 알림으로 쳤더니 답이 한 줄도 안 나가 저쪽이 영영 기다렸다 (6회차 규약6ai-b J2).
    const 알림인가 = !('id' in 온것);

    Promise.resolve()
      .then(() => this.다루기(온것.method, 온것.params ?? {}))
      .then((결과) => {
        if (알림인가) return;   // 알림에는 답하지 않는다. 답하면 저쪽이 짝 없는 답을 받는다
        this.#쓰기({ jsonrpc: '2.0', id: 온것.id, result: 결과 ?? {} });
      })
      .catch((err) => {
        /*
         * 알림을 다루다 터진 것은 답할 데가 없다.
         *
         * 그렇다고 삼키면 무엇이 터졌는지 아무도 모른다. 표준오류에 적는다 —
         * ACP 는 에이전트가 stderr 에 로그를 적어도 된다고 분명히 허락한다.
         */
        if (알림인가) {
          try { process.stderr.write(`[acp] ${온것.method} 처리 중 오류: ${err?.message ?? err}${EOL}`); } catch { /* 여기서 또 터지면 할 게 없다 */ }
          return;
        }
        this.#쓰기({
          jsonrpc: '2.0',
          id: 온것.id,
          error: {
            code: Number.isInteger(err?.code) ? err.code : 오류번호.안쪽오류,
            message: String(err?.message ?? err ?? '알 수 없는 오류'),
            ...(err?.data !== undefined ? { data: err.data } : {}),
          },
        });
      });
  }

  /**
   * 관을 닫는다. 아직 답을 기다리던 요청은 전부 깨뜨린다.
   *
   * 안 깨뜨리면 그 프라미스를 붙들고 있던 자리가 영영 안 끝난다. 사람 눈에는
   * "에디터가 멈췄다" 로 보인다 — 원인은 이미 죽은 프로세스라 어디에도 안 남는다.
   */
  닫기(왜 = '관이 닫혔습니다') {
    this.닫혔나 = true;
    for (const [, 기다림] of this.기다리는것) {
      try { 기다림.깨기(new Error(왜)); } catch { /* 이미 정리된 것 */ }
    }
    this.기다리는것.clear();
  }
}

/** 모르는 방법이라고 답하게 하는 오류. 다루기 함수가 이걸 던지면 된다. */
export function 모르는방법오류(방법) {
  const e = new Error(`모르는 방법입니다: ${방법}`);
  e.code = 오류번호.모르는방법;
  return e;
}

/** 인자가 틀렸다고 답하게 하는 오류. */
export function 잘못된인자오류(무엇) {
  const e = new Error(무엇);
  e.code = 오류번호.잘못된인자;
  return e;
}

/**
 * 아직 인증(연결 설정)이 안 됐다고 답하게 하는 오류.
 *
 * 글은 그대로 사람에게 보인다. 그러니 **무엇을 하면 되는지**까지 적는다 —
 * 번호만 맞고 글이 「인증이 필요합니다」 면 어디서 무엇을 해야 하는지 여전히
 * 모른다.
 */
export function 인증필요오류(무엇) {
  const e = new Error(무엇);
  e.code = 오류번호.인증필요;
  return e;
}
