/** 한 줄. `상태` 는 ok · warn · no · unknown 넷뿐이다. */
const 줄 = (상태, 이름, 값, 덧말 = null) => ({ 상태, 이름, 값, 덧말 });

/*
 * ── 주소가 주소 꼴인가 ─────────────────────────────────────────────────
 *
 * 손으로 고친 프로필의 baseUrl 이 비었거나(`http://`) 빈칸이 들어 있으면, 부르는 쪽(bin/deel.js)은
 * 그 주소를 자물쇠에 못 올려 「두드려도 되나」 가 거짓이 된다. 여기는 주소를 안 보고 「✓ 주소」 를
 * 찍었고, 도달 줄에는 「자물쇠가 걸려 있거나 --offline」 이라고 적었다 — 둘 다 아니다. ✗ 가 없으니
 * 종료코드도 0 이었다. 담당자에게 보낼 한 장이 「멀쩡하다」 고 말한 셈이다.
 *
 * @returns {string|null} 틀린 까닭. 멀쩡하면 null.
 */
function 주소살펴보기(주소) {
  const s = String(주소 ?? '').trim();
  if (!s) return '비어 있습니다 — 프로필에 baseUrl 을 적거나 deel setup 을 다시 하세요';
  let u;
  try { u = new URL(s); } catch { return '주소 꼴이 아닙니다 (빈칸·빠진 호스트) — 예: http://127.0.0.1:11434/v1'; }
  if (!/^https?:$/.test(u.protocol)) return `http 나 https 로 시작해야 합니다 — 지금은 ${u.protocol}`;
  /*
   * 빈 호스트는 `u.hostname` 으로 못 잡는다 — http/https 는 호스트가 비면 위 `new URL` 이
   * 먼저 던진다(13,500 조합을 다 재 봤다. 걸리는 주소가 하나도 없었다). 정작 새는 꼴은
   * 슬래시가 셋인 주소다: 파서가 **경로를 호스트로 끌어올린다** (`http:///v1` → `http://v1/`).
   * 사람은 호스트를 안 적었는데 화면에는 ✓ 가 찍히고, 두드리는 곳은 `v1` 이라는 엉뚱한
   * 이름이 된다. 그래서 파서가 고쳐 놓은 값 말고 **적힌 글자**를 본다. (setup.js 의 주소꼴탈과 쌍둥이)
   */
  if (/^https?:\/\/\//i.test(s)) return '호스트가 없습니다 — 예: http://127.0.0.1:11434/v1';
  return null;
}

/**
 * 이 자리의 조건을 다 본다. 화면 그리기는 안 한다 — 부르는 쪽이 그린다.
 *
 * @param {object} o
 * @param {object|null} o.prof  고른 프로필
 * @param {string} o.root       작업 폴더
 * @param {boolean} o.바깥가도되나  네트워크를 실제로 두드려도 되나
 */
export async function 진찰(o = {}) {
  const { prof = null, root = process.cwd(), 바깥가도되나 = true, 설정자리 = null, 설정탈 = null } = o;
  const 줄들 = [];

  // ── 1. 이 프로그램이 도는 자리 ───────────────────────────────────────
  const major = parseInt(String(process.versions.node).split('.')[0], 10);
  줄들.push(줄(major >= 20 ? 'ok' : 'no', 'Node', `${process.versions.node} · ${process.platform}`,
    major >= 20 ? null : '20 이상이 필요합니다'));

  // ── 2. 설정 ─────────────────────────────────────────────────────────
  /*
   * ── 깨진 설정을 「✓ 설정 파일」 로 적고 있었다 ──────────────────────
   *
   * 부르는 쪽(bin/deel.js)이 읽기 오류를 `catch {}` 로 삼키고, 여기는 파일이
   * **있나**만 봤다. 그래서 쉼표 하나 틀린 설정이 이렇게 나왔다:
   *
   *   ✓ 설정 파일   …/config.json
   *   ✗ 프로필      (없음) — deel setup 을 먼저 하세요
   *
   * 프로필은 멀쩡히 적혀 있다. 이 화면을 받은 담당자는 setup 을 다시 시키고,
   * setup 은 같은 파일에서 또 죽는다. 까닭(몇째 줄 무엇)은 어디에도 없었다.
   * 이 파일의 규칙 그대로 — 못 읽은 것은 못 읽었다고, 왜인지까지 적는다.
   */
  if (설정탈) {
    줄들.push(줄('no', '설정 파일', 설정탈.자리 ?? 설정자리 ?? '(어느 파일인지 모름)',
      `못 읽었습니다 — ${String(설정탈.까닭 ?? '').replace(/\s+/g, ' ').trim()}`));
  } else if (설정자리) 줄들.push(줄(existsSync(설정자리) ? 'ok' : 'warn', '설정 파일', 설정자리));
  const 프로젝트설정 = join(root, '.deel', 'config.json');
  // 집 폴더에서 켜면 이 파일이 곧 이 PC 설정이다. 두 번 적으면 제 설정에 「deel trust」 를 권한다.
  if (existsSync(프로젝트설정) && !집설정파일인가(프로젝트설정)) {
    /*
     * 프로젝트 설정은 **믿는 폴더에서만** 읽는다 (safety/trust.js). 여기서
     * 읽었는지 안 읽었는지를 말해 주지 않으면, 적어 둔 사람은 자기 설정이
     * 왜 안 먹는지 영영 모른다 — 파일은 분명히 거기 있기 때문이다.
     */
    const 믿나결과 = 믿나(root);
    줄들.push(줄(믿나결과 ? 'ok' : 'warn', '프로젝트 설정', 프로젝트설정,
      믿나결과 ? '읽습니다' : '안 읽습니다 — 읽게 하려면 deel trust'));
  }
  if (!prof && 설정탈) {
    // 없는 것이 아니라 못 읽은 것이다. 「deel setup 을 먼저」 는 같은 파일에서 또 죽는다.
    줄들.push(줄('unknown', '프로필', '(모름)', '설정 파일을 못 읽어 알 수 없습니다 — 위 줄을 먼저 고치세요'));
    return { 줄들, 붙어봤나: false };
  }
  if (!prof) {
    줄들.push(줄('no', '프로필', '(없음)', 'deel setup 을 먼저 하세요'));
    return { 줄들, 붙어봤나: false };
  }
  줄들.push(줄('ok', '프로필', `${prof.name ?? prof.id ?? '(이름 없음)'} · ${prof.model ?? '(모델 없음)'}`));
  const 주소탈 = 주소살펴보기(prof.baseUrl);
  줄들.push(주소탈
    ? 줄('no', '주소', 주소가리기(String(prof.baseUrl ?? '').trim() || '(없음)'), 주소탈)
    : 줄('ok', '주소', 주소가리기(prof.baseUrl)));

  // ── 3. 열쇠 ─────────────────────────────────────────────────────────
  /*
   * 값은 절대 안 적는다. 있나 없나와 **어디서 왔나**만 적는다 — 고칠 사람이
   * 알아야 하는 것이 그 둘이다. 환경변수가 파일을 이기고 있는데 그걸 모르면
   * 파일만 백 번 고친다.
   */
  /*
   * 차례는 **여기서 정하지 않는다.** config.js 의 열쇠출처() 에게 물어본다.
   *
   * 여기가 제 차례를 따로 들고 있었다 — DEEL_API_KEY 를 맨 앞에 두고
   * 열쇠받기를 맨 뒤에 뒀는데, 실제로 나가는 차례는 그 반대다. 그래서 둘
   * 이상 넣어 둔 사람에게 **엉뚱한 자리를 가리켰다.** 자세한 것은
   * config.js 의 열쇠출처() 머리말에 적어 뒀다.
   */
  const 받기 = 받기설정(prof, { 정책값: 정책읽기().값 });
  const 받기판단 = 받기 ? 받기쓸수있나(받기, { auth: prof.auth ?? 'bearer' }) : { 된다: false, 왜: null };
  const 출처 = 열쇠출처(prof, { 받기쓰나: !!받기 && 받기판단.된다 });
  const 열쇠어디 = 출처.말 || null;
  const 열쇠있나 = !!(o.열쇠 ?? '');
  // 열쇠를 여기서 안 받아 본 판. 아래 401 을 결함으로 부르지 않는 근거다.
  const 열쇠를안돌려봤나 = !열쇠있나 && !!받기 && 받기판단.된다;
  if (prof.auth === 'none') 줄들.push(줄('ok', '열쇠', '안 씁니다 (auth: none)'));
  else if (열쇠있나) 줄들.push(줄('ok', '열쇠', `있습니다 · ${열쇠어디 ?? '어디서 왔는지 모름'}`));
  /*
   * ── 멀쩡한 구성에 고장 신고서를 써 주고 있었다 ──────────────────────
   *
   * 열쇠받기(SSO 명령) 프로필은 `apiKey` 도 환경변수도 없는 것이 **정상**
   * 이다. 토큰은 요청 직전에 명령으로 받는다(adapter.js 머리말짓기). 그런데
   * 여기는 `resolveKey` 가 준 빈 글자만 보고 이렇게 적었다:
   *
   *   ✗ 열쇠   못 꺼냈습니다 — 명령으로 받아 옵니다 에서 읽으려 했습니다
   *   ✗ 인증   401
   *   2군데가 막혀 있습니다. 위 줄을 그대로 담당자에게 보내시면 됩니다.
   *
   * 아무것도 안 망가진 상태다. `deel`·`deel run`·`deel acp` 가 다 붙는다.
   * 이 화면의 뜻이 「그대로 담당자에게 보낼 질문을 만드는 것」 인데,
   * 지어낸 결함을 담당자에게 보내게 만들었다. 종료코드도 1 이 된다.
   *
   * 이 파일의 규칙이 그 답이다 — **모르는 것은 모른다고 적는다.** 여기서는
   * 명령을 안 돌려 봤으니 안 재 본 것이다.
   */
  else if (받기 && 받기판단.된다) {
    줄들.push(줄('unknown', '열쇠', '요청 직전에 명령으로 받아 옵니다',
      `여기서는 안 돌려 봤습니다 — ${받기.곳}에 적힌 명령입니다`));
  } else if (받기 && 받기판단.왜) {
    줄들.push(줄('warn', '열쇠', '명령으로 받게 돼 있는데 지금은 안 부릅니다', 받기판단.왜));
  } else 줄들.push(줄('no', '열쇠', '못 꺼냈습니다', 열쇠어디 ? `${열쇠어디} 에서 읽으려 했습니다` : '적어 둔 것이 없습니다'));

  // ── 4. 우리 인증서 (mTLS) ───────────────────────────────────────────
  const 인증 = 인증서설정(prof);
  if (인증) {
    인증서등록(prof.baseUrl, 인증);
    try {
      인증서찾기(prof.baseUrl);      // 파일을 실제로 읽어 본다. 못 읽으면 던진다.
      줄들.push(줄('ok', '내 인증서', 인증서말(인증)));
    } catch (err) {
      줄들.push(줄('no', '내 인증서', 인증서말(인증), String(err?.message ?? err).split('\n')[0]));
    }
  }

  // ── 5. 사내 루트 (NODE_EXTRA_CA_CERTS) ──────────────────────────────
  const ca = process.env.NODE_EXTRA_CA_CERTS;
  if (ca) {
    let 됐나 = false;
    try { 됐나 = statSync(ca).isFile(); } catch { 됐나 = false; }
    줄들.push(줄(됐나 ? 'ok' : 'no', '사내 루트', ca, 됐나 ? null : '그 자리에 파일이 없습니다'));
  }

  // ── 6. 프록시 ───────────────────────────────────────────────────────
  /*
   * 「프록시를 켰다」 와 「이 주소가 그 프록시를 거친다」 는 다른 말이다.
   * NO_PROXY 하나로 거치지 않게 되는데, 그때 화면이 「프록시 켜짐」 만
   * 말하면 사람은 거치는 줄 알고 프록시 담당자에게 묻는다.
   */
  const 프록 = 프록시설정();
  const 이주소 = 프록시고르기(prof.baseUrl ?? '');
  if (프록.탈) 줄들.push(줄('warn', '프록시', '설정을 못 읽었습니다', 프록.탈));
  // 못 읽고서 「안 거칩니다」 라고 단정하면, 실제로는 프록시가 걸려 있는데 직접
  // 간다고 적은 셈이 된다 — 이 화면은 모르는 것을 모른다고 적는 자리다.
  else if (!프록.켜짐) 줄들.push(줄('ok', '프록시', '안 거칩니다 (직접)'));
  else if (이주소) {
    줄들.push(줄('ok', '프록시', `${주소가리기(이주소.url)} · ${이주소.출처}`,
      이주소.auth ? '인증 있음' : null));
  } else {
    줄들.push(줄('warn', '프록시', `${프록.프록시들.map((x) => `${주소가리기(x.url)}(${x.출처})`).join(' · ')}`,
      '이 주소는 프록시를 안 거칩니다 (NO_PROXY 나 이 컴퓨터 안)'));
  }

  // ── 7. MCP ──────────────────────────────────────────────────────────
  /*
   * ── 뜨지도 않을 서버를 세어서 초록으로 적었다 ───────────────────────
   *
   * 여기는 설정 읽기를 **따로 한 벌** 갖고 있었다 — `JSON.parse` 한 뒤
   * 열쇠 개수를 세는 것. 그래서 실제로 붙는 자(backend/mcp.js 의 설정읽기)
   * 가 거르는 것을 하나도 몰랐다:
   *
   *   · `<root>/.mcp.json` 만 있는 경우   — 여기서는 받아 주지만 실제로
   *     읽는 자리는 `<root>/.deel/mcp.json` 뿐이다. 0개가 붙는다.
   *   · `"disabled": true` · `"type": "sse"` · `url` 만 있는 항목 — 전부
   *     여기서는 세고 실제로는 거절된다.
   *
   * 화면에는 `✓ MCP  …/.mcp.json · 서버 3개` 가 뜨고 진찰은 초록으로
   * 끝난다. 모델에게는 MCP 도구가 하나도 없다. 왜인지는 아무 데도 없다.
   *
   * 그래서 **붙이는 자에게 물어본다.** 못 받은 것은 그자가 이미 까닭까지
   * 들고 있다(못받은것). 자리가 하나 늘면 그쪽만 고치면 된다.
   */
  const mcp = MCP설정읽기(root);
  const 남의자리 = join(root, '.mcp.json');
  if (mcp.있음 || existsSync(남의자리)) {
    if (mcp.오류) 줄들.push(줄('no', 'MCP', mcp.자리, mcp.오류));
    else if (!mcp.있음) {
      줄들.push(줄('warn', 'MCP', 남의자리,
        `여기는 안 읽습니다 — ${mcp.자리} 로 옮기세요`));
    } else {
      const 못받은 = mcp.못받은것 ?? [];
      // 안 믿는 폴더면 하나도 안 뜬다(아래 「MCP 신뢰」 줄). 그때 요약 줄까지 ✓ 로
      // 적으면 한 화면에 ✓ 와 「하나도 안 띄웁니다」 가 같이 보인다 — 진찰은 그 자리에서
      // 판단을 끝내 주는 화면이라 초록 하나가 그대로 결론이 된다.
      const 띄울수있나 = 믿나(root);
      줄들.push(줄(mcp.서버들.length && 띄울수있나 ? 'ok' : 'warn', 'MCP',
        `${mcp.자리} · 붙일 서버 ${mcp.서버들.length}개`,
        못받은.length
          ? `못 붙이는 것 ${못받은.length}개: ${못받은.map((x) => x.이름).join(' · ')}`
          : '실제로 띄워 보려면 deel 을 켜고 /mcp'));
      for (const x of 못받은) 줄들.push(줄('warn', `  ${x.이름}`, x.왜));
      /*
       * 붙는 조건이 둘 더 있다. 둘 다 「설정은 멀쩡한데 0개」 가 되는 길이라
       * 여기서 말해 준다 — 안 말하면 설정 파일만 들여다보게 된다.
       */
      if (mcp.서버들.length && !띄울수있나) {
        줄들.push(줄('warn', '  MCP 신뢰', '안 믿는 폴더라 하나도 안 띄웁니다', 'deel trust 를 하세요'));
      }
    }
  }

  // ── 7.5 훅 ───────────────────────────────────────────────────────────
  //
  // 훅은 사람이 적어 둔 명령을 돌리는 것이라, 안 도는 것도 도는 것도 둘 다 사고다.
  // 안 도는 쪽이 더 나쁘다 — 사내 규칙을 걸어 둔 줄 알고 있는데 실제로는 안 걸린
  // 상태이기 때문이다. 제일 흔한 까닭이 믿는 폴더가 아니어서인데, 그건 아무 데도 안
  // 찍힌다. 여기서 말해 준다.
  for (const 한줄 of 훅줄들(훅읽기(root))) 줄들.push(한줄);

  // 이름 붙인 하위 작업 (agent/agents.js). 못 읽은 정의를 말해 주는 자리는 여기뿐이다.
  for (const 한줄 of 에이전트줄들(에이전트읽기(root))) 줄들.push(한줄);

  // ── 8. 진짜로 두드려 본다 ───────────────────────────────────────────
  // 주소가 틀렸으면 두드릴 곳이 없다. 자물쇠 탓으로 적으면 사람은 엉뚱한 설정을 뒤진다.
  if (주소탈) {
    줄들.push(줄('unknown', '도달', '안 두드렸습니다', '주소부터 고치세요 — 위 「주소」 줄'));
    return { 줄들, 붙어봤나: false };
  }
  if (!바깥가도되나) {
    줄들.push(줄('unknown', '도달', '안 두드렸습니다', '자물쇠가 걸려 있거나 --offline 입니다'));
    return { 줄들, 붙어봤나: false };
  }

  const 주소 = String(prof.baseUrl ?? '').replace(/\/+$/, '');
  const t0 = Date.now();
  const r = await req(`${주소}/models`, {
    headers: headersFor(prof.auth ?? 'bearer', o.열쇠 ?? ''),
    timeout: 15000,
  });
  const 걸린 = Date.now() - t0;

  if (r.ok) {
    const 목록 = Array.isArray(r.json?.data) ? r.json.data : (Array.isArray(r.json?.models) ? r.json.models : []);
    줄들.push(줄('ok', '도달', `${r.status} · ${걸린}ms`));
    /*
     * 모델 목록에 **그 모델이 있나**까지 본다.
     *
     * 붙기는 되는데 모델 이름이 한 글자 틀린 자리가 흔하다. 그때 서버가 주는
     * 것은 404 나 400 이고, 그 화면은 「주소가 틀렸다」 와 구별이 안 된다.
     */
    const 이름들 = 목록.map((m) => String(m?.id ?? m?.name ?? '')).filter(Boolean);
    if (!이름들.length) 줄들.push(줄('unknown', '모델 목록', '안 알려 줍니다', '목록을 안 내는 서버도 있습니다'));
    else if (이름들.includes(String(prof.model))) 줄들.push(줄('ok', '모델', `${prof.model} · 목록 ${이름들.length}개`));
    else {
      const 비슷 = 이름들.filter((n) => n.includes(String(prof.model ?? '')) || String(prof.model ?? '').includes(n));
      줄들.push(줄('no', '모델', `${prof.model} 이 목록에 없습니다`,
        (비슷.length ? `비슷한 것: ${비슷.slice(0, 3).join(' · ')}` : `있는 것: ${이름들.slice(0, 3).join(' · ')}${이름들.length > 3 ? ' …' : ''}`)));
    }
  } else if (r.status === 401 || r.status === 403) {
    // 닿기는 닿았다. 그 둘을 갈라 줘야 사람이 프록시가 아니라 열쇠를 본다.
    줄들.push(줄('ok', '도달', `${r.status} · ${걸린}ms`, '주소는 닿습니다'));
    /*
     * 빈 열쇠로 두드린 401 은 **결함이 아니다.**
     *
     * 위 「열쇠」 줄 머리말이 이미 적어 둔 이야기인데(✗ 열쇠 · ✗ 인증 401 …
     * 「지어낸 결함을 담당자에게 보내게 만들었다」), 고쳐진 것은 그 한 줄뿐이라
     * 여기가 그대로 남아 종료코드까지 1 이 됐다. 열쇠받기(SSO) 프로필은 토큰을
     * 요청 직전에 받는다 — 여기서는 안 돌려 봤으니 **안 재 본 것**이다.
     */
    if (열쇠를안돌려봤나) {
      줄들.push(줄('unknown', '인증', `${r.status}`,
        '빈 열쇠로 두드린 결과입니다 — 토큰은 요청 직전에 명령으로 받습니다'));
    } else 줄들.push(줄('no', '인증', `${r.status}`, '열쇠나 인증 방식(auth)을 보세요'));
  } else {
    줄들.push(줄('no', '도달', r.status ? `${r.status}` : '못 닿았습니다', r.error ?? null));
  }
  return { 줄들, 붙어봤나: true };
}
