// 읽은 파일을 들고 있다가, 다시 읽을 때 **바뀐 만큼만** 싣는다.
//
// ── 무엇이 아까웠나 ─────────────────────────────────────────────────────
//
// 「폴더/파일을 읽으면 그 값을 가져와있다가 수정되면 수정하고, 필요하면
//  필요할때마다 해당 값을 써야 토큰이 덜 발생하는거 아니야?」
//
// 맞는 말이다. 여태 이랬다.
//
//   Read src/a.js      1,200줄이 대화에 들어간다
//   Edit src/a.js      한 줄 고친다
//   Read src/a.js      **1,200줄이 또 들어간다**
//
// 두 번째 1,200줄 중 실제로 새로운 것은 한 줄이다. 나머지 1,199줄은 이미
// 대화 안에 그대로 있다. 그런데 창은 그만큼 밀리고, 밀린 만큼 앞엣것이
// 접혀 나간다 — 돈을 두 번 내고 기억을 잃는 셈이다.
//
// loop.js 에도 되풀이를 막는 자리가 있지만 거기는 **결과가 똑같을 때**만
// 본다. 그리고 그 표는 턴 하나짜리다. 고치고 다시 읽는 것 — 제일 흔한
// 모양 — 은 거기에 안 걸린다.
//
// ── 지키는 선 ───────────────────────────────────────────────────────────
//
// **줄이는 것과 잃는 것은 다르다.** 「앞에서 읽은 그대로입니다」 는 앞엣것이
// 대화에 살아 있을 때만 참이다. 그래서 요약해서 접을 때(compact.js) 이
// 기억도 같이 버린다. 안 버리면 모델은 있지도 않은 글을 가리키는 쪽지만
// 받는다 — 그게 통째로 다시 싣는 것보다 훨씬 나쁘다.
//
// **부분만 읽은 것은 안 기억한다.** offset·limit 로 잘라 읽었거나 창이 좁아
// 앞부분만 준 경우, 우리가 들고 있는 것은 파일이 아니라 조각이다. 그걸
// 「그대로」 라고 하면 모델은 안 본 부분을 봤다고 여긴다.
import { diffLines } from '../ui/diff.js';

/*
 * 바뀐 만큼만 싣는 것이 언제 이득인가.
 *
 * 조금 바뀌었으면 확실히 이득이다. 그런데 절반이 바뀌었으면 diff 가 원본보다
 * 오히려 길어진다(뺀 줄과 넣은 줄이 둘 다 실리니까). 그때는 그냥 통째로
 * 싣는 편이 짧고, 무엇보다 **읽기 쉽다.**
 */
const 이득선 = 0.6;

/** 한 줄이라도 남기려면 이만큼은 있어야 한다 — 너무 짧은 파일은 diff 가 무의미하다. */
const 최소줄 = 40;

export class 파일기억 {
  constructor() {
    /** 경로 → { 글, 언제 } — 마지막으로 대화에 통째로 실은 내용. */
    this.것들 = new Map();
  }

  /**
   * 요약해서 접었다 = 앞엣것이 대화에서 사라졌다. 기억도 같이 버린다.
   *
   * 경로를 주면 **그 파일만** 잊는다. 도구 결과를 한 줄로 접을 때 쓰는
   * 길이다(agent/compact.js 의 foldToolResults) — 그때 사라지는 것은 접힌
   * 파일뿐이라, 전부 잊으면 멀쩡히 대화에 살아 있는 나머지까지 다음에
   * 통째로 다시 싣게 된다.
   *
   * 안 잊으면 더 나쁘다. 내용은 접혀 없어졌는데 기억에는 남아 있어서,
   * 그 파일을 다시 읽으면 「앞에서 읽은 그대로입니다」 만 돌아간다 —
   * 모델은 어디에도 없는 글을 가리키는 쪽지를 받고, 결국 또 읽는다.
   */
  잊기(경로 = null) {
    if (경로) this.것들.delete(경로);
    else this.것들.clear();
  }

  /**
   * 이번에 실을 글을 정한다.
   *
   * @param {string} 경로       파일의 절대 경로
   * @param {string} 새글       이번에 읽은 것(줄 번호가 붙은 그대로)
   * @param {object} [옵션]
   * @param {boolean} [옵션.부분인가] offset·limit·창 상한으로 잘라 읽었나
   * @returns {{글: string, 어떻게: 'full'|'same'|'diff'}}
   */
  실을것(경로, 새글, { 부분인가 = false } = {}) {
    const 글 = String(새글 ?? '');
    if (!경로 || 부분인가) return { 글, 어떻게: 'full' };

    const 앞것 = this.것들.get(경로);
    this.것들.set(경로, { 글, 언제: Date.now() });
    if (!앞것) return { 글, 어떻게: 'full' };

    if (앞것.글 === 글) {
      return {
        글: '앞에서 읽은 그대로입니다 — 파일이 바뀌지 않았습니다.'
          + ' 앞에 실린 내용을 그대로 쓰세요. (같은 글을 두 번 싣지 않습니다)',
        어떻게: 'same',
      };
    }

    const 줄인것 = 바뀐데만(앞것.글, 글);
    if (줄인것) return { 글: 줄인것, 어떻게: 'diff' };
    return { 글, 어떻게: 'full' };
  }
}

/*
 * 줄 번호를 떼고 견준다.
 *
 * Read 는 `     12\t코드` 처럼 줄 번호를 붙여 돌려준다. 그걸 그대로 견주면
 * **맨 앞에 한 줄만 끼어도 그 아래 전부가 바뀐 줄로 잡힌다** — 번호가 다
 * 밀리기 때문이다. 그러면 diff 가 원본보다 길어져서 줄이는 뜻이 사라진다.
 * 그래서 번호를 떼고 견주고, 적을 때 **새 파일의 번호**로 다시 붙인다.
 */
function 번호떼기(글) {
  const 몸 = [];
  const 번호 = [];
  for (const l of String(글).split('\n')) {
    const m = l.match(/^(\s*)(\d+)\t([\s\S]*)$/);
    if (m) { 번호.push(m[2]); 몸.push(m[3]); } else { 번호.push(null); 몸.push(l); }
  }
  return { 몸: 몸.join('\n'), 번호 };
}

/**
 * 바뀐 자리만 뽑아 적는다. 이득이 없으면 null 을 돌려준다.
 *
 * 줄 번호는 **새 파일의 번호**로 적는다. 모델은 그 번호로 Edit 을 걸기
 * 때문에, 여기서 1부터 다시 세면 엉뚱한 줄을 고친다.
 */
export function 바뀐데만(앞글, 새글) {
  const 새줄들 = String(새글).split('\n');
  if (새줄들.length < 최소줄) return null;

  const A = 번호떼기(앞글);
  const B = 번호떼기(새글);
  const d = diffLines(A.몸, B.몸, { context: 3 });
  if (!d.changed || d.tooBig || !d.hunks?.length) return null;

  const 자리 = (n) => (n == null ? '      ' : String(n).padStart(6));
  const 조각들 = [];
  for (const h of d.hunks) {
    const 줄들 = [];
    for (let p = h.from; p <= h.to; p += 1) {
      const op = d.opAt(p);
      // 지운 줄에는 새 파일의 번호가 없다. 자리만 비워 두고 뺐다고만 적는다.
      if (op.t === '-') 줄들.push(`-${' '.repeat(6)}\t${d.linesA[op.a] ?? ''}`);
      else if (op.t === '+') 줄들.push(`+${자리(B.번호[op.b])}\t${d.linesB[op.b] ?? ''}`);
      else 줄들.push(` ${자리(B.번호[op.b])}\t${d.linesB[op.b] ?? d.linesA[op.a] ?? ''}`);
    }
    조각들.push(줄들.join('\n'));
  }

  const 몸 = 조각들.join('\n   …\n');
  // 이득이 없으면 통째로 싣는 편이 짧고 읽기도 쉽다.
  if (몸.length >= String(새글).length * 이득선) return null;

  return '앞에서 읽은 것에서 **바뀐 자리만** 적습니다'
    + ` (+${d.added} −${d.removed}). 나머지는 앞에 실린 그대로입니다.\n`
    + '줄 번호는 **지금 파일의 번호**입니다 — 이 번호로 고치면 됩니다.\n\n'
    + 몸;
}
