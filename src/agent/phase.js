/**
 * 종합 모드에서 **단계가 일을 따라간다.**
 *
 * 종합 모드는 턴이 시작할 때 한 번 작업 모드를 고른다(agent/route.js). 긴 턴에서는
 * 일의 성격이 중간에 바뀐다 — 디버그로 시작해 원인을 찾은 뒤의 남은 걸음은 고치는
 * 일인데, 시킴말(「재현부터 하라」)과 화면의 `~디버그` 는 끝까지 그대로다.
 *
 * ── 무엇으로 옮기나 ─────────────────────────────────────────────────────
 *
 * 모델에게 「지금 무슨 단계냐」 고 다시 묻지 않는다(걸음마다 왕복이 늘고, route.js
 * 의 낱말 판단보다 나을 것도 없다). **이미 일어난 일**로 옮긴다. 짐작이 아니라
 * 잰 것이다.
 *
 *   할 일을 적었다 (TodoWrite 에 남은 일이 있다)   → 계획은 끝났다
 *   파일을 실제로 바꿨다                            → 만드는 중이다
 *
 * ── 앞으로만 간다 ───────────────────────────────────────────────────────
 *
 * 한 걸음 읽었다고 조사 단계로 되돌리면 단계가 걸음마다 오르내려 시킴말이 바뀐다 —
 * 캐시를 걸음마다 깨뜨리면서 모델에게는 갈피를 못 잡게 하는 짓이다.
 *
 * ── 사람이 고른 모드는 안 건드린다 ──────────────────────────────────────
 *
 * `/plan` 을 직접 친 사람에게 계획 모드는 **약속**이다. 옮기는 것은 라우터가
 * **짐작한** 단계뿐이고, 그 둘을 가르는 것은 `종합인가` 하나다.
 */

/*
 * ── 단계가 넘어가는 표 ──────────────────────────────────────────────────
 *
 * 왼쪽에서 오른쪽으로만 간다. 여기 없는 모드는 안 옮긴다.
 *
 *   auto  → code   무슨 일인지 못 고른 채로 시작했는데 파일을 바꾸기 시작했다.
 *                  그러면 지금 하는 일은 만드는 일이다.
 *   debug → code   원인을 찾아 고치기 시작했다. 남은 걸음은 만드는 일이다.
 *   plan  → code   계획을 다 적었다. 다만 이건 조건이 하나 더 붙는다 (아래).
 *
 * `architect` · `inspect` · `ask` 는 **안 옮긴다.**
 *
 * 셋 다 라우터가 「이 턴은 말로 답하는 턴」 이라고 본 자리다. 그리고 그렇게
 * 보려면 사람의 말에 고치라는 말이 없어야 한다(route.js 의 손대라했나 가
 * 그 셋을 후보에서 뺀다). 즉 **사람이 고쳐 달라고 안 했다.** 안 시킨 일을
 * 스스로 시작하는 것은 단계가 나아가는 것이 아니라 시킨 범위를 넘는 것이다.
 */
const 넘어갈곳 = {
  auto: 'code',
  debug: 'code',
  plan: 'code',
};

/*
 * `plan` 만 조건이 더 붙는다. **두 개다.**
 *
 * 계획 모드는 파일을 바꾸는 도구가 없다. 여기서 넘어가면 도구가 늘어 앞머리가
 * 바뀌므로 캐시가 한 번 끊긴다. 게다가 이 자리는 **시킨 범위를 넘을 수 있는
 * 유일한 자리**다 — 다른 단계는 이미 파일을 바꿀 수 있는 자리에서 시작한다.
 *
 *   (1) 사람이 「묻지 말고 끝까지」 라고 적어 뒀어야 한다.
 *
 *       「계획해서 만들어줘」 는 계획을 내고 승인을 받아 이어서 하는 길이 따로
 *       있다(route.js 의 겹친요청). 여기서 몰래 넘어가면 사람이 보자고 한
 *       계획을 못 보고 파일부터 바뀐다. 다만 그 길은 「묻지 말라」 고 적은
 *       사람에게는 꺼져 있다(승인 창이 손해이므로). 계획만 내고 멈추는
 *       나머지 절반이 이 자리다.
 *
 *   (2) 그리고 사람이 **고쳐 달라고 했어야 한다** (route.js 의 손대라했나).
 *
 *       「계획만 세워줘. 알아서 진행해」 는 계획만 원하면서 묻지 말라고도 적은
 *       말이다. (1)만 보면 할 일을 적는 순간 파일이 바뀐다. 「묻지 마라」 는
 *       **어떻게** 하라는 말이고 「고쳐라」 는 **무엇을** 하라는 말이다. 범위를
 *       정하는 것은 뒤엣것이므로 둘 다 있어야 넘어간다.
 */
const 말에있어야하는것 = {
  plan: (말) => 말.묻지말라 === true && 말.손대라 === true,
};

/** 이 단계에서 다음으로 넘어가려면 무엇이 일어나야 하나. */
const 신호 = {
  // 파일을 바꾸기 전에는 아직 조사 중이다.
  auto: (본것) => 본것?.바꿈 === true,
  debug: (본것) => 본것?.바꿈 === true,
  // 계획은 파일을 못 바꾼다. 그러니 「바꿨나」 로는 영영 안 넘어간다.
  // 계획이 끝났다는 신호는 **적어 둔 할 일**이다.
  plan: (본것) => 본것?.할일 === true,
};

/**
 * 지금 걸음에서 어느 단계여야 하나.
 *
 * @param {object} 것
 * @param {string} 것.지금      지금 단계 (작업 모드 id)
 * @param {boolean} 것.종합인가 사람이 고른 모드가 아니라 종합 모드인가
 * @param {object} 것.본것      { 할일: boolean, 바꿈: boolean } — 이번 턴에 일어난 일
 * @param {boolean} 것.묻지말라 사람이 「묻지 말고 끝까지」 라고 적어 뒀나
 * @param {boolean} 것.손대라   사람이 고쳐 달라고 했나 (route.js 의 손대라했나)
 * @returns {string|null} 옮길 곳. 안 옮기면 null.
 */
export function 다음단계({ 지금, 종합인가, 본것, 묻지말라 = false, 손대라 = false }) {
  // 사람이 고른 모드는 약속이다. 짐작만 옮긴다.
  if (!종합인가) return null;
  const 갈곳 = 넘어갈곳[지금];
  if (!갈곳 || 갈곳 === 지금) return null;
  const 잠금 = 말에있어야하는것[지금];
  if (잠금 && !잠금({ 묻지말라, 손대라 })) return null;
  return 신호[지금]?.(본것) ? 갈곳 : null;
}

/** 넘어가면서 도구가 늘어나나 — 늘면 앞머리를 다시 쓰게 되므로 사람에게 말해야 한다. */
export function 도구가늘어나나(옛모드, 새모드, 도구가져오기) {
  const 옛 = new Set(도구가져오기(옛모드));
  return 도구가져오기(새모드).some((t) => !옛.has(t));
}
