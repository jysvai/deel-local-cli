// 되묻기 전에 통과해야 하는 관문.
//
// ── 무엇을 막나 ────────────────────────────────────────────────────────
//
// 실제로 받은 제보다. 사용자가 네 가지를 번호까지 매겨 적어 줬는데, deel 이
// 한참 뒤에 이렇게 물었다 —
//
//   ┌ 물어봅니다
//   │ 어떤 것부터 진행할까요?
//   │ 1 붙여넣기 표시
//   │ 2 ESC 중단
//   │ 3 요청 누락
//   │ 4 여러 파일 편집
//   └ 번호로 골라 주세요
//
// 사용자가 적어 준 목록을 그대로 되읽어 준 것이다. 새로 알아낸 것도, 정해야
// 할 갈림길도 없다. 사람 입장에서는 **읽지도 않고 되묻는** 것으로 보인다.
// "이렇게 내용 못 알아먹고 무작정 계획표 질문하는 이런 것 좀 없으면 좋겠어."
//
// ── 왜 프롬프트로 안 하나 ───────────────────────────────────────────────
//
// 도구 설명에 이미 적혀 있었다 — "이미 사용자가 말한 것을 다시 묻지 마라."
// 그래도 이런 일이 났다. 작은 모델은 그 말을 잘 안 듣고, 큰 모델도 컨텍스트가
// 길어지면 앞의 규칙보다 지금 눈앞의 목록에 이끌린다.
//
// 그래서 여기서 막는다. 막는 것은 모델의 협조가 필요 없다.
//
// ── 무엇을 못 하나 ──────────────────────────────────────────────────────
//
// 이 관문은 **뜻을 모른다.** 글자만 본다. 그래서 "정말 물을 만한 것인가" 는
// 판단하지 않는다 — 그건 애초에 글자로 알 수 없다. 대신 글자로 확실히 알 수
// 있는 것만 막는다: 이해를 안 적었나 · 사용자가 이미 적어 준 것을 되읽나 ·
// 한 번에 여럿을 묻나. 애매하면 통과시킨다. 못 묻게 막는 것이 더 나쁘다.

import { 손대라했나 } from './route.js';
/*
 * 두 글자씩 쪼갠다.
 *
 * 낱말로 자르면 한국어에서 안 맞는다 — '붙여넣기' 와 '붙여넣기한' 과
 * '붙여넣기를' 이 서로 다른 낱말이 된다. 조사가 붙는 말에서 낱말 짝짓기는
 * 거의 언제나 빗나간다.
 *
 * 두 글자 조각으로 보면 그 셋이 '붙여·여넣·넣기' 를 함께 가진다. 영어에도
 * 그대로 통한다(postgres → po·os·st…). 빈칸과 문장부호는 지운다 — 사람이
 * 띄어쓰기를 어떻게 하든 같은 것으로 봐야 한다.
 */
export function 두글자들(글) {
  const 민글 = String(글 ?? '').toLowerCase().replace(/[^0-9a-z가-힣ㄱ-ㅎㅏ-ㅣ]/g, '');
  const 것 = new Set();
  for (let i = 0; i + 2 <= 민글.length; i++) 것.add(민글.slice(i, i + 2));
  return 것;
}

/** 앞엣것이 뒤엣것 안에 얼마나 들어 있나. 0~1. 잴 것이 없으면 0. */
export function 얼마나들었나(작은것, 큰것) {
  const a = 두글자들(작은것);
  if (!a.size) return 0;
  const b = 두글자들(큰것);
  let 든것 = 0;
  for (const x of a) if (b.has(x)) 든것 += 1;
  return 든것 / a.size;
}

/*
 * 사용자가 낱낱이 적어 준 항목이 몇 개인가.
 *
 * 번호(1. 2)·글머리(- ·)·동그라미 숫자를 센다. 줄머리에 있는 것만 센다 —
 * 글 가운데 있는 "1.6.1" 같은 것을 항목으로 세면 안 된다.
 */
export function 항목수(요청) {
  const 줄들 = String(요청 ?? '').split('\n');
  let 몇 = 0;
  for (const 줄 of 줄들) {
    if (/^\s*(\d{1,2}\s*[.)]|[-*·▪️•]|[①-⑮])\s+\S/.test(줄)) 몇 += 1;
  }
  return 몇;
}

/*
 * 알맹이가 없는 이해.
 *
 * "요청을 이해했습니다" 는 이해가 아니다. 무엇으로 이해했는지가 없으면
 * 사람은 그 말을 읽고도 deel 이 제대로 봤는지 알 수 없다 — 그럴 바에는
 * 안 적은 것과 같다.
 */
const 빈말 = [
  /^(사용자|당신)?\s*(의)?\s*(요청|말씀|내용|질문)\s*(을|를)?\s*(잘)?\s*(이해|확인|파악)\s*(했|하였|하겠|합니)/,
  /^(무엇|뭘|어떤\s*것)\s*(을|를)?\s*(원하|바라|하고\s*싶)/,
  /^(어떻게|어떤\s*식으로)\s*(진행|처리|작업)\s*(할지|하면)/,
  /^(더|좀)?\s*(자세한|정확한|구체적인)\s*(내용|정보|설명)\s*(이)?\s*(필요|있어야)/,
  /^i\s+understand\s+(your\s+)?(request|question)/i,
  /^(to\s+)?(better\s+)?(understand|clarify)\s+(what|your)/i,
];

/** 알맹이 없는 이해인가. */
export function 빈이해인가(이해) {
  const s = String(이해 ?? '').trim();
  return 빈말.some((re) => re.test(s));
}

// '무엇부터 할까요' 꼴. 이 물음이 위험한 것은, 사용자가 이미 적어 준 목록
// 앞에서 나올 때다. 그때는 정할 것이 없다 — 순서를 정하는 것이 deel 의 일이다.
const 고르라는물음 = /어(느|떤)\s*(것|거|쪽|부분|순서)|무엇(부터|을)|뭐(부터|를)|어디(부터|서부터)|먼저\s*(할|진행|하)|우선\s*순위|순서(를|는)?\s*(어떻|정)|which\s+(one|of these)|where\s+(should|would)\s+(i|we)\s+start/i;

/*
 * 「그래서 무슨 일을 할까요」 꼴.
 *
 * 위의 고르라는물음 보다 **훨씬 좁다.** 이건 갈림길을 묻는 말이 아니라
 * 무엇을 할지 자체를 되묻는 말이다. 사람이 이미 "만들어 줘" 라고 했는데
 * 이 말이 나오면, 읽기는 했는데 못 알아들은 것이다.
 *
 * 실제로 받은 화면이 이랬다. 사람은 「부문별로 A4 가로 2쪽 PDF 를 OCR 내용
 * 기반으로 따로따로 만들어 줘」 라고 했는데 —
 *
 *   ┌ 물어봅니다
 *   │ 어떤 작업을 진행할까요?
 *   │ 1 내용·디자인 검토  2 내용 업데이트  3 PDF 생성·검증  4 문구 수정
 *   └ 번호로 골라 주세요
 *
 * 답을 주고 나서도 몇 걸음 뒤에 거의 같은 물음이 또 나왔다.
 *
 * '어느 쪽으로 할까요' 는 여기 안 넣는다. 그건 진짜 갈림길일 때가 많다.
 */
const 무슨일할까 = /(어떤|무슨)\s*(작업|일)(을|를)?\s*(진행|할|하)|무엇을\s*(할|진행|해\s*드릴)|뭘\s*(할|해\s*드릴)|어떤\s*것부터|무엇부터|뭐부터|what\s+(should|would)\s+(i|we)\s+(do|work\s+on)|how\s+(should|would)\s+(i|we)\s+proceed/i;

/*
 * 이만큼 겹치면 "이미 물어본 것" 으로 본다.
 *
 * 같은 것 문턱(0.5)보다 조금 낮게 둔다. 두 번째 물음은 첫 번째를 그대로
 * 베끼지 않고 조금 줄여서 다시 적기 때문이다 — 위 화면에서도
 * "현재 A3 경영진보고 편집 파일과 원본 자료를 확인했습니다. 어떤 작업을
 * 진행할까요?" 가 "A3 경영진 보고 편집본에서 어떤 작업을 진행할까요?" 로
 * 바뀌어 다시 나왔다.
 */
const 또물음문턱 = 0.45;

// 한 턴에 이만큼까지만. 세 번 물으면 그건 대화가 아니라 뺑뺑이다.
const 한턴에최대 = 2;

/*
 * 이만큼 겹치면 "사용자가 이미 적어 준 것" 으로 본다.
 *
 * 값을 재서 정했다. 처음에 0.6 으로 뒀더니 제보에 나온 그 물음을 못 잡았다 —
 * 모델은 사용자 말을 그대로 베끼지 않고 **줄여서 다시 적기** 때문이다.
 *
 *   "붙여넣기 해도 창에 붙여넣기된 내용이 다 뜨는 게 아니야"
 *     → 선택지 "붙여넣기 내용 표시"        0.57
 *   "다른 cli 쓰다가 deel 쓰면 기능적으로…"
 *     → 선택지 "다른 cli 대비 기능"         0.63
 *
 * 반대쪽도 쟀다. 진짜 갈림길의 선택지는 0.2 언저리다 —
 *   "버린다 — 긴 붙여넣기에서 메모리를 아낀다"  0.19
 * '붙여넣기' 라는 말이 그대로 들어 있는데도 그렇다. 나머지가 다 새 말이라서다.
 *
 * 0.5 는 그 사이다. 여기서 더 내리면 진짜 갈림길이 막히기 시작한다.
 */
const 같은것문턱 = 0.5;

/**
 * 이 물음을 사람에게 내보내도 되나.
 *
 * @param {object} 것
 * @param {string} 것.물음
 * @param {string[]} [것.고를것]
 * @param {string} [것.이해]  이번 요청을 무엇으로 알아들었는지
 * @param {string} [것.요청]  사용자가 실제로 친 말
 * @returns {{ok: true} | {ok: false, 왜: string, 할말: string}}
 *          할말 은 모델에게 그대로 돌려줄 글이다 — 무엇이 모자란지와
 *          대신 무엇을 하라는 것까지 적는다. "안 됩니다" 만 돌려주면
 *          모델은 같은 것을 다시 부른다.
 */
export function 물음검사({ 물음 = '', 고를것 = [], 이해 = '', 요청 = '', 이미물은것 = [] } = {}) {
  const 물 = String(물음 ?? '').trim();
  const 이 = String(이해 ?? '').trim();
  const 것들 = (Array.isArray(고를것) ? 고를것 : []).map((x) => String(x ?? '').trim()).filter(Boolean);

  // ── 1. 이해를 먼저 말한다 ────────────────────────────────────────────
  if (이.length < 10) {
    return {
      ok: false,
      왜: '이해가 없음',
      할말: '묻기 전에 `이해` 를 채우세요 — 이번 요청을 무엇으로 알아들었는지 한 줄로.'
        + ' 사람은 그 줄을 보고 네가 제대로 읽었는지 판단합니다.'
        + ' 그 줄을 못 쓰겠으면 아직 물을 때가 아닙니다. 먼저 읽어 보세요.',
    };
  }
  if (빈이해인가(이)) {
    return {
      ok: false,
      왜: '이해가 알맹이 없음',
      할말: `"${이}" 는 이해가 아니라 인사말입니다. **무엇을** 하라는 것으로 알아들었는지`
        + ' 그 일의 내용을 넣어 다시 적으세요 (예: "붙여넣은 글이 화면에 다 안 뜨는 것을'
        + ' 접힌 표시로 바꾸라는 것으로 이해했습니다").',
    };
  }

  // ── 2. 이미 적어 준 것을 되읽지 않는다 ───────────────────────────────
  //
  // 선택지 하나하나가 사용자 말 안에 이미 들어 있으면, 그건 갈림길이 아니라
  // 목록을 되읽어 준 것이다. 둘 이상이면 그렇게 본다 — 하나는 우연일 수 있다.
  const 이미있는것 = 것들.filter((x) => 얼마나들었나(x, 요청) >= 같은것문턱);
  if (이미있는것.length >= 2) {
    return {
      ok: false,
      왜: `선택지 ${이미있는것.length}개가 이미 사용자 말 안에 있음`,
      할말: `선택지로 내민 것 중 ${이미있는것.length}개(${이미있는것.slice(0, 3).join(' · ')})는`
        + ' 사용자가 이미 적어 준 것입니다. 그건 갈림길이 아니라 할 일 목록입니다.'
        + ' 묻지 말고 **전부** 하세요. 순서를 정하는 것은 네 일입니다 —'
        + ' TodoWrite 로 적고 시작하세요.',
    };
  }

  // 선택지 없이 "무엇부터 할까요" 만 던지는 것도 같다.
  const 적어준것 = 항목수(요청);
  if (적어준것 >= 2 && 고르라는물음.test(물)) {
    return {
      ok: false,
      왜: `사용자가 ${적어준것}개를 적어 줬는데 무엇부터냐고 물음`,
      할말: `사용자가 이미 ${적어준것}가지를 적어 줬습니다. 무엇부터 할지는 묻는 것이 아니라`
        + ' 네가 정하는 것입니다. TodoWrite 로 그 목록을 그대로 적고 첫 번째부터 시작하세요.'
        + ' 순서를 바꾸는 편이 낫다고 보면 그 까닭을 한 줄로 밝히고 그렇게 하세요.',
    };
  }

  // ── 3. 하라고 한 일을 두고 "무슨 일 할까요" 라고 되묻지 않는다 ───────
  if (손대라했나(요청) && 무슨일할까.test(물)) {
    return {
      ok: false,
      왜: '하라고 한 일을 두고 무슨 일을 할지 되물음',
      할말: '사용자는 이미 무엇을 하라고 말했습니다. 무슨 일을 할지는 묻는 것이 아닙니다.'
        + ' 그 말대로 하세요 — 시킨 것을 TodoWrite 로 적고 첫 번째부터 시작하세요.'
        + ' 정말 정할 것이 남았으면 그 **한 가지**만 콕 집어 물으세요'
        + ' (예: "글꼴 파일이 zip 안에 둘인데 어느 것을 쓸까요?").',
    };
  }

  // ── 4. 같은 것을 또 묻지 않는다 ──────────────────────────────────────
  //
  // 물어보고, 답을 듣고, 몇 걸음 뒤에 거의 같은 것을 또 묻는 화면을 받았다.
  // 사람 눈에는 앞의 대답이 통째로 무시된 것으로 보인다 — 실제로도 그렇다.
  const 앞것 = (Array.isArray(이미물은것) ? 이미물은것 : []);
  for (const 앞 of 앞것) {
    const 앞물음 = String(앞?.물음 ?? 앞 ?? '');
    if (!앞물음) continue;
    if (얼마나들었나(물, 앞물음) < 또물음문턱) continue;
    const 답 = String(앞?.답 ?? '').trim();
    return {
      ok: false,
      왜: '이번 턴에 이미 물어본 것',
      할말: `이미 물었습니다 — "${앞물음}"`
        + (답 ? `\n사람의 답은 이것이었습니다: "${답}"` : '\n사람이 답을 안 했습니다.')
        + '\n같은 것을 또 묻지 마세요. 그 답대로 진행하세요.'
        + ' 답이 애매했으면 애매한 채로 가장 그럴듯한 쪽을 골라 진행하고,'
        + ' 무엇을 그렇게 정했는지 끝에 한 줄 적으세요.',
    };
  }

  if (앞것.length >= 한턴에최대) {
    return {
      ok: false,
      왜: `한 턴에 ${앞것.length}번 물음`,
      할말: `이번 턴에 이미 ${앞것.length}번 물었습니다. 더 묻지 말고 진행하세요.`
        + ' 세 번을 묻는다는 것은 물음으로 풀 문제가 아니라는 뜻입니다 —'
        + ' 지금 아는 것으로 가장 그럴듯한 쪽을 골라서 하고, 무엇을 가정했는지 끝에 적으세요.',
    };
  }

  // ── 5. 한 번에 하나만 ────────────────────────────────────────────────
  const 물음표 = (물.match(/[?？]/g) ?? []).length;
  if (물음표 >= 2) {
    return {
      ok: false,
      왜: '한 번에 여럿을 물음',
      할말: '한 번에 하나만 물으세요. 두 가지를 한 줄에 넣으면 사람은 한쪽만 답하고,'
        + ' 나머지는 답을 받은 것으로 착각한 채 진행하게 됩니다.'
        + ' 정말 둘 다 필요하면 더 급한 것부터 하나만 묻고, 나머지는 그 답을 받고 나서.',
    };
  }

  return { ok: true };
}
