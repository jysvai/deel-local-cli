/**
 * 배운 것을 파일에서 읽어들일 때 **모양을 잰다.**
 *
 * ── 왜 따로 있나 ────────────────────────────────────────────────────────
 *
 * confidence.js 는 「이 셈을 얼마나 믿을까」 를 정한다. 여기는 그 앞이다 —
 * 「이게 애초에 우리가 적은 모양이 맞나」. 통계와 문지기는 다른 일이고,
 * 섞어 두면 통계 문턱을 만질 때마다 문지기도 같이 흔들린다.
 *
 * ── 왜 문지기가 필요한가 ────────────────────────────────────────────────
 *
 * `배운것.json` 은 그냥 파일이다. 사람이 열어 고칠 수 있고, 다른 판이 다른
 * 모양으로 적어 뒀을 수도 있고, 쓰다 만 채로 남았을 수도 있다.
 *
 * 그런데 그 안의 **열쇠는 시스템 프롬프트에 그대로 실린다** (evolve.js 의
 * 요약 — 역따옴표로 감싸서 나간다). 그러니 이 파일을 읽는 자리가 곧 프롬프트로
 * 들어가는 문이고, 문에는 자물쇠가 있어야 한다.
 *
 * 여기서 재는 것은 「참인가」 가 아니라 **「실려도 되는 꼴인가」** 다.
 * 참인지는 confidence.js 가 정한다.
 */

const 열쇠최대 = 40;

/*
 * 무엇을 막을지가 아니라 **무엇만 받을지**를 적는다.
 *
 * 막을 것을 적으면 언젠가 빠뜨린다. 이 열쇠는 명령 이름 두 낱말이라 받을 것이
 * 좁게 정해져 있다 — 글자·숫자·띄어쓰기와 경로에 쓰는 몇 개뿐이다.
 *
 * 역따옴표와 줄바꿈이 이 목록에 없는 것이 요점이다. 이 글자는 프롬프트에서
 * 역따옴표로 감싸여 나가므로, 역따옴표 하나면 그 자리에서 틀이 깨지고
 * 그다음 글이 명령 이름 행세를 한다.
 */
const 받을꼴 = /^[A-Za-z0-9 _.:@+/-]+$/;

export function 성한열쇠인가(열쇠) {
  const s = String(열쇠 ?? '');
  // 빈칸뿐인 열쇠는 명령 이름이 아니다 — 받을꼴에 빈칸이 들어 있어 그냥 지났다.
  if (!s.trim() || s.length > 열쇠최대) return false;
  return 받을꼴.test(s);
}

export function 성한기록인가(r) {
  if (!r || typeof r !== 'object' || Array.isArray(r)) return false;
  /*
   * 「숫자로 바꿔지면 숫자」 가 아니다.
   *
   * Number() 로 재면 '3'·null·true·[] 가 전부 통과한다 — 우리가 그렇게 적은 적이
   * 없는 꼴이다(evolve.js 는 0 에서 시작해 1씩 더한다). 이 머리말이 적어 둔 대로
   * **무엇만 받을지**를 적는다. 남의 손이 닿은 파일을 고쳐서 받지도 않는다.
   */
  for (const 칸 of ['ok', 'no']) {
    const v = r[칸];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < 0) return false;
  }
  // 날짜가 없거나 못 읽으면 못 믿는다. 나이를 모르는 주장은 안 싣는다
  // (confidence.js 의 며칠됐나 가 그때 무한대를 돌려준다).
  return Number.isFinite(Date.parse(String(r.at ?? '')));
}

/**
 * 표에서 모양이 안 맞는 것을 걷어낸 **사본**을 돌려준다.
 *
 * 고쳐서 쓰지 않는다. 모양이 안 맞는 것을 우리 짐작으로 고쳐 놓으면, 무엇이
 * 어떻게 바뀌었는지가 또 아무 데도 안 남는다.
 */
export function 거른표(표) {
  const out = {};
  // 목록은 표가 아니다. Object.entries([r]) 는 ['0', r] 을 주고 '0' 은 받을꼴에
  // 걸려 통과한다 — 명령 이름 자리에 0 이 적힌 채 프롬프트로 나간다.
  if (!표 || typeof 표 !== 'object' || Array.isArray(표)) return out;
  for (const [k, v] of Object.entries(표)) {
    if (성한열쇠인가(k) && 성한기록인가(v)) out[k] = v;
  }
  return out;
}
