/** 인자에서 사람이 알아볼 한 조각만 뽑는다. 경로가 제일 쓸모 있다. */
function 어디(args) {
  if (!args || typeof args !== 'object') return '';
  for (const k of ['file_path', 'path', 'pattern', 'command', 'query', 'url', '목적']) {
    const v = args[k];
    if (typeof v === 'string' && v.trim()) return v.trim().replace(/\s+/g, ' ').slice(0, 60);
  }
  return '';
}

/*
 * ── 그림은 따로 뺀다 ───────────────────────────────────────────────────
 *
 * 위의 접기는 도구 결과(role:'tool')만 건드린다. 사람 말은 한 글자도 안 건드리는
 * 것이 그 함수의 약속이라 그렇다. 그런데 그림은 **사람 말 자리에** 실린다
 * (backend/vision.js 의 그림메시지 머리말 — 도구 결과에는 못 넣는다).
 *
 * 그림 한 장은 base64 로 몇 MB 다. 화면 사진 몇 장을 이어 보여 주면 대화가
 * 그것만으로 무거워지고, 오래된 사진은 이미 이야기가 끝난 것이다. 그래서
 * 최근 몇 장만 남기고 나머지는 **무엇이었는지만 남기고** 뺀다.
 *
 * 사람이 쓴 말은 그대로 둔다 — 빼는 것은 그림 조각뿐이다.
 */
const KEEP_IMAGES = 2;

/** 오래된 그림을 이름만 남기고 뺀다. @returns {{뺀것:number, 뺀것들:Array}} */
export function foldImages(session, { keep = KEEP_IMAGES } = {}) {
  const ms = session.messages ?? [];
  const 자리 = [];
  ms.forEach((m, i) => { if (그림장수(m)) 자리.push(i); });

  /*
   * ── 남기는 것은 **장수**다, 메시지 수가 아니다 ─────────────────────────
   *
   * `KEEP_IMAGES` 는 위 머리말대로 「최근 몇 **장**」 이다. 그런데 자리를
   * 메시지 단위로 세고 거기서 keep 을 빼고 있었다. 그래서 한 메시지에 여러
   * 장이 실리면(`@a.png @b.png @c.png` 를 한 줄로 붙이면 그렇게 된다)
   * **남는 장수가 keep 을 훌쩍 넘었다.**
   *
   *   석 장 실린 메시지 + 한 장 실린 메시지  →  자리가 둘이라 한 장도 안 뺀다
   *                                            (남는 것은 넉 장. keep 은 둘)
   *
   * 몇 MB 짜리 사진 셋이 「최근 둘만 남긴다」 는 이름 아래 그대로 남는다.
   *
   * ── 그러면서도 한 덩이는 쪼개지 않는다 ────────────────────────────────
   *
   * 사람이 한 번에 붙인 사진들은 한 이야기다. 그 안에서 어느 장이 더 오래된
   * 것인지 알 길도 없다. 그래서 **마지막 덩이는 몇 장이든 남기고**, 그보다
   * 앞엣것은 장수를 더해 keep 을 안 넘을 때만 남긴다. 마지막 덩이를 빼지
   * 않는 까닭: 방금 보여 준 사진을 그 자리에서 없애면 그 턴이 헛턴이 된다.
   */
  let 남긴장수 = 0;
  let 첫남길자리 = 자리.length;
  for (let k = 자리.length - 1; k >= 0; k--) {
    const 이번장수 = 그림장수(ms[자리[k]]);
    // 마지막 덩이는 무조건 남긴다. 그 뒤로는 넘치면 거기서 끊는다.
    if (k < 자리.length - 1 && 남긴장수 + 이번장수 > keep) break;
    남긴장수 += 이번장수;
    첫남길자리 = k;
  }

  const 뺄것 = 자리.slice(0, 첫남길자리);
  const 뺀것들 = [];
  for (const i of 뺄것) {
    const m = ms[i];
    const 장수 = 그림장수(m);
    const 글 = 글만(m);
    ms[i] = { ...m, content: `${글}
${접힘표} 그림 ${장수}장은 자리를 비우려고 뺐습니다. 필요하면 다시 여세요.` };
    delete ms[i].images;
    뺀것들.push({ 장수 });
  }
  /*
   * `뺀것` 은 **장수**다.
   *
   * 여기가 `뺄것.length` — 곧 **메시지 수**였다. 화면은 이 값을 「그림 N장을
   * 뺐습니다」 로 적으므로, 한 메시지에서 넉 장을 뺀 판에 「1장」 이라고
   * 떴다. 사람이 세어 볼 수 있는 숫자라 틀리면 바로 거짓이 된다.
   */
  return { 뺀것: 뺀것들.reduce((a, x) => a + x.장수, 0), 뺀메시지: 뺄것.length, 뺀것들 };
}

/*
 * ── 로컬은 창을 끝까지 쓰지 않는다 ──────────────────────────────────────
 *
 * 로컬 서버는 문맥이 길수록 생성까지 느려진다. 창 몫(80%)으로만 재면 65k 창은 5만 2천
 * 토큰까지 차야 접기 시작하고, 그때는 이미 답이 눈에 띄게 느리다. 큰 창의 로컬은 요약을
 * 4만 토큰에서 시작하도록 접기·요약·비우기 문턱을 같은 배율로 당긴다. 바깥 연결과 작은
 * 창은 값이 그대로다. 부르는 쪽이 `at` 을 직접 주면 배율을 안 건다.
 */
const 로컬요약토큰 = 40000;

export function 문턱배율(session) {
  if (바깥인가(session?.conn?.base)) return 1;
  const 요약자리 = (session?.breakdown?.()?.total ?? 0) * COMPACT_AT;
  return 요약자리 > 로컬요약토큰 ? 로컬요약토큰 / 요약자리 : 1;
}

export function shouldFold(session, at = null) {
  const b = session.breakdown();
  const 문턱 = at ?? (캐시가도나(session) ? FOLD_AT_캐시 : FOLD_AT) * 문턱배율(session);
  return b.total > 0 && b.used / b.total >= 문턱;
}

/**
 * 이 연결에서 「이만큼은 비워야 접는다」 는 값 (토큰).
 *
 * 캐시가 안 도는 자리에서는 여태 쓰던 고정값(최소이득)이다. 도는 자리에서는
 * 창에 견준 몫으로 잰다 — 위 머리말의 손익분기 때문이다.
 */
export function 접을이득문턱(session) {
  if (!캐시가도나(session)) return 최소이득;
  const 창 = session?.breakdown?.()?.total ?? 0;
  return 창 > 0 ? Math.max(최소이득, Math.floor(창 * 캐시일때비울몫)) : 최소이득;
}

/**
 * 오래된 도구 결과를 한 줄로 접는다.
 *
 * 짝은 안 건드린다 — 메시지를 지우는 게 아니라 **내용만** 바꾸므로 호출과
 * 결과의 짝이 그대로다. 규격이 깨질 자리가 아예 없다.
 *
 * @returns {{접은것: number, 아낀토큰: number}}
 */
export function foldToolResults(session, { keep = KEEP_RECENT, min = FOLD_MIN, 이득문턱 = null } = {}) {
  const ms = session.messages ?? [];
  // 안 적어 주면 이 연결에 맞는 값으로 (위 접을이득문턱 — 캐시가 도는지가 가른다).
  const 넘을것 = 이득문턱 ?? 접을이득문턱(session);

  /*
   * 호출 쪽에서 이름과 인자를 가져온다. 결과 메시지에는 그게 안 실려 있다.
   *
   * 부름도 결과도 규격마다 다른 자리에 담긴다(backend/adapter.js). 여기가
   * `tool_calls` 와 `role:'tool'` 만 보던 동안 Anthropic 창구에서는 **접은 것이
   * 늘 0 이었다** — 55% 에서 싸게 자리를 비우는 단계가 통째로 죽어 있었고,
   * 그대로 80% 의 손실 있는 요약으로 직행했다. 캐시가 제일 중요한 창구에서
   * 캐시를 지키려고 만든 단계가 안 돈 것이다.
   */
  const 이름표 = new Map();
  /*
   * id 가 없는 규격(Ollama)은 결과가 부름을 **차례로** 짝짓는다. id 로만 찾으면 그 규격에서는
   * 인자가 늘 비어서 경로를 못 뽑았다 — 접힌 파일의 기억이 안 지워지고, 다시 읽으면
   * 「앞에서 읽은 그대로입니다」 만 돌아갔다. 바로 앞 부름들을 차례대로 맞춘다.
   */
  const 차례짝 = new Map();   // `${메시지 자리}:${결과 자리}` → 부름
  let 남은부름 = [];
  ms.forEach((m, i) => {
    const 부름 = 부른것들(m);
    if (부름.length) {
      for (const c of 부름) if (c.id) 이름표.set(c.id, { name: c.name ?? '도구', args: c.args ?? {} });
      남은부름 = [...부름];
      return;
    }
    결과들(m).forEach((x, k) => {
      const j = x?.id ? 남은부름.findIndex((c) => c.id === x.id) : -1;
      if (j >= 0) { 남은부름.splice(j, 1); return; }
      if (!x?.id && 남은부름.length) 차례짝.set(`${i}:${k}`, 남은부름.shift());
    });
  });

  const 자리 = [];
  ms.forEach((m, i) => {
    if (!도구결과인가(m)) return;
    const 것들 = 결과들(m);
    // 한 메시지에 결과가 여럿 실리는 규격이 있다. 그때는 이어 붙여 한 자리로 본다.
    const 글 = 것들.map((x) => x.글).join('\n');
    if (글.startsWith(접힘표)) return;      // 이미 접은 것
    const 첫 = 것들[0];
    /*
      * 이름과 인자를 **여기서** 뽑아 둔다.
      *
      * 아래 접는 자리가 이걸 안 쓰고 `이름표.get(m.tool_call_id)` 로 다시
      * 뽑고 있었다. `tool_call_id` 는 OpenAI 꼴 짐작이라 Anthropic·Ollama
      * 에서는 늘 undefined 였고, 그러면 이름이 「도구」로, 인자가 `{}` 로
      * 떨어진다. 인자가 비면 경로도 못 뽑아서 파일 기억이 안 지워지고,
      * 접힌 파일을 다시 읽을 때 「앞에서 읽은 그대로입니다」 만 돌아온다.
      * 같은 것을 두 번 뽑을 까닭이 없다 — 한 번 뽑아서 같이 들고 간다.
      */
     const 아는것 = 이름표.get(첫?.id) ?? 차례짝.get(`${i}:0`) ?? null;
     /*
      * 이름은 **한 메시지에 실린 것 전부**를 들고 간다.
      *
      * 아래 「마지막 할 일 목록은 안 접는다」 가 이 이름을 본다. 그런데
      * 첫 것만 들고 가면, 모델이 한 턴에 `Read` 와 `TodoWrite` 를 같이 부른
      * 판에서 — Anthropic 꼴은 그 결과 둘을 **한 메시지**에 싣는다 —
      * 이름이 'Read' 로 잡혀 할 일 목록이 지킴 목록에서 빠진다. 그러면
      * 그 자리가 접히면서 남은 항목이 어디에도 없어진다.
      *
      * 아래 머리말이 「접는 순간 남은 항목이 어디에도 없어진다」 고 적어 둔
      * 바로 그 일이, 도구를 둘 같이 부른 판에서만 조용히 일어났다.
      */
     const 이름들 = 것들.map((x, k) => 이름표.get(x?.id)?.name ?? 차례짝.get(`${i}:${k}`)?.name ?? x?.name ?? '').filter(Boolean);
     자리.push({
       i, 글, 이름들,
       이름: 아는것?.name ?? 첫?.name ?? '',
       args: 아는것?.args ?? {},
       // 한 메시지에 결과가 여럿이면 인자도 여럿이다 — 경로를 다 뽑아야 파일 기억을 다 지운다.
       args들: 것들.map((x, k) => (이름표.get(x?.id) ?? 차례짝.get(`${i}:${k}`))?.args).filter(Boolean),
     });
  });

  /*
   * ── 가장 최근 할 일 목록은 안 접는다 ─────────────────────────────────
   *
   * 접힘 문구는 「필요하면 다시 읽으세요」다. 파일이면 맞는 말이다 — 읽는
   * 값은 싸고 하던 일을 잊는 값은 비싸니까. 그런데 **할 일 목록은 다시
   * 읽을 파일이 없다.** 접는 순간 남은 항목이 어디에도 없어진다.
   *
   * 그래서 긴 작업일수록 뒤로 갈수록 시킨 것을 빠뜨렸다 — 「대화를 잘
   * 기억 못 한다」로 제보받은 것의 큰 몫이 여기였다.
   *
   * 옛 목록은 그대로 접는다. 새 목록이 나온 순간 옛것은 이미 틀린 것이라
   * 남겨 둘수록 해롭다. 지키는 것은 **마지막 하나**뿐이고, 목록 하나는
   * 몇백 글자라 자리도 거의 안 먹는다.
   */
  const 지킬할일 = 자리.filter((x) => x.이름들.includes('TodoWrite')).at(-1)?.i ?? -1;

  const 접을것 = 자리
    .slice(0, Math.max(0, 자리.length - keep))
    .filter((x) => x.글.length >= min && x.i !== 지킬할일);

  /*
   * 비울 수 있는 양이 문턱에 못 미치면 **이번에는 안 접는다.**
   *
   * 한 줄 아끼자고 앞머리를 깨면 그 걸음에 대화가 통째로 다시 나간다.
   * 모아 두었다가 한 번에 접는 편이 눈에 띄게 싸다. 자리가 정말 모자라면
   * 80% 에서 요약 압축이 받아 준다 — 안전망은 그쪽에 있다.
   *
   * ── 토큰만 세는 것으로는 묶음이 안 된다 ──────────────────────────────
   *
   * 이 머리말은 「접기는 묶음으로 한다」 고 적어 두고, 걸음마다 하나씩 접던
   * 것을 고쳤다고 말한다. 그런데 막는 자가 이득문턱(2,000토큰) 하나뿐이라
   * **평범한 Read 결과 하나가 혼자서 그 문턱을 넘는다.** 60줄짜리 결과 하나가
   * 3천 토큰이다. 그래서 55% 를 넘긴 뒤로는 실제로 **걸음마다 한 개씩** 접혔다
   * — 고쳤다고 적어 둔 바로 그 모양 그대로. 재 보니 접을 만한 20걸음에서
   * 20번 접었다.
   *
   * 값이 어떻게 되나: 한 걸음에 3천 토큰 아끼려고, 접힌 자리 뒤 전부(1만
   * 2천 토큰쯤)를 캐시 읽기가 아니라 정가 입력으로 다시 보낸다. 그걸 걸음마다
   * 한다. 로컬이면 그 걸음마다 프리필을 통째로 다시 돈다.
   *
   * 그래서 **개수도 같이 본다.** 최근 keep 개는 어차피 남기므로, 새로 밀려난
   * 것이 keep 개 모일 때까지 기다렸다가 한 번에 접는다. 접는 횟수가 1/keep 로
   * 줄고, 한 번 깰 때 아끼는 양은 그만큼 커진다 — 깨는 값은 같은데.
   *
   * 이미 접힌 것은 여기 안 셈해진다(위 filter 의 min 이 걸러낸다 — 접힌 자국은
   * 100자도 안 된다). 그래서 이 수는 언제나 **새로 접을 것**의 수다.
   */
  const 예상이득 = 접을것.reduce((a, x) => a + estimateTokens(x.글), 0);
  /*
   * ── 개수를 기다리는 것이 손해가 되는 판 ────────────────────────────────
   *
   * 위 개수 문턱은 「3천 토큰 아끼려고 앞머리를 깨지 말라」 는 말이다. 맞는
   * 말인데, **아낄 것이 3만 토큰일 때도** 똑같이 기다렸다. 큰 파일 읽기 셋이
   * 쌓인 판에서 접기를 미루면 그 다음 안전망은 80% 요약 압축이고, 그쪽은
   * 대화를 **통째로 요약으로 갈아 치우는** 훨씬 비싼 일이다. 개수를 기다리다
   * 더 큰 것을 치르는 셈이다.
   *
   * 그래서 기다림을 **값으로** 판단한다. 앞머리를 깨는 값은 **접은 뒤에**
   * 그 자리부터 다시 보내야 하는 토큰이다 — 캐시에서 싸게 읽던 것을 정가로
   * 다시 쓴다. 아끼는 것이 그보다 크면 지금 접는 것이 이득이라, 개수를 더
   * 기다리지 않는다.
   *
   * 접기 전 양에서 아끼는 양을 뺀다. 접을 글 자체를 대가로 세면 안 된다 —
   * 그건 접은 뒤에 사라지는 것이라, 세는 순간 늘 「기다려라」 가 나온다.
   */
  const 깰자리 = 접을것[0]?.i ?? -1;
  const 깨는값 = 깰자리 < 0 ? Infinity
    : Math.max(0, ms.slice(깰자리).reduce((a, m) => a + estimateTokens(
      도구결과인가(m) ? 결과들(m).map((x) => x.글).join('\n')
        : (typeof m.content === 'string' ? m.content : JSON.stringify(m.content ?? '')),
    ), 0) - 예상이득);
  const 기다릴까 = 접을것.length < keep && 예상이득 <= 깨는값;
  if (예상이득 < 넘을것 || 기다릴까) {
    return {
      접은것: 0, 아낀토큰: 0, 접은것들: [], 미룸: true,
      모인것: 예상이득, 모인개수: 접을것.length, 넘을것,
    };
  }

  let 아낀토큰 = 0;
  // 무엇을 버렸는지 이름으로 남긴다.
  //
  // 조용히 버리면 사람이 모른다 — "아까 그 파일 내용 어디 갔지" 를 스스로 답할
  // 길이 없다. 접힌 자리에 표시가 남긴 하지만 그건 모델이 보는 쪽이고,
  // 사람 화면에는 여기서 돌려주는 목록으로 알려 준다.
  const 접은것들 = [];

  for (const { i, 글, 이름, args, args들 } of 접을것) {
    const m = ms[i];
    const 도구이름 = 이름 || '도구';
    const 곳 = 어디(args);
    const 줄수 = 글.split('\n').length;
    const 전 = estimateTokens(글);
    const 접은글 = `${접힘표} ${도구이름}${곳 ? `(${곳})` : ''} — ${줄수}줄. `
      + '자리를 비우려고 내용을 접었습니다. 필요하면 다시 읽으세요.';
    /*
     * 글만 갈아 끼운다 — 메시지를 통째로 덮으면 짝이 깨진다.
     *
     * Anthropic 꼴 결과는 `tool_result` 블록 안에 `tool_use_id` 를 들고 있다.
     * `{ ...m, content: 접은글 }` 로 덮으면 그 id 가 없어지고, 앞 차례의
     * `tool_use` 가 짝을 잃어 다음 요청이 400 이다. 규격별로 어디를 바꿔야
     * 하는지는 backend/adapter.js 가 안다 (결과바꾸기).
     */
    ms[i] = 결과바꾸기(m, 접은글);
    const 아낀것 = 전 - estimateTokens(접은글);
    아낀토큰 += 아낀것;
    /*
     * 자른 표시용 이름(곳)과 **진짜 경로**를 따로 담는다.
     *
     * 곳 은 화면에 쓰려고 60자에서 자른 것이라, 이걸로 파일 기억을 지우면
     * 긴 경로가 안 맞아서 조용히 안 지워진다 — 그러면 접힌 파일을 다시
     * 읽을 때 「앞에서 읽은 그대로입니다」 만 돌아간다(agent/filemem.js).
     */
    const 경로뽑기 = (a) => (typeof a?.file_path === 'string'
      ? a.file_path
      : (typeof a?.path === 'string' ? a.path : null));
    const 경로 = 경로뽑기(args);
    /*
     * 한 메시지에 결과가 둘 실리면(Anthropic) 첫 결과의 경로만 들고 가서, 두 번째 파일은
     * 내용이 접혔는데 기억이 남았다 — 다시 읽으면 「앞에서 읽은 그대로입니다」.
     */
    const 경로들 = [...new Set([경로, ...(args들 ?? []).map(경로뽑기)].filter(Boolean))];
    접은것들.push({ 도구: 도구이름, 곳, 경로, 경로들, 줄수, 토큰: Math.max(0, 아낀것) });
  }

  /*
   * 캐시를 다시 쓰게 된다는 것도 같이 올린다.
   *
   * 접기는 값이 드는 일인데(위 손익분기), 화면에는 「몇 토큰을 비웠다」 만
   * 나왔다. 그러면 사람은 이득만 보고 대가는 며칠 뒤 청구서에서 본다.
   * 캐시가 도는 자리에서만 참이므로, 실제로 읽힌 것을 봤을 때만 적는다.
   */
  return {
    접은것: 접을것.length, 아낀토큰: Math.max(0, 아낀토큰), 접은것들,
    /*
     * 화면에 「캐시를 다시 씁니다」 를 적을까.
     *
     * `캐시가도나()` 를 그대로 쓰고 있었다. 그 함수는 **결정**을 위해 모르는
     * 쪽을 「있다」 로 기울인다(그 머리말) — 그래서 첫 턴에는, 캐시가 아예
     * 없는 창구에서도 늘 참이었다. 그러면 화면은 「값과 지연이 한 번 튑니다」
     * 라고 겁을 주는데 잃을 캐시가 애초에 없다.
     *
     * 결정은 기울여도 되지만 **화면은 아는 것만 적는다.** 캐시를 정말 읽어
     * 본 적이 있을 때만 말한다.
     */
    캐시다시씀: (session?.usage?.cacheRead ?? 0) > 0,
  };
}

/**
 * 접힌 파일을 **파일 기억에서 지울 때 쓸 열쇠** (agent/filemem.js).
 *
 * 접은 자리에 남은 경로는 모델이 적어 보낸 글자 그대로다 — 대개 `src/a.js`
 * 같은 상대 경로다. 그런데 파일 기억은 `ctx.scope.resolve()` 를 거친 **절대
 * 경로**로 묶여 있다(tools/index.js 의 읽은것). 그대로 지우면 Map 이 안 맞아서
 * 조용히 아무것도 안 지워지고, 그러면 접혀 사라진 파일을 다시 읽을 때
 * 「앞에서 읽은 그대로입니다」 가 돌아간다. 모델은 대화 어디에도 없는 글을
 * 가리키는 쪽지를 받고, 결국 또 읽는다 — 접기로 아낀 것을 되읽기로 도로 쓴다.
 *
 * 울타리 밖이라 못 풀면 적힌 그대로 돌려준다. 둘 다 지워 보는 것은 부르는
 * 쪽 몫이다 — 지우는 일은 없는 열쇠에도 안전하다.
 *
 * @param {string} 경로  접은 자리에 적혀 있던 경로 (모델이 준 그대로)
 * @param {object|null} scope  safety/guard.js 의 울타리
 * @returns {string} 지울 때 쓸 열쇠
 */
export function 접힌파일열쇠(경로, scope = null) {
  const 적힌것 = String(경로 ?? '');
  if (!적힌것) return 적힌것;
  try { return scope?.resolve?.(적힌것) ?? 적힌것; } catch { return 적힌것; }
}

