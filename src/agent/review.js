// 쓴 사람은 제가 쓴 것을 못 본다. 방금 그 코드를 왜 그렇게 썼는지 머릿속에
// 남아 있어서, 읽을 때 그 기억이 빈자리를 메워 준다. 모델도 똑같다 — 같은
// 대화 안에서 "다시 봐" 라고 하면 제가 한 말을 근거로 제 코드를 변호한다.
//
// 그래서 **새 창에서** 본다. 지금 대화는 한 줄도 안 보낸다. 보내는 것은
// 바뀐 코드와 검사표뿐이다. 무엇을 하려던 것인지 모르는 눈으로 봐야
// "이건 왜 이렇게 돼 있지" 가 나온다.
//
// ── 무엇을 안 하나 ─────────────────────────────────────────────────────
//
// **고치지 않는다.** 도구를 아예 안 준다. 찾은 것을 말로만 돌려준다.
// 리뷰가 제 손으로 고치기 시작하면 사람이 무엇을 승인한 것인지 흐려지고,
// 찾은 것 중 무엇이 진짜인지 가릴 기회가 없어진다. 고칠지 말지는 사람이
// 정한다 — 그게 리뷰의 전부다.
