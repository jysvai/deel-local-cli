/**
 * 무엇을 볼지 고른다.
 *
 * 이번 대화가 바꾼 것이 있으면 그것만 본다 — 사람이 방금 시킨 일이 그것이라
 * 지금 궁금한 것도 그것이다. 없으면 저장소가 들고 있는 변경(작업 트리)을 본다.
 *
 * @returns {{ok:boolean, 어디:string, diff:string, 통계:string, 파일들:string[], 왜?:string}}
 */
export function 볼것(session, ctx) {
  const 여기 = ctx?.scope?.root ?? session?.root ?? process.cwd();
  const 뿌리 = 저장소뿌리(여기);
  if (!뿌리) return { ok: false, 왜: '여기는 git 저장소가 아닙니다 — 무엇이 바뀌었는지 알 방법이 없습니다.' };

  // 이번 대화가 손댄 파일 (agent/commit.js 가 쓰는 것과 같은 셈법 — 살림 폴더와
  // 저장소 밖은 빠지고, 폴더째 적힌 것은 안 딸려 온다).
  const 안쪽 = [...이번에바꾼것(session, 뿌리)];

  const 인자 = 안쪽.length
    ? ['diff', 'HEAD', '--', ...안쪽]
    : ['diff', 'HEAD'];
  const 몸통 = 깃(뿌리, 인자, {});
  const 통계 = 깃(뿌리, [...인자.slice(0, 2), '--stat', ...인자.slice(2)], {});
  const 이름 = 깃(뿌리, [...인자.slice(0, 2), '--name-only', ...인자.slice(2)], {});
  const 파일들 = 이름.out.split('\n').map((x) => x.trim()).filter(Boolean);

  if (!몸통.out.trim()) {
    return {
      ok: false,
      왜: 안쪽.length
        ? '이번 대화가 바꾼 파일이 저장소 기준으로는 그대로입니다 — 볼 것이 없습니다.'
        : '바뀐 것이 없습니다.',
    };
  }
  return {
    ok: true,
    어디: 안쪽.length ? '이번 대화가 바꾼 것' : '저장소의 바뀐 것 전부',
    diff: 몸통.out,
    통계: 통계.out.trimEnd(),
    파일들,
  };
}

/** 리뷰어에게 보낼 한 덩이. 지금 대화는 한 줄도 안 들어간다. */
export function 보낼것({ diff, 통계, 파일들 }) {
  const 자른것 = diff.length > DIFF상한
    ? `${diff.slice(0, DIFF상한)}\n… (diff 가 길어 여기서 잘랐습니다 — 잘린 뒤는 못 봤습니다)`
    : diff;
  return [
    지시,
    `바뀐 파일:\n${통계 || 파일들.map((f) => `- ${f}`).join('\n')}`,
    `----- diff -----\n${자른것}`,
  ].join('\n\n');
}

/*
 * 답을 줄로 가른다.
 *
 * 모델이 형식을 안 지킬 때가 있다. 그때 통째로 버리면 사람은 아무것도 못
 * 본다 — 그래서 못 가른 줄은 **그대로 보여 준다.** 우리가 못 읽은 것이지
 * 모델이 아무 말도 안 한 것이 아니다.
 */
/*
 * 낱말 경계(`\b`)를 한글 뒤에 못 쓴다.
 *
 * 자바스크립트의 낱말 경계는 ASCII 기준이라 '심각' 뒤에는 경계가 안 생긴다.
 * `/^심각\b/` 는 "심각  a.js:1" 에 **안 걸린다.** 그래서 한글은 뒤에 올 수
 * 있는 글자로 끊고, 영어에만 `\b` 를 쓴다. 조용히 안 걸리는 규칙은 없느니만
 * 못하다 — 리뷰가 아무것도 못 찾은 것처럼 보인다.
 */
const 급표 = [
  [/^\s*심각(?=[\s:.·—-]|$)/, '심각'],
  [/^\s*(critical|high)\b/i, '심각'],
  [/^\s*보통(?=[\s:.·—-]|$)/, '보통'],
  [/^\s*(medium|moderate)\b/i, '보통'],
  [/^\s*사소(?=[\s:.·—-]|$)/, '사소'],
  [/^\s*(low|minor|nit)\b/i, '사소'],
];

export function 찾은것가르기(글) {
  const 줄들 = String(글 ?? '').split('\n');
  const 것들 = [];
  let 지금 = null;
  for (const 줄 of 줄들) {
    const 급 = 급표.find(([re]) => re.test(줄));
    if (급) {
      if (지금) 것들.push(지금);
      // 자리(파일:줄)를 같은 줄에서 찾아 둔다. 없으면 아래 줄에서 찾는다.
      지금 = { 급: 급[1], 머리: 줄.trim(), 몸: [], 자리: 자리찾기(줄) };
      continue;
    }
    if (지금) {
      지금.몸.push(줄);
      if (!지금.자리) 지금.자리 = 자리찾기(줄);
    }
  }
  if (지금) 것들.push(지금);
  return 것들;
}

/**
 * 리뷰어를 부른다.
 *
 * 지금 대화는 한 줄도 안 보낸다. 도구도 안 준다 — 새 창에서, 손 없이 본다.
 * 실패하면 **지어내지 않는다.** 못 봤으면 못 봤다고 돌려준다.
 */
export async function 리뷰받기(session, 것, { signal = null, onBackoff = null } = {}) {
  try {
    const r = await chat(session.conn, {
      messages: [{ role: 'user', content: 보낼것(것) }],
      maxTokens: 2000,
      think: session.conn.kind === 'ollama' ? false : 'low',
      signal,
      onBackoff,
      timeout: 180000,
    });
    const 글 = (r?.content ?? '').trim();
    if (!글) return { ok: false, 왜: '모델이 빈 답을 줬습니다 — 다시 시켜 보세요.' };
    return { ok: true, 글, 찾은것: 찾은것가르기(글) };
  } catch (err) {
    return { ok: false, 왜: err.message };
  }
}

/** `경로:줄` 을 찾는다. 못 찾으면 null — 지어내지 않는다. */
export function 자리찾기(줄) {
  const m = /([\w./\\가-힣-]+\.[A-Za-z0-9]{1,8}):(\d+)/.exec(String(줄 ?? ''));
  return m ? { 파일: m[1], 줄: Number(m[2]) } : null;
}
