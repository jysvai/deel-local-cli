//   한마디 할 때마다 왕복이 하나 늘고, 작은 로컬 모델은 이런 분류를 잘 못한다.
//   느려지고 틀리기까지 하면 자동으로 하는 의미가 없다.
//
//   그래서 낱말로 고른다. 대신 두 가지를 지킨다.
//     1) 애매하면 안 바꾼다. 종합 모드에 그대로 둔다.
//        잘못 바꾸는 것보다 안 바꾸는 편이 낫다 — 특히 읽기 전용 모드로
//        잘못 보내면 사용자는 "왜 파일을 안 고쳐?" 하고 막힌다.
//     2) 왜 그렇게 봤는지 남긴다. 화면에 그 이유가 같이 뜬다.
//
// 사용자가 직접 모드를 고르면 이건 아예 안 돈다. 사람이 고른 것을 뒤집지 않는다.

