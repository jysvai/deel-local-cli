// 이만큼은 되어야 바꾼다. 못 미치면 종합 모드 그대로 둔다.
//
// 읽기 전용 모드는 문턱을 높인다. 잘못 보내면 파일을 못 고쳐서 사용자가 막힌다.
// 파일을 고칠 수 있는 모드는 잘못 골라도 일이 막히지는 않으므로 낮게 둔다.
const 문턱 = {
  debug: 3,
  code: 3,
  orchestrator: 4,
  plan: 5,
  architect: 5,
  ask: 5,
};

/**
 * 이 한마디가 무슨 일인지 고른다.
 *
 * @param {string} text 사용자가 친 말
 * @returns {{ mode: string|null, score: number, why: string, 점수들: object }}
 *          mode 가 null 이면 '모르겠다' 는 뜻이다 — 종합 모드에 그대로 둔다.
 */
export function route(text) {
  const s = String(text ?? '');
  const 점수들 = {};
  const 근거 = {};

  for (const [mode, 규칙들] of Object.entries(표)) {
    let 합 = 0;
    const 걸린것 = [];
    for (const [re, 점] of 규칙들) {
      const m = s.match(re);
      if (!m) continue;
      합 += 점;
      걸린것.push(m[0].trim());
    }
    점수들[mode] = 합;
    근거[mode] = 걸린것;
  }

  const 순위 = Object.entries(점수들).sort((a, b) => b[1] - a[1]);
  const [으뜸, 점수] = 순위[0] ?? [null, 0];
  if (!으뜸 || 점수 < (문턱[으뜸] ?? 4)) {
    return { mode: null, score: 점수, why: '무슨 일인지 뚜렷하지 않음', 점수들 };
  }

  // 1·2등이 붙으면 고르지 않는다. 반반인 것을 억지로 정하면 절반은 틀린다.
  const 둘째 = 순위[1]?.[1] ?? 0;
  if (점수 - 둘째 < 2 && 둘째 >= (문턱[순위[1][0]] ?? 4)) {
    return { mode: null, score: 점수, why: `${으뜸} 과 ${순위[1][0]} 가 비슷함`, 점수들 };
  }

  return {
    mode: 으뜸,
    score: 점수,
    why: 근거[으뜸].slice(0, 2).map((x) => `'${x}'`).join(', '),
    점수들,
  };
}
