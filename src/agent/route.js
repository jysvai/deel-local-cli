/*
 * ── 겹친 요청 ───────────────────────────────────────────────────────────
 *
 * "계획해주고 만들어줘" 처럼 **계획과 실행이 한 말에 같이** 든 것.
 *
 * 이건 위의 점수표로는 못 고른다. '만들어' 가 code 3점 문턱을 그냥 넘어서
 * 곧장 코드 모드로 가 버리고, 사람이 보자고 한 계획은 안 나온다.
 * 실제로 겪었다 — "정리해서 만들어줘" 가 계획 한 줄 없이 파일부터 만들었다.
 *
 * 반대로 plan 으로 보내면 계획만 내고 멈춘다. 그것도 시킨 일의 절반이다.
 * 그래서 따로 알아본다. 계획을 내고 → 승인을 받고 → 그대로 실행까지 잇는다.
 *
 * 좁게 잡는다. 사용자는 자율 실행을 원했고, 승인 창은 그 결정을 갉아먹는
 * 쪽이다. '고쳐줘' 한마디에 창이 뜨면 그게 더 나쁘다.
 * 그래서 **계획말 + 잇는말** 이 앞에 있고 그 **뒤에** 실행말이 와야만 겹침이다.
 */
const 계획말 = '계획|플랜|설계|구상|기획|정리|검토|조사|파악|살펴|알아보|분석|로드맵|방향|순서|밑그림|초안';
// '정리하고' 처럼 잇는 꼴이어야 한다. 그냥 '정리' 하나로는 겹침이 아니다 —
// "코드 정리해줘" 는 계획이 아니라 그 자체가 할 일이다.
const 잇는말 = '해\\s*주고|해\\s*놓고|하고\\s*나서|하고서|한\\s*다음|한\\s*뒤|한\\s*후|하고|해서|잡고|짜고|세우고|낸\\s*뒤|낸\\s*다음';
const 실행말 = /만들어|만들자|만들어라|구현|작성|추가(해|하)|생성|써\s*(줘|주세요)|짜\s*(줘|주세요)|고쳐|세팅|설치|배포/;
const 계획먼저 = new RegExp(`(${계획말})\\s*(?:을|를)?\\s*(?:${잇는말})`);
/*
 * 영어도 같이 본다 — "plan and then build it" 처럼 붙여 넣는 일이 있다.
 *
 * ── 쉼표를 이음말로 세던 것 ────────────────────────────────────────────
 *
 * 이음말 목록에 `,` 가 들어 있었다. 그런데 영어에서 쉼표로 이어진 동사들은
 * **차례가 아니라 열거**다.
 *
 *   "independently design, implement, test, verify, and complete …"
 *
 * 이건 「설계하고 나서 만들어라」 가 아니라 「이것들을 다 해라」 다. 그런데
 * `design` 과 `implement` 가 예순 자 안에 있으니 겹침으로 잡혔고, 겹침이면
 * **계획 모드 + 승인 창**으로 간다 — 계획만 내고 멈춘다.
 *
 * 실제로 겪었다. 「Do not stop after producing a plan」 이라고 **명시적으로
 * 적어 둔** 지시문이 계획 모드로 갔다. 시킨 것과 정반대다.
 *
 * 그래서 쉼표를 뺀다. 차례를 뜻하는 말이 있을 때만 겹침이다. 한국어 쪽은
 * 처음부터 잇는말 목록으로 이렇게 하고 있었고, 영어 쪽만 헐거웠다.
 */
const 영어겹침 = /\b(plan|design|outline|draft)\b[\s\S]{0,60}?\b(?:and\s+then|then|and|after\s+(?:that|approval)|before\s+you)\s+(?:then\s+)?\b(build|implement|create|write|make|code)\b/i;

/*
 * ── 두 말이 **얼마나 붙어 있어야** 겹침인가 ─────────────────────────────
 *
 * 예순 자다. 영어 쪽은 처음부터 `[\s\S]{0,60}?` 로 거리를 두고 봤는데
 * 한국어 쪽만 「그 뒤 어디든」 이었다. 그 차이가 긴 글에서 그대로 터졌다.
 *
 * 실제로 겪은 것 — 1,300자짜리 지시문이었다. 「…배포 전 점검한다고 가정하고
 * 전체적으로 검토해줘 … 실제로 개선하는 것이다 … 코드 수정만 수행해라 …
 * 중간에 멈춰서 확인을 요청하지 말고 스스로 진행해라」.
 *
 * 여기서 800자 떨어진 두 조각 — 「검토해서」(9번째 문단)와 「추가하」(보고
 * 항목 이름) — 이 짝지어져 겹침으로 잡혔다. 그래서 **계획 모드**로 갔다.
 * 계획은 파일을 바꾸는 도구가 없는 모드이고, 그 지시문은 「고쳐라 · 테스트를
 * 만들어라 · 멈추지 마라」 였다. 사람은 고쳐 달라고 했는데 계획서 한 장을
 * 받고, 마지막에 「이대로 진행할까요?」 를 봤다 — 묻지 말라고 적어 둔 바로
 * 그 자리에서.
 *
 * 이 규칙이 잡으려던 것은 「정리해서 만들어줘」 같은 **한 문장**이다. 한 문장
 * 안에서 두 말은 예순 자를 안 넘는다. 그러니 거리를 재는 것이 규칙을 좁히는
 * 것이 아니라 **원래 뜻대로 되돌리는 것**이다.
 */
const 겹침거리 = 60;

/*
 * ── 「묻지 말고 끝까지」 라고 이미 적어 둔 사람 ─────────────────────────
 *
 * 겹침의 값은 「계획을 보여 주고 승인을 받는다」 다. 그런데 승인을 받지
 * 말라고 **글로 적어 둔** 사람에게 그 값은 손해뿐이다. 계획 모드는 계획을
 * 내고 멈추므로, 그 사람은 시킨 일의 절반도 못 받는다.
 *
 * 이건 짐작이 아니라 사람이 직접 쓴 말이다. 쓴 말이 규칙을 이긴다.
 */
const 멈추지마 = /(?:중간에\s*)?(?:멈추지|묻지|물어보지|확인\s*요청하지|되묻지)\s*(?:는)?\s*(?:말|마)|끝까지\s*(?:수행|진행|해)|스스로\s*진행|알아서\s*(?:진행|해)|승인\s*없이|\bwithout\s+(?:asking|stopping|confirmation)\b|\bdo\s*n[o']?t\s+(?:stop|ask|pause|halt)\b|\bcontinue\s+autonomously\b|\bproceed\s+autonomously\b|\bwithout\s+(?:pausing|waiting|approval)\b/i;

/** 사람이 「묻지 말고 끝까지 하라」 고 적어 뒀나. */
export function 묻지말라했나(text) {
  return 멈추지마.test(String(text ?? ''));
}

/**
 * 계획과 실행이 한 말에 같이 들었나.
 *
 * @returns {{겹침: boolean, why: string}} 겹침이 아니면 why 는 빈 글.
 */
export function 겹친요청(text) {
  const s = String(text ?? '');
  // 묻지 말라고 적어 둔 사람에게 승인 창을 띄우지 않는다. 위 머리말 참고.
  if (묻지말라했나(s)) return { 겹침: false, why: '' };

  const 영어 = s.match(영어겹침);
  if (영어) return { 겹침: true, why: `'${영어[1]}' 과 '${영어[2]}'` };

  const 앞 = s.match(계획먼저);
  if (!앞) return { 겹침: false, why: '' };
  /*
   * 실행말이 계획말 **바로 뒤에** 와야 한다.
   *
   * 「뒤에」 였지 「글 어디든」 이 아니었다 — 거리를 안 재면 긴 지시문에서는
   * 언제나 짝이 하나쯤 걸린다(위 겹침거리 머리말). "만들고 나서 정리해줘" 가
   * 안 걸리는 것도 그대로다. 그건 만드는 일이 먼저고, 미리 볼 계획이 없다.
   */
  const 남은것 = s.slice(앞.index + 앞[0].length, 앞.index + 앞[0].length + 겹침거리);
  const 뒤 = 남은것.match(실행말);
  if (!뒤) return { 겹침: false, why: '' };
  return { 겹침: true, why: `'${앞[0].trim()}' 뒤에 '${뒤[0].trim()}'` };
}

/*
 * ── 손대라는 말 ─────────────────────────────────────────────────────────
 *
 * "폴더 구조 개선해줘" 가 설계 모드로 갔다. 설계는 **읽기만 하는 모드**라,
 * 사람은 고쳐 달라고 했는데 설계안 한 장을 받고 끝났다. 이 파일 맨 위에
 * 적어 둔 것이 정확히 그 경우다 — "읽기 전용 모드로 잘못 보내면 사용자는
 * '왜 파일을 안 고쳐?' 하고 막힌다."
 *
 * 낱말 점수로는 못 막는다. '구조' 와 '개선' 이 둘 다 설계의 강한 신호라서,
 * 뒤에 붙은 '해줘' 를 아무리 봐도 점수로는 안 뒤집힌다.
 *
 * 그래서 **동사를 따로 본다.** 손대라는 말이 있으면 읽기만 하는 모드
 * (설계·계획·묻기)는 후보에서 뺀다. 남은 것 중에 고르고, 없으면 종합에
 * 그대로 둔다 — 종합은 파일을 고칠 수 있다.
 *
 * 가르는 자리가 미묘하다. '설명해줘' 와 '개선해줘' 는 둘 다 '…해줘' 지만
 * 하나는 읽고 말하라는 말이고 하나는 고치라는 말이다. 그래서 어미가 아니라
 * **동사 목록**으로 본다. 목록에 없으면 손대라는 말이 아니다.
 */
export const 손대는동사 = '만들|고쳐|고치|바꿔|바꾸|추가|넣어|지워|삭제|옮겨|나눠|나누|합쳐|정리|개선|구현|작성|적용|설치|배포|리팩터링|리팩터|분리|통일|세팅|갈아|손봐|손보|수정';
/*
 * 동사 바로 뒤에 시킴꼴이 붙어야 한다. 빈칸을 안 넘으므로 "나누는 설계만 봐줘"
 * 는 안 걸린다 — 그건 나누라는 말이 아니라 나누는 안을 보자는 말이다.
 *
 * ── 해라체가 통째로 빠져 있었다 ─────────────────────────────────────────
 *
 * 끝맺음 목록이 전부 **부탁하는 말**이었다(줘 · 주세요 · 해라 · 할래). 그래서
 * 시키는 말투로 쓴 사람은 이 검사에 한 번도 안 걸렸다 —
 *
 *   「재현 검사를 먼저 만들어라 … 최소 범위의 코드 수정만 수행해라
 *     … 중간에 멈추지 말고 스스로 진행해라」
 *
 * 이 지시문이 「고치라는 말이 아니다」 로 읽혀서 읽기 전용 모드로 갔다.
 * 사람은 고쳐 달라고 세 번 적었는데 아무것도 안 바뀐 화면을 받는다.
 *
 * 「어라 · 아라」 와 맨 「라」 가 그 문을 연다. 맨 라 는 낱말 끝일 때만 본다 —
 * 「지워라」 는 지우라는 말이지만 「바꾸라는 말」 은 아니다. 뒤에 무엇이
 * 붙어 있나로 그 둘이 갈린다.
 * 「만들어라」 는 언제나 만들라는 말이다.
 */
/*
 * ── 여기 백슬래시 하나가 빠져 있었다 ────────────────────────────────────
 *
 * 이 무늬는 **템플릿 글**로 짓는다(동사 목록을 끼워 넣어야 해서). 그런데
 * 템플릿 글 안에서 `\s` 는 정규식에 닿기 전에 자바스크립트가 먼저 먹는다 —
 * 모르는 이스케이프라 백슬래시를 떼고 **글자 `s`** 만 남긴다.
 *
 *     적은 것   ...|라(?=[\s.!?~,]|$))
 *     닿은 것   ...|라(?=[s.!?~,]|$))     ← 빈칸이 아니라 알파벳 s
 *
 * 그래서 맨 「라」 뒤에 **빈칸이나 줄바꿈이 오면 안 걸렸다.** 걸리는 것은
 * 「라」 가 글 맨 끝이거나 바로 뒤에 . ! ? ~ , 가 붙을 때뿐이었다.
 *
 *     "그것 좀 바꿔라"        걸림   (글 끝)
 *     "바꿔라 지금 해줘"      안 걸림 ← 여러 마디로 시키면 거의 다 이쪽이다
 *     "지워라 그리고 저장해"  안 걸림
 *
 * 위 주석이 「사람은 고쳐 달라고 세 번 적었는데 아무것도 안 바뀐 화면을
 * 받는다」 고 적어 둔 바로 그 고장이, 고쳐 놓고도 백슬래시 하나 때문에
 * 그대로 남아 있었다. `\\s` 로 적어야 정규식이 `\s` 를 받는다.
 *
 * (`\\S{0,3}` 는 처음부터 두 개라 멀쩡했다. 한 무늬 안에서 한쪽만 틀렸으니
 *  눈으로는 더 안 보인다.)
 */
const 손대라는말 = new RegExp(`(${손대는동사})\\S{0,3}(줘|주세요|주라|해라|하라|하자|해다오|해줄래|할래|어라|아라|여라|라(?=[\\s.!?~,]|$))`);

// 파일을 못 고치는 모드. modes.js 에서 쓰기 도구를 안 주는 것들과 같아야 한다.
export const 읽기만하는모드 = new Set(['architect', 'plan', 'ask', 'inspect']);

/*
 * ── 영어로 시킨 말은 하나도 못 보고 있었다 ──────────────────────────────
 *
 * 위 규칙은 어미(`줘` · `해라` …)로 시킴꼴을 가린다. 영어에는 그 어미가 없다.
 * 그래서 "Build a complete web application." 이 **손대라는 말이 아닌 것**으로
 * 읽혔고, 읽기 전용 모드(설계·계획·점검·묻기)가 후보에서 안 빠졌다.
 *
 * 영어는 **문장 첫머리의 명령형**으로 가린다. 그래야 시키는 말과 설명하는
 * 말이 갈린다 —
 *
 *   "Build a work request app."          → 손대라는 말이다
 *   "Explain how the build works."       → 아니다 (build 가 첫머리가 아니다)
 *   "The build system is broken."        → 아니다
 *
 * 목록에 없는 동사는 손대라는 말이 아니다. 한국어 쪽과 같은 규칙이다 —
 * 넓히면 「설명해 줘」 가 고치라는 말이 되고, 그러면 읽기 전용 모드가 영영
 * 안 골라진다.
 */
/*
 * 정규식 리터럴로 적는다. 글자열을 이어 붙여 new RegExp 에 넣으면 홑따옴표
 * 안에서 `\s` 의 역슬래시가 사라지고 `\b` 는 백스페이스 글자가 된다 —
 * 검사에서 잡히기 전까지 조용히 아무것도 안 맞는다. 실제로 그렇게 났다.
 */
// 위에서 세운 공용 무늘 그대로다. 두 벌로 두면 한쪽만 늘어난다.
const 영어손대라 = 영어시킴말;

/** 파일을 손대라는 말이 들었나. */
export function 손대라했나(text) {
  const s = String(text ?? '');
  return 손대라는말.test(s) || 영어손대라.test(s);
}

/**
 * 이 한마디가 무슨 일인지 고른다.
 *
 * @param {string} text 사용자가 친 말
 * @returns {{ mode: string|null, score: number, why: string, 겹침: boolean, 점수들: object }}
 *          mode 가 null 이면 '모르겠다' 는 뜻이다 — 종합 모드에 그대로 둔다.
 *          겹침이 true 면 계획을 내고 승인을 받아 실행까지 이어야 한다는 뜻이다.
 */
export function route(text) {
  const s = String(text ?? '');

  // 겹친 요청은 점수표보다 먼저 본다. 점수표에 맡기면 '만들어' 가 이겨서
  // 계획을 건너뛴다 — 그게 바로 이 길을 만든 이유다.
  const 겹 = 겹친요청(s);
  if (겹.겹침) return { mode: 'plan', score: 0, why: 겹.why, 겹침: true, 점수들: {} };

  const 점수들 = {};
  const 근거 = {};

  for (const [mode, 규칙들] of Object.entries(표)) {
    let 합 = 0;
    const 걸린것 = [];
    for (const [re, 점] of 규칙들) {
      const m = s.match(re);
      if (!m) continue;
      합 += 점;
      걸린것.push(m[0].trim());
    }
    점수들[mode] = 합;
    근거[mode] = 걸린것;
  }

  /*
   * 손대라는 말이 있으면 읽기만 하는 모드는 후보에서 뺀다.
   *
   * 점수를 깎지 않고 **줄에서 뺀다.** 깎으면 얼마나 깎을지가 또 하나의 눈금이
   * 되고, 그 눈금은 아무도 못 지킨다. 여기서 가르는 것은 정도의 문제가 아니라
   * 종류의 문제다 — 고칠 수 있는 자리인가 아닌가.
   */
  const 손대라 = 손대라했나(s);
  const 뺀것 = [];
  let 순위 = Object.entries(점수들).sort((a, b) => b[1] - a[1]);
  if (손대라) {
    for (const [m, n] of 순위) if (읽기만하는모드.has(m) && n > 0) 뺀것.push(m);
    순위 = 순위.filter(([m]) => !읽기만하는모드.has(m));
  }
  /*
   * ── 긴 명세에서는 한 번 걸린 낱말이 결정하면 안 된다 ──────────────────
   *
   * 점수표는 **한마디**를 보라고 만든 것이다. 「이거 왜 안 되지」 처럼 짧은
   * 말에서는 낱말 하나가 곧 뜻이다.
   *
   * 그런데 5,000자짜리 명세를 붙여 넣으면 이야기가 달라진다. 그런 글에는
   * 모든 모드의 낱말이 한 번씩은 나온다 — 설계도 나오고, 검사도 나오고,
   * 보안도 나온다. 거기서 한 번 걸린 것은 **뜻이 아니라 소음**이다.
   *
   * 실제로 겪었다. 「빈 폴더에서 웹 앱을 처음부터 만들어라」 는 5,254자
   * 지시문이 `fails` 한 낱말 때문에 디버그로 갔다. 그 글에 그 낱말은
   * 「검사가 실패하면 원인을 조사하라」 는 조건절에 딱 한 번 있었다.
   *
   * 그래서 글이 길면 **더 뚜렷할 때만** 고른다. 못 고르면 종합에 그대로
   * 두는데, 긴 명세에는 그게 오히려 맞는 답이다 — 종합은 걸음마다 단계를
   * 따라가므로(agent/단계.js) 계획에서 시작해 만들기로 알아서 넘어간다.
   */
  const 긴글 = s.length >= 1500;
  const 더줘야 = 긴글 ? 2 : 0;

  const [으뜸, 점수] = 순위[0] ?? [null, 0];

  /*
   * ── 눈금을 올리는 것으로는 두 번째 낱말을 못 막는다 ────────────────────
   *
   * 위의 +2 는 **낱말 하나**를 막는다. 실제 벤치마크 지시문을 그대로 넣어
   * 보니 두 개가 걸렸다 — 둘 다 증상이 아니라 요구사항 조건절이었다.
   *
   *   "… handle duplicate requests, stale requests, unexpected server errors."  +3
   *   "… A failed operation must not leave state silently inconsistent."        +3
   *
   * 합이 6이라 3+2 를 넘어 디버그가 됐다. 고장 난 것이 하나도 없는 **빈
   * 폴더**에서 시작하라는 글인데, 디버그 모드는 「증상을 한 문장으로 다시
   * 적어라 · 재현 방법부터 확보해라」 를 시킨다. 없는 증상을 찾게 된다.
   *
   * 눈금을 또 올려도 세 낱말이면 그대로 뚫린다. 눈금은 글 길이만 보고
   * 정하는데, 지나가는 낱말은 길이가 아니라 **글의 종류**를 따라 늘기
   * 때문이다. 그래서 눈금이 아니라 견줌으로 본다.
   *
   * 같은 글에서 설계가 8점, 디버그가 6점이었다. 「고치라는 말이라 설계로는
   * 안 보낸다」 는 그대로 맞다 — 그런데 그것은 **설계로 보내지 말라**는 말
   * 이지, 그 글이 디버그라는 말이 아니다. 뺀 것이 남은 으뜸보다 세다면 이
   * 글이 무엇인지는 아직 안 정해진 것이다. 종합에 둔다 — 종합은 걸음마다
   * 단계를 따라가므로(agent/단계.js) 계획에서 시작해 만들기로 넘어간다.
   *
   * 짧은 말에는 안 건다. 짧은 말에서는 낱말 하나가 곧 뜻이다.
   */
  const 뺀최고 = Math.max(0, ...뺀것.map((m) => 점수들[m] ?? 0));
  const 지나가는말 = 긴글 && Boolean(으뜸) && 점수 < 뺀최고;

  // 골랐어야 할 만한 신호가 있었는데 일부러 안 보낸 자리인가.
  const 일부러 = Boolean(지나가는말 || 뺀것.length
    || (긴글 && 으뜸 && 점수 >= (문턱[으뜸] ?? 4)));

  if (!으뜸 || 지나가는말 || 점수 < (문턱[으뜸] ?? 4) + 더줘야) {
    // 왜 안 바꿨는지는 화면에 그대로 뜬다. "설계로 갈 뻔했는데 고치라는 말이라
    // 안 보냈다" 와 "그냥 모르겠다" 는 사람에게 아주 다른 말이다.
    const 왜 = 지나가는말
      ? `글이 길고 ${뺀것.join('·')}(${뺀최고}점) 가 ${으뜸}(${점수}점) 보다 세서 `
        + `${으뜸} 로 안 봄 — 종합에서 단계를 따라갑니다`
      : 긴글 && 으뜸 && 점수 >= (문턱[으뜸] ?? 4)
        ? `글이 길어 ${으뜸} 신호 하나로는 안 정함 — 종합에서 단계를 따라갑니다`
        : 뺀것.length
          ? `${뺀것.join('·')} 신호가 있었지만 고치라는 말이라 읽기 전용 모드로 안 보냄`
          : '무슨 일인지 뚜렷하지 않음';
    /*
     * ── 「일부러 안 골랐다」 와 「그냥 모르겠다」 는 다른 말이다 ─────────
     *
     * 바로 위 주석이 그 구분을 적어 뒀는데, 정작 화면에는 **둘 다 아무것도
     * 안 떴다.** 부르는 쪽(repl.js · oneshot.js)이 `if (골라진.mode)` 안에서만
     * 찍었기 때문이다. 여기서 지은 세 갈래 까닭은 한 번도 사람에게 안 갔다.
     *
     * 그렇다고 전부 찍으면 안 된다. 보통 한마디는 거의 다 여기로 오고 까닭은
     * 「무슨 일인지 뚜렷하지 않음」 이다 — 그건 소음이다.
     *
     * 그래서 **가르는 일을 여기서 한다.** 부르는 쪽이 `뺀것.length` 니
     * `글이 길` 이니를 다시 헤아리게 두면 두 자리에서 따로 어긋난다.
     */
    return { mode: null, score: 점수, why: 왜, 겹침: false, 점수들, 뺀것, 일부러 };
  }

  // 1·2등이 붙으면 고르지 않는다. 반반인 것을 억지로 정하면 절반은 틀린다.
  const 둘째 = 순위[1]?.[1] ?? 0;
  if (점수 - 둘째 < 2 && 둘째 >= (문턱[순위[1][0]] ?? 4)) {
    return {
      mode: null, score: 점수, why: `${으뜸} 과 ${순위[1][0]} 가 비슷함`,
      겹침: false, 점수들, 뺀것, 일부러: true,
    };
  }

  return {
    mode: 으뜸,
    score: 점수,
    why: [근거[으뜸].slice(0, 2).map((x) => `'${x}'`).join(', '),
      뺀것.length ? `(${뺀것.join('·')} 는 고치라는 말이라 뺐습니다)` : ''].filter(Boolean).join(' '),
    겹침: false,
    점수들,
  };
}
