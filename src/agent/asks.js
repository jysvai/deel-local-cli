// 시킨 것을 세고, 턴이 끝날 때 대조한다.
//
// ── 무엇을 막나 ────────────────────────────────────────────────────────
//
// 「요청사항이 다량의 요청사항일 경우 몇 번 까먹거나, 요청사항이 누락되거나
//   그런 이슈들이 생겨」
//
// 네 가지를 시키면 셋을 하고 끝낸다. 그것도 조용히 — 안 한 것을 안 했다고
// 말하지 않으니, 사람은 다 된 줄 알고 넘어갔다가 나중에 발견한다. 그때는
// 이미 그 위에 다른 것을 쌓아 둔 뒤다.
//
// 도구 호출을 열댓 번 하는 사이 앞의 것이 밀려나기 때문이다. 컨텍스트가
// 접히면 더 심해진다 — 요약은 「네 가지를 고쳐 달라고 했다」 로 뭉개지고,
// 그 네 가지가 무엇이었는지는 사라진다.
//
// ── 어떻게 막나 ────────────────────────────────────────────────────────
//
// 프롬프트로 "빠뜨리지 마라" 고 적는 것으로는 안 된다. 이미 적혀 있다.
// 그래서 **턴이 끝날 때 기계가 대조한다.** 시킨 것을 항목으로 쪼개 두고,
// 끝날 때 그 항목 하나하나가 어디엔가 닿았는지 본다 — 할 일 목록에 있나,
// 손댄 파일 이름에 있나, 마지막 보고에 있나.
//
// 닿은 자국이 없으면 그 항목은 **안 한 것**으로 본다. 그러면 한 번 되민다.
// 그래도 없으면 사람에게 그대로 말한다. 조용히 넘어가는 것보다 낫다.
//
// ── 무엇을 못 하나 ──────────────────────────────────────────────────────
//
// 글자만 본다. "정말 제대로 했나" 는 모른다 — 항목 이름이 보고에 적혀 있으면
// 닿은 것으로 친다. 그러니 이건 **품질 검사가 아니라 누락 검사**다.
// 애매하면 안 걸고 넘어간다. 다 했는데 안 했다고 하는 것이 더 나쁘다.
/*
 * 뜻이 없는 말.
 *
 * 이 낱말들이 자국에 보였다고 그 항목을 다룬 것은 아니다. '다른' 은 거의 모든
 * 글에 있고, '문제' 와 '이슈' 는 어떤 보고에도 나온다. 걸러 두지 않으면
 * "안 한 것" 이 하나도 안 잡힌다 — 있으나 마나 한 검사가 된다.
 */
const 뜻없는말 = new Set([
  '그리고', '그래서', '하지만', '그런데', '그러면', '그냥', '조금', '많이', '자꾸', '아직',
  '이런', '그런', '저런', '이거', '그거', '저거', '여기', '거기', '이게', '그게',
  '해줘', '주세요', '좀더', '같은', '같이', '때문', '경우', '정도', '부분', '다른',
  '문제', '이슈', '생겨', '있어', '없어', '되는', '하는', '해서', '해도', '으로',
  'the', 'and', 'for', 'with', 'that', 'this', 'issue', 'problem',
]);

/**
 * 항목에서 알맹이가 되는 낱말만 뽑는다.
 *
 * 두 글자 미만은 버린다 — 한 글자짜리는 어디에나 있다.
 */
export function 알맹이낱말(글) {
  const 것 = String(글 ?? '').toLowerCase().split(/[^0-9a-z가-힣]+/);
  return [...new Set(것.filter((w) => w.length >= 2 && !뜻없는말.has(w)))];
}

/*
 * 이 낱말이 자국에 보이나.
 *
 * 한국어는 말끝이 붙는다 — '누락되는' 과 '누락된' 과 '누락' 은 같은 말이다.
 * 그래서 뒤에서 한두 글자를 떼고도 본다. 앞에서 떼지는 않는다 — 한국어는
 * 앞이 뿌리다.
 */
function 낱말이닿았나(낱말, 덩어리) {
  if (덩어리.includes(낱말)) return true;
  /*
   * 한글은 앞에서부터 줄여 가며 본다. 두 글자까지 내려간다.
   *
   * '요청사항이' 와 '요청', '누락되는' 과 '누락' 은 같은 말인데 뒤가 다 다르다.
   * 한 글자만 떼서는 못 만난다 — 실제로 "요청 누락 대조" 라고 적어 둔 일을
   * 안 했다고 말한 적이 있다.
   *
   * 두 글자까지 내려가는 것이 헐거운 줄 안다. 그래서 이쪽으로 틀린다 —
   * 다룬 것으로 잘못 보는 쪽. 안 한 것을 놓치면 예전과 같아질 뿐이지만,
   * 다 한 일을 안 했다고 말하면 사람이 이 말을 안 믿게 된다.
   *
   * 영문은 안 줄인다. cli·deel·npm 처럼 원래 짧아서, 줄이면 아무 데나 걸린다.
   */
  if (!/^[가-힣]/.test(낱말)) return false;
  for (let n = 낱말.length - 1; n >= 2; n--) {
    if (덩어리.includes(낱말.slice(0, n))) return true;
  }
  return false;
}

/*
 * 시킴꼴 끝맺음.
 *
 * 줄마다 시킨 것을 적는 사람이 많다. 번호를 안 붙여도 "…해줘" 로 끝나는 줄이
 * 여럿이면 그건 목록이다.
 */
const 시킴꼴 = /(줘|주세요|주라|해라|하라|하자|해다오|할래|해야\s*(해|돼|한다)|바랍니다|부탁(해|합니다|드립니다))[\s.!~]*$/;

// 줄머리 표. 번호(1. 2))·글머리(- * ·)·동그라미 숫자.
const 줄머리 = /^\s*(?:(\d{1,2})\s*[.)]|[-*·▪️•]|[①-⑮])\s+/;

/**
 * 시킨 것을 항목으로 쪼갠다.
 *
 * 두 가지만 본다 — 번호·글머리를 붙인 줄, 그리고 시킴꼴로 끝나는 줄.
 * 문장 하나를 쉼표로 더 쪼개지는 않는다. 쪼갤수록 없는 항목이 생기고,
 * 없는 항목을 "안 했다" 고 말하는 것이 제일 나쁘다.
 *
 * @returns {Array<{번호:number, 글:string}>}
 */
export function 요청항목들(요청) {
  const 줄들 = String(요청 ?? '').split('\n').map((l) => l.trimEnd());

  // 1) 번호·글머리를 붙인 줄
  const 표붙은것 = [];
  for (const 줄 of 줄들) {
    const m = 줄머리.exec(줄);
    if (!m) continue;
    const 글 = 줄.slice(m[0].length).trim();
    if (글) 표붙은것.push(글);
  }
  if (표붙은것.length >= 2) return 표붙은것.map((글, i) => ({ 번호: i + 1, 글 }));

  // 2) 표는 없지만 줄마다 시키는 꼴
  const 시킨줄 = 줄들.map((l) => l.trim()).filter((l) => l && 시킴꼴.test(l));
  if (시킨줄.length >= 2) return 시킨줄.map((글, i) => ({ 번호: i + 1, 글 }));

  return [];
}

/*
 * ── 언제 "안 했다" 고 하나 ──────────────────────────────────────────────
 *
 * 처음에는 항목 글 전체가 자국에 얼마나 겹치는지로 쟀다. 안 됐다. 시킨 말은
 * "붙여넣기 해도 창에 붙여넣기된 내용이 다 뜨는 게 아니야" 인데 한 일은
 * "붙여넣기된 내용 표시 고침" 이라, 사이의 이음말이 다 달라서 0.32 밖에
 * 안 나왔다. 문턱을 그 밑으로 내리면 이번에는 아무것도 안 잡힌다.
 *
 * 그래서 **알맹이 낱말이 하나라도 닿았나** 로 바꿨다. 하나도 안 닿았다는 것은
 * 할 일 목록에도, 손댄 파일 이름에도, 마지막 보고에도 그 말이 한 번도 안
 * 나왔다는 뜻이다. 그건 잊은 것이 거의 확실하다.
 *
 * 느슨한 잣대인 것을 알고 고른 것이다. 틀리는 방향이 한쪽으로 심하게 기울기
 * 때문이다 — 안 한 것을 놓치면 예전과 같아질 뿐이지만, **다 한 일을 안 했다고
 * 말하면** 사람은 이 말을 믿지 않게 되고, 그때부터 이 검사는 없느니만 못하다.
 */

/**
 * 시킨 것 중 자국이 하나도 없는 항목.
 *
 * @param {object} 것
 * @param {string} 것.요청     사용자가 친 말
 * @param {string[]} [것.자국]  한 일의 자국 — 할 일 목록·손댄 파일·마지막 보고
 * @returns {Array<{번호:number, 글:string, 닿은낱말:number, 낱말수:number}>}
 */
export function 빠진것({ 요청 = '', 자국 = [] } = {}) {
  const 항목 = 요청항목들(요청);
  // 하나짜리 요청은 대조하지 않는다. 한 가지를 시켰는데 안 했으면 그건
  // 누락이 아니라 그냥 안 한 것이고, 그건 다른 자리(되밀기)가 본다.
  if (항목.length < 2) return [];

  const 덩어리 = (Array.isArray(자국) ? 자국 : [자국])
    .filter(Boolean).join('\n').toLowerCase();

  const 빠진 = [];
  for (const x of 항목) {
    const 낱말 = 알맹이낱말(x.글);
    // 알맹이가 하나도 없는 항목("그리고 그것도")은 잴 수가 없다. 안 건다.
    if (!낱말.length) continue;
    const 닿은낱말 = 낱말.filter((w) => 낱말이닿았나(w, 덩어리)).length;
    if (닿은낱말 === 0) 빠진.push({ ...x, 닿은낱말, 낱말수: 낱말.length });
  }
  return 빠진;
}

/**
 * 모델에게 되밀 때 하는 말.
 *
 * 무엇이 빠졌는지 **그대로 다시 적어 준다.** "빠뜨린 것이 있습니다" 만으로는
 * 모델이 무엇을 빠뜨렸는지 스스로 못 찾는다 — 못 찾으니까 빠뜨린 것이다.
 */
export function 빠졌다는말(빠진, { 영어 = false } = {}) {
  const 목록 = 빠진.map((x) => `  ${x.번호}. ${x.글}`).join('\n');
  if (영어) {
    return `You have not addressed ${빠진.length} of the things that were asked:\n${목록}\n`
      + 'Do them now. If one of them genuinely cannot be done, say in one line why —'
      + ' do not finish while leaving it unmentioned.';
  }
  return `시킨 것 중 ${빠진.length}가지에 아직 손을 안 댔습니다:\n${목록}\n`
    + '지금 하세요. 정말 못 하는 것이면 왜 못 하는지 한 줄로 밝히세요 —'
    + ' 말없이 빼놓고 끝내지 마세요.';
}
