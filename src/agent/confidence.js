/**
 * 겪은 것을 **얼마나 믿을까.**
 *
 * evolve.js 는 「무엇을 겪었나」 를 센다. 이 파일은 그 셈을 보고 「그것을 사실로 말해도
 * 되나」 를 정한다. 섞어 두면 셈을 고칠 때마다 믿음의 문턱이 같이 흔들리고, 그것은
 * **화면에 안 나타난다.**
 *
 * ── 막으려는 것 ─────────────────────────────────────────────────────────
 *
 * 자기가 쓴 기록을 자기가 다시 읽는 프로그램은 두 가지로 썩는다.
 *
 *   1. **작은 표본을 확신으로 읽는다.** 두 번 실패한 것은 우연일 수 있다.
 *
 *   2. **틀린 부정이 스스로를 봉인한다.** 「다시 부르지 마라」 가 프롬프트에 들어가면
 *      모델이 안 부르고, 안 부르니 성공 셈이 영영 안 늘고, 그 줄이 영영 안 사라진다.
 *      지난달에 없던 프로그램을 오늘 깔아도 없다고 우긴다. 고쳐질 길이 **구조적으로** 막힌다.
 *
 * ── 빌려 온 방식 ────────────────────────────────────────────────────────
 *
 *   **윌슨 점수 아래끝 (Wilson score lower bound)**
 *   비율을 그대로 믿지 않고 표본이 적으면 그만큼 **깎아서** 본다. 두 번 성공은 두 번어치만
 *   믿는다. 근거: Evan Miller, "How Not To Sort By Average Rating" (evanmiller.org).
 *
 *   **시간 할인 (discounted counts · Discounted-UCB)**
 *   관측마다 `γ^(지난 날수)` 를 곱해 두면 다시 안 겪은 사실은 저절로 힘이 빠진다.
 *   근거: Garivier & Moulines, "On Upper-Confidence Bound Policies for Switching Bandit
 *   Problems" (Discounted-UCB · Sliding-Window UCB).
 *
 * **이 둘을 겹치면 2번이 저절로 풀린다.** 「안 된다」 는 다시 안 겪으면 힘이 빠지고, 말하기를
 * 멈추면 모델이 다시 해 보고, 그 결과가 새 관측이 된다. 잊는 것이 곧 다시 해 보는 것이다.
 *
 * ── 범위 ────────────────────────────────────────────────────────────────
 *
 * 파일에서 읽은 것이 애초에 우리가 적은 모양이 맞나는 여기서 안 본다(agent/recordshape.js).
 * **지우지 않는다** — 못 믿겠다는 것과 없던 일이라는 것은 다르다. 지우면 다시 겪을 때 두
 * 번을 처음부터 채워야 한다. 여기가 정하는 것은 「말할까」 하나이고 셈은 evolve.js 가 든다.
 */

/*
 * 믿음의 폭. z=1 은 약 68% 구간이다.
 *
 * 95%(z≈1.96)로 조이면 열 번을 겪어야 말할 수 있는데, 같은 폴더에서 같은 명령을 열 번
 * 돌리기 전에 대화가 끝난다 — 기능이 켜져 있으나 마나다. z=1 은 「두 번 겪으면 말하고,
 * 한 번은 말하지 않는다」 에 맞는다.
 */
export const z = 1;

/** 이 위로 올라가야 「된다」 고 말한다 (성공률 아래끝). */
export const 좋음문턱 = 0.6;
/** 이 아래로 내려가야 「안 된다」 고 말한다 (성공률 위끝). */
export const 나쁨문턱 = 0.4;

/*
 * ── 반감기가 둘인 까닭 ──────────────────────────────────────────────────
 *
 * 다시 안 겪은 관측이 절반으로 줄기까지의 날수. **「된다」 와 「안 된다」 에 다른 값을 준다.**
 *
 * 틀린 긍정("이 명령이 된다")은 한 번 해 보면 들통나고, 그 실패가 새 관측이 되어 스스로를
 * 고친다. 틀린 부정("안 된다")은 **해 보는 일 자체를 막는다** — 들통날 기회를 자기가 없앤다.
 *
 * 그래서 부정은 더 빨리 잊는다. 반감기 사흘이면 두 번 겪은 「안 된다」 는 하루쯤 뒤에 입을
 * 다물고, 모델이 다시 해 보고, 정말 안 되면 그날 다시 쌓인다(다섯 번 겪은 것은 닷새쯤).
 * 하루 한 번의 헛부름은 한 달 내내 틀린 말을 프롬프트에 싣는 것보다 싸다.
 *
 * 긍정은 세 주다. 이레면 금요일에 확인한 명령이 월요일 아침에 백지가 된다 — 잊는 것이 아니라
 * 안 배우는 것이다. 세 주면 두 번 겪은 사실은 아흐레쯤, 다섯 번 겪은 사실은 한 달을 넘긴다.
 */
export const 반감기된다 = 21;
export const 반감기안된다 = 3;

/** 하루에 곱해지는 값. 반감기에서 나온다 — 두 곳에 따로 적으면 언젠가 갈린다. */
export const 하루할인된다 = Math.pow(0.5, 1 / 반감기된다);
export const 하루할인안된다 = Math.pow(0.5, 1 / 반감기안된다);

/**
 * 며칠 지났나. 못 재면 무한대다.
 *
 * **모르는 것을 「오늘」 로 치지 않는다.** 옛 판에서 넘어왔거나 손으로 고쳐진
 * 기록에는 날짜가 없을 수 있는데, 그것을 오늘 겪은 것으로 치면 나이를 알 수
 * 없는 주장이 통째로 되살아난다 — 이 파일이 막으려는 바로 그 오염이다.
 *
 * 미래에 적힌 것은 0일로 친다. 시계가 틀어진 PC 에서 음수 날수가 나오면
 * 할인이 1보다 커져서 **겪지도 않은 것이 더 세진다.**
 */
export function 며칠됐나(지금, 그때) {
  const a = Date.parse(String(지금 ?? ''));
  const b = Date.parse(String(그때 ?? ''));
  if (!Number.isFinite(a) || !Number.isFinite(b)) return Infinity;
  return Math.max(0, (a - b) / 86400000);
}

/**
 * 지난 셈을 오늘 기준으로 삭힌다 (Discounted-UCB 의 할인).
 *
 * 관측 하나하나에 날짜를 달아 두지 않아도 된다. 마지막으로 손댄 날부터
 * 오늘까지의 할인을 통째로 한 번 곱하면 같은 값이 된다 — 그래서 기록은
 * `{ok, no, at}` 세 칸 그대로다.
 *
 * 아주 작아진 값은 0 으로 떨군다. 안 그러면 10^-9 짜리 부스러기가 표에 남아
 * 자리만 차지하고, 그 부스러기가 `줄이기` 에서 진짜 기록을 밀어낸다.
 */
export const 부스러기 = 0.01;

export function 삭힘({ ok = 0, no = 0 } = {}, 날수 = 0) {
  if (!Number.isFinite(날수)) return { ok: 0, no: 0 };
  const a = (Number(ok) || 0) * Math.pow(하루할인된다, 날수);
  const b = (Number(no) || 0) * Math.pow(하루할인안된다, 날수);
  return { ok: a < 부스러기 ? 0 : a, no: b < 부스러기 ? 0 : b };
}

/*
 * ── 윌슨 점수 구간 ──────────────────────────────────────────────────────
 *
 * 성공 s 번, 전체 n 번일 때 진짜 성공률이 어느 사이에 있는가. n 이 작을 때 평균은
 * 거짓말을 한다 — 1승 0패의 100% 는 아무것도 안 말해 준다.
 *
 * 알고 넘어가는 어긋남: 윌슨 점수는 **정수 시행**을 전제로 하는데 여기 넣는 n 은 삭힌
 * 소수다. 가중 관측의 유효 표본 수 `(Σw)² / Σw²` 는 언제나 `Σw` 보다 작아서 `Σw` 를 쓰면
 * **분산을 덜 잡는다** — 실제보다 조금 더 확신하는 쪽으로 틀린다. 제대로 하려면 관측마다
 * 무게를 들고 베타 사후분포를 봐야 해서 기록이 `{ok, no, at}` 세 칸으로 안 끝난다. 답이
 * 「말한다 / 안 한다」 둘뿐이라 그만한 정밀도는 필요 없고, 어긋나는 방향만 알고 문턱을
 * 넉넉히 잡았다.
 */
function 구간(s, n) {
  if (!(n > 0)) return { 아래: 0, 위: 1 };
  const p = Math.min(1, Math.max(0, s / n));
  const z2 = z * z;
  const 나눔 = 1 + z2 / n;
  const 가운데 = (p + z2 / (2 * n)) / 나눔;
  const 폭 = (z / 나눔) * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n));
  return { 아래: Math.max(0, 가운데 - 폭), 위: Math.min(1, 가운데 + 폭) };
}

/** 성공률의 아래끝. 표본이 적으면 그만큼 깎인다. */
export function 윌슨아래(s, n) { return 구간(s, n).아래; }
/** 성공률의 위끝. 「안 된다」 를 말해도 되는지는 이쪽으로 잰다. */
export function 윌슨위(s, n) { return 구간(s, n).위; }

/**
 * 이 기록을 보고 무엇을 말할 수 있나.
 *
 * @returns {'된다'|'안된다'|'모름'}
 *
 * 「모름」 이 제일 흔한 답이고, 그래야 맞다. 우리가 프롬프트에 한 줄을 더하는
 * 것은 모델의 판단을 그쪽으로 미는 일이라, 확실하지 않으면 안 미는 편이 낫다.
 */
export function 뭐라할까(기록, 지금) {
  const { ok, no } = 삭힘(기록, 며칠됐나(지금, 기록?.at));
  const n = ok + no;
  if (!(n > 0)) return '모름';
  if (윌슨아래(ok, n) >= 좋음문턱) return '된다';
  if (윌슨위(ok, n) <= 나쁨문턱) return '안된다';
  return '모름';
}
