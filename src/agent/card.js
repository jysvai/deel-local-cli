// 모델 카드 — 겪어 본 버릇을 하네스 설정으로 바꾼다.
//
// ── 왜 만드나 ───────────────────────────────────────────────────────────
//
// 다른 도구들은 프론티어 모델을 전제한다. 여기 붙는 모델은 사정이 다르다.
// 2026년에 나온 재기들이 문서로 남긴 것만 봐도 이렇다.
//
//   · 도구를 불러야 할 때와 아닐 때를 26.5~54% 헷갈린다 (3B~8B)
//   · 7B 는 2~3걸음 뒤 일관성이 무너진다
//   · 오류에서 회복할 때 같은 호출을 되풀이하거나 퇴행 루프에 빠진다
//   · 파라미터 수보다 세대가 더 잘 맞힌다 (Qwen2.5 는 전부 실패, Qwen3 는 전부 통과)
//
// deel 은 이미 이걸 지켜보고 있었다(grade.js 의 지켜본것). 그런데 지켜보기만 하고
// **말로만** 넘겼다 — "인자를 자주 잘라 먹었으니 Append 를 써라" 하고 프롬프트에
// 적는 것이 전부였다. 작은 모델은 그 말을 잘 안 듣는다. 그게 작은 모델이다.
//
// ── 그래서 무엇이 다른가 ────────────────────────────────────────────────
//
// 카드는 모델에게 **부탁하는 대신 deel 이 제 행동을 바꾼다.**
//
//   인자가 자주 잘린다     → 출력 상한을 처음부터 넉넉히 준다 (잘린 뒤 다시 부르지 않게)
//   같은 것을 되풀이한다   → 되풀이 한계를 3 에서 2 로 좁힌다
//   Edit 이 자주 빗나간다  → 빗나갔을 때 파일을 더 넓게 보여 준다
//
// 셋 다 모델의 협조가 필요 없다. 그게 요점이다.
//
// ── 안 하는 것 ──────────────────────────────────────────────────────────
//
// 조금 겪고 함부로 바꾸지 않는다. 걸음이 얼마 안 될 때 우연히 한 번 잘린 것으로
// 하네스를 조이면, 멀쩡한 모델을 붙들어 매는 셈이 된다 — 안 배우느니만 못하다.
// 그래서 걸음 상한과 비율 문턱을 둘 다 넘어야 움직인다.

import { 내장카드, 추론형왜 } from './preset.js';

/** 이 아래로는 판단하지 않는다. 걸음이 적으면 비율이 아무 뜻도 없다. */
export const 최소걸음 = 12;
/** 이 비율을 넘어야 '버릇' 으로 본다. */
export const 문턱 = 0.15;

/** 아무것도 안 겪었을 때의 값. 지금 하네스가 쓰는 그대로다. */
export function 기본조정() {
  return {
    // 잘린 뒤에 올리지 말고 처음부터 넉넉히 줄까 (loop.js 의 cap)
    상한먼저올리기: false,
    // 같은 자리를 몇 번까지 봐 줄까 (loop.js 의 MAX_SAME)
    같은것한계: 3,
    // Edit 이 빗나갔을 때 파일을 몇 줄이나 보여 줄까 (tools/index.js)
    빗나갔을때보일줄: 1,
  };
}

/**
 * 카드 한 장.
 *
 * @param {string} 모델
 * @param {object} 본것    이번 대화에서 본 것 (grade.js 의 지켜본것)
 * @param {object} 겪은것  지난번까지 쌓인 것 (evolve.js 의 집.모델[모델])
 */
export function 카드(모델, 본것 = null, 겪은것 = null) {
  // 이번 것과 지난 것을 **합쳐서** 본다.
  //
  // 이번 대화에서 세 걸음 걸었는데 지난 대화에서 백 걸음을 걸었다면 그 백 걸음이
  // 더 믿을 만하다. 켤 때마다 처음부터 다시 겪지 않는 것이 이 기능의 값이다.
  const 셈 = (이름) => (Number(본것?.[이름]) || 0) + (Number(겪은것?.[이름]) || 0);
  const 걸음 = 셈('걸음');

  const 만들기 = (이름) => {
    const n = 셈(이름);
    return { n, 율: 걸음 ? n / 걸음 : 0 };
  };
  const 버릇 = {
    잘린인자: 만들기('잘린인자'),
    빈답: 만들기('빈답'),
    편집실패: 만들기('편집실패'),
    되풀이: 만들기('되풀이'),
  };

  const 조정 = 기본조정();
  const 왜 = [];

  /*
   * 겪기 전에 이미 아는 것 (preset.js).
   *
   * 최소걸음 관문 **앞**에 선다 — 이것만은 겪어서 아는 것이 아니라 공개 문서로
   * 아는 것이라, 걸음 수와 무관하게 참이기 때문이다. 추론 모델은 생각이 출력
   * 예산을 먹어 답이 잘린다; 열두 걸음 걸으며 다시 확인할 일이 아니다.
   * 문서로 확인 가능한 이 한 가지만 미리 적용하고, 나머지 버릇은 지금까지처럼
   * 겪어서만 잡는다.
   */
  const 내장 = 내장카드(모델);
  if (내장?.추론형) {
    조정.상한먼저올리기 = true;
    왜.push(추론형왜());
  }

  // 걸음이 모자라면 아무것도 안 바꾼다. 여기서 일찍 나가는 것이 안전장치다.
  if (걸음 >= 최소걸음) {
    if (버릇.잘린인자.율 >= 문턱) {
      조정.상한먼저올리기 = true;
      왜.push(`인자가 ${백분율(버릇.잘린인자.율)} 잘렸습니다 — 잘린 뒤에 올리지 말고 처음부터 넉넉히 줍니다.`);
    }
    if (버릇.되풀이.율 >= 문턱) {
      // 2 아래로는 안 내린다. 한 번에 끊으면 멀쩡한 재시도까지 막힌다 —
      // 처음 실패하고 방법을 바꿔 다시 해 보는 것은 되풀이가 아니라 일하는 것이다.
      조정.같은것한계 = 2;
      왜.push(`같은 자리를 ${백분율(버릇.되풀이.율)} 되풀이했습니다 — 세 번까지 안 기다리고 두 번에서 끊습니다.`);
    }
    if (버릇.편집실패.율 >= 문턱) {
      조정.빗나갔을때보일줄 = 5;
      왜.push(`Edit 이 ${백분율(버릇.편집실패.율)} 빗나갔습니다 — 빗나갔을 때 파일을 더 넓게 보여 줍니다.`);
    }
  }

  return {
    모델: String(모델 ?? ''),
    걸음,
    버릇,
    보정: Number(겪은것?.보정) || 1,
    조정,
    왜,
    // 미리 아는 모델이면 그 이름표. 모르면 null — 아는 척하지 않는다.
    내장,
    // 판단을 아직 못 하는 상태인지 화면이 알아야 한다 — '바꾼 것 없음' 과
    // '아직 모름' 은 다른 말이다.
    아직모름: 걸음 < 최소걸음,
  };
}

function 백분율(r) { return `${Math.round(r * 100)}%`; }
