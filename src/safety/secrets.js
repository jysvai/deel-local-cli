// 비밀이 모델에게, 그리고 디스크에 남는 대화 기록에 끼어드는 것을 막는다.
//
// ── 어디서 새나 ────────────────────────────────────────────────────────
//
// 사람이 열쇠를 붙여 넣는 일은 드물다. 새는 자리는 거의 항상 **명령 출력**이다.
//
//   env · printenv · set              환경변수를 통째로 찍는다
//   git remote -v                     https://사람:토큰@github.com/... 이 그대로
//   docker inspect · kubectl get -o   설정에 박힌 열쇠가 그대로
//   curl -v                           Authorization 헤더가 그대로
//   검사 실패 로그                     연결 문자열이 통째로
//
// 이게 왜 문제인가. 그 글은 모델에게 실려 가고 — 사내 게이트웨이라 해도
// 그쪽 로그에 남는다 — 동시에 `.deel/sessions/*.jsonl` 로 디스크에 적힌다.
// 그 파일은 나중에 `/recall` 로 다시 읽히고, `deel pack` 에 딸려 갈 수도 있다.
// 한 번 새면 여러 벌이 된다.
//
// ── 파일 내용은 안 가린다 ───────────────────────────────────────────────
//
// 여기서 제일 중요한 결정이다. **읽은 파일은 손대지 않는다.**
//
// 가리고 싶은 마음이 드는 자리가 바로 `.env` 인데, 거기를 가리면 이렇게 된다 —
// 모델이 가려진 글을 보고, 그걸 고쳐서 Write 로 되돌려 쓴다. 그러면 진짜
// 열쇠가 있던 자리에 `«가림»` 이 적힌다. **사람의 열쇠가 우리 손에 지워진다.**
// 비밀을 지키려다 비밀을 파괴하는 셈이다.
//
// 그래서 파일 쪽은 가리는 대신 **알린다** — 감사기록에 남기고 화면에 띄운다.
// 무엇을 못 막는지 분명히 말하는 편이, 막았다고 해 놓고 파일을 망가뜨리는 것보다
// 언제나 낫다.
//
// 가리는 것은 **한 번 쓰고 버려지는 출력**뿐이다. 명령 출력·웹에서 받아온 글은
// 모델이 그대로 되돌려 쓸 일이 없다.

/** 가려진 자리에 남는 표. 종류를 같이 적어 무엇이 가려졌는지 알 수 있게 한다. */
const 표 = (종류) => `«가림:${종류}»`;

/**
 * 찾는 것들.
 *
 * 순서가 뜻을 갖는다 — 좁은 것을 먼저 본다. `sk-ant-...` 를 `sk-...` 가 먼저
 * 집어삼키면 무엇이 가려졌는지가 뭉개진다.
 *
 * 넓게 잡지 않는다. 코드에 흔한 글자를 비밀로 오인해 가려 버리면, 모델이 보는
 * 코드가 조용히 달라진다. 그건 여기서 막으려는 것보다 더 나쁜 고장이다.
 */
/**
 * 한 줄에서 `#` 주석을 뗀다.
 *
 * 주석 안은 코드가 아니다. 떼지 않으면 `# https://api.example.com` 의 `//`,
 * `# (운영환경용)` 의 괄호, `# type: bearer` 의 `type` 이 전부 「이 줄은 코드」
 * 라는 증거로 읽혀 **그 줄의 비밀이 평문으로 나간다**(14차 리뷰).
 *
 * 무늬 하나로는 안 된다. 무늬로 하면 둘 중 하나를 고르게 된다(16차 리뷰).
 *
 * - `#` 앞 빈칸을 **요구하면** `API_KEY=prod.v1.secret#(운영)` 이 샌다.
 * - **안 요구하면** `msg = "a # b"; x.API_KEY = config.apiKey;` 처럼 글자열
 *   안의 `#` 부터 잘려 뒤쪽 `;` 이 사라지고, 멀쩡한 코드가 가려진다.
 *
 * 그래서 따옴표를 세면서 걷는다. **따옴표 밖**의 첫 `#` 부터가 주석이다.
 *
 * 자바스크립트의 몰래칸(`#`)은 넘긴다 — `obj.#몰래칸` 처럼 점 뒤에 오거나,
 * `  #apiKey = config.apiKey;` 처럼 줄머리에 온다. 뒤에 이름씨 글자가 붙어
 * 있어야 몰래칸이다. 안 넘기면 그 선언 줄이 통째로 잘려 나가고, 남은 빈 줄에
 * 코드의 표시가 없어 멀쩡한 코드가 가려진다(17차 리뷰).
 *
 * 앞에 수식하는 낱말이 붙어도 줄머리로 친다 — `static` · `readonly` ·
 * `accessor` · `override`. `static` 만 멀쩡했던 것은 그 낱말이 마침
 * `코드표시` 목록에 있어서였다. 목록에 없는 낱말(`accessor`)에서는 그대로
 * 뭉갰다(19차 리뷰). 글자와 빈칸만 있는 앞자리는 코드의 수식어로 본다 —
 * 설정 줄이라면 그 자리에 `:` 나 `=` 가 있다.
 *
 * 줄머리 `#` 을 안 잘라도 설정 줄은 안 상한다 — `# API_KEY: 값` 은 잘라도
 * 안 잘라도 코드의 표시가 없어 어차피 가려진다.
 */
const 몰래칸 = (줄, i) => /^[\p{L}_$]/u.test(줄[i + 1] ?? '')
  && (줄[i - 1] === '.' || /^[ \t]*(?:[A-Za-z]+[ \t]+)*$/.test(줄.slice(0, i)));

const 주석떼기 = (줄) => {
  let 따 = '';
  for (let i = 0; i < 줄.length; i += 1) {
    const 자 = 줄[i];
    if (따) {
      if (자 === '\\') i += 1;
      else if (자 === 따) 따 = '';
      continue;
    }
    if (자 === '"' || 자 === "'" || 자 === '`') { 따 = 자; continue; }
    if (자 === '#' && !몰래칸(줄, i)) return 줄.slice(0, i);
  }
  return 줄;
};

/**
 * `자리` 가 놓인 **한 줄**을 떼어 낸다.
 *
 * 줄바꿈을 `\n` 으로만 찾으면 `\r` 만 쓰는 글에서 파일 통째가 한 줄이 되고,
 * 그러면 저 아래 어딘가의 `;` 하나 때문에 이 줄이 코드로 뒤집힌다(16차 리뷰).
 * CRLF 의 `\r` 도 여기서 같이 떨어진다 — 안 떨어뜨리면 줄 끝을 보는 규칙이
 * 통째로 헛돈다(15차 리뷰). 이 저장소가 도는 자리가 윈도우다.
 */
const 줄떼기 = (전체, 자리) => {
  const 앞 = Math.max(전체.lastIndexOf('\n', 자리), 전체.lastIndexOf('\r', 자리)) + 1;
  const 남은 = 전체.slice(자리).search(/[\r\n]/);
  return 전체.slice(앞, 남은 < 0 ? 전체.length : 자리 + 남은);
};

/**
 * `.env` · YAML 한 줄에는 없고 코드 한 줄에는 있는 것들.
 *
 * 넣지 않은 것들에도 까닭이 있다.
 *
 * - `export` — `.env` 도 `export FOO=bar` 를 쓴다.
 * - `{}` — YAML 흐름 표기(`{ API_KEY: 값 }`)가 문법상 중괄호를 쓴다.
 *   중괄호를 증거로 삼으면 그 한 줄이 통째로 샜다.
 * - 쌍반점은 그냥 증거로 둔다. `.env` 값 끝에 쌍반점이 붙어 오면
 *   (`API_KEY=prod.v1.secret;`) 그 줄은 샌다. 그런데 그것과 한 줄짜리
 *   타입 표기(`API_KEY: types.ApiKey;`)는 **글자로 구별이 안 된다** —
 *   둘 다 점으로 이은 값 뒤에 쌍반점 하나다. 뒤에 무언가 더 있는
 *   쌍반점만 보게 좁혀 봤더니 그 타입 표기가 뭉개졌다(검사가 잡았다).
 *
 * 줄 끝 `,` 는 거꾸로 코드의 표시다. YAML 블록 매핑은 줄 끝에 쉼표를 안 찍고,
 * 여러 줄 객체 리터럴은 찍는다.
 */
const 코드표시 = /[()]|=>|\/\/|\/\*|;|,[ \t]*$|\b(?:const|let|var|interface|type|class|enum|function|def|readonly|declare|public|private|protected|static|final)\b/;

/**
 * 점으로 이은 값이 **비밀인가 코드가 가리키는 이름인가**.
 *
 * ── 빈칸은 가르는 신호가 아니었다 (13차 리뷰) ──────────────────────────
 *
 * 여태 「값 앞에 빈칸이 있으면 코드」 로 갈랐다. `.env` 는 `NAME=값` 으로
 * 붙여 쓰니 빈칸이 있으면 코드라는 셈이었다. 재 보니 **넷 중 하나만**
 * 맞혔다.
 *
 *     API_KEY=prod.v1.secret                    가림    맞음
 *     API_KEY: token.v1.secret       (YAML)     그대로  비밀이 평문으로 남음
 *     API_KEY= prod.v1.secret        (.env)     그대로  같은 자리
 *     interface Cfg { API_KEY:types.ApiKey; }   가림    코드를 망가뜨림
 *
 * YAML 은 문법이 쌍점 뒤 빈칸을 **요구한다.** 그러니 빈칸을 코드의 표시로
 * 읽는 한 YAML 에 적힌 비밀은 언제까지고 샌다. 그리고 붙여 쓴 타입
 * 표기(`API_KEY:types.ApiKey`)는 거꾸로 코드인데 가려졌다.
 *
 * ── 그 줄이 코드인가만 본다 ───────────────────────────────────────────
 *
 * `.env` 와 YAML 한 줄에는 이름과 값밖에 없다. `주석` 을 떼고 남은 자리에
 * `코드표시` 가 하나라도 있으면 코드다.
 *
 * ── 값 모양으로 가르려다 물러섰다 ─────────────────────────────────────
 *
 * 처음엔 값도 같이 봤다 — 「숫자가 끼거나 마디가 길면 비밀」. 그러면
 * `config.api_key` 를 놔두면서 `token.v1.secret` 을 가릴 수 있다. 그런데
 * 이 저장소에 이미 박혀 있는 검사가 **`API_KEY=my.secret.value` 를 가리라고**
 * 한다. 그것과 `config.api_key` 는 문법으로 구별이 안 된다 — 둘 다 짧은
 * 낱말을 점으로 이은 꼴이다. 그러니 값 모양으로 가를 수 있다는 생각을
 * 버린다. 갈리지 않는 것을 갈리는 척하면 그게 더 위험하다.
 *
 * 점 뒤의 `#` 도, 물음표 이음(`config?.apiKey`)도 이름씨의 한 조각이다.
 *
 * 이름씨는 영문만이 아니다. `설정.비밀번호` 를 이름씨로 안 보면
 * `const API_KEY = 설정.비밀번호;` 가 가려진다 — 이 저장소 집안 스타일이
 * 한글 이름씨라 제 코드부터 뭉갰다(16차 리뷰). 글자 갈래로 본다.
 *
 * 점이 없는 맨 값(`const API_KEY = apiKey;`)까지 줄을 묻게 넓혀 봤더니,
 * 이 저장소가 **가리라고 못 박아 둔** `const API_KEY = ENV-PROD-SECRET-KEY-12345;`
 * 와 `call(API_KEY = abcd1234)` 가 같이 풀렸다. 점 없는 한 낱말은 이름씨일
 * 수도 비밀일 수도 있고, 그 둘은 여기서 갈리지 않는다. 그래서 점이 있는
 * 값만 줄을 묻는다 — 뭉개지는 쪽이 아니라 가리는 쪽으로 남긴다.
 *
 * ── 그래서 치르는 값 ──────────────────────────────────────────────────
 *
 * 한 줄만 보니, 한 줄에 표시가 없는 코드는 설정 줄과 똑같이 생긴다.
 *
 *     API_KEY = config.api_key            파이썬 대입인데 가려진다
 *     { API_KEY: config.apiKey }          한 줄 물건인데 가려진다
 *     interface Cfg {
 *       API_KEY: types.ApiKey             쌍반점을 생략하면 가려진다
 *     }
 *
 * 이건 알고 받는 값이다. 줄이 망가지는 것보다 **비밀이 나가는 것이 훨씬
 * 나쁘다**(1.19.0 에 적어 둔 대로). 가려도 줄은 읽힌다 —
 * `API_KEY = «가림:환경변수»` 로 남고, 무엇이 있었는지도 보인다.
 *
 * 위 칸을 메우려면 앞뒤 줄을 봐야 하는데, 그 자리에 갈릴 것이 없다 —
 * 들여 쓴 `API_KEY: 값` 은 YAML 겹 매핑이면 비밀이고 객체 리터럴이면
 * 코드인데, 두 줄이 글자 하나 안 다르다. 겹 매핑이 훨씬 흔하므로
 * **가리는 쪽으로 둔다.**
 *
 * @param {string} 전체  가리는 글 통째로
 * @param {number} 자리  이 짝이 시작한 자리
 * @param {string} 값    점으로 이어졌을 수 있는 값
 * @returns {boolean} 가릴까
 */
const 점값을가릴까 = (전체, 자리, 값) => {
  if (!/^[\p{L}_$][\p{L}\p{N}_$]*(?:\??\.#?[\p{L}_$][\p{L}\p{N}_$]*)+$/u.test(값)) return true;
  return !코드표시.test(주석떼기(줄떼기(전체, 자리)));
};

