/**
 * 화면 말 고르기 — 한국어 / 영어.
 *
 * ── 왜 이제 와서 ────────────────────────────────────────────────────────
 *
 * deel 은 한국어로 쓴 도구다. 함수 이름도 변수 이름도 한글이고, 그게 이
 * 저장소의 뜻이다. 그건 안 바꾼다.
 *
 * 바꾸는 것은 **화면에 나가는 말**뿐이다. GitHub 에 올려 두고 보니, 처음
 * 켠 사람이 `/help` 한 번 치고 나가 버린다. 명령 이름은 이미 영어인데
 * (help·model·undo…) 그 옆의 설명이 전부 한글이라, 무엇을 하는 명령인지
 * 알 길이 없어서다. 코드는 한국어로 두고 화면만 갈아 끼운다.
 *
 * ── 지키는 선 ───────────────────────────────────────────────────────────
 *
 * 1) **빈칸을 절대 안 낸다.** 영어 말이 없으면 한국어를 그대로 낸다.
 *    반쯤 번역된 화면에서 제일 나쁜 것이 '아무것도 안 적힌 자리' 다 —
 *    사람은 그걸 고장으로 읽지, 번역이 덜 됐다고 읽지 않는다.
 * 2) **없는 열쇠도 안 죽는다.** 열쇠를 그대로 돌려준다. 화면이 좀 이상해도
 *    프로그램은 돈다. 화면 말 하나 때문에 대화가 끊기면 안 된다.
 * 3) **얼마나 됐는지 숨기지 않는다.** 검사가 안 옮긴 열쇠를 세어 적는다.
 *    다 된 척하는 것보다 "298개 중 47개는 아직 한국어" 가 낫다.
 * 4) 기본은 **한국어**다. 시스템 로캘을 안 본다 — 윈도우·WSL 에서
 *    LANG=en_US 인 한국 사람이 많아서, 그걸 보면 멀쩡히 쓰던 사람 화면이
 *    어느 날 영어로 바뀐다. 영어는 **고른 사람만** 본다.
 */
import { ko } from './ko.js';
import { en } from './en.js';
import { ja } from './ja.js';
import { zh } from './zh.js';

export const 언어들 = ['ko', 'en', 'ja', 'zh'];
export const 기본언어 = 'ko';

const 표 = { ko, en, ja, zh };

/*
 * 못 찾았을 때 어디로 물러나나.
 *
 * 한국어로만 물러나면, 일본어를 고른 사람이 안 옮긴 자리에서 **한글**을 본다.
 * 그 사람에게는 영어가 훨씬 읽힌다. 그래서 ko 가 아닌 말은 영어를 한 번
 * 거쳐서 내려간다. 어느 쪽이든 빈칸은 안 낸다 — 빈칸은 고장으로 읽힌다.
 */
const 물러날곳 = { ko: [], en: ['ko'], ja: ['en', 'ko'], zh: ['en', 'ko'] };

let 지금 = 기본언어;

/** 넘어온 값을 아는 언어로. 모르면 null. */
export function 언어고르기(값) {
  const v = String(값 ?? '').trim().toLowerCase();
  if (!v) return null;
  if (v === 'ko' || v === 'kr' || v === 'korean' || v === '한국어' || v === '한글') return 'ko';
  if (v === 'en' || v === 'eng' || v === 'english' || v === '영어') return 'en';
  if (v === 'ja' || v === 'jp' || v === 'jpn' || v === 'japanese' || v === '일본어' || v === '日本語') return 'ja';
  if (v === 'zh' || v === 'cn' || v === 'chs' || v === 'chinese' || v === '중국어' || v === '中文' || v === '简体中文') return 'zh';
  // ko_KR.UTF-8 · en-US 같은 것도 받는다.
  const 앞 = v.split(/[-_.]/)[0];
  return 언어들.includes(앞) ? 앞 : null;
}

/** 지금 언어. */
export function 언어() { return 지금; }

/**
 * 언어를 정한다. 모르는 값이면 안 바꾸고 false.
 * @returns {boolean} 바꿨나
 */
export function 언어정하기(값) {
  const v = 언어고르기(값);
  if (!v) return false;
  지금 = v;
  return true;
}

/**
 * 켤 때 한 번. 환경변수 → 설정 순으로 본다.
 *
 * 환경변수가 이긴다. 한 번만 영어로 켜 보고 싶은 사람이 설정을 건드리지
 * 않고 `DEEL_LANG=en deel` 로 할 수 있어야 한다.
 */
export function 언어잡기({ env = process.env, cfg = null } = {}) {
  지금 = 언어고르기(env.DEEL_LANG) ?? 언어고르기(cfg?.lang) ?? 기본언어;
  지시 = 언어고르기(env.DEEL_PROMPT_LANG) ?? 언어고르기(cfg?.promptLang) ?? null;
  return 지금;
}

/*
 * ── 시키는 말과 보는 말은 다른 축이다 ──────────────────────────────────
 *
 * 여태 하나였다. /lang en 을 켜면 화면도, **모델에게 주는 글도**, 모델이
 * 답하는 말도 한꺼번에 영어가 됐다. 그래서 "영어로 시키고 한국어로 받기" 가
 * 아예 안 됐는데, 그게 실제로 쓸모가 있다:
 *
 *   · 값이 눅다. 한글은 글자당 약 1토큰, 영문은 약 3.6자당 1토큰이다
 *     (session.js 의 estimateTokens). 8k 창에서 고정 몫이 눈에 띄게 준다.
 *   · 작은 모델이 영어 지시를 더 잘 따른다. 학습에 그쪽이 훨씬 많았다.
 *
 * 그런데 **읽는 사람은 한국 사람**이다. 그래서 둘을 갈랐다. 화면 말은
 * 언어() 가, 모델에게 주는 글은 지시말() 이 정한다.
 *
 * null 이면 "따로 안 정했다" 는 뜻이고, 그때는 화면 말을 따라간다.
 * 여태 쓰던 사람에게 아무것도 안 바뀌게 하려고 그렇게 뒀다.
 */
let 지시 = null;

/** 모델에게 주는 글의 말. 따로 안 정했으면 화면 말을 따른다. */
export function 지시말() { return 지시 ?? 지금; }

/** 지시말을 따로 정한다. 빈 값·auto 면 다시 화면 말을 따라간다. */
export function 지시말정하기(값) {
  const v = String(값 ?? '').trim().toLowerCase();
  if (!v || v === 'auto' || v === '따라') { 지시 = null; return true; }
  const 고른것 = 언어고르기(v);
  if (!고른것) return false;
  지시 = 고른것;
  return true;
}

/** 따로 정해 뒀나. 화면에 "따라감" 과 "영어로 못 박음" 을 갈라 보이려고 쓴다. */
export function 지시말따로정했나() { return 지시 !== null; }

/*
 * 조사는 앞 글자의 받침을 보고 갈린다.
 *
 * 끼워 넣는 값이 그때그때 달라지는 자리에서 조사를 글에 박아 두면
 * "기사 으로 바꿨습니다" 같은 것이 나온다. 안 터지고, 검사도 안 잡고,
 * 화면에서만 어색하다 — 그래서 오래 남는다.
 *
 * `{것:으로}` 처럼 자리 이름 뒤에 조사를 적으면 값을 보고 골라 붙인다.
 * 영어 글에는 안 적으면 그만이라 `{것}` 그대로 둬도 된다.
 *
 * 값과 조사 사이에 뭔가 끼어야 할 때 — 따옴표가 대표적이다 — 이름 앞에
 * `~` 를 붙이면 **조사만** 나온다: `"{값}"{~값:은는}` → `"없는거"는`.
 */
const 조사표 = {
  은는: ['은', '는'],
  이가: ['이', '가'],
  을를: ['을', '를'],
  과와: ['과', '와'],
  으로: ['으로', '로'],
};

/**
 * 이 값 뒤에 붙일 조사.
 *
 * 한글이 아닌 것으로 끝나면(영어 낱말·기호) **받침 없는 쪽**을 씁니다.
 * 한국어 화면에 들어오는 값은 거의 한글이라 여기까지 오는 일이 드물고,
 * 여기서 더 따지면 규칙만 늘고 맞는 자리는 안 늘어납니다.
 */
export function 조사붙이기(값, 갈래) {
  const 짝 = 조사표[갈래];
  if (!짝) return '';
  // 색 입힌 값이 그대로 들어온다(`\x1b[92m⌂\x1b[0m`). 벗기지 않으면 마지막
  // 글자가 언제나 리셋 문자열의 'm' 이라, 무슨 값이 와도 답이 하나로 굳는다.
  const 끝 = String(값 ?? '').replace(/\x1b\[[0-9;]*m/g, '').trimEnd().slice(-1);
  const cp = 끝.codePointAt(0);
  if (cp === undefined || cp < 0xac00 || cp > 0xd7a3) return 짝[1];
  const 받침 = (cp - 0xac00) % 28;
  if (받침 === 0) return 짝[1];
  // `으로` 만 다르다. ㄹ(받침 8) 뒤에서는 받침이 없는 것처럼 '로' 가 붙는다.
  if (갈래 === '으로' && 받침 === 8) return 짝[1];
  return 짝[0];
}

/**
 * 말 한 마디.
 *
 * @param {string} 열쇠
 * @param {Record<string, string|number>} [채움]  `{이름}` · `{이름:조사}` 자리에 끼워 넣을 것
 * @returns {string}
 */
export function 말(열쇠, 채움 = null) {
  const k = String(열쇠 ?? '');
  // 있는 것 → 한국어 → 열쇠. 어느 자리에서도 빈칸이 안 나오게 세 겹으로 받친다.
  let 글 = 표[지금]?.[k];
  if (글 === undefined) {
    for (const 뒤 of 물러날곳[지금] ?? ['ko']) {
      if (표[뒤]?.[k] !== undefined) { 글 = 표[뒤][k]; break; }
    }
  }
  if (글 === undefined) 글 = ko[k] ?? k;
  if (!채움) return 글;
  /*
   * 자리 이름에 \w 를 쓰면 안 된다.
   *
   * 한글은 \w 가 아니다. `{안}` 은 영영 안 맞아서 화면에 중괄호째로 찍힌다 —
   * 이 저장소에서 같은 함정을 이미 한 번 밟았다 — commands.js 의 배분 낱말 경계.
   * 자리 이름은 한글로 짓는 편이 읽기 좋으니, 규칙을 글자 종류가 아니라
   * **중괄호와 빈칸이 아닌 것**으로 잡는다.
   *
   * 안 준 자리는 그대로 둔다. 지워 버리면 "0개 턴" 처럼 틀린 말이 되고,
   * 틀린 숫자는 안 적힌 것보다 나쁘다.
   */
  return String(글).replace(/\{([^{}\s:]+)(?::([^{}\s]+))?\}/g, (통째, 이름, 갈래) => {
    const 조사만 = 이름.startsWith('~');
    const 진짜이름 = 조사만 ? 이름.slice(1) : 이름;
    if (!Object.prototype.hasOwnProperty.call(채움, 진짜이름)) return 통째;
    const 값 = String(채움[진짜이름]);
    if (조사만) return 갈래 ? 조사붙이기(값, 갈래) : '';
    return 갈래 ? 값 + 조사붙이기(값, 갈래) : 값;
  });
}

/*
 * 세는 말 한 조각 — `3개 파일` · `1건` · `12줄`.
 *
 * 도구 결과 한 줄은 이 조각들을 ` · ` 로 이어 만든다. 왜 통짜 문장으로
 * 안 두는지는 ko.js 의 '세는 말' 묶음에 적어 두었다.
 *
 * **하나일 때 열쇠가 갈린다.** 한국어는 「1개 파일」 로 끝이지만 영어는
 * `1 files` 가 나오면 그 줄 전체가 대충 만든 것으로 읽힌다. 그래서 홑을
 * 따로 두는 갈래만 모아 뒀다 — 여기 없는 갈래(자·회·초)는 영어에서도
 * 홑복수가 안 갈려서 열쇠를 늘릴 까닭이 없다.
 *
 * 숫자는 여기서 toLocaleString() 을 거친다. 부르는 쪽마다 하면 어디선가
 * 빠져서 `50700` 과 `50,700` 이 한 화면에 같이 뜬다.
 */
const 홑이따로인것 = new Set(['files', 'hits', 'lines', 'spots', 'places', 'count', 'turns']);

export function 세말(갈래, n) {
  const 수 = Number(n);
  const 홑 = 홑이따로인것.has(갈래) && 수 === 1;
  return 말(`unit.${갈래}${홑 ? '1' : ''}`, { n: Number.isFinite(수) ? 수.toLocaleString() : String(n) });
}

/** 이 열쇠가 지금 언어로 옮겨져 있나. 검사와 /lang 이 본다. */
export function 옮겨졌나(열쇠, 언어이름 = 지금) {
  return Object.prototype.hasOwnProperty.call(표[언어이름] ?? {}, String(열쇠));
}

/**
 * 얼마나 옮겨졌나.
 *
 * 숨기지 않으려고 둔다. 다 된 척하는 화면보다 "298개 중 47개는 아직
 * 한국어입니다" 가 낫다 — 그래야 도와줄 사람이 어디를 도울지 안다.
 */
export function 옮긴만큼(언어이름 = 지금) {
  const 전부 = Object.keys(ko);
  const 있는것 = 전부.filter((k) => 옮겨졌나(k, 언어이름));
  return {
    언어: 언어이름,
    전체: 전부.length,
    옮김: 있는것.length,
    남음: 전부.length - 있는것.length,
    안옮긴열쇠: 전부.filter((k) => !옮겨졌나(k, 언어이름)),
  };
}

/** 한국어 쪽에 없는 열쇠가 영어 쪽에 있으면 그건 죽은 말이다. 검사가 본다. */
export function 짝없는열쇠(언어이름) {
  return Object.keys(표[언어이름] ?? {}).filter((k) => !Object.prototype.hasOwnProperty.call(ko, k));
}
