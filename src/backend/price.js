/**
 * 요금 셈 — 쓴 토큰을 돈으로 옮긴다.
 *
 * ── 이 파일에는 값이 박힌 요금표가 없다 ────────────────────────────────
 *
 * 일부러 안 넣었다. 요금은 회사가 아무 때나 바꾸는 값이고, 소스에 박아 두면
 * 고칠 사람이 없다. 그러면 이 도구는 **틀린 금액을 자신 있게 찍는 도구**가
 * 된다. 토큰 수를 안 보여 주는 것보다 그쪽이 훨씬 나쁘다 — 사람은 화면에
 * 뜬 숫자를 믿고 예산을 잡는다.
 *
 * 그래서 값의 출처는 둘뿐이다.
 *
 *   1. 사람이 설정에 적은 값  (.deel/config.json 의 `요금`)
 *   2. 제공자 서술 파일이 들고 있는 값 (src/providers/*.js 의 `요금`)
 *
 * 2번은 지금 전부 비어 있다. 확인한 값만 넣기로 했고, 확인하지 못했다.
 * 비어 있는 표는 「모른다」 고 말하지만, 지어낸 표는 거짓말을 한다.
 *
 * 모르면 돈을 안 찍는다. 토큰만 찍고 「요금 모름」 이라고 적는다.
 *
 * ── 단위 ───────────────────────────────────────────────────────────────
 *
 * 100만 토큰당 달러로 적는다. 회사들이 요금표를 그 단위로 내놓기 때문이다.
 * 사람이 요금표에서 본 숫자를 그대로 옮겨 적을 수 있어야 한다. 여기서
 * 1000토큰당으로 받으면 1000배 틀린 값이 조용히 들어온다.
 */
import { 제공자고르기 } from '../providers/index.js';

// 100만 토큰당. 요금표에 적힌 숫자를 그대로 받기 위한 단위다.
export const 단위 = 1000000;

/*
 * 기준 날짜가 이만큼 지나면 「오래됨」 이라고 덧붙인다.
 *
 * 값을 버리지는 않는다. 오래된 값도 자릿수는 맞으므로 안 보여 주는 것보다
 * 낫다. 다만 그대로 믿게 두면 안 된다. 반년이면 회사가 요금을 한 번쯤
 * 손대는 기간이라 이렇게 잡았다.
 */
export const 낡는날 = 180;

/**
 * 설정에 적힌 값이 쓸 수 있는 요금인가.
 *
 * 문자열로 적어도 받는다 — 사람이 JSON 에 "2.5" 라고 적는 일은 흔하고,
 * 그걸 튕기면 조용히 「요금 모름」 이 되어 왜 안 나오는지 알 길이 없다.
 * 대신 숫자가 아닌 것·음수는 받지 않고, 왜 못 받았는지 말로 남긴다.
 */
function 값읽기(x) {
  if (x == null || x === '') return null;
  const v = typeof x === 'string' ? Number(x.trim()) : Number(x);
  if (!Number.isFinite(v) || v < 0) return null;
  return v;
}

/**
 * 모델 이름이 이 열쇠에 걸리나.
 *
 * 딱 맞는 이름이 먼저다. `*` 를 쓴 열쇠(`gpt-4o*`)는 사람이 **일부러**
 * 적었을 때만 걸린다 — 우리가 알아서 앞머리를 잘라 맞추면, 값이 다른
 * 형제 모델(`-mini`)에 비싼 요금이 붙어도 아무도 모른다.
 */
function 걸리나(열쇠, 모델) {
  if (열쇠 === 모델) return { 맞나: true, 딱: true };
  if (!열쇠.includes('*')) return { 맞나: false };
  const 무늬 = new RegExp(`^${열쇠.split('*').map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('.*')}$`);
  return { 맞나: 무늬.test(모델), 딱: false };
}

function 한칸읽기(열쇠, 값, 어디서) {
  const 입 = 값읽기(값?.입력 ?? 값?.in ?? 값?.input);
  const 출 = 값읽기(값?.출력 ?? 값?.out ?? 값?.output);
  if (입 == null || 출 == null) {
    return { 탈: `${어디서} 의 '${열쇠}' 요금이 숫자가 아닙니다 (입력·출력 둘 다 필요합니다)` };
  }
  const 기준 = 값?.기준 ?? 값?.asOf ?? null;
  return { 입력: 입, 출력: 출, 기준: 기준 ? String(기준) : null, 어디서, 열쇠 };
}

/**
 * 이 모델의 요금을 찾는다.
 *
 * 사람이 적은 값이 먼저다. 딸려 온 표가 낡았을 때 사람이 고칠 방법이
 * 그것뿐이라 그렇다. 못 찾으면 null 을 준다 — 0 이 아니다. 0 을 주면
 * 「공짜」 와 「모름」 이 화면에서 같아진다.
 *
 * @param {string} 모델
 * @param {{설정?: object|null, 제공자?: object|null, 이제?: number}} o
 */
export function 요금찾기(모델, { 설정 = null, 제공자 = null, 이제 = Date.now() } = {}) {
  const 이름 = String(모델 ?? '').trim();
  if (!이름) return null;
  const 탈들 = [];

  for (const [표, 어디서] of [[설정, '설정'], [제공자?.요금, '딸려 온 표']]) {
    if (!표 || typeof 표 !== 'object') continue;
    // 딱 맞는 이름 먼저, 그다음에 사람이 `*` 로 적어 둔 것.
    for (const 딱먼저 of [true, false]) {
      for (const [열쇠, 값] of Object.entries(표)) {
        const g = 걸리나(열쇠, 이름);
        if (!g.맞나 || !!g.딱 !== 딱먼저) continue;
        const 읽은 = 한칸읽기(열쇠, 값, 어디서);
        if (읽은.탈) { 탈들.push(읽은.탈); continue; }
        const 기준 = 읽은.기준 ?? (어디서 === '딸려 온 표' ? 제공자?.요금기준 ?? null : null);
        return { ...읽은, 기준, 낡았나: 낡았나(기준, 이제), 탈들 };
      }
    }
  }
  return 탈들.length ? { 없음: true, 탈들 } : null;
}

/**
 * 이 대화에 걸린 요금값.
 *
 * 상태줄은 글자를 칠 때마다 다시 그려진다. 그때마다 표를 훑으면 아까우니
 * 모델 이름이 그대로인 동안은 찾은 것을 들고 있는다. 모델을 갈아타면
 * (/model) 이름이 달라지므로 저절로 다시 찾는다 — 갈아탈 때 이걸 지워
 * 달라고 부탁하는 방식은 언젠가 한 군데를 빠뜨린다.
 */
export function 세션요금(session, { 이제 = Date.now() } = {}) {
  const 모델 = String(session?.conn?.model ?? '');
  if (session?.요금캐시 && session.요금캐시.모델 === 모델) return session.요금캐시.값;
  const 값 = 요금찾기(모델, {
    설정: session?.요금표 ?? null,
    제공자: session?.제공자 ? 제공자고르기(session.제공자) : null,
    이제,
  });
  if (session) session.요금캐시 = { 모델, 값 };
  return 값;
}

/** 기준 날짜가 반년보다 오래됐나. 날짜가 없으면 「모른다」 — 오래됐다고 치지 않는다. */
export function 낡았나(기준, 이제 = Date.now()) {
  if (!기준) return false;
  const t = Date.parse(기준);
  if (!Number.isFinite(t)) return false;
  return (이제 - t) / 86400000 > 낡는날;
}

/**
 * 토큰을 달러로.
 *
 * 요금을 모르면 null 이다. 여기서 0 을 돌려주면 부르는 쪽이 「$0.00」 을
 * 찍게 되고, 그건 공짜라는 뜻이 되어 버린다.
 */
export function 돈셈({ in: 입 = 0, out: 출 = 0 } = {}, 값) {
  if (!값 || 값.없음 || 값.입력 == null || 값.출력 == null) return null;
  const 입돈 = (Number(입) || 0) / 단위 * 값.입력;
  const 출돈 = (Number(출) || 0) / 단위 * 값.출력;
  return { 달러: 입돈 + 출돈, 입력: 입돈, 출력: 출돈 };
}

/**
 * 돈을 사람이 읽는 글로.
 *
 * 아주 작은 값을 `$0.00` 으로 반올림하면 안 된다. 로컬에서 한두 턴 돌린
 * 뒤 화면에 `$0.00` 이 서 있으면 「공짜네」 로 읽히고, 그 상태로 백 턴을
 * 돌린다. 자릿수가 안 되면 반올림하지 말고 미만이라고 적는다.
 */
export function 돈말(달러) {
  const v = Number(달러);
  if (!Number.isFinite(v) || v < 0) return null;
  if (v === 0) return '$0';
  if (v < 0.0001) return '<$0.0001';
  if (v < 1) return `$${v.toFixed(4)}`;
  if (v < 1000) return `$${v.toFixed(2)}`;
  return `$${Math.round(v).toLocaleString()}`;
}

/**
 * 이 금액이 어디서 온 값인지 한 줄로.
 *
 * 금액만 찍으면 사람은 그게 오늘 요금표에서 온 값이라고 믿는다. 어디서
 * 왔는지·언제 기준인지를 같이 적어야 의심할 거리가 생긴다.
 */
export function 어디서온값(값) {
  if (!값 || 값.없음) return null;
  const 조각 = [값.어디서];
  if (값.열쇠 && 값.열쇠.includes('*')) 조각.push(`'${값.열쇠}' 로 맞춤`);
  if (값.기준) 조각.push(`${값.기준} 기준${값.낡았나 ? ' · 오래됨' : ''}`);
  else 조각.push('기준 날짜 없음');
  return 조각.join(' · ');
}

/**
 * 요금을 모를 때 사람에게 할 말.
 *
 * 「모릅니다」 로 끝내면 사람이 할 수 있는 일이 없다. 어디에 무엇을 적으면
 * 되는지까지 적는다. 요금표 주소를 아는 제공자면 그것도 같이 준다.
 */
export function 요금적는법(모델, { 제공자 = null, 설정파일 = '.deel/config.json' } = {}) {
  const 줄 = [
    `요금을 모릅니다. ${설정파일} 에 100만 토큰당 달러로 적으면 셈합니다.`,
    `  "요금": { "${모델 || '모델이름'}": { "입력": 0, "출력": 0, "기준": "${new Date().toISOString().slice(0, 10)}" } }`,
  ];
  if (제공자?.요금표주소) 줄.push(`  요금표: ${제공자.요금표주소}`);
  return 줄;
}
