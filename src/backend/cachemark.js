/** 표식을 붙여도 되는 블록인가. */
const 붙일수있나 = (b) => {
  const t = b?.type;
  if (t === 'thinking' || t === 'redacted_thinking') return false;
  if (t === 'text') return String(b.text ?? '').length > 0;
  return t === 'tool_result' || t === 'tool_use' || t === 'image' || t === 'document';
};

/*
 * ── 되돌아보기 창은 **블록** 스무 개다. 메시지 스무 개가 아니다 ─────────
 *
 * 서버는 표식에서 뒤로 **블록 20개**까지만 훑어 먼저 굳혀 둔 것을 찾는다.
 * 그 안에 앞선 표식이 없으면 못 찾고, 못 찾으면 앞이 통째로 다시 나간다.
 * 닻은 바로 그 일이 안 나게 꼬리 앞에 하나 더 박아 두는 것이다.
 *
 * 그런데 여기서 **메시지 수로** 세고 있었다. 그 둘은 도구를 도는 대화에서
 * 완전히 다른 값이다 — 한 차례가 블록 여럿이기 때문이다.
 *
 *   assistant  [글 하나 + 도구 부름 둘]        → 3블록
 *   user       [도구 결과 둘]                  → 2블록
 *   즉 한 바퀴가 메시지 2개인데 블록은 5개다.
 *
 * 그래서 「끝에서 메시지 12개」 는 실제로 **30블록**이었다. 창이 20인데.
 * 닻이 창 밖에 박혀 있으니 꼬리 표식은 그걸 못 보고, 결국 매 턴 앞이 통째로
 * 다시 나갔다. 닻을 박은 값이 하나도 없었던 셈이다.
 *
 * 더 나쁜 것은 **하필 도구를 많이 쓰는 대화에서만** 그랬다는 점이다. 그건
 * 이 프로그램이 하는 일 그 자체다. 짧은 문답에서는 메시지와 블록 수가 비슷해
 * 잘 맞고, 길게 일을 시킬수록 어긋난다 — 아낄 것이 제일 많은 자리에서만
 * 안 아꼈다.
 *
 * 이제 블록으로 센다.
 */
/** 서버가 표식에서 뒤로 훑는 칸 수. 이 값은 서버가 정한 것이다. */
export const 창블록 = 20;
/** 닻은 꼬리에서 이만큼 **블록** 앞에 박는다. 창(20)보다 넉넉히 안쪽이어야 한다. */
export const 닻블록 = 14;
/** 대화가 이 블록 수를 넘으면 닻을 하나 더 박는다. 그 아래면 꼬리 하나로 닿는다. */
export const 닻문턱 = 20;

/** 메시지 하나가 몇 블록인가. 글 한 덩이짜리는 1블록이다. */
const 블록수 = (m) => (Array.isArray(m?.content) ? m.content.length : 1);

/** 이 배열이 통틀어 몇 블록인가. */
const 통블록 = (ms) => ms.reduce((n, m) => n + 블록수(m), 0);

/**
 * 메시지 하나의 **마지막 성한 블록**에 표식을 붙인 사본을 돌려준다.
 * 붙일 자리가 없으면 원본 그대로.
 */
export function 블록에붙이기(msg, 칸 = 'cache_control') {
  if (!msg) return msg;
  const 본래 = Array.isArray(msg.content)
    ? msg.content
    : [{ type: 'text', text: String(msg.content ?? '') }];
  let 자리 = -1;
  for (let i = 본래.length - 1; i >= 0; i--) {
    if (붙일수있나(본래[i])) { 자리 = i; break; }
  }
  if (자리 < 0) return msg;
  const 새 = 본래.map((b, i) => (i === 자리 ? { ...b, [칸]: 표식값(칸) } : b));
  return { ...msg, content: 새 };
}

/**
 * 시스템 글 조각들을 블록 배열로 만든다.
 *
 * 첫 조각이 **굳은 부분**이다 (agent/session.js 의 시스템조각). 그 끝에
 * 표식을 박으면 도구 정의까지 같이 잡힌다 — 규격이 tools 를 system 앞에
 * 렌더하기 때문이다.
 *
 * 조각이 하나뿐이면 그 끝에 박는다. 그때는 모드가 바뀔 때마다 다시 쓰지만,
 * 안 박는 것보다는 낫다.
 *
 * @param {string[]} 조각들
 * @param {boolean} 표식쓰나
 */
export function 시스템블록(조각들, 표식쓰나, 칸 = 'cache_control', { 긴수명 = true } = {}) {
  const 있는것 = (조각들 ?? []).map((x) => String(x ?? '')).filter((x) => x.length);
  if (!있는것.length) return null;
  if (!표식쓰나) return 있는것.join('');
  const 굳은끝 = 0;   // 첫 조각이 굳은 부분이다
  /*
   * 굳은 부분에는 **한 시간짜리**를 붙인다 (표식긴것).
   *
   * 이 자리가 크고 안 바뀐다 — 도구 정의와 시스템 글이다. 오래 살려 두면
   * 도구가 도는 몇 분 동안에도 안 죽는다. 굴러가는 꼬리는 어차피 다음 턴에
   * 무효가 되므로 거기까지 두 배를 낼 까닭이 없다 (메시지표식 은 짧은 것).
   *
   * 안 받는 창구가 있으면 카드가 끈다 (backend/wire.js 의 긴수명).
   */
  return 있는것.map((text, i) => (
    i === 굳은끝 ? { type: 'text', text, [칸]: 표식값(칸, 긴수명) } : { type: 'text', text }
  ));
}

/**
 * 메시지 배열에 옮겨 가는 표식을 붙인 **사본**을 돌려준다.
 *
 * @param {object[]} messages  차례합치기를 이미 거친 배열
 * @returns {object[]}
 */
/**
 * 그 자리에 표식을 **붙일 수 있나.** 없으면 한 칸씩 앞으로 물러선다.
 *
 * 도구만 부른 차례는 붙일 자리가 없다 — OpenAI 규격에서 그런 차례는
 * `content: null` 이고(adapter.js 의 assistantMessage), 빈 글에는 표식을
 * 못 붙인다(붙일수있나).
 *
 * 문제는 그때 `블록에붙이기` 가 **원본을 그대로 돌려준다**는 것이다. 아무
 * 말도 안 하므로 그 요청은 닻 없이 나가고, 화면은 여전히 「캐시 표식」 이라고
 * 적는다. 도구를 도는 턴은 `assistant(부름)` ↔ `tool(결과)` 이 번갈아 오므로
 * **닻 자리가 절반 확률로 부름 차례에 떨어진다.** 하필 그 닻이 되돌아보기
 * 창(스무 자리)을 넘기지 않으려고 박아 둔 것이라, 없어지면 앞이 통째로 다시 나간다.
 *
 * 그래서 못 붙이면 앞으로 물러서서 붙는 자리를 찾는다. 한 칸 앞이면 결과
 * 차례라 거의 바로 걸린다.
 */
function 붙는자리(ms, 부터) {
  for (let i = Math.min(부터, ms.length - 1); i >= 0; i--) {
    const 그자리 = 블록에붙이기(ms[i], 'cache_control');
    if (그자리 !== ms[i]) return i;
  }
  return -1;
}

/**
 * 꼬리에서 **블록으로** 닻블록 만큼 앞선 자리를 찾는다.
 *
 * 뒤에서부터 블록을 세어 올라가다 닻블록 을 넘는 순간 멈춘다. 메시지 수로
 * 세면 도구를 도는 대화에서 창 밖으로 나간다 (위 주석).
 */
function 닻자리(ms, 꼬리) {
  let 센것 = 0;
  for (let i = 꼬리; i >= 0; i--) {
    센것 += 블록수(ms[i]);
    if (센것 >= 닻블록) return i;
  }
  return 0;
}

export function 메시지표식(messages, 칸 = 'cache_control') {
  const ms = messages ?? [];
  if (!ms.length) return ms;
  const 붙일자리 = new Set();
  const 꼬리 = 붙는자리(ms, ms.length - 1);
  if (꼬리 >= 0) 붙일자리.add(꼬리);
  /*
   * 도구를 길게 늘어놓는 턴에서 되돌아보기 창을 넘기지 않게 닻을 하나 더.
   * 통틀어 창 안에 들어오면 꼬리 하나로 앞까지 닿으니 닻이 필요 없다.
   */
  if (통블록(ms) > 닻문턱) {
    const 닻 = 붙는자리(ms, 닻자리(ms, 꼬리 >= 0 ? 꼬리 : ms.length - 1));
    // 꼬리와 같은 자리면 닻이 아니다 — 그건 표식 하나짜리다.
    if (닻 >= 0 && 닻 !== 꼬리) 붙일자리.add(닻);
  }
  return ms.map((m, i) => (붙일자리.has(i) ? 블록에붙이기(m, 칸) : m));
}

/**
 * 이 요청에 표식을 붙일 만한가.
 *
 * 너무 작으면 서버가 안 잡는다. 붙여도 탈은 없지만, 안 잡히는 표식을 붙여
 * 놓고 「캐시를 켰다」 고 말하면 화면이 거짓말을 한다.
 *
 * 재는 자는 이 프로그램이 이미 쓰는 것으로 맞춘다(agent/session.js 의
 * estimateTokens). 여기는 **글자 수를 토큰의 두 배로** 치고 있었는데, 그건
 * 영어·코드에서만 맞는 셈이다. 한글은 글자당 1토큰이라 두 배로 나누면 절반이
 * 되고, Bedrock 처럼 최소가 4,096 인 창구에서는 실제로는 2,300 토큰밖에 안
 * 되는 대화에 「잡힐 만하다」 고 답했다. 그러면 안 잡힐 표식을 붙여 놓고
 * `/status` 가 「캐시 표식」 이라고 적는다 — 이 함수가 막겠다고 적어 둔 바로
 * 그 거짓말이다.
 */
export function 잡힐만한가(messages, 최소토큰 = 1024, 곁 = null) {
  let 토큰 = 0;
  /*
   * 도구 정의도 **앞머리에 나가는 것**이다.
   *
   * 이 자가 메시지만 세고 있었다. 그런데 전선에 실릴 때 순서는
   * `tools → system → messages` 라, 도구 스키마가 캐시 앞머리의 **맨 앞**
   * 이다. 내장 도구 스무 개의 스키마는 1,800토큰쯤 된다.
   *
   * 그래서 시킴말과 사람말이 합쳐 500토큰인 판에서 이 자가 「문턱을 못
   * 넘는다」 고 답했고, 표식을 하나도 안 붙였다. 실제로는 2,300토큰이라
   * 넘고도 남는다. **덜 세서 캐시를 안 켠 것**인데, 화면에는 아무 말도
   * 안 난다 — 그냥 매 턴 값이 더 나온다.
   *
   * 세는 것과 보내는 것이 다르면, 세는 쪽이 틀린 것이다.
   */
  if (곁) {
    for (const 것 of [곁.tools, 곁.system]) {
      if (것 == null) continue;
      토큰 += estimateTokens(typeof 것 === 'string' ? 것 : JSON.stringify(것));
      if (토큰 > 최소토큰) return true;
    }
  }
  for (const m of messages ?? []) {
    토큰 += estimateTokens(typeof m?.content === 'string' ? m.content : JSON.stringify(m?.content ?? ''));
    if (토큰 > 최소토큰) return true;
  }
  return false;
}
