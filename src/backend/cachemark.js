// 캐시 표식을 어디에 붙일까.
//
// ── 무엇이 문제였나 ─────────────────────────────────────────────────────
//
// 이 프로그램은 캐시 표식을 **어디에도 안 붙이고 있었다.** 그래서 서버가
// 알아서 앞머리를 캐시해 주는 자리(Bedrock · OpenAI)에서는 정적 앞머리만
// 잡혔고, 안 해 주는 자리(Anthropic 직통)에서는 하나도 안 잡혔다.
//
// 실제로 이런 모양이었다 — 열 번을 잇달아 부르는 동안 —
//
//   총 토큰   19,654 → 60,267   대화가 자란다
//   캐시       5.9K  →  5.9K    앞머리에서 멈춰 있다
//
// 5.9K 는 시스템 프롬프트(약 4,045)와 도구 정의(약 1,800)를 합친 값이다.
// 즉 **자라는 대화는 한 번도 캐시된 적이 없다.** 매 걸음 전액 다시 보내고
// 전액 다시 냈다.
//
// ── 어디에 붙이나 ───────────────────────────────────────────────────────
//
// 규격이 정한 렌더 차례는 tools → system → messages 다. 표식 하나는 그
// 자리까지의 앞머리를 통째로 잡는다. 그래서 두 자리면 충분하다.
//
//   1. 시스템의 **굳은 부분 끝**   — 도구까지 같이 잡힌다 (한 번 쓰고 계속 읽는다)
//   2. 마지막 메시지 끝            — 걸음마다 앞으로 옮겨 간다 (자라는 대화를 잡는다)
//
// 2번이 이 파일의 핵심이다. 표식이 앞으로 옮겨 가면, 다음 요청은 지난번
// 표식 자리까지를 **읽고** 그 뒤만 새로 쓴다. 안 옮기면 대화는 영영 캐시
// 밖에 있다.
//
// ── 되돌아보기 창 ───────────────────────────────────────────────────────
//
// 표식은 뒤로 스무 자리까지만 지난 것을 찾는다. 도구를 길게 늘어놓는 턴은
// 그 스무 자리를 넘길 수 있고, 그러면 **말없이** 캐시를 못 찾는다. 그래서
// 대화가 길면 중간에 닻을 하나 더 박는다. 표식은 넷까지라 셋은 여유가 있다.
//
// ── 안 붙이는 자리 ──────────────────────────────────────────────────────
//
// 생각 블록에는 안 붙인다 — 우리가 나르기만 하는 블록이라 손대지 않는다.
// 빈 글 블록에도 안 붙인다. 둘 다 거절당할 수 있고, 그 400 은 화면에서
// 열쇠가 틀린 것과 구별이 안 된다.

/** 표식 한 개. 기본 수명(5분). 굴러가는 꼬리에는 이걸 쓴다. */
export const 표식 = { type: 'ephemeral' };

/**
 * **굳은 앞머리**에 쓰는 표식. 한 시간을 산다.
 *
 * ── 왜 바꿨나 ───────────────────────────────────────────────────────────
 *
 * 여기 「한 시간짜리는 쓰기 값이 두 배라 안 쓴다」 고 적혀 있었다. 그 셈이
 * **견줄 상대를 잘못 잡았다.**
 *
 *   5분이 지나 캐시가 죽으면 상대는 「싼 쓰기」 가 아니라 **전액 재전송**이다.
 *
 *   5분  쓰기 1.25배 → 5분 넘으면 죽는다 → 다음 턴에 또 1.25배 → 매 턴 1.25배
 *   1시간 쓰기 2배   → 한 시간 산다     → 다음 턴부터 0.1배
 *
 * 두 턴만 넘어가도 1시간이 이긴다(2 + 0.1 = 2.1 대 1.25 + 1.25 = 2.5).
 *
 * 그리고 코딩 에이전트는 **5분을 넘기는 것이 예외가 아니라 일상**이다. 검사
 * 한 번이 6분이고 빌드가 3분이다. 그 사이 도구가 도는 동안 모델은 안 불린다 —
 * 5분 수명은 그 틈을 못 넘긴다.
 *
 * 나란히 재 봤을 때 이것이 숫자로 나왔다(docs/ko/benchmark.md). 같은 일을
 * 시킨 비교에서 캐시 쓰기가 **1.5M 대 247.6K — 여섯 배**였고, 적중률이
 * 94.3% 대 99.3% 였다. 토큰을 28.7% 적게 쓰고도 비용이 22% 높았다. 캐시를
 * 자꾸 다시 쓰느라 그랬다.
 *
 * ── 왜 앞머리에만 붙이나 ────────────────────────────────────────────────
 *
 * 굳은 앞머리(도구 정의 + 시스템 글)는 **크고 안 바뀐다.** 오래 살려 둘 값이
 * 있는 자리다. 반대로 대화 꼬리는 다음 턴에 새 메시지가 붙는 순간 어차피
 * 무효가 된다 — 거기에 두 배를 내는 것은 그냥 버리는 돈이다.
 *
 * 그래서 수명을 자리에 맞춰 나눈다. 이게 「한 시간을 켠다」 와 다른 점이다.
 */
export const 표식긴것 = { type: 'ephemeral', ttl: '1h' };

/**
 * 표식을 적는 **칸 이름**들.
 *
 * 같은 뜻을 두 규격이 다른 이름으로 적는다. 어느 쪽인지는 창구가 아니라
 * **규격**이 정하므로, 여기서는 이름만 알고 고르는 것은 카드가 한다
 * (backend/wire.js 의 표식칸).
 *
 *   cache_control            Anthropic 규격의 칸. Claude 를 앞에 둔 창구는
 *                            몸이 OpenAI 꼴이어도 이 칸으로 알아듣는다.
 *   prompt_cache_breakpoint  OpenAI 규격의 칸. 규격 문서의 text 조각에
 *                            정식으로 들어 있다.
 *
 * 어느 것도 「업체별 예외」 가 아니다. 둘 다 문서에 있는 칸이고, 안 받는
 * 서버는 400 으로 말해 준다 — 그러면 카드가 배운다(backend/wire.js).
 */
export const 표식칸들 = ['cache_control', 'prompt_cache_breakpoint'];

/**
 * 그 칸에 적을 값. 칸마다 값의 모양이 다르다.
 *
 * `긴것` 은 Anthropic 규격에만 있다. OpenAI 규격의 `prompt_cache_breakpoint`
 * 에는 수명 칸이 없으므로 붙이지 않는다 — 없는 칸을 지어내면 400 이다.
 */
const 표식값 = (칸, 긴것 = false) => {
  if (칸 === 'prompt_cache_breakpoint') return { mode: 'explicit' };
  return 긴것 ? { ...표식긴것 } : { ...표식 };
};

