// 도구 부름 한 줄을 적을 때 **무엇으로 그 부름을 알아보나.**
//
// ── 왜 파일 하나를 따로 두나 ────────────────────────────────────────────
//
// `Read` 만 적으면 열 줄이 전부 `Read` 다. 무엇을 읽었는지가 빠지면 목록을
// 훑어보는 뜻이 없어진다. 그래서 인자에서 「이 부름을 대표하는 값」 하나를
// 뽑아 괄호에 넣는다 — `Read(src/a.js)`.
//
// 그 「대표하는 값」 을 고르는 **차례**가 여태 다섯 곳에 따로 적혀 있었다:
//
//   src/repl.js · src/oneshot.js · src/acp/map.js · src/ui/export.js ·
//   src/safety/audit.js
//
// 다섯이 조금씩 달랐다. 어떤 데는 `url` 이 있고 어떤 데는 없다. 새 도구가
// 새 인자 이름을 쓰면 그중 한두 곳만 고쳐지고, 나머지에서는 그 도구가 **빈
// 괄호**로 남는다 — 화면에도, 내보낸 보고서에도, 감사기록에도. 그 셋이
// 서로 다른 말을 하기 시작하면 무엇이 맞는지 알 길이 없다.
//
// 목록은 여기 하나다. 부르는 쪽은 제 사정(길이 자르기·일감 번호 같은 것)만
// 따로 얹는다.

/**
 * 이 인자가 무엇에 관한 부름인지 말해 주는 이름들. **차례가 뜻이다** —
 * 앞엣것이 더 또렷하다.
 *
 *   file_path  파일을 다루는 도구 (Read·Write·Edit)
 *   pattern    찾는 도구 (Grep·Glob)
 *   path       폴더를 다루는 도구
 *   url        웹을 읽는 도구
 *   name       이름으로 부르는 것 (스킬·플러그인·MCP)
 *   purpose/목적  하위 작업 — 무엇을 시켰는지가 곧 그 부름이다
 *   command    셸 — 제일 뒤다. 길고, 앞엣것이 있으면 그쪽이 더 또렷하다.
 */
export const 이름칸들 = ['file_path', 'pattern', 'path', 'url', 'name', 'purpose', '목적'];

/**
 * 인자에서 대표하는 값 하나. 없으면 null.
 *
 * `command` 는 **여기서 안 본다.** 글이 길어서 부르는 쪽마다 자르는 길이가
 * 다르고(화면은 52자, 기록은 통째로), 그 판단까지 여기서 하면 한쪽이 반드시
 * 어색해진다. 부르는 쪽이 이 자를 먼저 물어보고, 없으면 제 방식으로 command
 * 를 다룬다.
 */
export function 첫이름(인자) {
  const a = 인자 ?? {};
  for (const 칸 of 이름칸들) {
    const v = a[칸];
    if (typeof v === 'string' && v) return v;
    if (typeof v === 'number') return String(v);
  }
  return null;
}
