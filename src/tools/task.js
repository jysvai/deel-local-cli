/**
 * 하위가 일할 모드를 정한다 — **부모보다 셀 수는 없다.**
 *
 * 이게 이 파일에서 제일 중요한 함수다.
 *
 * 설계·계획·묻기 모드는 "파일을 안 바꾼다" 는 약속이다. 사람은 그 약속을 믿고
 * /architect 를 켠다. 그런데 하위 작업이 제 모드를 스스로 고를 수 있으면,
 * 설계 모드에서 `Task({모드:'code'})` 한 번으로 그 약속이 깨진다. 화면에는
 * 여전히 설계 모드라고 떠 있는 채로 파일이 바뀐다 — 제일 나쁜 종류의 구멍이다.
 *
 * 그래서 부모가 못 쓰는 것은 하위도 못 쓴다. 부모가 읽기 전용이면 하위가
 * 무엇을 부탁하든 읽기 전용으로 내린다.
 */
export function 하위모드(요청, 부모모드) {
  const 고른것 = normWork(요청) ?? 'code';
  if (canWrite(부모모드)) return 고른것;
  // 부모가 못 바꾸면 하위도 못 바꾼다. 읽기만 하는 모드 중에서 고른다.
  return canWrite(고른것) ? 'ask' : 고른것;
}

/**
 * 하위가 끝난 뒤 부모 대화에 실을 글.
 *
 * 하위가 무엇을 했는지가 아니라 **부모가 다음 걸음을 정하는 데 필요한 것**만
 * 담는다. 파일 목록은 디스크를 보고 적은 사실이고(loop.js 의 파일현황),
 * 하위가 "만들었습니다" 라고 말한 것이 아니다.
 *
 * 못 끝낸 것을 빼면 안 된다. 부모는 그걸 보고 이어서 할지 정한다 —
 * 다 됐다고 알면 안 끝난 일 위에 다음 일을 쌓는다.
 */
export function 하위요약({ 목적, 모드, 끝, 글자수, 보인이름 = (p) => p }) {
  const 줄 = [];
  const w = workMode(모드);
  const 왜끝났나 = {
    done: '끝냄',
    limit: '걸음 수를 다 써서 멈춤 — 다 못 했습니다',
    stuck: '같은 자리를 되풀이해서 스스로 멈춤 — 다 못 했습니다',
    aborted: '사용자가 중단함 — 다 못 했습니다',
  }[끝?.type] ?? '끝난 이유를 알 수 없음';

  줄.push(`하위 작업 "${목적}" · ${w.name} 모드 · ${끝?.steps ?? 0}걸음 · ${왜끝났나}`);

  const 파일들 = (끝?.files ?? []).filter((f) => !f.dir);
  if (파일들.length) {
    줄.push('');
    줄.push('건드린 파일 (디스크에서 확인한 것):');
    for (const f of 파일들) {
      const 이름 = 보인이름(f.path);
      if (f.missing) { 줄.push(`  ✗ ${이름} — 만들어지지 않았습니다`); continue; }
      const kb = f.bytes >= 1024 ? `${(f.bytes / 1024).toFixed(1)}KB` : `${f.bytes}B`;
      줄.push(`  ✓ ${이름} · ${f.lines}줄 · ${kb}`);
    }
  } else {
    줄.push('건드린 파일: 없음');
  }

  const 남 = 끝?.남은할일 ?? [];
  if (남.length) {
    줄.push('');
    줄.push('아직 안 끝난 것:');
    for (const t of 남) 줄.push(`  · ${t.text ?? t.title ?? String(t)}`);
  }

  if (끝?.why) { 줄.push(''); 줄.push(`막힌 데: ${끝.why}`); }

  const 말 = String(끝?.text ?? '').trim();
  if (말) {
    줄.push('');
    줄.push('하위가 한 말:');
    // 자를 때는 자른 사실을 말한다. 조용히 자르면 부모는 그게 전부인 줄 안다.
    줄.push(말.length > 글자수 ? `${말.slice(0, 글자수)}\n  …(길어서 여기까지만 옮겼습니다)` : 말);
  }

  return 줄.join('\n');
}
