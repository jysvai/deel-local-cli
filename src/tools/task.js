/**
 * Task — 하위 작업. 큰 일의 한 덩이를 **따로 떨어진 창**에서 돌린다.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────────────────
 *
 * 파일 여덟 개짜리 프로젝트를 한 창에서 만들면, 여덟 개 파일 내용이 전부 그
 * 창에 쌓인다. 32k 모델이면 서너 개째에 창이 차고, 차면 앞엣말이 접혀 나간다.
 * 그때부터 모델은 자기가 무엇을 만들던 중이었는지를 잊는다 — 화면에는 아무
 * 오류도 안 뜨는데 결과만 이상해진다. "대시보드 만들어줘" 가 계획표 한 장으로
 * 끝나던 일의 뿌리가 이것이다.
 *
 * 하위 작업은 그 덩이를 **새 대화**에서 돌리고, 부모에게는 요약 한 덩이만
 * 돌려준다. 하위가 파일 열 개를 읽고 고쳐도 부모 창이 받는 것은 요약뿐이다.
 * 그래서 8k 모델도 여러 파일짜리 일을 끝까지 끌고 갈 수 있다.
 *
 * ── 여기 없는 것 ───────────────────────────────────────────────────────
 *
 * 실행은 여기 없다. loop.js 가 가로채서 직접 돈다.
 *
 * 도구는 `{content, summary}` 만 돌려줄 뿐 이벤트를 못 흘린다. 하위 작업을
 * 평범한 도구로 돌리면 그 몇 분 동안 화면이 완전히 죽는다 — 사람은 멈춘 건지
 * 도는 건지 알 수 없다. 그래서 loop.js 가 하위 루프의 이벤트를 그대로 받아
 * 한 단 들여쓴 채 위로 올려보낸다.
 *
 * 이 파일이 갖는 것은 스키마와, **경계를 지키는 판단들**이다.
 */
import { get as workMode, canWrite, normalize as normWork } from '../agent/modes.js';

